"""
По запросу ли вакансия.

Источник ищет слова запроса во всех полях вакансии, включая название
компании. По запросу «Арт-директор» так пришла 331 вакансия ресторанов
работодателя «АРТ РЕСТ»: «арт» в названии компании, «директор» где-то
в тексте. Все они входили в медианы зарплат и частоты навыков
профессии, и топ навыков арт-директора открывали «Счета», «Работа с
гостями» и «Касса».

Сбор теперь ищет только в названии и описании (`ПОЛЯ_ПОИСКА` в
клиенте), и новых таких вакансий не приходит. Этот модуль нужен для
собранного раньше: пометить, а не удалить. Удаление необратимо, а
правило сопоставления — приближение, и его придётся править.

**Сопоставление нестрогое намеренно.** «Рендеринг» совпадает с
«рендер», «3ds Max» — с «3dsmax». Первая, буквальная версия объявила
мусором 88 % проверенных вакансий — почти все зря.

**Помечается только доказанная причина.** Первая версия правила
помечала всё, где слов запроса нет в тексте вакансии, — 1 419 штук.
Проверка глазами разделила их надвое. Там, где слова запроса стоят в
названии компании (777), — мусор без исключений: рестораны, сборщики
заказов от «Найм персонал PRO». Там, где их нет и в названии компании
(642), — в основном законные вакансии: по «Разработчик» источник отдал
«Java Backend Developer», по «найм» — «Рекрутер». Источник знает
синонимы, которых не знает это правило, и отсутствие слова в тексте
ничего не доказывает. Поэтому пометку получает только первый класс.
"""

from __future__ import annotations

import re
from typing import Iterable, List, Optional

РАЗМЕТКА = re.compile(r"<[^>]+>")
СЛОВА = re.compile(r"[a-zа-я0-9]+")

# Короче этого слитное написание не сравнивается: «ai» нашлось бы
# внутри любого «email» и «training».
МИНИМУМ_СЛИТНОГО = 4


def слова(текст: Optional[str]) -> List[str]:
    """Слова текста в нижнем регистре, без разметки и с «е» вместо «ё»."""
    return СЛОВА.findall(РАЗМЕТКА.sub(" ", текст or "").lower().replace("ё", "е"))


def _основа(слово: str) -> str:
    """Слово без окончания: «дизайнера» и «дизайнер» должны совпасть."""
    return слово[:-2] if len(слово) > 5 else слово


def встречается(запрос: str, текст: Optional[str]) -> bool:
    """
    Есть ли запрос в тексте.

    Два способа, достаточно любого. По словам: каждое слово запроса
    начинает какое-то слово текста («рендер» — «рендеринг»). Слитно:
    запрос без пробелов есть в тексте без пробелов («3dsmax» — «3ds
    max», «арт-директор» — «артдиректор»).
    """
    слова_запроса = слова(запрос)
    слова_текста = слова(текст)
    if not слова_запроса or not слова_текста:
        return False

    if all(any(слово.startswith(_основа(з)) for слово in слова_текста) for з in слова_запроса):
        return True

    слитно = "".join(слова_запроса)
    return len(слитно) >= МИНИМУМ_СЛИТНОГО and слитно in "".join(слова_текста)


def запросы(source_keyword: Optional[str]) -> List[str]:
    """
    Запросы, по которым вакансия была найдена.

    В базе они лежат одной строкой через запятую: вакансия, пришедшая
    по трём запросам, помнит все три.
    """
    return [часть.strip() for часть in (source_keyword or "").split(",") if часть.strip()]


def не_по_запросу(
    source_keyword: Optional[str],
    название: Optional[str],
    навыки: Optional[str] = None,
    описание: Optional[str] = None,
    отрывок: Optional[str] = None,
    компания: Optional[str] = None,
) -> Optional[bool]:
    """
    Найдена ли вакансия не по запросу.

    Returns:
        True — слов запроса нет ни в названии, ни в навыках, ни в
        тексте, зато они есть в названии компании: источник нашёл
        вакансию по нему. False — хотя бы один запрос встречается в
        самой вакансии. None — слов нет нигде, и в названии компании
        тоже: скорее всего источник подставил синоним, и вакансия
        законна, но доказать это нечем. Такие не помечаются.
    """
    искомые = запросы(source_keyword)
    if not искомые:
        return None

    видимое = " ".join(filter(None, [название, навыки, описание, отрывок]))
    if any(встречается(запрос, видимое) for запрос in искомые):
        return False

    if компания and _в_названии_компании(искомые, компания):
        return True

    return None


def _в_названии_компании(искомые: Iterable[str], компания: str) -> bool:
    """Хотя бы одно слово хотя бы одного запроса начинает слово в названии компании."""
    слова_компании = слова(компания)
    return any(
        слово.startswith(_основа(з))
        for запрос in искомые
        for з in слова(запрос)
        for слово in слова_компании
    )
