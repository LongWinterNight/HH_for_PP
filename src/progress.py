"""
Ход сбора числом: сколько сделано из того, что предстоит.

Прежний процент делил собранное за весь сбор на найденное по текущему
запросу. На первом запросе это совпадало с правдой, на втором уже нет:
712 вакансий, собранных двумя запросами, делились на 175, найденных по
второму, и полоса показывала 99 % при трёх запросах впереди.

Здесь единица работы — запрос. Сбор из пяти запросов состоит из пяти
равных долей; пройденные запросы дают свои доли целиком, идущий — ту
часть, что уже просмотрена. Равные доли — упрощение: запросы бывают на
сто вакансий и на две тысячи. Но объём следующих запросов неизвестен до
их первой страницы, и взвешивать по нему значило бы пересчитывать
знаменатель на ходу — полоса при этом ходила бы назад.

Считает одна функция: процент показывается из памяти процесса, а после
перезапуска приложения — из базы, и двух формул здесь быть не должно.
"""

from __future__ import annotations

import math
from typing import Optional

# Сколько вакансий источник отдаёт на странице выдачи.
НА_СТРАНИЦЕ = 100

# Сто процентов ставит только завершение сбора: запись в базу и итоги
# идут после последней страницы, и «готово» до них было бы обещанием.
ПОТОЛОК = 99


def возьмём(найдено: Optional[int], страниц: int, на_странице: int = НА_СТРАНИЦЕ) -> int:
    """
    Сколько вакансий запроса будет просмотрено.

    Источник называет, сколько нашёл, а отдаёт не больше глубины обхода.
    Знаменателем служит второе: найдено 5 000 при десяти страницах — это
    тысяча к просмотру, и по первому числу полоса встала бы на 20 %.
    """
    if not найдено or найдено < 0:
        return 0
    return min(найдено, max(страниц, 0) * на_странице)


def процент(
    запрос: int,
    всего_запросов: int,
    просмотрено: int = 0,
    к_просмотру: int = 0,
    запрос_пройден: bool = False,
) -> int:
    """
    Процент готовности сбора.

    Args:
        запрос: Номер идущего запроса, с единицы
        всего_запросов: Сколько запросов в сборе
        просмотрено: Сколько вакансий текущего запроса уже просмотрено
        к_просмотру: Сколько их будет просмотрено (см. `возьмём`)
        запрос_пройден: Текущий запрос обойдён и записан

    Returns:
        Целое от 0 до 99. Без числа запросов — ноль: процент без
        знаменателя был бы выдумкой.
    """
    if всего_запросов <= 0 or запрос <= 0:
        return 0

    пройдено = min(запрос - 1, всего_запросов)
    if запрос_пройден:
        доля = 1.0
    elif к_просмотру > 0:
        доля = min(1.0, max(0, просмотрено) / к_просмотру)
    else:
        # Первая страница ещё не пришла: объём запроса неизвестен.
        доля = 0.0

    return min(ПОТОЛОК, int((пройдено + доля) / всего_запросов * 100))


def страниц_ожидается(найдено: Optional[int], страниц: int, на_странице: int = НА_СТРАНИЦЕ) -> int:
    """
    Сколько страниц выдачи будет прочитано по запросу.

    «Страница 1 из 10» при выдаче в 175 вакансий обещает восемь страниц,
    которых нет: глубина обхода — предел, а не план.
    """
    объём = возьмём(найдено, страниц, на_странице)
    return math.ceil(объём / на_странице) if объём else 0


def осталось_секунд(прошло_секунд: float, готово_процентов: int) -> Optional[int]:
    """
    Сколько ещё ждать, если сбор пойдёт с той же скоростью.

    До пяти процентов оценки нет: по первым секундам она скачет в разы,
    и число, которое через минуту сменится втрое, хуже отсутствующего.
    """
    if готово_процентов < 5 or прошло_секунд <= 0:
        return None
    return int(прошло_секунд * (100 - готово_процентов) / готово_процентов)
