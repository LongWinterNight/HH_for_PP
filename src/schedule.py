"""
Расписание сбора: что обещано и выполняется ли обещание.

Сам запуск по времени делает планировщик Windows — он переживает
перезагрузку и не требует, чтобы приложение было открыто. Здесь то,
что планировщик не знает и знать не должен:

- запись о расписании рядом с данными (`data/schedule.json`): приложению
  нужно знать, как часто обещан сбор, не спрашивая об этом планировщик
  на каждый запрос экрана;
- проверка «сбор должен был пройти, но не прошёл»: планировщик может
  молча не запустить задание — компьютер выключен, пользователь не
  вошёл, путь к Python изменился. Отказ сбора шлёт оповещение сам, а
  отсутствие запуска не шлёт ничего — его видно только по календарю;
- копия базы перед сбором, который никто не видит.
"""

from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

from src.utils import get_logger

logger = get_logger(__name__)

# Имя задания в планировщике. Латиницей: планировщик принимает кириллицу,
# а командная строка, которой задание проверяют руками, — не всегда.
ЗАДАНИЕ = "BaseVacancy-Collect"

# Сколько сбор может запоздать, прежде чем считается пропущенным.
# Задание догоняет пропущенный запуск при включении компьютера, а сам
# сбор идёт десятки минут — четверть суток покрывает и то, и другое.
ЗАПАС_ЧАСОВ = 6

# Сколько копий базы, сделанных перед сбором по расписанию, хранится.
КОПИЙ_ХРАНИТЬ = 3
ПРИСТАВКА_КОПИИ = "расписание_"


def файл_расписания() -> Path:
    from src.config import PROJECT_ROOT

    return PROJECT_ROOT / "data" / "schedule.json"


def прочитать(путь: Optional[Path] = None) -> Optional[Dict[str, Any]]:
    """Расписание, если оно установлено. Испорченный файл — «не установлено»."""
    путь = путь or файл_расписания()
    if not путь.exists():
        return None
    try:
        запись = json.loads(путь.read_text(encoding="utf-8"))
        время = str(запись["время"])
        datetime.strptime(время, "%H:%M")
        return {
            "время": время,
            "каждые_дней": max(1, int(запись.get("каждые_дней", 1))),
            "установлено": str(запись.get("установлено", "")),
        }
    except (OSError, ValueError, KeyError, TypeError):
        logger.warning(f"Файл расписания не читается: {путь}")
        return None


def записать(время: str, каждые_дней: int = 1, путь: Optional[Path] = None, сейчас: Optional[datetime] = None) -> Dict[str, Any]:
    """Запомнить расписание. Время проверяется: «25:00» планировщик не поймёт."""
    datetime.strptime(время, "%H:%M")
    if каждые_дней < 1:
        raise ValueError("Сбор не может идти чаще, чем раз в день")
    запись = {
        "время": время,
        "каждые_дней": каждые_дней,
        "установлено": (сейчас or datetime.now()).isoformat(timespec="seconds"),
    }
    путь = путь or файл_расписания()
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(запись, ensure_ascii=False, indent=2), encoding="utf-8")
    return запись


def убрать(путь: Optional[Path] = None) -> bool:
    путь = путь or файл_расписания()
    if путь.exists():
        путь.unlink()
        return True
    return False


def следующий_запуск(расписание: Dict[str, Any], сейчас: Optional[datetime] = None) -> datetime:
    """
    Когда сбор пойдёт в следующий раз.

    Считается от дня установки: при расписании «раз в три дня» запуск
    приходится на каждый третий день от него, а не на ближайшую полночь.
    """
    сейчас = сейчас or datetime.now()
    часы, минуты = (int(часть) for часть in расписание["время"].split(":"))
    try:
        начало = datetime.fromisoformat(расписание.get("установлено") or "")
    except ValueError:
        начало = сейчас
    первый = начало.replace(hour=часы, minute=минуты, second=0, microsecond=0)
    if первый < начало:
        первый += timedelta(days=1)

    шаг = timedelta(days=расписание["каждые_дней"])
    if первый >= сейчас:
        return первый
    пропущено = (сейчас - первый) // шаг + 1
    return первый + пропущено * шаг


def состояние(storage, сейчас: Optional[datetime] = None, путь: Optional[Path] = None) -> Dict[str, Any]:
    """
    Расписание и то, держится ли оно.

    Пропуском считается не «сбор не по расписанию», а «сбора не было
    дольше обещанного»: человек, который собрал руками вчера, ничего не
    пропустил, даже если ночное задание не сработало.
    """
    сейчас = сейчас or datetime.now()
    расписание = прочитать(путь)

    последний = storage.get_last_parser_run(only_successful=True)
    когда = None
    if последний:
        try:
            когда = datetime.fromisoformat(последний.get("completed_at") or последний.get("started_at") or "")
        except ValueError:
            когда = None

    итог: Dict[str, Any] = {
        "установлено": расписание is not None,
        "время": расписание["время"] if расписание else None,
        "каждые_дней": расписание["каждые_дней"] if расписание else None,
        "следующий": следующий_запуск(расписание, сейчас).isoformat(timespec="minutes") if расписание else None,
        "последний_сбор": когда.isoformat(timespec="seconds") if когда else None,
        "дней_без_сбора": (сейчас - когда).days if когда else None,
        "пропущен": False,
        "задание": ЗАДАНИЕ,
    }
    if not расписание:
        return итог

    срок = timedelta(days=расписание["каждые_дней"], hours=ЗАПАС_ЧАСОВ)
    # Отсчёт идёт от последнего удачного сбора, а пока их не было — от
    # дня установки: расписание, поставленное час назад, ещё ничего не
    # пропустило.
    try:
        установлено = datetime.fromisoformat(расписание["установлено"])
    except ValueError:
        установлено = сейчас
    точка = max(когда, установлено) if когда else установлено
    итог["пропущен"] = сейчас - точка > срок
    return итог


# ---------------------------------------------------------------------------
# Копия базы перед сбором, который никто не видит
# ---------------------------------------------------------------------------

def копия_базы(база: Path, папка: Optional[Path] = None, сейчас: Optional[datetime] = None) -> Optional[Path]:
    """
    Снять копию базы и убрать лишние прежние.

    Копия снимается средствами SQLite, а не копированием файла: база в
    это время открыта приложением, и файл, скопированный посреди записи,
    может не открыться.
    """
    if not база.exists():
        return None
    папка = папка or база.parent / "backups"
    папка.mkdir(parents=True, exist_ok=True)
    цель = папка / f"{ПРИСТАВКА_КОПИИ}{(сейчас or datetime.now()):%Y%m%d_%H%M%S}.db"

    откуда = sqlite3.connect(f"file:{база}?mode=ro", uri=True)
    куда = sqlite3.connect(цель)
    try:
        откуда.backup(куда)
    finally:
        куда.close()
        откуда.close()

    убрать_лишние_копии(папка)
    return цель


def убрать_лишние_копии(папка: Path, хранить: int = КОПИЙ_ХРАНИТЬ) -> List[Path]:
    """Оставить последние копии. Чужие файлы в папке не трогаются."""
    свои = sorted(папка.glob(f"{ПРИСТАВКА_КОПИИ}*.db"), key=lambda файл: файл.name)
    лишние = свои[:-хранить] if хранить > 0 else свои
    for файл in лишние:
        try:
            файл.unlink()
        except OSError as e:
            logger.warning(f"Не удалось убрать старую копию базы {файл.name}: {e}")
    return лишние
