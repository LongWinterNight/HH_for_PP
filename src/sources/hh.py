"""
hh.ru как реализация общего контракта источника.

Здесь и только здесь живут имена полей hh: `alternate_url`,
`key_skills`, `snippet.requirement`, `salary_range.mode`. Всё, что
ниже по течению — поиск навыков, зарплаты, копии по городам, — работает
с общей записью и о существовании hh.ru не знает.

Это первая реализация контракта, а не «главная»: второй источник
добавляется рядом, не трогая общий код. Проверка тому — S8‑3b.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from src.api_client import HHAPIClient
from src.salary_mode import ПОДПИСИ
from src.sections import текст_для_навыков
from src.sources.контракт import Источник, пустая_запись
from src.utils import get_logger

logger = get_logger(__name__)

ИМЯ = "hh.ru"

# Как источник называет валюты и как их называем мы. Расхождение одно и
# давнее: рубль у hh.ru — «RUR», код из девяностых, которого нет в
# нынешнем ISO 4217.
ВАЛЮТЫ = {"RUR": "RUB"}


def _валюта(код: Optional[str]) -> str:
    return ВАЛЮТЫ.get(код or "RUB", код or "RUB")


def _период(вакансия: Dict[str, Any]) -> Optional[str]:
    """
    Период выплаты: месяц, смена, час, вахта, услуга.

    None — источник его не назвал. Пустое значение честнее, чем «месяц
    по умолчанию»: часовая ставка, посчитанная месячной, — это ошибка в
    сорок раз, и она уже случалась.
    """
    диапазон = вакансия.get("salary_range") or {}
    режим = диапазон.get("mode") or {}
    код = режим.get("id")
    return код if код in ПОДПИСИ else None


def _текст(вакансия: Dict[str, Any]) -> str:
    """
    Текст, по которому ищутся навыки.

    Выжимка из выдачи плюс полезные разделы описания плюс название.
    Больше ниоткуда: поля работодателя дают ложные совпадения.

    Из описания берутся не все разделы. «Условия», «Мы предлагаем» и
    «О компании» рассказывают о работодателе, а не о кандидате, и поиск
    по ним давал «Подарки» у 70 вакансий и «Развитие» у 260 — «Подарки»
    дошли до топ-10 навыков на дашборде.
    """
    выжимка = вакансия.get("snippet") or {}
    куски = [
        выжимка.get("requirement") or "",
        выжимка.get("responsibility") or "",
        текст_для_навыков(вакансия.get("description") or ""),
        вакансия.get("name") or "",
    ]
    return " ".join(кусок.lower() for кусок in куски if кусок)


def _навыки_работодателя(вакансия: Dict[str, Any]) -> List[str]:
    """
    Навыки из `key_skills` — в том порядке, в каком их назвал человек.

    Приведение написания к канону здесь не делается: это правило
    продукта, а не источника, и живёт оно в `skills_store`.
    """
    сырые = вакансия.get("key_skills") or []
    навыки, видели = [], set()

    for запись in сырые:
        имя = (запись.get("name") if isinstance(запись, dict) else запись) or ""
        имя = имя.strip()
        ключ = имя.lower()
        if имя and ключ not in видели:
            видели.add(ключ)
            навыки.append(имя)

    return навыки


def в_общую_запись(вакансия: Dict[str, Any]) -> Dict[str, Any]:
    """
    Перевести ответ hh.ru в общую запись.

    Args:
        вакансия: Как её отдал источник — из выдачи, из карточки или из
            файла прошлого сбора

    Returns:
        Запись с полями `ПОЛЯ_ВАКАНСИИ`. Чего источник не сказал — то
        `None`, а не выдумано.
    """
    запись = пустая_запись()

    регион = вакансия.get("area") or {}
    работодатель = вакансия.get("employer") or {}
    зарплата = вакансия.get("salary") or {}
    опыт = вакансия.get("experience") or {}
    занятость = вакансия.get("employment") or {}
    график = вакансия.get("schedule") or {}

    запись.update({
        "источник": ИМЯ,
        "идентификатор": вакансия.get("id"),
        "название": вакансия.get("name") or "",
        "опубликовано": вакансия.get("published_at"),
        "ссылка": вакансия.get("alternate_url") or "",

        "работодатель": работодатель.get("name") or "",
        "работодатель_ид": работодатель.get("id") or "",
        "работодатель_ссылка": работодатель.get("url") or "",

        "регион": регион.get("name") or "",
        "опыт": опыт.get("name") or "",
        "занятость": занятость.get("name") or "",
        "график": график.get("name") or "",

        "зарплата_от": зарплата.get("from") if зарплата else None,
        "зарплата_до": зарплата.get("to") if зарплата else None,
        "валюта": _валюта(зарплата.get("currency") if зарплата else None),
        "до_вычета": bool(зарплата.get("gross")) if зарплата else False,
        "период": _период(вакансия),

        "навыки_работодателя": _навыки_работодателя(вакансия),
        "текст": _текст(вакансия),

        # Служебные пометки сбора. Для старых файлов, где их нет,
        # наличие карточки определяется по самим данным — так же, как
        # это делает живой сбор.
        "запрос": вакансия.get("_source_keyword"),
        "есть_карточка": bool(
            вакансия.get("_has_details") or вакансия.get("description")
        ),
    })

    return запись


class ИсточникHH(Источник):
    """hh.ru за общим контрактом."""

    # hh.ru обрывает пагинацию на 2000 записях, сколько бы ни «нашёл»:
    # по «Рекрутеру» он знает 10 294 и показывает пятую часть. Отсюда и
    # берётся резка на срезы — обойти этот потолок иначе нельзя.
    потолок_выдачи = 2000

    имя = ИМЯ

    def __init__(self, клиент: Optional[HHAPIClient] = None) -> None:
        self.клиент = клиент or HHAPIClient()

    def искать(
        self,
        запрос: str,
        страница: int = 0,
        на_странице: int = 100,
        регион: Optional[str] = None,
        дата_от: Optional[str] = None,
        дата_до: Optional[str] = None,
    ) -> Optional[Dict[str, Any]]:
        ответ = self.клиент.search_vacancies(
            запрос,
            page=страница,
            per_page=на_странице,
            date_from=дата_от,
            area=регион,
            date_to=дата_до,
        )
        if ответ is None:
            return None

        return {
            "вакансии": [в_общую_запись(в) for в in ответ.get("items") or []],
            "найдено": ответ.get("found"),
            "страниц": ответ.get("pages"),
            # Ответ источника целиком — для проверки контракта схемы и
            # для сохранения сырых данных. Общий код в него не смотрит.
            "сырое": ответ,
        }

    def карточка(self, идентификатор: str) -> Optional[Dict[str, Any]]:
        ответ = self.клиент.get_vacancy_details(идентификатор)
        return в_общую_запись(ответ) if ответ else None

    def регионы(self) -> List[Dict[str, Any]]:
        from src import regions

        return regions.загрузить(self.клиент)
