"""
Общий контракт источника вакансий.

Зачем. Движок сросся с hh.ru: имена его полей — `alternate_url`,
`key_skills`, `snippet.requirement`, `salary_range.mode` — доходили до
самой записи в базу. Второй источник (другой сайт РФ, Китая, Европы)
означал бы копию всего движка вместе с его пониманием того, как
устроена вакансия.

Здесь описано, что движок вправе знать о вакансии, независимо от того,
кто её отдал. Ниже по течению — поиск навыков, зарплаты, регионы — код
работает только с этими полями.

**Почему словарь, а не класс.** Запись проходит через нормализацию,
pandas и SQLite, и на каждом шаге превращалась бы обратно в словарь.
Класс добавил бы два преобразования и ничего не проверил бы: набор
полей всё равно задаётся здесь и проверяется тестом.

**Чего здесь нет намеренно.** Полей, которые есть только у hh: рейтинга
работодателя, меток «срочно», внутренних идентификаторов регионов.
Общий контракт — это пересечение того, что умеют все источники, а не
объединение. То, что нужно одному источнику, живёт в его слое.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

# Поля общей записи вакансии. Порядок — как читается человеком: кто,
# что, где, за сколько.
ПОЛЯ_ВАКАНСИИ = (
    # Кто отдал запись и под каким идентификатором она у него значится.
    # Вместе они образуют ключ: у разных источников идентификаторы
    # совпадают, и без имени источника записи столкнулись бы.
    "источник",
    "идентификатор",

    "название",
    "опубликовано",
    "ссылка",

    "работодатель",
    "работодатель_ид",
    "работодатель_ссылка",

    "регион",
    "опыт",
    "занятость",
    "график",

    "зарплата_от",
    "зарплата_до",
    "валюта",
    "до_вычета",
    "период",

    # Навыки, названные работодателем отдельным полем. Это прямое
    # утверждение, а не догадка по тексту, — лучший источник навыков.
    "навыки_работодателя",

    # Текст, по которому ищутся навыки: выжимка из выдачи плюс полезные
    # разделы описания. Собирает его слой источника — он знает, где у
    # него лежит описание и что в нём считается разделом.
    "текст",

    # Служебное: по какому запросу нашли и была ли прочитана карточка.
    "запрос",
    "есть_карточка",
)


def пустая_запись() -> Dict[str, Any]:
    """
    Запись со всеми полями и пустыми значениями.

    Слой источника заполняет, что знает, и не обязан помнить весь
    список: недостающее поле — это `None`, а не отсутствующий ключ.
    Разница важна ниже по течению: `KeyError` роняет разбор, а пустое
    значение честно означает «источник этого не сказал».
    """
    запись = {поле: None for поле in ПОЛЯ_ВАКАНСИИ}
    запись["навыки_работодателя"] = []
    запись["текст"] = ""
    запись["есть_карточка"] = False
    return запись


def проверить_запись(запись: Dict[str, Any]) -> List[str]:
    """
    Каких обязательных полей не хватает.

    Обязательный минимум — то, без чего запись бесполезна: чем она
    отличается от других (источник и идентификатор), как называется и
    кто её разместил. Остального может не быть: вакансия без зарплаты и
    без описания — обычное дело.
    """
    обязательные = ("источник", "идентификатор", "название", "работодатель")
    return [поле for поле in обязательные if not запись.get(поле)]


class Источник:
    """
    Что движок вправе спросить у источника вакансий.

    Реализация обязана уметь три вещи: искать, брать карточку и
    называть свои регионы. Всё остальное — заголовки, ключи, форматы
    дат, правила частоты — её личное дело.

    Классом, а не протоколом: так реализация видна в одном месте и
    может завести общее поведение — например, счётчик отказов.
    """

    # Как источник называется в базе и на экране. Короткое имя, по
    # которому запись отличается от записи другого источника.
    имя: str = ""

    # Пределы принадлежат источнику, а не движку. У каждой площадки свой
    # потолок выдачи, своя терпимость к частоте и свои санкции за напор:
    # общая пара значений в `.env` работала, пока источник был один, и
    # ломается на втором. Реализация переопределяет то, что знает про
    # себя, и наследует разумное по умолчанию.

    # Сколько срезов движок вправе обойти по одному запросу. Предохранитель
    # от обхода всех городов всех стран, а не оптимизация.
    предел_срезов: int = 100

    # Пауза между обращениями, секунды. Нижняя граница вежливости —
    # источник вправе просить больше, и тогда движок её увеличит сам.
    пауза: float = 1.0

    # Сколько записей выдачи источник вообще отдаёт по одному запросу,
    # сколько бы ни «нашёл». Ноль означает «предел неизвестен»: тогда
    # признак «запрос упёрся» считается только по нашему пределу страниц.
    потолок_выдачи: int = 0

    def искать(
        self,
        запрос: str,
        страница: int = 0,
        на_странице: int = 100,
        регион: Optional[str] = None,
        дата_от: Optional[str] = None,
        дата_до: Optional[str] = None,
    ) -> Optional[Dict[str, Any]]:
        """
        Страница выдачи по запросу.

        Returns:
            {"вакансии": [...], "найдено": int, "страниц": int} либо
            None при отказе источника. Вакансии — в общем виде
            (`ПОЛЯ_ВАКАНСИИ`), а не в том, в каком их отдал сайт.
        """
        raise NotImplementedError

    def карточка(self, идентификатор: str) -> Optional[Dict[str, Any]]:
        """Полная запись одной вакансии или None, если не отдалась."""
        raise NotImplementedError

    def регионы(self) -> List[Dict[str, Any]]:
        """
        Дерево регионов источника для резки запроса на срезы.

        Пустой список означает «источник этого не умеет»: тогда запрос
        режется только по датам, а недобор честно остаётся недобором.
        """
        return []
