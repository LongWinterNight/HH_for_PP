"""
Память между запросами: таблица вакансий и готовые ответы.

Зачем. Каждый запрос экрана заново читал всю таблицу вакансий — 250 мс,
— а экран шлёт таких запросов четыре-пять сразу. Данные при этом
меняются несколько раз в сутки: сбором и разбором модели. Читать одно и
то же двадцать раз в минуту незачем.

Главный вопрос любой такой памяти — когда она устарела. Здесь на него
отвечает сама база: `PRAGMA data_version` меняется, как только базу
изменило любое другое соединение — в этом процессе или в чужом. Сбор по
расписанию, фоновый разбор моделью, миграция из консоли — всё это
другие соединения, и всё это память сбрасывает. Сроков годности «на
глаз» здесь нет: число, которое врёт пять минут после сбора, хуже
медленного.

Отметка читается до данных, а не после. Если запись случилась между
двумя чтениями, в память ляжет свежая таблица под старой отметкой, и
следующий запрос прочитает её ещё раз — лишняя работа, но не устаревший
ответ. Обратный порядок дал бы старую таблицу под новой отметкой.

Под тестами память выключена: тесты подменяют базу на лету, и ответ,
запомненный для одной, не должен достаться другой. Тесты самой памяти
включают её явно.
"""

from __future__ import annotations

import copy
import functools
import os
import sqlite3
import sys
import threading
import time
from collections import OrderedDict
from pathlib import Path
from typing import Any, Callable, Dict, Optional, Tuple

from src.utils import get_logger

logger = get_logger(__name__)

# Сколько готовых ответов держать. Ответ — словарь в килобайты; предел
# нужен не памяти ради, а чтобы перебор параметров не растил её без конца.
ОТВЕТОВ = 256

# Ответы зависят не только от базы, но и от часов: «за неделю», «период
# не закончился». Отметка времени в ключе ограничивает такое устаревание
# одной минутой, даже если база молчит сутки.
ОКНО_СЕКУНД = 60

_замок = threading.RLock()
_сторожа: Dict[str, sqlite3.Connection] = {}
_таблицы: Dict[Tuple[str, Any], Tuple[int, Any]] = {}
# Очередь на чтение каждой таблицы: см. `таблица`.
_чтения: Dict[Tuple[str, Any], threading.Lock] = {}
_ответы: "OrderedDict[Tuple, Any]" = OrderedDict()
_включена: Optional[bool] = None
счётчики = {"таблица_из_памяти": 0, "таблица_прочитана": 0, "ответ_из_памяти": 0, "ответ_посчитан": 0}


def включена() -> bool:
    """Работает ли память. Выключается под тестами и переменной DATA_CACHE=0."""
    if _включена is not None:
        return _включена
    if os.getenv("DATA_CACHE", "1").lower() in ("0", "false", "no"):
        return False
    return "pytest" not in sys.modules and not os.getenv("PYTEST_CURRENT_TEST")


def включить(значение: Optional[bool]) -> None:
    """Принудительно включить или выключить; None — вернуть правило по умолчанию."""
    global _включена
    _включена = значение


def сбросить() -> None:
    """Забыть всё и закрыть сторожевые соединения — для тестов и остановки."""
    with _замок:
        _таблицы.clear()
        _чтения.clear()
        _ответы.clear()
        for соединение in _сторожа.values():
            try:
                соединение.close()
            except sqlite3.Error:
                pass
        _сторожа.clear()
        for ключ in счётчики:
            счётчики[ключ] = 0


def версия(путь: Any) -> Optional[int]:
    """
    Отметка состояния базы. None — узнать не удалось, и памяти верить нельзя.

    Спрашивает одно и то же долгоживущее соединение: отметка сравнима
    только сама с собой в пределах одного соединения.
    """
    ключ = str(путь)
    if not ключ or ключ == ":memory:" or not Path(ключ).is_file():
        return None
    with _замок:
        try:
            соединение = _сторожа.get(ключ)
            if соединение is None:
                # Только чтение: сторож не должен ни создать базу, ни
                # удержать её от записи.
                соединение = sqlite3.connect(
                    f"{Path(ключ).as_uri()}?mode=ro", uri=True, check_same_thread=False, timeout=5
                )
                _сторожа[ключ] = соединение
            return int(соединение.execute("PRAGMA data_version").fetchone()[0])
        except sqlite3.Error as ошибка:
            logger.warning(f"Отметка состояния базы недоступна ({ошибка}) — читаем без памяти")
            плохое = _сторожа.pop(ключ, None)
            if плохое is not None:
                try:
                    плохое.close()
                except sqlite3.Error:
                    pass
            return None


def таблица(путь: Any, ключ: Any, загрузить: Callable[[], Any]) -> Any:
    """
    Таблица вакансий: из памяти, если база с прошлого раза не менялась.

    Возвращается копия без копирования данных. В pandas 3 запись в такую
    копию оригинал не трогает, поэтому запрос, который дописывает себе
    колонку или правит значения, не портит таблицу соседям.
    """
    if not включена():
        return загрузить()
    отметка = версия(путь)
    if отметка is None:
        return загрузить()

    место = (str(путь), ключ)
    with _замок:
        запись = _таблицы.get(место)
        if запись is not None and запись[0] == отметка:
            счётчики["таблица_из_памяти"] += 1
            return запись[1].copy(deep=False)
        очередь = _чтения.setdefault(место, threading.Lock())

    # Читает один, остальные ждут. Экран шлёт пять запросов разом, и на
    # первом заходе после изменения базы ни один из них ещё не успел
    # запомнить таблицу: без очереди все пятеро читали бы её сами, и
    # память экономила бы только со второго захода.
    with очередь:
        with _замок:
            запись = _таблицы.get(место)
            if запись is not None and запись[0] == отметка:
                счётчики["таблица_из_памяти"] += 1
                return запись[1].copy(deep=False)
        свежая = загрузить()
        with _замок:
            _таблицы[место] = (отметка, свежая)
            счётчики["таблица_прочитана"] += 1
    return свежая.copy(deep=False)


def запомнить(функция: Callable) -> Callable:
    """
    Запомнить ответ расчёта до следующего изменения базы.

    Ключ — имя расчёта, его параметры, отметка базы и минута на часах.
    Наружу отдаётся копия: тот, кто получил ответ и что-то в нём
    поправил, не должен менять его для следующего.
    """
    @functools.wraps(функция)
    def обёртка(*args, **kwargs):
        if not включена():
            return функция(*args, **kwargs)
        from src.config import settings

        отметка = версия(settings.db_path)
        if отметка is None:
            return функция(*args, **kwargs)
        ключ = (
            функция.__name__, repr(args), repr(sorted(kwargs.items())),
            отметка, int(time.time() // ОКНО_СЕКУНД),
        )
        with _замок:
            if ключ in _ответы:
                _ответы.move_to_end(ключ)
                счётчики["ответ_из_памяти"] += 1
                return copy.deepcopy(_ответы[ключ])

        ответ = функция(*args, **kwargs)
        with _замок:
            _ответы[ключ] = ответ
            счётчики["ответ_посчитан"] += 1
            while len(_ответы) > ОТВЕТОВ:
                _ответы.popitem(last=False)
        return copy.deepcopy(ответ)

    return обёртка
