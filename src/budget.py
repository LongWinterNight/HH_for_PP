"""
Бюджет сбора: сколько запросов к источнику и сколько это займёт.

Зачем. Экран обещал «ориентировочно 1 мин» на запрос, считая по
полминуты за каждый. Живые сборы из истории: 1 411 вакансий за 18 минут,
1 141 за 23 минуты. Обещание расходилось с явью в двадцать раз — то
есть было не оценкой, а украшением кнопки.

Настоящая цена складывается из трёх частей:

- **страницы выдачи** — до `max_pages` запросов на каждый поисковый
  запрос, по сотне вакансий в каждом;
- **карточки вакансий** — отдельный запрос на каждую новую вакансию.
  Это главная часть: страниц десятки, карточек тысячи. Известные
  вакансии карточку не запрашивают, поэтому дописывание к базе идёт
  быстрее первого сбора — но насколько, заранее неизвестно;
- **пауза между запросами** — она же скорость. Всё остальное — это
  число запросов, умноженное на неё.

Отсюда и вид ответа: не одно число, а вилка. Нижняя граница — если все
вакансии уже известны и карточки не нужны; верхняя — если все новые.
Показывать одно число значило бы выбрать, в какую сторону соврать.
"""

from __future__ import annotations

from typing import Any, Dict, Optional

from src.coverage import склонение

# Сколько вакансий источник отдаёт на странице выдачи.
НА_СТРАНИЦЕ = 100

# Накладные расходы на запрос: пауза между запросами в коде сбора,
# сохранение в базу, разбор навыков. Замерено по истории сборов —
# отношение фактического времени к сумме пауз держится около этого.
НАКЛАДНЫЕ = 1.15


def запросов_к_источнику(
    запросов: int,
    max_pages: int,
    доля_новых: float = 1.0,
    срезов: int = 1,
) -> int:
    """
    Сколько обращений к источнику потребует сбор.

    Args:
        запросов: Сколько поисковых запросов в списке
        max_pages: Предел страниц на один запрос
        доля_новых: Какая часть найденных вакансий окажется новыми. От
            неё зависит число карточек: известные вакансии карточку не
            запрашивают
        срезов: Во сколько раз режется запрос по регионам. 1 — резка
            выключена

    Returns:
        Число обращений. Это верхняя оценка: запрос, по которому вакансий
        меньше страницы, оборвётся раньше.
    """
    запросов = max(0, запросов)
    срезов = max(1, срезов)
    страниц_прямо = max(0, max_pages)
    # Карточки берутся только у прямого чтения запроса. Внутри срезов их
    # не запрашивают (S4‑5a): резка отвечает за охват, а глубину догоняет
    # отдельный проход. Прежняя формула умножала карточки на число
    # срезов — оттого резка и выглядела неподъёмной по цене.
    карточек = страниц_прямо * НА_СТРАНИЦЕ * max(0.0, min(1.0, доля_новых))
    страниц_срезами = страниц_прямо * (срезов - 1)
    return int(запросов * (страниц_прямо + страниц_срезами + карточек))


def минут(обращений: int, пауза: float) -> float:
    """Во что обращения обходятся по времени при заданной паузе."""
    return обращений * max(0.0, пауза) * НАКЛАДНЫЕ / 60


def оценка(
    запросов: int,
    max_pages: int,
    пауза: float,
    срезов: int = 1,
    упрутся: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Вилка бюджета сбора.

    Returns:
        {
            "запросов_к_источнику": [нижняя, верхняя],
            "минут": [нижняя, верхняя],
            "фраза": то же словами, для показа человеку,
        }

        Нижняя граница считается по десятой доле новых вакансий — так
        выглядит повторный сбор по тем же запросам; верхняя по всем
        новым — так выглядит первый.

        `упрутся` — сколько запросов упрётся в предел выдачи и будет
        разрезано. Его называет разведка (`VacancyCollector.разведать`).
        None означает «неизвестно», и тогда считается по худшему: режутся
        все. Экран, обещающий сотни часов там, где сбор идёт сорок минут,
        не оценка, а украшение кнопки — ровно так эта функция и
        появилась.
    """
    # Режутся не все запросы, а только упёршиеся в предел выдачи. Пока
    # разведка не сказала сколько их, считаем по худшему — но отдельно от
    # обычных, иначе цена завышается на порядки.
    упёршихся = запросов if упрутся is None else max(0, min(запросов, упрутся))
    обычных = max(0, запросов - упёршихся)

    def всего(доля_новых: float) -> int:
        return (
            запросов_к_источнику(обычных, max_pages, доля_новых, срезов=1)
            + запросов_к_источнику(упёршихся, max_pages, доля_новых, срезов=срезов)
        )

    мало, много = всего(0.1), всего(1.0)

    от, до = минут(мало, пауза), минут(много, пауза)
    от_целых, до_целых = max(1, round(от)), max(1, round(до))

    if от_целых == до_целых:
        время = f"около {от_целых} мин"
    else:
        время = f"от {от_целых} до {до_целых} мин"

    слово = склонение(запросов, "запрос", "запроса", "запросов")

    return {
        "запросов_к_источнику": [мало, много],
        "минут": [round(от, 1), round(до, 1)],
        "фраза": f"{запросов} {слово} · {время}",
    }
