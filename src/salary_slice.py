"""
Срез зарплат: всё, что окно «Распределение зарплат» показывает о выборке.

Зачем отдельный модуль. Окно было одной гистограммой по всей базе. Чтобы
оно отвечало на вопросы «а у новичков?», «а на удалёнке?», «а кто в этом
столбце?», нужны три вещи поверх одной выборки: срез (чем сузить),
уровни (с чем сравнить) и состав корзины (что внутри). Считаются они
здесь, а не в обработчике запроса: расчёт без веб-сервера проверяется
тестом на десяти строках.

Отбор не изобретается заново. Регион, опыт и валюта — те же условия,
что на экране «Вакансии», и применяет их тот же `выборка.отобрать`.
Период, сфера и формат работы пока живут только здесь; когда из окна
появится ссылка на список вакансий (N1‑4a), они переедут в общий отбор.

Правила чисел те же, что везде в продукте: только правдоподобные
зарплаты, копии одной вакансии по городам считаются за одну, средней
нет, выборка меньше пяти чисел не даёт.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, replace
from typing import Any, Dict, List, Optional

import pandas as pd

from src.copies import без_копий
from src.salary_sanity import только_правдоподобные
from src.выборка import Фильтры, отобрать

# Ниже этого объёма числа не показываются: медиана по трём вакансиям —
# случайность, а выглядит как зарплата рынка.
МАЛО = 5

КОРЗИН = 7

# Период — по дате публикации: вопрос «сколько платят» относится к
# моменту, когда работодатель это предлагал.
ПЕРИОДЫ: Dict[str, Optional[int]] = {"week": 7, "month": 30, "quarter": 90, "all": None}

# По чему можно разложить зарплаты на уровни: имя для запроса и колонка.
ИЗМЕРЕНИЯ: Dict[str, str] = {
    "experience": "experience",
    "sphere": "source_keyword",
    "format": "_формат",
    "area": "area",
}

# Опыт идёт по росту стажа, а не по деньгам и не по алфавиту: уровни —
# лестница, и переставленные ступени перестают ею быть.
ПОРЯДОК_ОПЫТА = ["Нет опыта", "От 1 года до 3 лет", "От 3 до 6 лет", "Более 6 лет"]

# Сколько групп показывать там, где их бывают сотни (сферы, регионы).
ПРЕДЕЛ_ГРУПП = 12

НА_МЕСТЕ, УДАЛЁННО, ГИБРИД, НА_ВЫБОР, РАЗЪЕЗДНОЙ, НЕ_УКАЗАН = (
    "На месте", "Удалённо", "Гибрид", "На выбор", "Разъездной", "Не указан",
)


def формат_работы(график: Any) -> str:
    """
    Формат работы одним словом из поля графика.

    Источник пишет поле как «На месте работодателя, Гибрид · 5/2»: до
    точки — где работать, после — по какому расписанию. Разных написаний
    в базе больше двухсот, а вопрос у человека один: можно ли работать
    из дома. Вакансия, где перечислено несколько форматов, — «На выбор»:
    это отдельный случай, и относить его к удалёнке значило бы завысить
    её долю.
    """
    if not isinstance(график, str) or not график.strip():
        return НЕ_УКАЗАН
    где = график.split("·")[0].strip().lower()
    if not где:
        return НЕ_УКАЗАН
    части = [часть.strip() for часть in где.split(",") if часть.strip()]
    найдено = []
    for часть in части:
        if "удал" in часть:
            найдено.append(УДАЛЁННО)
        elif "гибрид" in часть:
            найдено.append(ГИБРИД)
        elif "месте" in часть:
            найдено.append(НА_МЕСТЕ)
        elif "разъезд" in часть:
            найдено.append(РАЗЪЕЗДНОЙ)
    найдено = list(dict.fromkeys(найдено))
    if not найдено:
        return НЕ_УКАЗАН
    if len(найдено) == 1:
        return найдено[0]
    # «На месте, Разъездной» — это всё ещё работа на месте, с выездами.
    if set(найдено) == {НА_МЕСТЕ, РАЗЪЕЗДНОЙ}:
        return НА_МЕСТЕ
    return НА_ВЫБОР


@dataclass(frozen=True)
class Срез:
    """Условия, которыми окно сужает выборку. Пустое значение — «не сужать»."""

    # «currency» — внутри одной валюты, «rub» — вся выборка в рублёвом
    # эквиваленте по курсу ЦБ.
    вид: str = "currency"
    валюта: str = "RUB"
    период: str = "all"
    опыт: str = ""
    сфера: str = ""
    формат: str = ""
    регион: str = ""

    @property
    def в_рублях(self) -> bool:
        return self.вид == "rub"

    @property
    def колонка(self) -> str:
        return "salary_from_rub" if self.в_рублях else "salary_from"

    def словарём(self) -> Dict[str, str]:
        return {
            "period": self.период if self.период in ПЕРИОДЫ else "all",
            "experience": self.опыт, "sphere": self.сфера, "format": self.формат, "area": self.регион,
        }


def _с_форматом(df: pd.DataFrame) -> pd.DataFrame:
    if "_формат" in df.columns:
        return df
    график = df["schedule"] if "schedule" in df.columns else pd.Series([None] * len(df), index=df.index)
    return df.assign(_формат=график.map(формат_работы))


def сузить(df: pd.DataFrame, срез: Срез) -> pd.DataFrame:
    """
    Вакансии среза — ещё с теми, где зарплата не указана.

    Нужны оба числа: сколько вакансий в срезе и у скольких из них есть
    зарплата. Без первого подпись «по 40 вакансиям» не говорит, много
    это или мало.
    """
    if df is None or df.empty:
        return pd.DataFrame() if df is None else df

    df = _с_форматом(df)
    # Валюта здесь не применяется: срез считает и вакансии без зарплаты,
    # а у них валюты нет. Она отбирается там, где начинается расчёт.
    if срез.опыт:
        df = отобрать(df, Фильтры(опыт=срез.опыт))
    # Регион — точным совпадением, а не вхождением, как в поиске на
    # экране «Вакансии»: там человек набирает начало названия, здесь он
    # нажал на строку списка. По вхождению «Ростов» захватил бы
    # «Ростов-на-Дону», и выборка разошлась бы с числом в строке.
    if срез.регион and "area" in df.columns:
        df = df[df["area"] == срез.регион]

    if срез.сфера and "source_keyword" in df.columns:
        df = df[df["source_keyword"] == срез.сфера]
    if срез.формат:
        df = df[df["_формат"] == срез.формат]

    дней = ПЕРИОДЫ.get(срез.период)
    if дней and "published_at" in df.columns:
        даты = pd.to_datetime(df["published_at"], errors="coerce", utc=True, format="mixed")
        df = df[даты >= pd.Timestamp.now(tz="UTC") - pd.Timedelta(days=дней)]
    return df


def с_зарплатой(df: pd.DataFrame, срез: Срез) -> pd.DataFrame:
    """Из среза — то, по чему можно считать: правдоподобные зарплаты, копии за одну."""
    if df.empty or срез.колонка not in df.columns:
        return df.iloc[0:0]
    if not срез.в_рублях and "salary_currency" in df.columns:
        df = df[df["salary_currency"] == срез.валюта]
    df = без_копий(только_правдоподобные(df), срез.колонка)
    return df[df[срез.колонка].notna()]


def считаемые(df: pd.DataFrame, срез: Срез) -> pd.DataFrame:
    """
    Вакансии, по которым окно считает числа, уже суженные срезом.

    Порядок важен: сначала копии одной вакансии по городам сводятся к
    одной по всей базе, потом применяется срез. Наоборот выходило
    расхождение, которое видно глазами: строка уровней обещала «по 449»,
    а нажатие на неё давало выборку 453 — у копий одной вакансии бывает
    разный опыт, и внутри среза их схлопывалось меньше.
    """
    if df is None or df.empty:
        return pd.DataFrame() if df is None else df
    return сузить(с_зарплатой(_с_форматом(df), срез), срез)


def format_short(value) -> str:
    """Короткая подпись оси: 120 000 -> «120 тыс», 8 000 000 -> «8 млн».
    Ось графика — единственное место системы, где число сокращается."""
    value = float(value)
    if abs(value) >= 1_000_000:
        return f"{value / 1_000_000:.1f}".replace(".0", "") + " млн"
    if abs(value) >= 1_000:
        return f"{value / 1_000:.0f} тыс"
    return f"{value:.0f}"


def salary_histogram(values, bins: int = КОРЗИН) -> List[Dict[str, Any]]:
    """Корзины зарплат внутри одной величины.

    Границы считаются по самим данным, а не задаются словами «50k-100k»:
    те же корзины для узбекских сумов бессмысленны — там вся выборка
    попадёт в последнюю. Верхняя граница обрезается 95-м перцентилем,
    иначе одна вакансия с опечаткой растягивает шкалу на весь график,
    и остальные корзины схлопываются в первый столбец.
    """
    clean = values.dropna()
    if len(clean) < МАЛО:
        return []

    low = float(clean.min())
    high = float(clean.quantile(0.95))
    if high <= low:
        high = float(clean.max())
    if high <= low:
        return [{"label": format_short(low), "count": int(len(clean)), "from": low, "to": low}]

    step = (high - low) / bins
    result = []
    for i in range(bins):
        start = low + step * i
        end = low + step * (i + 1)
        last = i == bins - 1
        count = int(((clean >= start) & (clean <= end)).sum()) if last else int(((clean >= start) & (clean < end)).sum())
        result.append({
            "label": format_short(start) + ("+" if last else ""),
            "count": count,
            "from": start,
            "to": end,
        })

    # Всё, что выше 95-го перцентиля, досыпается в последнюю корзину:
    # эти вакансии существуют, и терять их нельзя.
    tail = int((clean > high).sum())
    if tail and result:
        result[-1]["count"] += tail
        result[-1]["label"] = format_short(result[-1]["from"]) + "+"

    return result


def _в_корзине(значения: pd.Series, корзины: List[Dict[str, Any]], номер: int) -> pd.Series:
    """Маска вакансий корзины — тем же правилом границ, каким она построена."""
    корзина = корзины[номер]
    if номер == len(корзины) - 1:
        return значения >= корзина["from"]
    return (значения >= корзина["from"]) & (значения < корзина["to"])


def гистограмма(значения: pd.Series) -> List[Dict[str, Any]]:
    """
    Корзины с долей и отметкой той, куда попала медиана.

    Отметка нужна графику: маркер на гистограмме один, и стоит он на
    корзине с медианой. Считать её на экране по границам значило бы
    повторить правило границ вторым кодом.
    """
    корзины = salary_histogram(значения)
    всего = sum(к["count"] for к in корзины)
    if not всего:
        return корзины
    медиана = float(значения.median())
    с_медианой = len(корзины) - 1
    for номер, корзина in enumerate(корзины[:-1]):
        if корзина["from"] <= медиана < корзина["to"]:
            с_медианой = номер
            break
    for номер, корзина in enumerate(корзины):
        корзина["share"] = round(корзина["count"] / всего * 100, 1)
        корзина["has_median"] = номер == с_медианой
    return корзины


def числа(значения: pd.Series) -> Dict[str, Any]:
    """Медиана и вилки. Пусто, если выборка мала."""
    if len(значения) < МАЛО:
        return {}
    return {
        "sample": int(len(значения)),
        "median": float(значения.median()),
        "q1": float(значения.quantile(0.25)),
        "q3": float(значения.quantile(0.75)),
        "p10": float(значения.quantile(0.10)),
        "p90": float(значения.quantile(0.90)),
    }


def уровни(df: pd.DataFrame, колонка: str, измерение: str) -> Dict[str, Any]:
    """
    Зарплатные уровни: медиана и вилка Q1–Q3 по группам одного измерения.

    Группа с выборкой меньше пяти чисел не получает. Там, где групп
    немного и все они осмысленны сами по себе (опыт, формат), слабая
    группа остаётся в списке без чисел: «у стажёров данных мало» — тоже
    ответ. Там, где групп сотни (сферы, регионы), слабые уходят из
    списка, а их число называется.
    """
    поле = ИЗМЕРЕНИЯ.get(измерение, ИЗМЕРЕНИЯ["experience"])
    if df.empty or поле not in df.columns:
        return {"by": измерение, "items": [], "hidden_small": 0, "beyond": 0}

    все_группы = измерение in ("experience", "format")
    строки: List[Dict[str, Any]] = []
    малых = 0
    for значение, группа in df[df[поле].notna()].groupby(поле):
        суммы = группа[колонка]
        if len(суммы) < МАЛО:
            малых += 1
            if все_группы:
                строки.append({"label": str(значение), "sample": int(len(суммы)), "weak": True,
                               "q1": None, "median": None, "q3": None})
            continue
        строки.append({
            "label": str(значение), "sample": int(len(суммы)), "weak": False,
            "q1": float(суммы.quantile(0.25)), "median": float(суммы.median()), "q3": float(суммы.quantile(0.75)),
        })

    if измерение == "experience":
        место = {название: номер for номер, название in enumerate(ПОРЯДОК_ОПЫТА)}
        строки.sort(key=lambda с: место.get(с["label"], len(место)))
        return {"by": измерение, "items": строки, "hidden_small": 0, "beyond": 0}

    # Сначала те, по кому данных больше всего: первая строка списка
    # должна быть надёжной, а не самой денежной из пяти вакансий.
    строки.sort(key=lambda с: (с["weak"], -с["sample"]))
    показать = строки if все_группы else строки[:ПРЕДЕЛ_ГРУПП]
    # Внутри показанного — по деньгам: так читается лестница уровней.
    показать.sort(key=lambda с: (с["weak"], -(с["median"] or 0)))
    return {
        "by": измерение, "items": показать,
        "hidden_small": 0 if все_группы else малых,
        "beyond": max(0, len(строки) - len(показать)),
    }


def _по_убыванию(счёт: pd.Series, сколько: int) -> List[tuple]:
    """
    Первые строки счёта: по убыванию, при равенстве — по алфавиту.

    Порядок при равном счёте задан явно. Прежде он зависел от порядка
    обхода множества, а тот в Python меняется от запуска к запуску: при
    пятнадцати навыках со счётом «один» в список из восьми каждый раз
    попадали другие три, и один и тот же экран показывал разное.
    """
    пары = sorted(((str(метка), int(число)) for метка, число in счёт.items()), key=lambda п: (-п[1], п[0]))
    return пары[:сколько]


def _топ(значения: pd.Series, сколько: int) -> List[Dict[str, Any]]:
    счёт = значения.dropna().astype(str).value_counts()
    return [{"label": метка, "value": число} for метка, число in _по_убыванию(счёт, сколько)]


def _топ_навыков(df: pd.DataFrame, сколько: int = 8) -> List[Dict[str, Any]]:
    """
    Навыки вакансий корзины: жёсткие и инструменты, без повтора внутри вакансии.

    Считается по колонкам целиком, а не обходом строк: на корзине в
    семьсот вакансий построчный обход занимал треть всего расчёта окна.
    """
    поля = [поле for поле in ("hard_skills", "tools") if поле in df.columns]
    if df.empty or not поля:
        return []
    склеенные = df[поля[0]].fillna("").astype(str)
    for поле in поля[1:]:
        склеенные = склеенные + "," + df[поле].fillna("").astype(str)
    пары = склеенные.reset_index(drop=True).str.split(",").explode().str.strip()
    пары = пары[пары != ""]
    # Навык считается один раз на вакансию: повтор в двух колонках — не
    # два упоминания.
    пары = пары.reset_index().drop_duplicates()
    счёт = пары.iloc[:, 1].value_counts()
    return [{"label": навык, "value": число} for навык, число in _по_убыванию(счёт, сколько)]


def состав(df: pd.DataFrame, колонка: str, корзины: List[Dict[str, Any]], номер: int) -> Optional[Dict[str, Any]]:
    """Что внутри корзины: какие сферы, уровни опыта, форматы и навыки."""
    if not корзины or not (0 <= номер < len(корзины)):
        return None
    внутри = df[_в_корзине(df[колонка], корзины, номер)]
    корзина = корзины[номер]
    return {
        "index": номер,
        "label": корзина["label"],
        "from": корзина["from"],
        "to": None if номер == len(корзины) - 1 else корзина["to"],
        "count": int(len(внутри)),
        "share": корзина.get("share"),
        "sphere": _топ(внутри["source_keyword"], 6) if "source_keyword" in внутри.columns else [],
        "experience": _топ(внутри["experience"], 4) if "experience" in внутри.columns else [],
        "format": _топ(внутри["_формат"], 5) if "_формат" in внутри.columns else [],
        "skills": _топ_навыков(внутри),
    }


def варианты(
    df: pd.DataFrame, срез: Срез, готовая: Optional[pd.DataFrame] = None
) -> Dict[str, List[Dict[str, Any]]]:
    """
    Что можно выбрать в списках срезов, с числом вакансий с зарплатой.

    Счёт идёт без остальных срезов: список — это меню, и пункт не должен
    исчезать оттого, что выбран соседний фильтр. Пункт без единой
    вакансии с зарплатой в меню не попадает — выбрать его значило бы
    получить пустое окно.
    """
    основа = (
        готовая if готовая is not None
        else (с_зарплатой(_с_форматом(df), Срез(вид=срез.вид, валюта=срез.валюта)) if not df.empty else df)
    )

    def список(поле: str, сколько: int) -> List[Dict[str, Any]]:
        if основа.empty or поле not in основа.columns:
            return []
        счёт = основа[поле].dropna().astype(str).value_counts().head(сколько)
        return [{"value": метка, "count": int(число)} for метка, число in счёт.items()]

    опыт = список("experience", 10)
    место = {название: номер for номер, название in enumerate(ПОРЯДОК_ОПЫТА)}
    опыт.sort(key=lambda п: место.get(п["value"], len(место)))
    return {
        "experience": опыт,
        "sphere": список("source_keyword", 40),
        "format": [п for п in список("_формат", 10) if п["value"] != НЕ_УКАЗАН],
        "area": список("area", 30),
    }


# Шаг ряда во времени и сколько последних периодов показывать.
ШАГИ: Dict[str, tuple] = {"week": ("W-SUN", 26), "month": ("M", 12)}

# С какого объёма период годится в концы итоговой фразы «медиана выросла
# на столько-то». Точку на графике даёт и неделя с пятью вакансиями — её
# ненадёжность видна по столбику объёма. Итог же читают как вывод о
# рынке, и строить его от пятнадцати вакансий к пятистам значит
# сравнивать случайность с рынком.
НАДЁЖНО = 30

# Сколько рядов сравнивать на одном графике: пятая линия уже не
# отличается от соседних ни цветом, ни глазом.
РЯДОВ = 4


def _подписи_периода(период: pd.Period, шаг: str) -> Dict[str, str]:
    if шаг == "week":
        начало, конец = период.start_time, период.end_time
        return {
            "label": начало.strftime("%d.%m"),
            "title": f"{начало.strftime('%d.%m')} — {конец.strftime('%d.%m.%Y')}",
        }
    return {"label": период.strftime("%m.%Y"), "title": период.strftime("%m.%Y")}


def _точка(суммы: Optional[pd.Series]) -> Dict[str, Any]:
    """Числа одного периода. Меньше пяти вакансий — только объём."""
    объём = int(len(суммы)) if суммы is not None else 0
    if объём < МАЛО:
        return {"sample": объём, "median": None, "q1": None, "q3": None}
    return {
        "sample": объём,
        "median": float(суммы.median()),
        "q1": float(суммы.quantile(0.25)),
        "q3": float(суммы.quantile(0.75)),
    }


def ряд_во_времени(
    df: pd.DataFrame,
    колонка: str,
    шаг: str = "week",
    группы: Optional[pd.DataFrame] = None,
    измерение: str = "",
    сейчас: Optional[pd.Timestamp] = None,
) -> Dict[str, Any]:
    """
    Медиана и вилка по периодам, а при сравнении — ещё и ряды по группам.

    Период считается по дате публикации. Сетка идёт от первого периода,
    где есть хоть одна вакансия, до текущего, без пропусков: неделя, в
    которую ничего не публиковали, остаётся на оси пустой, а не
    склеивается с соседними.

    Текущий период помечен незакрытым: семнадцать вакансий за неполную
    неделю читаются как обвал, а это просто вторник.

    Args:
        df: Вакансии среза с зарплатой
        группы: Вакансии для рядов сравнения — срез без условия по
            самому измерению, иначе после выбора строки остался бы один ряд
        измерение: По чему сравнивать; пусто — без сравнения
        сейчас: Текущий момент — подставляется в тестах
    """
    шаг = шаг if шаг in ШАГИ else "week"
    частота, предел = ШАГИ[шаг]
    сейчас = сейчас if сейчас is not None else pd.Timestamp.now()
    if сейчас.tzinfo is not None:
        сейчас = сейчас.tz_localize(None)
    текущий = сейчас.to_period(частота)
    пусто = {"step": шаг, "periods": [], "series": [], "by": "", "change": None}

    def с_периодом(выборка: Optional[pd.DataFrame]) -> pd.DataFrame:
        if выборка is None or выборка.empty or "published_at" not in выборка.columns:
            return pd.DataFrame(columns=["_период", колонка])
        даты = pd.to_datetime(выборка["published_at"], errors="coerce", utc=True, format="mixed").dt.tz_localize(None)
        готовая = выборка.assign(_период=даты.dt.to_period(частота))
        return готовая[готовая["_период"].notna() & готовая[колонка].notna() & (готовая["_период"] <= текущий)]

    рабочая = с_периодом(df)
    if рабочая.empty:
        return пусто

    первый = max(рабочая["_период"].min(), текущий - (предел - 1))
    сетка = pd.period_range(start=первый, end=текущий, freq=частота)
    по_периодам = {период: группа[колонка] for период, группа in рабочая.groupby("_период")}

    периоды = [
        {
            "key": str(период), **_подписи_периода(период, шаг),
            **_точка(по_периодам.get(период)), "open": период == текущий,
        }
        for период in сетка
    ]

    ряды: List[Dict[str, Any]] = []
    поле = ИЗМЕРЕНИЯ.get(измерение) if измерение else None
    основа = с_периодом(группы if группы is not None else df) if поле else pd.DataFrame()
    if поле and not основа.empty and поле in основа.columns:
        в_окне = основа[основа["_период"] >= первый]
        объёмы = в_окне[в_окне[поле].notna()].groupby(поле).size().sort_values(ascending=False)
        названия = [str(н) for н in объёмы.index if str(н) != НЕ_УКАЗАН and объёмы[н] >= МАЛО]
        if измерение == "experience":
            место = {название: номер for номер, название in enumerate(ПОРЯДОК_ОПЫТА)}
            названия.sort(key=lambda н: место.get(н, len(место)))
        for название in названия[:РЯДОВ]:
            своя = в_окне[в_окне[поле].astype(str) == название]
            по_своим = {период: группа[колонка] for период, группа in своя.groupby("_период")}
            точки = []
            for период in сетка:
                точка = _точка(по_своим.get(период))
                точки.append({"sample": точка["sample"], "median": точка["median"]})
            ряды.append({"label": название, "sample": int(len(своя)), "points": точки})

    # Изменение — между закрытыми периодами: неполная неделя сдвинула
    # бы итог тем, сколько вакансий успели опубликовать к вторнику.
    закрытые = [п for п in периоды if not п["open"] and п["median"] is not None and п["sample"] >= НАДЁЖНО]
    изменение = None
    if len(закрытые) >= 2 and закрытые[0]["median"]:
        изменение = {
            "from": закрытые[0]["title"], "to": закрытые[-1]["title"],
            "from_median": закрытые[0]["median"], "to_median": закрытые[-1]["median"],
            "from_sample": закрытые[0]["sample"], "to_sample": закрытые[-1]["sample"],
            "percent": round((закрытые[-1]["median"] / закрытые[0]["median"] - 1) * 100, 1),
        }

    return {"step": шаг, "periods": периоды, "series": ряды, "by": измерение if ряды else "", "change": изменение}


# Какому срезу соответствует каждое измерение уровней.
СРЕЗ_ИЗМЕРЕНИЯ = {"experience": "опыт", "sphere": "сфера", "format": "формат", "area": "регион"}


def _без_своего_среза(срез: Срез, измерение: str) -> Срез:
    """
    Срез для списка уровней: все условия, кроме условия по самому измерению.

    Список уровней — одновременно и сравнение, и переключатель среза.
    Если считать его по уже суженной выборке, после выбора «Более 6 лет»
    в нём остаётся одна строка: сравнивать не с чем и вернуться нечем.
    Остальные срезы действуют как обычно — «уровни по опыту на удалёнке»
    остаются уровнями на удалёнке.
    """
    поле = СРЕЗ_ИЗМЕРЕНИЯ.get(измерение)
    return replace(срез, **{поле: ""}) if поле else срез


def собрать(
    df: pd.DataFrame,
    срез: Срез,
    по: str = "experience",
    корзина: Optional[int] = None,
    шаг: str = "week",
    сравнить: str = "",
) -> Dict[str, Any]:
    """
    Весь ответ окна одним расчётом.

    Корзина по умолчанию — та, где медиана: окно открывается с ответом на
    вопрос «что в середине рынка», а не с пустым местом и просьбой
    что-нибудь нажать.
    """
    по = по if по in ИЗМЕРЕНИЯ else "experience"
    в_срезе = сузить(df, срез)
    # Отсев неправдоподобных зарплат и копий по городам — самая дорогая
    # часть расчёта, и от срезов она не зависит. Раньше она выполнялась
    # заново для выборки, для уровней, для меню и для рядов сравнения;
    # теперь один раз, а срезы применяются к готовому.
    основа = с_зарплатой(_с_форматом(df), срез) if df is not None and not df.empty else pd.DataFrame()

    def из_основы(условия: Срез) -> pd.DataFrame:
        return сузить(основа, условия) if not основа.empty else основа

    отобранные = из_основы(срез)
    суммы = отобранные[срез.колонка] if not отобранные.empty else pd.Series(dtype=float)

    корзины = гистограмма(суммы)
    с_медианой = next((номер for номер, к in enumerate(корзины) if к.get("has_median")), None)
    выбранная = корзина if корзина is not None and 0 <= корзина < len(корзины) else с_медианой

    ответ = {
        "basis": "equivalent" if срез.в_рублях else "currency",
        "currency": "RUB" if срез.в_рублях else срез.валюта,
        "slice": срез.словарём(),
        # Сколько вакансий в срезе всего и у скольких зарплата годится в
        # расчёт: второе без первого не говорит, много это или мало.
        "slice_total": int(len(в_срезе)),
        "sample": int(len(суммы)),
        "histogram": корзины,
        "median_bin": с_медианой,
        "stats": числа(суммы),
        "levels": уровни(из_основы(_без_своего_среза(срез, по)), срез.колонка, по),
        "bucket": состав(отобранные, срез.колонка, корзины, выбранная) if выбранная is not None else None,
        "options": варианты(df, срез, готовая=основа),
        "trend": ряд_во_времени(
            отобранные, срез.колонка, шаг,
            группы=из_основы(_без_своего_среза(срез, сравнить)) if сравнить in ИЗМЕРЕНИЯ else None,
            измерение=сравнить if сравнить in ИЗМЕРЕНИЯ else "",
        ),
    }

    return ответ
