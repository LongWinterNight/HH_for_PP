"""
Словарь навыков как данные.

Зачем. Словарь из 1158 позиций лежал в `config.yaml` вперемешку с
настройками сбора: поисковыми запросами, параметрами обработки. Данные,
которые меняются еженедельно, жили в файле, который меняют раз в
полгода, и правка словаря выглядела как правка конфигурации приложения.

Здесь он отдельно — `data/skills.yaml`, — и у него появилось то, чего
не могло быть в списке строк: **синонимы**.

**Зачем синонимы.** Работодатели пишут одно и то же по-разному, и для
продукта это разные навыки. Живой счёт по базе (09.09.2026):

    3ds Max 131 · 3D Max 90 · 3dmax 1 · 3DsMax 1 · 3D-max 1
    JavaScript 103 · Java Script 2
    VueJS 12 · Vue.js 9
    Битрикс24 44 · Битрикс 24 4

В топе навыков «3ds Max» и «3D Max» стоят двумя строками, деля между
собой 221 упоминание. Свести их — значит увидеть настоящую величину.

**Почему список, а не правило.** Напрашивается нормализация: убрать
пробелы, дефисы и регистр — и одинаковые написания сольются сами. В тех
же данных лежит опровержение: у «C#» и «C++» такой «скелет» совпадает.
Автоматика свела бы два разных языка в один. Поэтому синонимы —
проверенный человеком список, а скелет годится только на то, чтобы
подсказать кандидатов в него.

Совместимость. Пока файла данных нет, словарь читается из `config.yaml`
как раньше: перенос делает отдельный скрипт, а не первый же запуск.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

from src.config import PROJECT_ROOT, config_loader
from src.utils import get_logger

logger = get_logger(__name__)

ПУТЬ_СЛОВАРЯ = PROJECT_ROOT / "data" / "skills.yaml"

# Разделы словаря. Названия те же, что в конфиге: перенос не должен
# требовать ещё и переучивания.
РАЗДЕЛЫ = ("hard", "soft", "tools")


def _прочитать_файл(путь: Path) -> Optional[Dict[str, Any]]:
    if not путь.exists():
        return None
    try:
        with open(путь, "r", encoding="utf-8") as f:
            данные = yaml.safe_load(f)
        return данные if isinstance(данные, dict) else None
    except (OSError, yaml.YAMLError) as ошибка:
        # Испорченный файл — не повод остаться без навыков вовсе:
        # откатываемся к конфигу и говорим об этом вслух.
        logger.error(f"Словарь навыков не прочитан ({путь}): {ошибка}")
        return None


def загрузить(путь: Optional[Path] = None) -> Dict[str, Any]:
    """
    Словарь навыков: разделы и синонимы.

    Returns:
        {"hard": [...], "soft": [...], "tools": [...],
         "synonyms": {канон: [вариант, ...]}}

        Пока файла данных нет, разделы берутся из `config.yaml`, а
        синонимов нет вовсе: в конфиге их негде было держать.
    """
    данные = _прочитать_файл(путь or ПУТЬ_СЛОВАРЯ)

    if данные is None:
        # Читаем конфиг напрямую, а не через его же свойства: те сами
        # спрашивают этот модуль, и вышел бы замкнутый круг.
        return {
            "hard": list(config_loader.раздел_из_конфига("hard_skills")),
            "soft": list(config_loader.раздел_из_конфига("soft_skills")),
            "tools": list(config_loader.раздел_из_конфига("tools")),
            "synonyms": {},
        }

    итог = {раздел: list(данные.get(раздел) or []) for раздел in РАЗДЕЛЫ}
    итог["synonyms"] = данные.get("synonyms") or {}
    return итог


def таблица_синонимов(словарь: Optional[Dict[str, Any]] = None) -> Dict[str, str]:
    """
    Плоская таблица «как написали» → «как считать».

    Ключи приведены к нижнему регистру: варианты различаются регистром
    чаще всего («PhotoShop», «jira»), и хранить их по отдельности значило
    бы переписывать в файл одно и то же трижды.

    Канон тоже отображается сам на себя: код, приводящий навык к канону,
    не должен знать, был ли навык уже каноническим.
    """
    словарь = словарь if словарь is not None else загрузить()
    таблица: Dict[str, str] = {}

    for канон, варианты in (словарь.get("synonyms") or {}).items():
        таблица[str(канон).strip().lower()] = str(канон)
        for вариант in варианты or []:
            таблица[str(вариант).strip().lower()] = str(канон)

    return таблица


def привести_к_канону(навык: str, таблица: Optional[Dict[str, str]] = None) -> str:
    """
    Название навыка так, как его считать.

    Незнакомое название возвращается как есть: догадываться, что «Java
    Script» — это «JavaScript», а «C++» — не «C#», по написанию нельзя.
    """
    if not навык:
        return навык
    таблица = таблица if таблица is not None else таблица_синонимов()
    return таблица.get(навык.strip().lower(), навык)


def _первая_заглавная(значение: str) -> str:
    return значение[:1].upper() + значение[1:] if значение else значение


def _по_title_кейсу(слово: str) -> bool:
    """
    Слово выглядит как «Персонала»: кириллица, первая заглавная,
    остальные строчные.

    Именно так `str.title()` уродовал русские фразы. Проверка нарочно
    узкая: «MS», «iOS», «1С», «Photoshop» под неё не подходят — там
    заглавные стоят по делу, и трогать их нельзя.
    """
    if not слово or not слово[0].isupper():
        return False
    if not all("а" <= с.lower() <= "я" or с.lower() == "ё" for с in слово):
        return False
    # Одна буква — это предлог или союз: «Внимательность К Деталям».
    # Аббревиатур из одной кириллической буквы не бывает.
    return len(слово) == 1 or слово[1:].islower()


def _без_середины_заглавных(значение: str) -> str:
    """
    Убрать заглавные, которые расставил `title()` внутри фразы.

    Первое слово не трогается: с него фраза начинается, и заглавная там
    уместна. Слова после него понижаются, только если это чистая
    кириллица в виде «Ххххх»: «Оценка Персонала» → «Оценка персонала»,
    а «Adobe Photoshop», «MS Office» и «Power BI» остаются как есть.
    """
    слова = значение.split(" ")
    if len(слова) < 2:
        return значение

    итог = [слова[0]]
    for слово in слова[1:]:
        итог.append(слово[0].lower() + слово[1:] if _по_title_кейсу(слово) else слово)
    return " ".join(итог)


def известные_названия(словарь: Optional[Dict[str, Any]] = None) -> set:
    """
    Все навыки словаря в нижнем регистре.

    Нужны, чтобы отличить «Оценка Персонала» — испорченное `title()`
    написание словарного навыка — от «MS Office», где заглавные внутри
    стоят по делу. Первое надо привести к «Оценка персонала», второе не
    трогать.
    """
    словарь = словарь if словарь is not None else загрузить()
    return {
        str(значение).strip().lower()
        for раздел in РАЗДЕЛЫ
        for значение in (словарь.get(раздел) or [])
    }


def для_показа(
    навык: str,
    таблица: Optional[Dict[str, str]] = None,
    известные: Optional[set] = None,
) -> str:
    """
    Название навыка так, как его показывать человеку.

    Прежде здесь стоял `str.title()` — заглавная буква у каждого слова.
    Он ломал сразу двумя способами, и оба видны в топе навыков базы:

        Llm 232 · Rag 201 · Crm 176 · Api 166 · Ml 106 · Sql 91
        Оценка Персонала 237 + Оценка персонала 154
        Адаптация Персонала 208 + Адаптация персонала 164

    Аббревиатуры превращались в слова, а русские фразы — во вторую
    версию того же навыка: словарный «Оценка Персонала» и названный
    работодателем «Оценка персонала» считались разными, и каждый был
    занижен вдвое.

    Правильное написание известно только там, где его записал человек:
    в таблице синонимов. Всё остальное получает заглавную первую букву
    и не трогается дальше — так «iOS» остаётся «iOS», если он записан
    так, а «подбор персонала» становится «Подбор персонала», а не
    «Подбор Персонала».
    """
    if not навык:
        return навык

    таблица = таблица if таблица is not None else таблица_синонимов()
    известное = таблица.get(навык.strip().lower())
    if известное:
        return известное

    очищенный = навык.strip()
    return _первая_заглавная(_без_середины_заглавных(очищенный))


def без_дублей(значения: List[str]) -> List[str]:
    """
    Одна позиция — одна запись, порядок сохранён.

    Сравнение по нижнему регистру и обрезанным краям: в конфиге
    накопилось 78 повторов, и почти все — «Docker» в hard и в tools или
    разный регистр одного слова.
    """
    видели = set()
    итог = []
    for значение in значения or []:
        ключ = str(значение).strip().lower()
        if not ключ or ключ in видели:
            continue
        видели.add(ключ)
        итог.append(str(значение).strip())
    return итог


def _скаляр(значение: str) -> str:
    """Строка в том виде, в каком её прочитает YAML: «c#» и «1с: бухгалтерия» — в кавычках."""
    return yaml.safe_dump(значение, allow_unicode=True, default_flow_style=True).split("\n")[0].removesuffix(" ...")


def в_синонимы(канон: str, написания: List[str], путь: Optional[Path] = None) -> int:
    """
    Дописать написания навыка под его канон в разделе `synonyms`.

    Как и `кандидаты.в_словарь`, правит файл построчно, а не
    сериализатором: словарь правят и руками, и перезапись целиком
    утопила бы одну новую строку в тысяче переформатированных. Канон,
    который уже есть в разделе, ищется без учёта регистра: «Ai-инструменты»
    и «AI-инструменты» — один ключ, второй рядом с ним не заводится.

    После записи файл перечитывается: если написания под каноном не
    видны, прежний текст возвращается и поднимается ошибка — испорченный
    словарь хуже недописанного.

    Returns:
        Сколько написаний добавлено (0 — все уже были)
    """
    путь = путь or ПУТЬ_СЛОВАРЯ
    канон = str(канон).strip()
    if not канон:
        raise ValueError("У канона пустое название")

    синонимы = загрузить(путь)["synonyms"]
    ключ_файла = next((к for к in синонимы if str(к).strip().lower() == канон.lower()), None)
    уже = {str(в).strip().lower() for в in (синонимы.get(ключ_файла) or [])} | {канон.lower()}
    новые: List[str] = []
    for написание in написания or []:
        запись = " ".join(str(написание).lower().split())
        if запись and запись not in уже:
            уже.add(запись)
            новые.append(запись)
    if not новые:
        return 0

    прежний = путь.read_text(encoding="utf-8")
    строки = прежний.split("\n")
    начало = next((i for i, с in enumerate(строки) if с.rstrip() == "synonyms:"), None)
    if начало is None:
        строки += ["synonyms:"]
        начало = len(строки) - 1
    конец = next(
        (i for i in range(начало + 1, len(строки)) if строки[i] and not строки[i].startswith((" ", "-", "#"))),
        len(строки),
    )
    while конец > начало + 1 and not строки[конец - 1].strip():
        конец -= 1
    пункты = [f"  - {_скаляр(з)}" for з in новые]

    место = None
    if ключ_файла is not None:
        for i in range(начало + 1, конец):
            строка = строки[i]
            if not строка.startswith("  ") or строка.startswith("   ") or строка.lstrip().startswith(("-", "#")):
                continue
            try:
                разобрано = yaml.safe_load(строка.strip())
            except yaml.YAMLError:
                continue
            if isinstance(разобрано, dict) and ключ_файла in разобрано:
                if строка.rstrip().endswith("[]"):
                    строки[i] = строка.rstrip()[:-2].rstrip()
                место = i + 1
                while место < конец and строки[место].startswith("  -"):
                    место += 1
                break
    if место is None:
        строки[конец:конец] = [f"  {_скаляр(канон)}:"] + пункты
    else:
        строки[место:место] = пункты

    путь.write_text("\n".join(строки), encoding="utf-8")
    проверка = загрузить(путь)["synonyms"]
    ключ_после = next((к for к in проверка if str(к).strip().lower() == канон.lower()), None)
    видны = {str(в).strip().lower() for в in (проверка.get(ключ_после) or [])}
    if ключ_после is None or not set(новые) <= видны:
        путь.write_text(прежний, encoding="utf-8")
        raise ValueError(f"Написания «{канон}» не легли в словарь — файл возвращён как был")

    logger.info(f"Словарь навыков: к «{ключ_после}» добавлены написания {', '.join(новые)}")
    return len(новые)