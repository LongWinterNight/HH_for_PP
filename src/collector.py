def keyword_для_лога(area) -> str:
    """Как назвать срез в сообщении: по региону или «всю выдачу»."""
    return f"регион {area}" if area else "всю выдачу"


@dataclass
class ProgressEvent:
    """
    Что происходит по ходу сбора.

    Единственный способ узнать о ходе работы извне. Прежде веб-слой
    получал эти сведения, подменяя методы коллектора и его клиента: он
    переписывал `_collect_by_keyword` и `search_vacancies` своими
    функциями с фиксированными аргументами. Любое изменение в клиенте
    ломало сбор — так и случилось, когда у поиска появился `date_from`.

    Поля заполняются по мере того, как становятся известны: на старте
    запроса ещё неизвестен ожидаемый объём, он приходит с первой
    страницей.
    """

    stage: str  # keyword_started | page_fetched | keyword_saved | finished
    keyword: str = ""
    page: int = 0
    collected: int = 0
    found: Optional[int] = None
    keyword_index: int = 0
    keywords_total: int = 0
    # Ход внутри текущего запроса: сколько вакансий его выдачи уже
    # просмотрено и сколько будет просмотрено всего. `collected` для
    # этого не годится — он копится по всему сбору, и деление его на
    # найденное по одному запросу давало 99 % на втором запросе из пяти.
    keyword_done: int = 0
    keyword_total: int = 0
    # Последняя обработанная вакансия: название, компания, регион. По ней
    # экран показывает, что сбор приносит, а не только что он идёт.
    vacancy: Optional[Dict[str, str]] = None
    # Что запрос принёс в базу — известно только после записи.
    new: Optional[int] = None
    updated: Optional[int] = None


def _для_ленты(vacancy: Dict[str, Any]) -> Dict[str, str]:
    """
    Три поля вакансии для ленты «только что найдено».

    Не вся вакансия: событие хода уходит в состояние, которое экран
    опрашивает раз в секунду, и тащить в него описание незачем.
    """
    return {
        "name": str(vacancy.get("name") or ""),
        "employer": str((vacancy.get("employer") or {}).get("name") or ""),
        "area": str((vacancy.get("area") or {}).get("name") or ""),
    }


class VacancyCollector:
    """
    Сборщик вакансий с HH.ru.

    Реализует логику поэтапного сбора данных:
    1. Поиск по каждому ключевому слову из конфига
    2. Перебор страниц результатов (до max_pages)
    3. Фильтрация по дате публикации
    4. Сохранение сырых данных в JSON

    Атрибуты:
        client (HHAPIClient): Клиент для работы с API
        output_dir (Path): Директория для сохранения данных
        max_pages (int): Максимальное количество страниц для сбора
        days_back (int): За сколько дней собирать вакансии

    Пример использования:
        >>> collector = VacancyCollector()
        >>> collector.collect_all()  # Сбор по всем запросам из конфига
        >>> stats = collector.get_statistics()
        >>> print(f"Собрано вакансий: {stats['total']}")
    """

    # Через сколько обработанных вакансий сообщать о ходе работы внутри
    # страницы. Обработка страницы — это до ста запросов карточек, и без
    # промежуточных событий счётчик стоит на месте минутами.
    PROGRESS_EVERY = 5

    def __init__(
        self,
        client: Optional[HHAPIClient] = None,
        output_dir: Optional[Path] = None,
        max_pages: Optional[int] = None,
        detailed_pages: Optional[int] = None,
        days_back: Optional[int] = None,
        use_cache: bool = False,
        incremental: bool = False,
        on_progress: Optional[Callable[[ProgressEvent], None]] = None,
        резать_упёршиеся: Optional[bool] = None
    ) -> None:
        """
        Инициализация сборщика.

        Args:
            client: Готовый HHAPIClient. Если None, создаётся новый
            output_dir: Директория для сохранения. Если None, берётся из конфига
            max_pages: Максимум страниц для сбора. Если None, берётся из конфига
            days_back: За сколько дней собирать. Если None, берётся из конфига
            use_cache: Брать ответы поиска из кэша, если они там есть
            incremental: Не запрашивать карточки вакансий, уже лежащих в
                базе. Сами вакансии всё равно сохраняются — обновляются
                зарплата, график и статус
            on_progress: Обработчик событий хода сбора. Через него, а не
                подменой методов, внешний код узнаёт, что происходит
            резать_упёршиеся: Резать запрос, упёршийся в предел выдачи,
                на срезы по регионам и датам. None — взять из настроек,
                где это включено. Внутри среза карточки не запрашиваются,
                поэтому резка стоит минут, а не часов; выключать её имеет
                смысл разве что при отладке

        Note:
            Режимы — это флаги одного сборщика, а не разные классы.
            Прежде существовали два почти одинаковых коллектора, и выбор
            между ними шёл по условию `incremental or use_cache`: режим
            данных выбирал реализацию. Копии успели разойтись в разборе
            навыков — набор навыков в базе зависел от флагов запуска.
        """
        # Создаём или используем готовый клиент
        self.client = client or HHAPIClient()

        # Директория для сохранения сырых данных
        self.output_dir = output_dir or settings.raw_data_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

        # Параметры сбора из конфига или параметров
        self.max_pages = max_pages or settings.max_pages
        # None означает «взять из настроек», а не «ноль»: ноль здесь —
        # осмысленное значение, «карточка у каждой новой вакансии».
        self.detailed_pages = (
            settings.detailed_pages if detailed_pages is None else detailed_pages
        )
        self.days_back = days_back or settings.days_back

        # Вычисляем дату отсечки — вакансии старше не собираем
        self.cutoff_date = datetime.now() - timedelta(days=self.days_back)

        # Кэш ответов поиска. Выключен по умолчанию: ручной сбор должен
        # приносить сегодняшние данные, а не вчерашние.
        self.use_cache = use_cache
        self.api_cache = APICache() if use_cache else None
        if self.api_cache:
            # Протухшее убирается на входе, а не по расписанию: сбор —
            # единственный, кто трогает кэш, и другого повода зайти в
            # него не будет. Без этого файл рос бесконечно: срок годности
            # выдачи шесть часов, а уборка была только ручная.
            self.api_cache.убрать_протухшие()

        # Инкрементальный режим экономит запросы карточек по известным
        # вакансиям — сами вакансии из сохранения не выпадают.
        self.incremental = incremental
        self.existing_ids: Set[str] = set()
        if incremental:
            self._load_existing_ids()

        # Статистика сбора
        self._stats: Dict[str, Any] = {
            "total_vacancies": 0,
            "unique_vacancies": 0,
            "pages_processed": 0,
            "errors": 0,
            "cache_hits": 0,
            "cache_misses": 0,
            "details_skipped": 0,
            # Карточки, отложенные резкой. Это не потеря, а перенос:
            # вакансия сохраняется с пометкой «деталей нет», и её
            # подхватывает проход дозапроса (S2‑2a). Число нужно, чтобы
            # после глубокого сбора было видно, сколько ждёт догона.
            "details_deferred": 0,
            # Сколько раз ответ источника разошёлся с контрактом.
            "schema_violations": 0,
            # Качество собранного копится по ходу: считать его потом по
            # базе нельзя — там записи прошлых сборов, и сегодняшнее
            # ухудшение в них тонет.
            "качество": пустая_сводка(),
            "by_keyword": {}
        }

        # Множество ID уже собранных вакансий (для избежания дубликатов)
        self._seen_ids: Set[str] = set()
        # Номер идущего запроса и их число: уходят в каждое событие хода.
        self._ход: Tuple[int, int] = (0, 0)

        # Что источник отдал по каждому запросу и был ли проход полным.
        # Нужно, чтобы после сбора погасить вакансии, пропавшие из
        # выдачи, — но только по запросам, прочитанным до конца.
        self._keyword_seen: Dict[str, Set[str]] = {}
        self._keyword_complete: Dict[str, bool] = {}

        # Резка запроса на срезы. Включена: с тех пор как охват отделён
        # от глубины (S4‑5a), внутри среза читается только выдача, и
        # обход стоит минуты. Признак остаётся выключаемым — для отладки
        # и для источников, где резать нечего.
        self.резать_упёршиеся = (
            settings.резать_упёршиеся if резать_упёршиеся is None else резать_упёршиеся
        )
        # Бюджет срезов на весь сбор: предохранитель от обхода всех
        # городов всех стран. Непройденное честно попадает в недобор.
        #
        # Предел спрашивается у источника: у каждой площадки свой потолок
        # выдачи и своя терпимость к частоте, и общее число из настроек
        # работало, пока источник был один. Настройка остаётся верхней
        # границей — ею человек может ограничить и щедрый источник.
        предел_источника = getattr(self.client, "предел_срезов", None)
        self._срезов_осталось = min(
            settings.max_slices,
            предел_источника if isinstance(предел_источника, int) else settings.max_slices,
        )
        # Бюджет взвешивания. Лёгкие запросы, которыми срезы
        # упорядочиваются по величине, раньше не считались никак: обход
        # уходил вглубь, и каждый уровень опрашивал все свои части —
        # страны, потом регионы страны, потом города региона. Замер
        # 11.09.2026 поймал это на живом запросе: 408 секунд работы и
        # две собранные вакансии, потому что бюджет обходов кончился, а
        # взвешивание продолжалось.
        #
        # Пять лёгких запросов на срез — столько, чтобы упорядочить
        # десяток частей, и не столько, чтобы обход утонул в разведке.
        # Предел считается от бюджета обходов на момент проверки, а не
        # запоминается: бюджет тает по ходу, и разведка должна таять
        # вместе с ним.
        self._взвешиваний_сделано = 0
        # Справочник регионов читается один раз за сбор и только если
        # резка понадобилась.
        self._регионы: Optional[List[Dict[str, Any]]] = None

        self.on_progress = on_progress

        # Остановка живёт в событии потока: сбор идёт в фоновой задаче, а
        # просьба остановиться приходит из обработчика HTTP — это разные
        # потоки, и обычный флаг здесь ненадёжен.
        self._stop_event = threading.Event()

        logger.info(
            f"VacancyCollector инициализирован. max_pages={self.max_pages}, "
            f"days_back={self.days_back}, кэш={'да' if use_cache else 'нет'}, "
            f"инкрементально={'да' if incremental else 'нет'}"
        )

    @property
    def stop_requested(self) -> bool:
        """Просили ли остановить сбор."""
        return self._stop_event.is_set()

    @stop_requested.setter
    def stop_requested(self, value: bool) -> None:
        """
        Совместимость с прежним флагом: код и тесты, которые писали
        `collector.stop_requested = True`, продолжают работать.
        """
        if value:
            self._stop_event.set()
        else:
            self._stop_event.clear()

    def request_stop(self) -> None:
        """Попросить сбор остановиться. Безопасно из другого потока."""
        logger.info("Запрошена остановка сбора")
        self._stop_event.set()

    def _emit(self, stage: str, **kwargs) -> None:
        """
        Сообщить о ходе работы.

        Ошибка в обработчике не должна ронять сбор: событие — это отчёт о
        работе, а не сама работа. Уронить сбор из-за неудачной записи
        прогресса значило бы потерять данные ради индикатора.
        """
        if not self.on_progress:
            return
        # Номер запроса и их число идут в каждом событии: обработчик
        # считает по ним процент и не должен помнить, какой запрос шёл
        # в прошлом событии.
        номер, всего = getattr(self, "_ход", (0, 0))
        kwargs.setdefault("keyword_index", номер)
        kwargs.setdefault("keywords_total", всего)
        try:
            self.on_progress(ProgressEvent(stage=stage, **kwargs))
        except Exception as e:
            logger.warning(f"Обработчик событий сбора дал сбой: {e}")

    def _date_from(self) -> str:
        """
        Нижняя граница даты публикации для запроса к источнику.

        Считается от той же даты отсечки, что и локальная проверка
        возраста: две границы обязаны совпадать, иначе сбор либо
        выбрасывает то, что честно скачал, либо оставляет то, что должен
        был отсечь.
        """
        return self.cutoff_date.strftime("%Y-%m-%d")

    def _load_existing_ids(self) -> None:
        """
        Загрузить идентификаторы вакансий, уже лежащих в базе.

        Архив тоже нужен: вакансия, снятая с публикации и вернувшаяся, не
        должна попасть в базу вторым экземпляром.
        """
        from src.storage import VacancyStorage

        logger.info("Загрузка известных вакансий для инкрементального режима…")
        try:
            storage = VacancyStorage()
            # Известной считается любая вакансия базы, включая снятые и
            # найденные не по запросу: иначе сбор примет их за новые и
            # потратит запрос на карточку, которая уже есть.
            df = storage.get_all_vacancies(include_inactive=True, include_off_query=True)
            self.existing_ids = set(df["vacancy_id"].astype(str)) if not df.empty else set()
            storage.close()
            logger.info(f"Известных вакансий: {len(self.existing_ids)}")
        except Exception as e:
            # Не смогли прочитать базу — работаем как при полном сборе.
            # Это дороже по запросам, но не теряет данные.
            logger.warning(f"Не удалось загрузить известные вакансии: {e}")
            self.existing_ids = set()

    def _search_with_cache(
        self,
        keyword: str,
        page: int,
        per_page: int = 100,
        area: Optional[str] = None,
        окно: Optional[Tuple[str, Optional[str]]] = None,
    ) -> Optional[Dict[str, Any]]:
        """
        Поиск вакансий с учётом кэша.

        Кэш спрашивается до сети и наполняется после неё. Когда он
        выключен, метод сводится к обычному запросу.

        Args:
            area: Регион запроса. Ключ кэша учитывает его вместе с
                границами даты: без этого срез по одному региону читал бы
                ответ, сохранённый для другого.
            окно: Границы публикации `(от, до)`. None — обычное окно
                сбора: от даты отсечки и до сегодня.
        """
        date_from, date_to = окно if окно else (self._date_from(), None)

        if self.api_cache:
            cached = self.api_cache.get(keyword, page, per_page, area=area,
                                        date_from=date_from, date_to=date_to)
            if cached:
                self._stats["cache_hits"] += 1
                logger.debug(f"Кэш: «{keyword}», страница {page}")
                return cached
            self._stats["cache_misses"] += 1

        # Возраст вакансий ограничивается на стороне источника: скачивать
        # страницы, которые тут же будут выброшены по дате, — это лимит
        # запросов, потраченный на мусор.
        response = self.client.search_vacancies(
            keyword, page, per_page, date_from=date_from, area=area, date_to=date_to
        )

        if response and self.api_cache:
            self.api_cache.set(keyword, page, response, area=area,
                               date_from=date_from, date_to=date_to)

        return response

    def _deactivate_missing(self, storage, only: Optional[str] = None) -> int:
        """
        Погасить вакансии, пропавшие из выдачи по полностью прочитанным
        запросам.

        Args:
            storage: Открытое хранилище — то же, в которое только что
                записали сбор
            only: Ограничить одним запросом. Сбор сохраняет результат
                каждого запроса сразу, и гасить при этом нужно только
                его: остальные либо ещё не собраны, либо уже погашены

        Returns:
            Сколько вакансий погашено

        Note:
            Запрос, прерванный ошибкой, остановкой или упёршийся в предел
            страниц, пропускается: мы не видели всей выдачи, а значит не
            имеем права утверждать, что чего-то в ней нет.
        """
        total = 0
        for keyword, complete in self._keyword_complete.items():
            if only is not None and keyword != only:
                continue
            if not complete:
                continue
            total += storage.deactivate_missing(keyword, self._keyword_seen.get(keyword, set()))
        return total

    def _mark_origin(self, vacancy: Dict[str, Any], keyword: str, has_details: bool) -> None:
        """
        Пометить, каким запросом вакансия найдена и собрано ли описание.

        Пометки живут в самой вакансии под служебными именами: сохранение
        получает общий список по всем запросам, и связь «вакансия →
        запрос» иначе теряется по дороге.
        """
        vacancy["_source_keyword"] = keyword
        vacancy["_has_details"] = has_details

    def _save_to_json(self, data: List[Dict[str, Any]], filename: str) -> Path:
        """
        Сохранение данных в JSON файл.

        Args:
            data: Список словарей с данными вакансий
            filename: Имя файла (без расширения)

        Returns:
            Полный путь к сохранённому файлу

        Note:
            Файл сохраняется в директории data/raw/
            Имя файла включает timestamp для уникальности
        """
        # Формируем имя файла с датой и временем
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filepath = self.output_dir / f"{filename}_{timestamp}.json"

        # Сохраняем с красивым форматированием (indent=2)
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        logger.info(f"Данные сохранены в {filepath}")
        return filepath

    def _is_vacancy_fresh(self, vacancy: Dict[str, Any]) -> bool:
        """
        Проверка даты публикации вакансии.

        Страховка, а не основной фильтр: возраст ограничивается запросом
        `date_from` на стороне источника. Проверка остаётся, потому что
        границы суток у источника и у нас считаются в разных часовых
        поясах, и на краю диапазона одна-две вакансии могут разойтись.

        Args:
            vacancy: Словарь с данными вакансии из API

        Returns:
            True, если вакансия опубликована за последние days_back дней

        Note:
            HH.ru возвращает поле 'published_at' в формате ISO 8601
            Пример: "2024-01-15T10:30:00+0300"
        """
        published_at = vacancy.get("published_at")

        if not published_at:
            # Если даты нет, считаем вакансию свежей (не фильтруем)
            return True

        try:
            # Парсим дату публикации
            # Формат ISO 8601 с часовым поясом
            pub_date = datetime.fromisoformat(published_at.replace("Z", "+00:00"))

            # Приводим cutoff_date к timezone-aware для корректного сравнения
            cutoff_aware = self.cutoff_date.replace(tzinfo=timezone.utc)

            # Сравниваем с датой отсечки
            return pub_date >= cutoff_aware

        except (ValueError, TypeError) as e:
            # Если не удалось распарсить дату, не фильтруем вакансию
            logger.warning(f"Не удалось распарсить дату {published_at}: {e}")
            return True

    def _collect_by_keyword(
        self,
        keyword: str,
        delay_between_pages: float = 1.0,
        area: Optional[str] = None,
        окно: Optional[Tuple[str, Optional[str]]] = None,
        внутри_среза: bool = False,
    ) -> List[Dict[str, Any]]:
        """
        Сбор вакансий по одному ключевому слову.

        Args:
            keyword: Ключевое слово для поиска
            delay_between_pages: Задержка между страницами в секундах
            area: Регион среза. None — запрос без региона, по всему
                источнику. Когда такой запрос упирается в предел выдачи,
                он не читается вглубь: вместо этого тот же запрос
                обходится по регионам, у каждого из которых свой предел
            окно: Границы публикации `(от, до)` для среза по датам. Им
                режется запрос, который упёрся, а делить его по регионам
                уже некуда — вакансии одного города
            внутри_среза: Этот вызов — часть разрезанного запроса. Тогда
                карточки не запрашиваются: резка отвечает за охват, а
                глубину догоняет отдельный проход. Один и тот же обход
                стоит две минуты или четыре часа ровно по этому признаку

        Returns:
            Список словарей с данными вакансий

        Note:
            ДЕТАЛЬНЫЙ ПАРСИНГ ТОЛЬКО ПЕРВЫХ 2 СТРАНИЦ (200 вакансий)
            Остальные страницы - базовая информация (для скорости)
        """
        logger.info(f"Начало сбора по запросу: '{keyword}'")

        all_vacancies: List[Dict[str, Any]] = []
        keyword_stats = {"found": 0, "fresh": 0, "pages": 0}

        # Время и кэш считаются по каждому запросу отдельно: в общем
        # итоге не видно, какой из них тормозил и какой пришёл из кэша.
        started_at = time.monotonic()
        cache_hits_before = self._stats["cache_hits"]
        errors_before = self._stats["errors"]
        # Отказы по частоте считает сам клиент: по ним видно, что выборка
        # неполна из-за ограничений источника, а не из-за отсутствия вакансий.
        limits_before = getattr(self.client, "rate_limit_hits", 0)

        # Что источник отдал по этому запросу и дошли ли мы до конца
        # выдачи. Второе решает, можно ли гасить вакансии, которых здесь
        # не оказалось: по неполному проходу это объявило бы закрытыми
        # живые вакансии со страниц, которые мы не читали.
        seen_here: Set[str] = set()
        complete = False

        # До какой страницы запрашивать карточки вакансий.
        #
        # Раньше здесь стояла двойка, и на живой базе это давало детали у
        # 43 % записей. Разница видна в данных: у вакансии с карточкой
        # 14,7 навыка, без неё — 2,4, а из 1268 вакансий без единого
        # навыка почти все именно такие. Экономия выходила мнимой: мы
        # берегли запросы к источнику и получали базу, по которой нельзя
        # считать.
        #
        # Ноль означает «карточка у каждой новой вакансии». Известные
        # вакансии карточку не запрашивают в любом случае — их данные
        # обновляются из выдачи.
        DETAILED_PAGES = self.detailed_pages

        # Перебираем страницы
        for page in range(self.max_pages):
            if self.stop_requested:
                logger.info(f"Сбор остановлен пользователем на странице {page}")
                break

            # Выдача читается целиком в любом режиме.
            #
            # Прежний коллектор при дописывании проверял первые двадцать
            # вакансий и, если все они известны, обрывал запрос. Экономия
            # выходила мнимой: известные вакансии в этом случае не
            # обновлялись никогда, то есть зарплата и статус в базе
            # застывали на дне первой встречи. Настоящая экономия
            # дописывания — не запрашивать карточки известных вакансий:
            # там один запрос на вакансию против одного на страницу.
            logger.debug(f"Запрос страницы {page + 1}/{self.max_pages}")

            response = self._search_with_cache(keyword, page, 100, area=area, окно=окно)

            if response is None:
                logger.warning(f"Пустой ответ для страницы {page}")
                self._stats["errors"] += 1
                continue

            # Обновляем статистику
            keyword_stats["pages"] += 1
            self._stats["pages_processed"] += 1

            # Схема источника проверяется на первой странице каждого
            # запроса. Дальше проверять незачем: схема меняется у
            # источника целиком, а не у отдельной вакансии. Пропажа поля
            # выглядит как пустое значение — так зарплата уехала в
            # `salary_range`, и сбор месяцами писал часовые ставки как
            # месячные, ничего не сообщая.
            if page == 0:
                self._проверить_схему(keyword, response)

            # Источник сообщает, сколько всего вакансий по запросу.
            # Это знаменатель прогресса: без него счётчик растёт, а
            # сколько осталось — неизвестно. Берём с первой страницы:
            # дальше число то же.
            if keyword_stats.get("found") in (None, 0):
                found = response.get("found")
                if isinstance(found, int):
                    keyword_stats["found"] = found

            # Развилка решается на первой странице, до того как потрачены
            # двадцать запросов на чтение вглубь: если найдено больше,
            # чем источник вообще отдаёт, читать этот срез бессмысленно —
            # он всё равно оборвётся, и остаток мы не увидим. Тот же
            # запрос по частям обходит предел: у каждого региона своя
            # выдача.
            if page == 0 and self._резать_ли(response, area, окно):
                # «Найдено» этого среза записывается до ухода вглубь:
                # оно и есть ответ на вопрос, сколько вакансий по
                # запросу знает источник. У частей числа свои, меньшие,
                # и без этой записи недобор считался бы по ним — то есть
                # оказался бы тем меньше, чем мельче мы порезали.
                #
                # Полнота вносится нейтральным True: за неё отвечают
                # сами срезы, а слияние берёт их пересечение.
                self._слить_статистику(
                    keyword,
                    {"found": keyword_stats.get("found"), "pages": 1},
                    set(),
                    True,
                )
                срезы = self._обойти_срезы(keyword, area, delay_between_pages, окно)
                if срезы is not None:
                    return срезы

            self._emit(
                "page_fetched",
                keyword=keyword,
                page=page,
                collected=len(self._seen_ids),
                found=keyword_stats.get("found"),
                keyword_done=len(seen_here),
                keyword_total=возьмём(keyword_stats.get("found"), self.max_pages),
            )

            items = response.get("items", [])

            # Если вакансий нет — прекращаем перебор страниц
            if not items:
                logger.info(f"Вакансии закончились на странице {page}")
                complete = self._stats["errors"] == 0
                break

            logger.info(f"Получено {len(items)} вакансий со страницы {page}")

            # Дошли ли мы по этой странице до вакансий старше нужного
            # возраста. Выдача отсортирована по дате, поэтому первая
            # старая вакансия означает, что дальше идут только старые.
            reached_old = False

            # Обрабатываем каждую вакансию
            for vacancy in items:
                vacancy_id = vacancy.get("id")
                if vacancy_id:
                    seen_here.add(str(vacancy_id))

                # Пропускаем дубликаты
                if vacancy_id in self._seen_ids:
                    continue

                # Проверяем дату публикации
                if not self._is_vacancy_fresh(vacancy):
                    logger.info(
                        f"Вакансия {vacancy_id} старше {self.days_back} дней — "
                        f"дальше по запросу «{keyword}» только старее"
                    )
                    reached_old = True
                    break

                # Карточка вакансии — отдельный запрос на каждую, поэтому
                # она берётся только для первых страниц и только для
                # вакансий, которых ещё нет в базе.
                #
                # Известная вакансия при этом не выпадает из сохранения:
                # её зарплата, график и статус обновятся из выдачи. Раньше
                # инкрементальный режим выбрасывал такие вакансии целиком,
                # и данные о них застывали навсегда, а «обновлено» в
                # истории сборов всегда равнялось нулю.
                known = self.incremental and str(vacancy_id) in self.existing_ids
                if known:
                    self._stats["details_skipped"] += 1

                # Внутри среза карточки не берутся. Резка нужна ради
                # охвата — «сколько вакансий мы вообще увидели», — и это
                # чтение выдачи, оно дёшево. Карточка же запрашивается на
                # каждую новую вакансию, и она-то и есть вся цена: по
                # замеру один глубокий запрос стоит две минуты без
                # карточек и почти четыре часа с ними. Глубину догоняет
                # отдельный проход по бюджету (S2‑2a), для которого
                # неважно, каким сбором вакансия попала в базу.
                берём_карточку = not внутри_среза and (
                    DETAILED_PAGES <= 0 or page < DETAILED_PAGES
                )
                if берём_карточку and not known:
                    logger.debug(f"Запрос деталей вакансии {vacancy_id} (страница {page})")
                    # Карточка почти не меняется, а запрашивается на каждую
                    # новую вакансию — это тысячи обращений на сбор и почти
                    # всё его время. Кэш здесь экономит больше, чем на
                    # выдаче, и срок ему нужен свой: неделя против шести
                    # часов (S6‑5b).
                    vacancy_details = (
                        self.api_cache.получить_карточку(vacancy_id)
                        if self.api_cache else None
                    )
                    не_из_кэша = vacancy_details is None
                    if не_из_кэша:
                        vacancy_details = self.client.get_vacancy_details(vacancy_id)
                        if vacancy_details and self.api_cache:
                            self.api_cache.сохранить_карточку(vacancy_id, vacancy_details)

                    if vacancy_details:
                        vacancy = {**vacancy, **vacancy_details}
                        self._mark_origin(vacancy, keyword, has_details=True)
                        logger.info(f"Получены детали вакансии {vacancy_id}")
                    else:
                        logger.warning(f"Не удалось получить детали вакансии {vacancy_id}")
                        self._mark_origin(vacancy, keyword, has_details=False)

                    # Задержка между запросами деталей. Из кэша карточка
                    # приходит без обращения к источнику — ждать нечего и
                    # некого.
                    if не_из_кэша:
                        time.sleep(self.client.delay)
                else:
                    if внутри_среза and not known:
                        self._stats["details_deferred"] += 1
                    self._mark_origin(vacancy, keyword, has_details=False)

                self._seen_ids.add(vacancy_id)
                all_vacancies.append(vacancy)
                keyword_stats["fresh"] += 1

                # Ход внутри страницы. Обработка одной страницы — это до
                # ста запросов карточек, то есть минуты: без этих событий
                # счётчик стоит на месте, пока страница не дочитана.
                #
                # Событие раз в несколько вакансий, а не на каждую:
                # обработчик может писать в базу или в сеть, и сотня
                # событий на страницу превратит отчёт о работе в работу.
                if keyword_stats["fresh"] % self.PROGRESS_EVERY == 0:
                    self._emit(
                        "vacancy_processed",
                        keyword=keyword,
                        page=page,
                        collected=len(self._seen_ids),
                        found=keyword_stats.get("found"),
                        keyword_done=len(seen_here),
                        keyword_total=возьмём(keyword_stats.get("found"), self.max_pages),
                        vacancy=_для_ленты(vacancy),
                    )

            # Дошли до вакансий старше нужного возраста — обход запроса
            # закончен. Прежде здесь прерывалась только обработка
            # страницы, а следующая всё равно запрашивалась: обрыв терял
            # данные и не экономил ни одного запроса.
            #
            # Это штатное завершение, а не обрыв на полпути: выдача
            # прочитана до нужной глубины, поэтому пропавшие вакансии
            # гасить можно.
            if reached_old:
                complete = self._stats["errors"] == 0
                break

            # Проверяем, не закончились ли вакансии
            if len(items) < 100:
                logger.info("Последняя страница (меньше 100 вакансий)")
                complete = self._stats["errors"] == 0
                break

            # Задержка между страницами
            time.sleep(delay_between_pages)

        # Сохраняем статистику
        #
        # «Взято» — сколько записей выдачи по этому запросу мы прочитали:
        # все страницы, до которых дошли, включая вакансии, уже
        # встреченные по другим запросам, и отсеянные по возрасту.
        # Именно это число сравнимо с «найдено» источника; new и updated
        # считают изменения в базе и на вопрос «сколько мы не увидели»
        # не отвечают.
        keyword_stats["взято"] = len(seen_here)
        keyword_stats["complete"] = complete
        keyword_stats["duration_ms"] = int((time.monotonic() - started_at) * 1000)
        keyword_stats["from_cache"] = self._stats["cache_hits"] - cache_hits_before
        keyword_stats["errors"] = self._stats["errors"] - errors_before
        keyword_stats["rate_limited"] = getattr(self.client, "rate_limit_hits", 0) - limits_before
        self._слить_статистику(keyword, keyword_stats, seen_here, complete)
        self._stats["total_vacancies"] += len(all_vacancies)

        if not complete:
            logger.info(
                f"Запрос «{keyword}»: выдача прочитана не до конца "
                f"(предел страниц, остановка или ошибка) — гашение пропавших не выполняется"
            )

        logger.info(
            f"Завершён сбор по запросу '{keyword}': "
            f"{len(all_vacancies)} вакансий за {keyword_stats['pages']} страниц"
        )

        return all_vacancies

    # =========================================================================
    # Резка запроса на срезы
    #
    # Источник отдаёт по запросу не больше 2000 вакансий: по «Рекрутеру»
    # он знает 10 294 и показывает первую пятую часть. Никакая настройка
    # глубины этого не меняет — предел стоит на его стороне.
    #
    # Обойти можно только одним способом: задать тот же запрос по частям.
    # У Москвы своя выдача со своим пределом, у Петербурга своя. Срез,
    # который сам упёрся, режется дальше — область на города; лист
    # дерева, который всё равно упёрся, честно уходит в недобор.
    # =========================================================================

    def _проверить_схему(self, keyword: str, response: Dict[str, Any]) -> None:
        """
        Сверить ответ источника с контрактом и сказать вслух о расхождении.

        Нарушение не роняет сбор: вакансия без описания всё равно даёт
        название, зарплату и работодателя, и терять её из-за пропавшего
        поля — хуже, чем собрать неполной. Но нарушение считается и
        попадает в статистику запроса: молчаливая смена схемы уже стоила
        месяцев неверных чисел.
        """
        итог = проверить_страницу(response)

        if итог["нарушен"]:
            self._stats["schema_violations"] += 1
            чего_нет = ", ".join(итог["ответ"] + итог["вакансия"])
            logger.error(
                f"Схема источника разошлась с контрактом на запросе "
                f"«{keyword}»: нет обязательных полей — {чего_нет}"
            )
        elif итог["подозрительно"]:
            logger.warning(
                f"Запрос «{keyword}»: у вакансий нет полей "
                f"{', '.join(итог['подозрительно'])} — возможно, источник "
                f"перенёс их в другое место"
            )

    def разведать(
        self,
        keywords: List[str],
        окно: Optional[Tuple[str, Optional[str]]] = None,
    ) -> Dict[str, Any]:
        """
        Сколько запросов упрётся в предел выдачи — до того, как собирать.

        Зачем. Оценка сбора умножала цену на весь бюджет срезов
        (`MAX_SLICES`, сто штук), потому что заранее не знала, сколько
        запросов вообще упрётся. Экран обещал сотни часов там, где сбор
        занимал сорок минут, и такому обещанию человек верить перестаёт.

        Разведка стоит по одному лёгкому запросу на ключевое слово:
        спрашивается страница из одной вакансии, из ответа берётся только
        «найдено». Тот же приём, что и при взвешивании срезов.

        Returns:
            `{"упрутся": [...], "обычные": [...], "найдено": {слово: n}}`
        """
        упрутся, обычные, найдено = [], [], {}
        for слово in keywords:
            if self.stop_requested:
                break
            ответ = self._search_with_cache(слово, 0, 1, окно=окно)
            число = (ответ or {}).get("found")
            найдено[слово] = число if isinstance(число, int) else None
            # Лёгкий запрос спрашивает одну вакансию, но упрётся ли
            # запрос — считается по настоящему размеру страницы: иначе
            # доступной глубиной окажется десять вакансий, и «упёрся»
            # скажется про любой запрос.
            упёрлось = упёрся({"found": число, "pages": self.max_pages}, self.max_pages)
            (упрутся if упёрлось else обычные).append(слово)
        logger.info(
            f"Разведка: из {len(keywords)} запросов упрутся в предел {len(упрутся)}"
        )
        return {"упрутся": упрутся, "обычные": обычные, "найдено": найдено}

    def _резать_ли(
        self,
        response: Dict[str, Any],
        area: Optional[str],
        окно: Optional[Tuple[str, Optional[str]]] = None,
    ) -> bool:
        """
        Нужно ли вместо чтения вглубь обойти этот срез по частям.

        Резка включается сама, когда что-то даёт: срез действительно
        упёрся в предел выдачи и его есть на что делить — по регионам или
        по датам. Отдельного разрешения она больше не требует.

        Раньше здесь стоял флаг `SPLIT_BY_REGION`, выключенный по
        умолчанию, и цена резки считалась вместе с карточками — оттого и
        казалась неподъёмной. Теперь охват и глубина разведены (S4‑5a):
        внутри среза читается только выдача, и весь конфиг из 58 запросов
        стоит около сорока минут вместо 225 часов. Молчать о недоборе,
        когда лекарство написано и лежит выключенным, дороже.
        """
        if not self.резать_упёршиеся:
            return False
        if self._срезов_осталось <= 0:
            return False
        if not упёрся(response, self.max_pages):
            return False

        части = self._части(area)
        if части:
            # Резка заменяет прямое чтение, а не дополняет его: обойдя
            # срезы, вглубь мы уже не идём. Значит бюджета должно хватить
            # хотя бы на все части этого уровня — иначе мы обойдём три
            # региона из девяноста и потеряем ту тысячу, которую прочли
            # бы напрямую.
            #
            # Замер 11.09.2026 поймал ровно это: при бюджете в шесть
            # срезов «Графический дизайнер» дал 55 вакансий вместо 1000.
            if self._срезов_осталось < len(части):
                logger.info(
                    f"Резать «{keyword_для_лога(area)}» не будем: бюджета "
                    f"{self._срезов_осталось} не хватит на {len(части)} частей — "
                    f"читаем запрос напрямую"
                )
                return False
            return True

        return bool(self._половины_окна(окно))

    def _части(self, area: Optional[str]) -> List[str]:
        """
        На что делится срез: страны для запроса без региона, вложенные
        регионы — для региона.
        """
        дерево = self._дерево_регионов()
        if not дерево:
            return []
        return regions.корни(дерево) if area is None else regions.дети(дерево, area)

    def _дерево_регионов(self) -> List[Dict[str, Any]]:
        """Справочник регионов, прочитанный один раз за сбор."""
        if self._регионы is None:
            self._регионы = regions.загрузить(self.client)
        return self._регионы

    def _половины_окна(
        self,
        окно: Optional[Tuple[str, Optional[str]]],
    ) -> List[Tuple[str, Optional[str]]]:
        """
        Разделить окно публикации пополам.

        Последний рубеж резки: когда срез упёрся, а делить его по
        регионам уже некуда — например, все вакансии в одном городе.
        Выдача отсортирована по дате, поэтому половины не пересекаются:
        верхняя граница одной становится нижней другой.

        Окно короче суток не делится: у источника разрешение границ —
        день, и деление ушло бы в бесконечность, возвращая то же самое.
        """
        от, до = окно if окно else (self._date_from(), None)

        начало = datetime.strptime(от[:10], "%Y-%m-%d")
        конец = datetime.strptime(до[:10], "%Y-%m-%d") if до else datetime.now()

        if (конец - начало) < timedelta(days=2):
            return []

        середина = начало + (конец - начало) / 2
        рубеж = середина.strftime("%Y-%m-%d")
        верх = до if до else конец.strftime("%Y-%m-%d")
        return [(от, рубеж), (рубеж, верх)]

    def _от_крупных(
        self,
        keyword: str,
        части: List[str],
        окно: Optional[Tuple[str, Optional[str]]],
    ) -> List[str]:
        """
        Переставить срезы так, чтобы первыми шли самые вакансиеёмкие.

        Порядок важен, когда бюджет срезов кончится раньше самих срезов:
        пропустить стоит мелкие. В справочнике регионы идут не по
        величине, а по внутреннему порядку источника, и живой замер это
        показал: при бюджете в двенадцать срезов обход уходил на Марий
        Эл, Удмуртию и Чувашию, а Москва с Петербургом не наступали
        вовсе. Охват вырос с 1000 до 1114 вакансий вместо тысяч.

        Цена — один лёгкий запрос на срез: спрашивается страница из
        одной вакансии, из ответа берётся только «найдено». Для срезов,
        которые в бюджет не попадут, этот запрос потрачен зря — но он на
        два порядка дешевле, чем обойти не тот регион.

        Замер 11.09.2026 показал, во что это обходится в живом дереве:
        девяносто с лишним регионов — девяносто лёгких запросов на каждый
        упёршийся запрос, дольше самого обхода. Пропускать взвешивание,
        когда бюджета хватает на все части, всё равно нельзя: сбор
        останавливают на середине, и тогда порядок решает, что успело
        собраться — Москва или Марий Эл. Экономить надо не здесь.

        Срез, о котором источник промолчал, уходит в конец: гадать за
        него нельзя, а выбрасывать — тем более.
        """
        if len(части) < 2:
            return части


        предел = self._срезов_осталось * ВЗВЕШИВАНИЙ_НА_СРЕЗ
        if self._взвешиваний_сделано + len(части) > предел:
            # На упорядочивание не хватает: обходим в порядке
            # справочника. Это хуже, чем по величине, но лучше, чем
            # потратить остаток обращений на разведку и не собрать
            # ничего — ровно это и случилось на замере 11.09.2026.
            logger.debug(
                f"Взвешивание пропущено: сделано {self._взвешиваний_сделано}, "
                f"частей {len(части)}, предел {предел}"
            )
            return части

        веса: Dict[str, int] = {}
        for часть in части:
            if self.stop_requested:
                break
            self._взвешиваний_сделано += 1
            ответ = self._search_with_cache(keyword, 0, 1, area=часть, окно=окно)
            найдено = (ответ or {}).get("found")
            веса[часть] = найдено if isinstance(найдено, int) else -1

        return sorted(части, key=lambda ч: веса.get(ч, -1), reverse=True)

    def _обойти_срезы(
        self,
        keyword: str,
        area: Optional[str],
        delay_between_pages: float,
        окно: Optional[Tuple[str, Optional[str]]] = None,
    ) -> Optional[List[Dict[str, Any]]]:
        """
        Обойти запрос по частям вместо чтения вглубь.

        Сначала по регионам: их выдачи не пересекаются, и каждая — про
        свой рынок. Когда регион дальше не делится, тот же срез режется
        по датам публикации.

        Returns:
            Собранное по всем частям, либо None — если резать не вышло и
            вызывающий должен читать срез как раньше. None, а не пустой
            список: пустой список означал бы «в этом срезе ничего нет»,
            и вакансии молча потерялись бы.
        """
        дерево = self._дерево_регионов()
        откуда = regions.имя(дерево, area) if area else "всей выдачи"

        части = self._части(area)
        по_датам: List[Tuple[str, Optional[str]]] = []
        if not части:
            по_датам = self._половины_окна(окно)
            if not по_датам:
                return None
            logger.info(
                f"Запрос «{keyword}» упёрся в предел выдачи {откуда} и дальше "
                f"по регионам не делится: режем окно публикации пополам"
            )
        else:
            logger.info(
                f"Запрос «{keyword}» упёрся в предел выдачи {откуда}: "
                f"режем на {len(части)} частей"
            )

        части = self._от_крупных(keyword, части, окно) if части else части

        собрано: List[Dict[str, Any]] = []
        for часть in части or по_датам:
            if self.stop_requested:
                logger.info(f"Сбор остановлен: срезы запроса «{keyword}» пройдены не все")
                break
            if self._срезов_осталось <= 0:
                # Бюджет срезов — предохранитель, а не оптимизация: без
                # него один запрос по стране с городами способен занять
                # тысячи обращений к источнику. Непройденные части
                # остаются в недоборе, и он их назовёт.
                logger.warning(
                    f"Бюджет срезов исчерпан на запросе «{keyword}»: "
                    f"часть срезов не обойдена"
                )
                break

            self._срезов_осталось -= 1
            if части:
                собрано.extend(
                    self._collect_by_keyword(
                        keyword, delay_between_pages, area=часть, окно=окно,
                        внутри_среза=True,
                    )
                )
            else:
                собрано.extend(
                    self._collect_by_keyword(
                        keyword, delay_between_pages, area=area, окно=часть,
                        внутри_среза=True,
                    )
                )

        return собрано

    def _слить_статистику(
        self,
        keyword: str,
        stats: Dict[str, Any],
        seen_here: Set[str],
        complete: bool,
    ) -> None:
        """
        Сложить результат среза с тем, что уже собрано по этому запросу.

        Раньше статистика запроса просто присваивалась: при одном
        проходе это одно и то же. Со срезами присваивание стирало бы
        всё, кроме последнего региона, — и «взято» по запросу оказалось
        бы меньше, чем по любому из его срезов.

        «Найдено» не суммируется: у каждого среза оно своё, а вопрос,
        на который отвечает это число, — сколько вакансий по запросу
        знает источник. Верное значение даёт самый широкий срез, то есть
        наибольшее из них.
        """
        накоплено = self._stats["by_keyword"].setdefault(keyword, {})

        for поле in ("pages", "взято", "fresh", "from_cache", "errors",
                     "rate_limited", "duration_ms", "new", "updated"):
            if поле in stats:
                накоплено[поле] = накоплено.get(поле, 0) + stats[поле]

        найдено = stats.get("found")
        if isinstance(найдено, int):
            накоплено["found"] = max(накоплено.get("found") or 0, найдено)

        # Полным запрос считается, только если полны все его срезы: по
        # неполному проходу гасить пропавшие вакансии нельзя.
        накоплено["complete"] = complete and накоплено.get("complete", True)

        self._keyword_seen.setdefault(keyword, set()).update(seen_here)
        self._keyword_complete[keyword] = накоплено["complete"]

    def collect_all(
        self,
        keywords: Optional[List[str]] = None,
        save_raw: bool = True,
        пройденные: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """
        Сбор вакансий по всем ключевым словам.

        Args:
            keywords: Список ключевых слов. Если None, берётся из конфига
            save_raw: Сохранять ли сырые данные в JSON
            пройденные: Запросы, обойдённые оборвавшимся сбором. Они
                пропускаются: их вакансии уже в базе, а повторный обход
                стоит столько же, сколько первый. Сбор из семи запросов,
                прерванный на шестом, прежде повторял все шесть

        Returns:
            Словарь с результатами сбора:
            {
                "total": int,              # Всего собрано
                "unique": int,             # Уникальных (без дублей)
                "by_keyword": Dict,        # Статистика по запросам
                "files": List[str]         # Сохранённые файлы
            }

        Note:
            Метод последовательно перебирает все ключевые слова.
            Дубликаты автоматически удаляются по ID вакансии.
        """
        # Берём ключевые слова из конфига или параметра
        if keywords is None:
            keywords = config_loader.search_queries

        уже_пройдено = set(пройденные or [])
        if уже_пройдено:
            logger.info(
                f"Продолжение оборванного сбора: пропускаем "
                f"{len(уже_пройдено)} уже пройденных запросов"
            )

        logger.info(f"Начало сбора вакансий. Запросов: {len(keywords)}")
        logger.info(f"Запросы: {', '.join(keywords)}")

        all_vacancies: List[Dict[str, Any]] = []
        saved_files: List[str] = []

        # Последовательно собираем по каждому запросу
        for i, keyword in enumerate(keywords, 1):
            if keyword in уже_пройдено:
                # Запрос обойдён прошлой попыткой целиком, и его вакансии
                # сохранены сразу после обхода. Повторять его — значит
                # заново потратить те же минуты на те же данные.
                logger.info(f"Запрос {i}/{len(keywords)} «{keyword}» пройден ранее — пропуск")
                continue

            if self.stop_requested:
                logger.info(f"Сбор остановлен: запрос {i} из {len(keywords)} не начат")
                break

            logger.info(f"Запрос {i}/{len(keywords)}: {keyword}")
            self._ход = (i, len(keywords))
            self._emit(
                "keyword_started",
                keyword=keyword,
                collected=len(self._seen_ids),
                keyword_index=i,
                keywords_total=len(keywords),
            )

            vacancies = self._collect_by_keyword(keyword)
            all_vacancies.extend(vacancies)

            # Сохраняем промежуточные результаты для каждого запроса
            if save_raw and vacancies:
                # Очищаем имя файла от спецсимволов
                safe_name = keyword.replace(" ", "_").replace("+", "plus")
                filepath = self._save_to_json(vacancies, f"vacancies_{safe_name}")
                saved_files.append(str(filepath))

            # Запрос сохраняется сразу, а не в конце всего сбора.
            #
            # Во-первых, только так видно, что принёс каждый запрос:
            # одним общим списком «новых» и «обновлённых» по запросам не
            # разложить. Во-вторых, сбор из семи запросов, упавший на
            # пятом, прежде терял всё собранное — теперь в базе остаётся
            # то, что успели прочитать.
            self._save_keyword_result(keyword, vacancies)
            self._emit(
                "keyword_saved",
                keyword=keyword,
                collected=len(self._seen_ids),
                found=self._stats["by_keyword"].get(keyword, {}).get("found"),
                keyword_index=i,
                keywords_total=len(keywords),
                new=self._stats["by_keyword"].get(keyword, {}).get("new", 0),
                updated=self._stats["by_keyword"].get(keyword, {}).get("updated", 0),
            )

            # Небольшая задержка между запросами (дополнительная защита)
            if i < len(keywords):
                time.sleep(2.0)

        # Общий файл сырых данных — по всем запросам разом
        unique_vacancies = self._deduplicate_vacancies(all_vacancies)
        if save_raw and unique_vacancies:
            filepath = self._save_to_json(unique_vacancies, "all_vacancies")
            saved_files.append(str(filepath))

        # Обновляем финальную статистику
        self._stats["unique_vacancies"] = len(unique_vacancies)

        new_total = sum(k.get("new", 0) for k in self._stats["by_keyword"].values())
        updated_total = sum(k.get("updated", 0) for k in self._stats["by_keyword"].values())
        # Сколько вакансий источник обещал по всем запросам вместе.
        # Это верхняя оценка: запросы пересекаются, и одна вакансия
        # может попасть в несколько.
        found_total = sum(k.get("found") or 0 for k in self._stats["by_keyword"].values())

        logger.info(
            f"Сбор завершён. Всего: {self._stats['total_vacancies']}, "
            f"уникальных: {self._stats['unique_vacancies']}, "
            f"новых: {new_total}, обновлено: {updated_total}"
        )

        self._emit(
            "finished",
            collected=self._stats["unique_vacancies"],
            found=found_total or None,
            keywords_total=len(keywords),
        )

        return {
            "total": self._stats["total_vacancies"],
            "unique": self._stats["unique_vacancies"],
            # «Новых» и «обновлено» приходят из результата записи, а не из
            # длины списка: прежде все собранные записывались в историю
            # как новые, и «обновлено» всегда равнялось нулю.
            "new": new_total,
            "updated": updated_total,
            "found_estimate": found_total,
            # Годятся ли собранные записи для аналитики: доля с
            # карточкой, доля без единого навыка и сколько запросов
            # прочитаны не до конца.
            "качество": сводка(self._stats["качество"], self._stats["by_keyword"]),
            "by_keyword": self._stats["by_keyword"],
            "отказ_текстов": self._stats.get("отказ_текстов"),
            "files": saved_files
        }

    def _save_keyword_result(self, keyword: str, vacancies: List[Dict[str, Any]]) -> None:
        """
        Сохранить вакансии одного запроса и записать, что он принёс.

        Args:
            keyword: Запрос, по которому собраны вакансии
            vacancies: Собранное по этому запросу

        Note:
            Числа «новых» и «обновлено» берутся из ответа хранилища, а не
            из длины списка: вакансия, которую источник отдал повторно, —
            это обновление, а не находка.
        """
        stats = self._stats["by_keyword"].setdefault(keyword, {})

        if not vacancies:
            stats.setdefault("new", 0)
            stats.setdefault("updated", 0)
            return

        written = self._save_to_database(vacancies, keyword=keyword)
        stats["new"] = written.get("inserted", 0)
        stats["updated"] = written.get("updated", 0)

    def _save_to_database(
        self,
        vacancies: List[Dict[str, Any]],
        keyword: Optional[str] = None
    ) -> Dict[str, int]:
        """
        Сохранение вакансий в БД.

        Args:
            vacancies: Список вакансий для сохранения
            keyword: Запрос, результат которого сохраняется. Ограничивает
                гашение пропавших этим запросом

        Returns:
            Статистика записи: сколько вставлено, обновлено, пропущено

        Note:
            Разбор вакансии живёт в src/normalize.py — одном месте для
            живого сбора и для восстановления истории из старых файлов.
        """
        from src.storage import VacancyStorage
        from src.normalize import SkillDictionaries, normalize_many
        import pandas as pd

        logger.info(f"Сохранение {len(vacancies)} вакансий в БД...")

        storage = VacancyStorage()
        try:
            dictionaries = SkillDictionaries.from_config()
            df = pd.DataFrame(normalize_many(vacancies, dictionaries))

            # Качество считается здесь — на разобранных записях, до
            # записи в базу. Позже это уже не измерить: в базе лежат и
            # вакансии прошлых сборов, а нужно знать, что принёс этот.
            self._stats["качество"] = сложить(
                self._stats["качество"], _метрики_качества(df)
            )

            # Пишем всё собранное: новое добавится, известное обновится.
            #
            # Прежде здесь отбирались только вакансии, которых нет в базе,
            # и этот отбор уходил в запись, заменявшую таблицу целиком, —
            # то есть каждый сбор оставлял в базе ровно то, что нашёл
            # сейчас, стирая всё собранное раньше.
            # Найденное этим сбором — по запросу: поиск идёт только по
            # названию и описанию. Вакансия, помеченная раньше как
            # найденная не по запросу, пометку теряет, если источник
            # теперь отдал её законно — по другому запросу или после
            # правки описания.
            if not df.empty:
                df["off_query"] = 0

            stats = storage.save_vacancies_incremental(df)

            # Вакансии записаны, а тексты описаний — нет: сбор удался,
            # но не целиком, и об этом должно быть сказано в записи
            # запуска, а не только в логе, которого никто не читает.
            if storage.отказ_текстов:
                self._stats["отказ_текстов"] = storage.отказ_текстов

            # Вакансии, пропавшие из выдачи, гасим — но только по тем
            # запросам, чью выдачу прочитали целиком.
            self._deactivate_missing(storage, only=keyword)

            if not df.empty:
                logger.info(
                    f"БД обновлена: {stats['inserted']} новых, "
                    f"{stats['updated']} обновлено"
                )
                total_skills = int(df["skill_count"].sum())
                logger.info(
                    f"Навыков найдено: {total_skills}, "
                    f"в среднем {total_skills / len(df):.1f} на вакансию"
                )
            else:
                logger.info("Нечего сохранять: пустой список вакансий")

            return stats

        except Exception as e:
            # Ошибка записи не гасится: сбор, не сохранивший данные, —
            # неудачный сбор, и он обязан закончиться статусом ошибки.
            logger.exception(f"Ошибка сохранения в БД: {e}")
            raise
        finally:
            storage.close()

    def _deduplicate_vacancies(
        self,
        vacancies: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:
        """
        Удаление дубликатов вакансий по ID.

        Args:
            vacancies: Список вакансий (возможно с дублями)

        Returns:
            Список уникальных вакансий

        Note:
            Используем OrderedDict-подобную логику через dict для сохранения порядка
        """
        seen: Dict[str, Dict[str, Any]] = {}

        for vacancy in vacancies:
            vacancy_id = vacancy.get("id")
            if vacancy_id and vacancy_id not in seen:
                seen[vacancy_id] = vacancy

        return list(seen.values())

    def get_statistics(self) -> Dict[str, Any]:
        """
        Получение статистики сбора.

        Returns:
            Словарь со статистикой:
            - total_vacancies: всего собрано
            - unique_vacancies: уникальных
            - pages_processed: обработано страниц
            - errors: количество ошибок
            - by_keyword: детализация по запросам
        """
        return self._stats.copy()

    def close(self) -> None:
        """Закрытие клиента и освобождение ресурсов."""
        if self.client:
            self.client.close()


