"""
Разбор одной вакансии моделью: собрать вход, проверить выход.

Здесь сходятся три вещи, которые по отдельности ничего не гарантируют:
промпт (что просим), схема (в каком виде ответ вообще возможен) и
контракт (чему из ответа верим). Модуль не знает, какая модель отвечает,
и не пишет в базу — он превращает текст вакансии в проверенный список
навыков либо говорит, что ответа нет.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List

from src.ai.поставщик import МодельНедоступна, Поставщик
from src.ai_contract import (
    ВИДЫ,
    ИзвлечённыйНавык,
    ОтветИзвлечения,
    ОтветСломан,
    без_выдуманного,
    разобрать_ответ,
)

# Версия промпта — имя его файла. Промпт меняется чаще кода, и каждая
# правка должна быть видна в истории и сопоставима с замером: новый
# промпт — новый файл, старый остаётся.
ВЕРСИЯ_ПРОМПТА = "извлечение_навыков_v1"

# Сколько знаков описания уходит модели. Длиннее бывают единицы
# вакансий, и хвост у них — условия и реквизиты, а не требования.
ЗНАКОВ_ОПИСАНИЯ = 9000

РАЗМЕТКА = re.compile(r"<[^>]+>")
КОНЕЦ_БЛОКА = re.compile(r"</(?:p|li|ul|ol|h\d|div)>|<br\s*/?>", re.IGNORECASE)
ПРОБЕЛЫ = re.compile(r"[ \t\xa0]+")
ПУСТЫЕ_СТРОКИ = re.compile(r"\n\s*\n+")

# Модель отвечает строками, а не JSON: первая строка — язык текста,
# дальше по строке на навык, поля через черту:
#
#     цитата|название|вид|уверенность[|родитель]
#
# JSON с полными именами полей стоил шестидесяти токенов на навык, и
# ответ на двадцать пять навыков шёл минуту; строка стоит двадцати.
# Строгость от этого не страдает: формат держит грамматика рантайма, а
# не аккуратность модели. В контракт строки переводятся при разборе.
#
# Ответ объектом JSON (с ключами `s`/`l` либо полными именами) тоже
# принимается: так отвечают тесты и так может отвечать поставщик, у
# которого грамматик нет, — ему выдаётся схема ниже.
КЛЮЧИ = {"q": "как_в_тексте", "n": "название", "k": "вид", "c": "уверенность", "p": "родитель"}
ВИДЫ_КРАТКО = {"tool": "инструмент", "tech": "технология", "method": "метод", "lang": "язык", "soft": "компетенция"}
assert set(ВИДЫ_КРАТКО.values()) == set(ВИДЫ), "виды модели разошлись с контрактом"

НАВЫКОВ_В_ОТВЕТЕ = 30

# Схема ответа — для поставщиков, которые понимают JSON Schema. Версий
# здесь нет намеренно: их знает наша сторона, а не модель; спрашивать у
# модели, какой она версии, значит получить выдумку.
СХЕМА_ОТВЕТА: Dict[str, Any] = {
    "type": "object",
    "properties": {
        "s": {
            "type": "array",
            "maxItems": НАВЫКОВ_В_ОТВЕТЕ,
            "items": {
                "type": "object",
                "properties": {
                    "n": {"type": "string", "minLength": 1, "maxLength": 80},
                    "q": {"type": "string", "minLength": 1, "maxLength": 160},
                    "k": {"type": "string", "enum": list(ВИДЫ_КРАТКО)},
                    "c": {"type": "number", "minimum": 0, "maximum": 1},
                    "p": {"type": ["string", "null"]},
                },
                "required": ["n", "q", "k", "c", "p"],
                "additionalProperties": False,
            },
        },
        "l": {"type": "string", "minLength": 2, "maxLength": 3},
    },
    "required": ["s", "l"],
    "additionalProperties": False,
}

# Грамматика рантайма — файл рядом с промптом. Число строк и длина
# полей ограничены самим построением: «модель не останавливается» здесь
# невозможно, а не маловероятно.
ВЕРСИЯ_ГРАММАТИКИ = "ответ_v1"
ГРАММАТИКА = (Path(__file__).parent / "промпты" / f"{ВЕРСИЯ_ГРАММАТИКИ}.gbnf").read_text(encoding="utf-8").strip()


@dataclass(frozen=True)
class Разбор:
    """Итог разбора одной вакансии."""

    ответ: ОтветИзвлечения
    # Навыки, чьей цитаты в тексте не нашлось. Их число — мера того,
    # насколько модели можно верить; до базы они не доходят.
    отброшены: List[ИзвлечённыйНавык] = field(default_factory=list)
    токенов_вход: int = 0
    токенов_выход: int = 0
    мс: int = 0
    # Ответ модели как он пришёл — для кэша: пересчитать разбор после
    # правки проверок можно без повторного вызова.
    сырой: str = ""


@lru_cache(maxsize=4)
def промпт(версия: str = ВЕРСИЯ_ПРОМПТА) -> str:
    файл = Path(__file__).parent / "промпты" / f"{версия}.md"
    return файл.read_text(encoding="utf-8").strip()


def текст_описания(описание: str) -> str:
    """
    Описание без разметки, но с абзацами.

    Границы блоков сохраняются переводом строки: по ним модель отличает
    пункт требований от пункта условий. Сплошная строка без них — то, на
    чём словарь и находил «Зарплату» в навыках.
    """
    текст = КОНЕЦ_БЛОКА.sub("\n", описание or "")
    текст = РАЗМЕТКА.sub(" ", текст)
    текст = текст.replace("&nbsp;", " ").replace("&amp;", "&").replace("&quot;", '"').replace("&lt;", "<").replace("&gt;", ">")
    текст = ПРОБЕЛЫ.sub(" ", текст)
    текст = "\n".join(строка.strip() for строка in текст.split("\n"))
    return ПУСТЫЕ_СТРОКИ.sub("\n", текст).strip()[:ЗНАКОВ_ОПИСАНИЯ]


def вход(название: str, описание: str) -> str:
    """Что видит модель: название вакансии и её описание."""
    return f"Название вакансии: {(название or '').strip()}\n\nОписание:\n{текст_описания(описание)}"


def из_сырого(сырой: str, описание: str, версия_модели: str, версия_промпта: str = ВЕРСИЯ_ПРОМПТА):
    """
    Проверенный ответ из текста, который вернула модель.

    Используется дважды: при живом вызове и при чтении кэша. Проверки
    одни и те же — кэш хранит ответ модели, а не наше доверие к нему.

    Returns:
        (очищенный ответ, отброшенные навыки)
    """
    if (сырой or "").lstrip().startswith("{"):
        try:
            данные = json.loads(сырой)
        except (TypeError, ValueError) as e:
            raise ОтветСломан(f"ответ не JSON: {e}") from e
        if not isinstance(данные, dict):
            raise ОтветСломан("ответ не объект")
    else:
        данные = из_строк(сырой)

    данные = полные_ключи(данные)

    # Версии ставит наша сторона: модель о них не знает.
    данные = {**данные, "версия_модели": версия_модели, "версия_промпта": версия_промпта}
    ответ = разобрать_ответ(данные)

    # Цитата сверяется с тем же текстом, который видела модель: в нём
    # нет разметки, и цитата «Jira для задач» не найдётся в описании,
    # где между словами стоит тег.
    текст = текст_описания(описание)
    ответ, отброшены = без_выдуманного(ответ, текст)
    ответ, отброшены = _вернуть_собранные(ответ, отброшены, текст)
    return _без_повторов(ответ), отброшены


СЛОВО_ЦИТАТЫ = re.compile(r"[a-zа-яё0-9#+.]{3,}")


def _вернуть_собранные(ответ: ОтветИзвлечения, отброшены: List[ИзвлечённыйНавык], текст: str):
    """
    Вернуть навыки, чья цитата собрана из слов одной строки текста.

    Модель цитирует не всегда дословно: из «знание основ REST, SOAP»
    она делает «знание основ SOAP», из «аналоги: Skype, WhatsApp» —
    «аналоги WhatsApp». Строгая проверка такой навык отбрасывала, хотя он
    в тексте назван. Выдумкой это не является — каждое слово цитаты
    стоит в одной и той же строке описания; выдуманному навыку такую
    строку не найти.

    Цитатой возвращённого навыка становится сама эта строка: человеку
    показывается то, что действительно написано в вакансии.
    """
    from dataclasses import replace

    from src.ai_contract import МИН_УВЕРЕННОСТЬ
    from src.normalize import без_гомоглифов

    строки = [строка for строка in текст.split("\n") if строка.strip()]
    подготовленные = [без_гомоглифов(строка.lower()) for строка in строки]

    возвращены, остались = [], []
    for навык in отброшены:
        слова = СЛОВО_ЦИТАТЫ.findall(без_гомоглифов(навык.как_в_тексте.lower()))
        где = None
        if слова and навык.уверенность >= МИН_УВЕРЕННОСТЬ:
            где = next((i for i, строка in enumerate(подготовленные) if all(слово in строка for слово in слова)), None)
        if где is None:
            остались.append(навык)
        else:
            возвращены.append(replace(навык, как_в_тексте=строки[где][:160]))
    if not возвращены:
        return ответ, отброшены
    return replace(ответ, навыки=[*ответ.навыки, *возвращены]), остались


def из_строк(сырой: str) -> Dict[str, Any]:
    """
    Ответ модели строками — в вид, который знает контракт.

    Строка, не похожая на навык, ломает ответ целиком: частичный разбор
    запрещён контрактом, а грамматика такой строки выдать не даёт — раз
    она здесь, ответ пришёл не от неё.
    """
    строки = [строка for строка in (сырой or "").split("\n") if строка.strip()]
    if not строки:
        raise ОтветСломан("ответ пуст")
    язык = строки[0].strip()
    if not язык.isalpha() or not 2 <= len(язык) <= 3:
        raise ОтветСломан(f"первая строка ответа не язык текста: «{язык[:20]}»")

    навыки = []
    for номер, строка in enumerate(строки[1:], 1):
        поля = [поле.strip() for поле in строка.split("|")]
        if len(поля) not in (4, 5):
            raise ОтветСломан(f"строка №{номер}: полей {len(поля)}, а не 4–5")
        цитата, название, вид, уверенность = поля[:4]
        if вид not in ВИДЫ_КРАТКО:
            raise ОтветСломан(f"строка №{номер}: неизвестный вид «{вид}»")
        if not уверенность.isdigit() or not 1 <= int(уверенность) <= 9:
            raise ОтветСломан(f"строка №{номер}: уверенность «{уверенность}» не цифра 1–9")
        навыки.append({
            "как_в_тексте": цитата, "название": название, "вид": ВИДЫ_КРАТКО[вид],
            "уверенность": int(уверенность) / 10,
            "родитель": (поля[4] or None) if len(поля) == 5 else None,
        })
    return {"навыки": навыки, "язык_текста": язык}


# Чему из ответа модели мы верим — по виду навыка.
#
# Замер на эталоне показал, что модель надёжна там, где у навыка есть
# собственное имя, и ненадёжна там, где его нет. Инструменты и
# технологии она называет с точностью 83 %; методы и личные качества —
# вперемешку с пересказом обязанностей и условий («повторная проверка»,
# «стабильная зарплата»), и если брать всё, точность падает до 40 %.
#
# Поэтому порог уверенности у видов разный: именованное принимается,
# когда модель назвала его хоть сколько-нибудь уверенно; остальное —
# только когда оно прямо названо в требованиях (уверенность 0,9).
ДОВЕРИЕ = {
    "инструмент": 0.7,
    "технология": 0.7,
    "метод": 0.9,
    "язык": 0.9,
    "компетенция": 0.9,
}


def достойные(навыки: List[ИзвлечённыйНавык]) -> List[ИзвлечённыйНавык]:
    """Навыки, которым хватило уверенности для своего вида."""
    return [навык for навык in навыки if навык.уверенность >= ДОВЕРИЕ.get(навык.вид, 1.0)]


def полные_ключи(данные: Dict[str, Any]) -> Dict[str, Any]:
    """
    Ответ модели с короткими ключами — в вид, который знает контракт.

    Ответ с полными ключами проходит без изменений: так его пишут тесты
    и так могут отвечать другие поставщики.
    """
    if "s" not in данные:
        return данные
    сырые = данные.get("s")
    if not isinstance(сырые, list):
        raise ОтветСломан("в ответе нет списка навыков")
    навыки = []
    for i, сырой in enumerate(сырые):
        if not isinstance(сырой, dict):
            raise ОтветСломан(f"навык №{i + 1} не объект")
        навык = {КЛЮЧИ.get(ключ, ключ): значение for ключ, значение in сырой.items()}
        навык["вид"] = ВИДЫ_КРАТКО.get(навык.get("вид"), навык.get("вид"))
        навыки.append(навык)
    return {"навыки": навыки, "язык_текста": данные.get("l")}


def _без_повторов(ответ: ОтветИзвлечения) -> ОтветИзвлечения:
    """Один навык — одна запись: остаётся та, в которой модель увереннее."""
    лучшие: Dict[str, ИзвлечённыйНавык] = {}
    for навык in ответ.навыки:
        ключ = навык.название.strip().lower()
        if ключ not in лучшие or навык.уверенность > лучшие[ключ].уверенность:
            лучшие[ключ] = навык
    from dataclasses import replace

    return replace(ответ, навыки=list(лучшие.values()))


def разобрать(модель: Поставщик, название: str, описание: str, версия_промпта: str = ВЕРСИЯ_ПРОМПТА) -> Разбор:
    """
    Разобрать вакансию моделью.

    Raises:
        МодельНедоступна: модель не ответила — вакансия ждёт следующего прохода
        ОтветСломан: ответ не прошёл проверку — в базу не попадает ничего
    """
    ответ_модели = модель.ответить(промпт(версия_промпта), вход(название, описание), СХЕМА_ОТВЕТА, ГРАММАТИКА)
    ответ, отброшены = из_сырого(ответ_модели.текст, описание, модель.версия, версия_промпта)
    return Разбор(
        ответ=ответ, отброшены=отброшены,
        токенов_вход=ответ_модели.токенов_вход, токенов_выход=ответ_модели.токенов_выход,
        мс=ответ_модели.мс, сырой=ответ_модели.текст,
    )


