"""
Прогон обогащения: модель проходит по вакансиям, которым не хватило словаря.

Работает по базе, после сбора и отдельно от него: сбор о слое не знает.
В очередь идут вакансии с текстом, у которых словарь нашёл меньше трёх
навыков, — от свежих к старым: если бюджет кончится, кончится он на
менее важном.

Прерванный прогон не начинается заново. Разобранная вакансия несёт
отметку версии, которой разобрана, и в очередь больше не попадает;
ответ модели лежит в кэше, и повторный разбор того же текста её не
зовёт. Поэтому повторный прогон по тем же данным даёт тот же результат.

Что прогон пишет и чего не пишет. Навыки модели ложатся в
`vacancies.ai_skills` — отдельно от навыков словаря; в частоты и
медианы они не входят. Найденное вне словаря копится кандидатами.
"""

from __future__ import annotations

import json
import sqlite3
import time
from dataclasses import asdict, dataclass
from datetime import datetime
from typing import Any, Dict, List, Optional

from src.ai import кандидаты, кэш
from src.ai.бюджет import Бюджет
from src.ai.извлечение import ВЕРСИЯ_ПРОМПТА, ГРАММАТИКА, СХЕМА_ОТВЕТА, вход, из_сырого, промпт
from src.ai.поставщик import МодельНедоступна, Поставщик
from src.ai_contract import ОтветСломан
from src.texts import разжать
from src.utils import get_logger

logger = get_logger(__name__)

# Меньше скольких навыков должен был найти словарь, чтобы вакансия пошла
# к модели.
МАЛО_НАВЫКОВ = 3

# После скольких отказов модели подряд прогон останавливается: модель
# упала, и перебирать оставшуюся очередь незачем.
ОТКАЗОВ_ПОДРЯД = 3


@dataclass
class Итог:
    """Что сделал прогон — для вывода, журнала и следующего запуска."""

    отобрано: int = 0
    разобрано: int = 0
    из_кэша: int = 0
    вызовов: int = 0
    навыков: int = 0
    отброшено: int = 0
    кандидатов: int = 0
    сломанных: int = 0
    отказов: int = 0
    секунд: float = 0.0
    токенов_вход: int = 0
    токенов_выход: int = 0
    # Почему прогон кончился раньше очереди. Пусто — очередь пройдена.
    остановка: str = ""
    метка: str = ""

    def словарём(self) -> Dict[str, Any]:
        return asdict(self)


def версия_разбора(модель: Поставщик, версия_промпта: str = ВЕРСИЯ_ПРОМПТА) -> str:
    """Чем извлечено: модель, квант, рантайм и промпт одной строкой."""
    return f"{модель.версия}|{версия_промпта}"


УСЛОВИЕ_ОЧЕРЕДИ = (
    "v.text_hash IS NOT NULL AND v.text_hash != '' AND COALESCE(v.skill_count, 0) < ? "
    "AND COALESCE(v.off_query, 0) = 0 AND COALESCE(v.ai_version, '') != ?"
)


def сколько_ждёт(conn: sqlite3.Connection, версия: str) -> int:
    """Сколько вакансий ждут разбора этой версией."""
    return conn.execute(
        f"SELECT COUNT(*) FROM vacancies v JOIN vacancy_texts t ON t.text_hash = v.text_hash WHERE {УСЛОВИЕ_ОЧЕРЕДИ}",
        (МАЛО_НАВЫКОВ, версия),
    ).fetchone()[0]


def очередь(conn: sqlite3.Connection, версия: str, предел: Optional[int] = None) -> List[tuple]:
    """Вакансии на разбор: активные и свежие — первыми."""
    запрос = (
        "SELECT v.id, v.vacancy_id, v.vacancy_name, v.employer_name, t.body "
        f"FROM vacancies v JOIN vacancy_texts t ON t.text_hash = v.text_hash WHERE {УСЛОВИЕ_ОЧЕРЕДИ} "
        "ORDER BY COALESCE(v.is_active, 1) DESC, v.first_seen_at DESC, v.id DESC"
    )
    параметры: tuple = (МАЛО_НАВЫКОВ, версия)
    if предел:
        запрос += " LIMIT ?"
        параметры += (предел,)
    return conn.execute(запрос, параметры).fetchall()


def провести(
    conn: sqlite3.Connection,
    модель: Поставщик,
    бюджет: Optional[Бюджет] = None,
    *,
    предел: Optional[int] = None,
    версия_промпта: str = ВЕРСИЯ_ПРОМПТА,
    ход=None,
) -> Итог:
    """
    Пройти очередь, пока есть бюджет.

    Args:
        conn: Соединение с базой. Запись подтверждается после каждой
            вакансии: прерванный прогон теряет не больше одной
        бюджет: Пределы прогона; без него очередь проходится целиком
        предел: Сколько вакансий взять из очереди
        ход: Необязательная функция `(номер, всего, итог)` — для вывода

    Returns:
        Итог прогона. Исключения модели наружу не выходят: отказ модели —
        не отказ прогона.
    """
    бюджет = бюджет or Бюджет()
    версия = версия_разбора(модель, версия_промпта)
    метка = datetime.now().strftime("%Y%m%d_%H%M%S")
    итог = Итог(метка=метка)
    начало = time.monotonic()

    строки = очередь(conn, версия, предел)
    итог.отобрано = len(строки)
    знает = кандидаты.известные()
    инструкция = промпт(версия_промпта)
    подряд = 0

    for номер, (ид, вакансия, название, работодатель, тело) in enumerate(строки, 1):
        описание = разжать(тело)
        текст = вход(название or "", описание)

        сырой = кэш.найти(conn, текст, модель.версия, версия_промпта)
        из_кэша = сырой is not None
        расход = None

        if not из_кэша:
            причина = бюджет.исчерпан()
            if причина:
                итог.остановка = причина
                break
            try:
                расход = модель.ответить(инструкция, текст, СХЕМА_ОТВЕТА, ГРАММАТИКА)
            except МодельНедоступна as e:
                # Вакансия остаётся неразобранной и попадёт в следующий
                # проход. Но если модель молчит раз за разом — она
                # упала, и очередь перебирать незачем.
                итог.отказов += 1
                подряд += 1
                logger.warning(f"Модель не разобрала вакансию {вакансия}: {e}")
                if подряд >= ОТКАЗОВ_ПОДРЯД:
                    итог.остановка = f"модель не отвечает ({подряд} отказа подряд)"
                    break
                continue
            подряд = 0
            бюджет.учесть_вызов()
            итог.вызовов += 1
            итог.токенов_вход += расход.токенов_вход
            итог.токенов_выход += расход.токенов_выход
            сырой = расход.текст

        try:
            ответ, отброшены = из_сырого(сырой, описание, модель.версия, версия_промпта)
            навыки = ответ.навыки
        except ОтветСломан as e:
            # Ответ не прошёл проверку: в базу не попадает ничего. Версия
            # всё равно отмечается — при нулевой температуре модель
            # ответит так же, и без отметки вакансия возвращалась бы в
            # очередь при каждом прогоне.
            logger.warning(f"Ответ модели по вакансии {вакансия} отброшен целиком: {e}")
            итог.сломанных += 1
            навыки, отброшены = None, []

        if расход is not None:
            кэш.записать(
                conn, текст, модель.версия, версия_промпта, сырой,
                токенов_вход=расход.токенов_вход, токенов_выход=расход.токенов_выход, мс=расход.мс,
                навыков=len(навыки or []), отброшено=len(отброшены), прогон=метка,
            )
            # Каждый вызов — строкой в журнале: траты видны по прогонам.
            logger.info(
                f"Разбор {вакансия}: {расход.токенов_вход}+{расход.токенов_выход} токенов, "
                f"{расход.мс} мс, навыков {len(навыки or [])}, отброшено {len(отброшены)}"
            )
        else:
            итог.из_кэша += 1

        записано = None if навыки is None else json.dumps(
            [
                {"название": н.название, "как_в_тексте": н.как_в_тексте, "вид": н.вид,
                 "уверенность": round(н.уверенность, 2), "родитель": н.родитель}
                for н in навыки
            ],
            ensure_ascii=False,
        )
        conn.execute("UPDATE vacancies SET ai_skills = ?, ai_version = ? WHERE id = ?", (записано, версия, ид))

        # Вакансию могли разбирать прежней версией: её прежние находки
        # не должны остаться встречами кандидатов, которых новая версия
        # в ней уже не видит.
        кандидаты.забыть_вакансию(conn, вакансия)
        if навыки:
            итог.кандидатов += кандидаты.учесть(conn, вакансия, работодатель or "", навыки, знает)
        conn.commit()

        итог.разобрано += 1
        итог.навыков += len(навыки or [])
        итог.отброшено += len(отброшены)
        if ход is not None:
            ход(номер, len(строки), итог)

    итог.секунд = round(time.monotonic() - начало, 1)
    logger.info(
        f"Прогон обогащения {метка}: разобрано {итог.разобрано} из {итог.отобрано}, вызовов {итог.вызовов}, "
        f"из кэша {итог.из_кэша}, навыков {итог.навыков}, кандидатов {итог.кандидатов}, отброшено {итог.отброшено}, "
        f"сломанных {итог.сломанных}, отказов {итог.отказов}, {итог.секунд} с"
        + (f"; остановлен: {итог.остановка}" if итог.остановка else "")
    )
    return итог
