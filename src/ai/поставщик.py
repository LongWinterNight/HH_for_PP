"""
Поставщик модели: один вызов — один ответ.

Остальной слой не знает, какая модель отвечает и как до неё достучаться.
Он знает три вещи: у поставщика есть версия, поставщик принимает
инструкцию, текст и схему ответа, и поставщик может отказать. Отсюда
смена модели — это смена одной реализации, а тесты идут на заглушке:
без видеокарты, без сети и за миллисекунды.

Формат ответа держит не просьба в промпте, а грамматика рантайма:
`llama.cpp` получает схему JSON и не может выдать токен, который её
нарушает. Сломанный JSON невозможен по построению. Это и защита от
второй беды локальных моделей — «не останавливается»: объект по схеме
конечен, а предел вывода стоит рядом.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass
from typing import Any, Callable, Dict, List, Optional, Protocol

import requests

from src.utils import get_logger

logger = get_logger(__name__)


class МодельНедоступна(RuntimeError):
    """
    Модель не ответила: не поднята, упала, не уложилась во время.

    Отказ модели — не отказ прогона: вакансия остаётся неразобранной и
    попадёт в следующий проход.
    """


@dataclass(frozen=True)
class ОтветМодели:
    """Что вернула модель и во что это обошлось."""

    текст: str
    токенов_вход: int = 0
    токенов_выход: int = 0
    мс: int = 0


class Поставщик(Protocol):
    """Интерфейс модели. Реализация меняется без правки остального слоя."""

    # Модель, квант и рантайм одной строкой. Уходит в ключ кэша и в
    # запись о разборе: после смены любого из трёх прошлые числа
    # остаются объяснимыми.
    версия: str

    def ответить(self, инструкция: str, текст: str, схема: Dict[str, Any], грамматика: str = "") -> ОтветМодели:
        """
        Один вызов. Бросает `МодельНедоступна`, если ответа нет.

        Формат ответа задан дважды: схемой JSON — её понимает любой
        поставщик — и грамматикой рантайма, которая строже: она не
        оставляет модели места даже на пробелы.
        """
        ...


class LlamaСервер:
    """
    Модель за `llama-server` на этой же машине.

    Сервер говорит на том же языке, что облачные поставщики
    (`/v1/chat/completions`), поэтому переезд на другой рантайм с тем же
    интерфейсом — смена адреса.
    """

    def __init__(
        self,
        адрес: str,
        версия: str,
        *,
        предел_вывода: int = 1200,
        ожидание: float = 300.0,
        без_рассуждений: bool = True,
    ) -> None:
        self.адрес = адрес.rstrip("/")
        self.версия = версия
        self.предел_вывода = предел_вывода
        self.ожидание = ожидание
        self.без_рассуждений = без_рассуждений

    def ответить(self, инструкция: str, текст: str, схема: Dict[str, Any], грамматика: str = "") -> ОтветМодели:
        запрос: Dict[str, Any] = {
            "messages": [
                {"role": "system", "content": инструкция},
                {"role": "user", "content": текст},
            ],
            # Ноль и постоянное зерно: один текст — один ответ. Числа,
            # которые меняются между прогонами без новых вакансий, — та
            # болезнь, из-за которой убрали среднюю зарплату.
            "temperature": 0,
            "seed": 0,
            "max_tokens": self.предел_вывода,
        }
        if грамматика:
            # Своя грамматика вместо построенной по схеме: та разрешает
            # пробелы и переносы, и модель тратила на отступы треть
            # вывода.
            запрос["grammar"] = грамматика
        else:
            запрос["response_format"] = {
                "type": "json_schema",
                "json_schema": {"name": "извлечение", "strict": True, "schema": схема},
            }
        if self.без_рассуждений:
            # Разметчику рассуждать вслух незачем: это токены, которые
            # не попадают в ответ, и время, которое стоит полный прогон.
            запрос["chat_template_kwargs"] = {"enable_thinking": False}

        начало = time.monotonic()
        try:
            ответ = requests.post(
                f"{self.адрес}/v1/chat/completions", json=запрос, timeout=self.ожидание,
                # Модель живёт на этой машине: системный прокси для
                # обращения к ней не нужен и только мешает.
                proxies={"http": None, "https": None},
            )
        except requests.RequestException as e:
            raise МодельНедоступна(f"модель не отвечает: {type(e).__name__}") from e
        мс = int((time.monotonic() - начало) * 1000)

        if ответ.status_code != 200:
            raise МодельНедоступна(f"модель ответила кодом {ответ.status_code}: {ответ.text[:200]}")
        try:
            данные = ответ.json()
            выбор = данные["choices"][0]
            содержимое = выбор["message"]["content"] or ""
        except (ValueError, KeyError, IndexError, TypeError) as e:
            raise МодельНедоступна(f"ответ модели не разобран: {type(e).__name__}") from e

        if выбор.get("finish_reason") == "length":
            # Вывод упёрся в предел: объект оборван, и разбирать его
            # половину запрещено контрактом.
            raise МодельНедоступна(f"ответ не уместился в {self.предел_вывода} токенов")

        расход = данные.get("usage") or {}
        return ОтветМодели(
            текст=содержимое,
            токенов_вход=int(расход.get("prompt_tokens") or 0),
            токенов_выход=int(расход.get("completion_tokens") or 0),
            мс=мс,
        )

    def жив(self) -> bool:
        try:
            ответ = requests.get(f"{self.адрес}/health", timeout=3, proxies={"http": None, "https": None})
            return ответ.status_code == 200
        except requests.RequestException:
            return False


class Заглушка:
    """
    Поставщик для тестов: отвечает заготовленным и считает вызовы.

    Ответ задаётся функцией от текста вакансии — так тест проверяет не
    «модель вызвана», а что слой делает с конкретным ответом.
    """

    def __init__(
        self,
        ответ: Optional[Callable[[str], Any]] = None,
        версия: str = "заглушка:1",
    ) -> None:
        self.версия = версия
        self._ответ = ответ or (lambda текст: "ru\n")
        self.вызовы: List[str] = []

    def ответить(self, инструкция: str, текст: str, схема: Dict[str, Any], грамматика: str = "") -> ОтветМодели:
        self.вызовы.append(текст)
        итог = self._ответ(текст)
        if isinstance(итог, Exception):
            raise итог
        содержимое = итог if isinstance(итог, str) else json.dumps(итог, ensure_ascii=False)
        return ОтветМодели(текст=содержимое, токенов_вход=len(текст) // 3, токенов_выход=len(содержимое) // 3, мс=1)
