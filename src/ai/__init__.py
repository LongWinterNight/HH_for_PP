"""
Слой понимания текста: модель читает вакансию и достаёт навыки,
которых словарь достать не может.

Границы полномочий слоя заданы решением S9‑6a и держатся кодом:

- модель не пишет числа в аналитику. Её находки лежат отдельно от
  навыков словаря (`vacancies.ai_skills`) и в частоты не входят;
- главный продукт слоя — кандидат в словарь. Найденное у трёх разных
  работодателей и подтверждённое человеком становится обычной позицией
  словаря и дальше находится без модели;
- ответ модели не попадает в базу напрямую — только через проверку
  схемой и проверку цитаты по тексту (`src/ai_contract.py`).

Модель локальная: тексты вакансий никуда не уходят.

Смена модели или промпта без прогона замера не принимается (S10‑9d):
    python scripts/maintenance/замер_извлечения.py --эталон --режим вместе
"""

from __future__ import annotations

import os


def включён() -> bool:
    """
    Включён ли слой.

    Выключенный слой не ломает ничего: продукт работает на словаре, как
    работал до него. По умолчанию слой выключен — включается он решением,
    принятым по замеру (S10‑9c), а не самим фактом установки модели.
    """
    return os.getenv("AI_LAYER", "0").strip().lower() in ("1", "true", "on", "да")
