"""
Кандидаты в словарь: главный продукт слоя понимания текста.

Модель находит в вакансии навык, которого словарь не знает. Такой навык
не уходит в аналитику и не теряется — он копится кандидатом. Когда он
встретился у трёх разных работодателей, его показывают человеку вместе
с цитатами, из которых он получен. Подтверждённый кандидат становится
обычной позицией словаря, и дальше его находит детерминированный код:
бесплатно и одинаково при каждом прогоне. Со временем модель работает
только по краю нового.

Порог «три работодателя», а не «три вакансии»: одна компания, разместив
вакансию в тридцати городах, тридцать раз повторяет одну свою опечатку.
"""

from __future__ import annotations

import re
import sqlite3
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

import yaml

from src import skills_store
from src.ai_contract import ИзвлечённыйНавык
from src.utils import get_logger

logger = get_logger(__name__)

# Сколько разных работодателей должны назвать навык, прежде чем он
# показывается человеку.
ПОРОГ_РАБОТОДАТЕЛЕЙ = 3

# Сколько цитат показывается у кандидата.
ЦИТАТ = 5

НОВЫЙ, ПОДТВЕРЖДЁН, ОТКЛОНЁН, СЛИТ = "new", "confirmed", "rejected", "merged"

# Раздел у кандидата, ставшего написанием навыка словаря, а не своей позицией.
НАПИСАНИЕ = "synonym"

# Встречи кандидата вместе со встречами слитых в него. Ключ группы —
# кандидат‑канон: у слитого это его цель, у прочих — он сам. Одна вакансия,
# где встретились и «ИИ», и «AI», считается в группе один раз.
#
# Встречи сводятся по группам до соединения с кандидатами, а не после.
# Соединение по вычисляемому ключу группы индексом не пользуется: на
# рабочей базе это 9 769 кандидатов на 23 601 встречу, и список отвечал
# 94 секунды. Сведённые итоги — по строке на группу, и база соединяет их
# с кандидатами через автоматический индекс.
ВСТРЕЧИ_ГРУПП = """
    WITH встречи AS (
        SELECT CASE WHEN m.status = 'merged' THEN m.target ELSE m.name_key END AS гр,
               h.vacancy_id, h.employer
        FROM skill_candidate_hits h JOIN skill_candidates m ON m.name_key = h.name_key
    ),
    итоги AS (
        SELECT гр, COUNT(DISTINCT vacancy_id) AS встреч,
               COUNT(DISTINCT NULLIF(LOWER(TRIM(employer)), '')) AS работодателей
        FROM встречи GROUP BY гр
    )
"""

# В какой раздел словаря идёт навык каждого вида. Раздел можно
# переопределить при подтверждении: вид назвала модель, а решает человек.
РАЗДЕЛ_ПО_ВИДУ = {
    "инструмент": "tools",
    "технология": "hard",
    "метод": "hard",
    "язык": "hard",
    "компетенция": "soft",
}


def ключ(название: str) -> str:
    """По чему кандидат узнаётся: «Figma» и «figma » — один кандидат."""
    return " ".join((название or "").lower().split())


def известные(словарь: Optional[Dict[str, Any]] = None) -> set:
    """Всё, что словарь уже знает: каноны и варианты написания."""
    словарь = словарь or skills_store.загрузить()
    знает = {ключ(имя) for имя in skills_store.известные_названия(словарь)}
    знает |= {ключ(вариант) for вариант in skills_store.таблица_синонимов(словарь)}
    return знает


def учесть(
    conn: sqlite3.Connection,
    вакансия: str,
    работодатель: str,
    навыки: Iterable[ИзвлечённыйНавык],
    знает: Optional[set] = None,
) -> int:
    """
    Запомнить, что навыки встречены в вакансии.

    Навык, который словарь уже знает, кандидатом не становится. Отклонённый
    кандидат продолжает копить встречи, но человеку больше не показывается:
    так видно, что отклонённое продолжает встречаться, и решение можно
    пересмотреть.

    Returns:
        Сколько навыков учтено как кандидаты
    """
    знает = известные() if знает is None else знает
    сейчас = datetime.now().isoformat(sep=" ")
    учтено = 0
    for навык in навыки:
        имя = ключ(навык.название)
        if not имя or имя in знает:
            continue
        conn.execute(
            "INSERT INTO skill_candidates (name_key, name, kind, status, created_at) VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT (name_key) DO NOTHING",
            (имя, навык.название.strip(), навык.вид, НОВЫЙ, сейчас),
        )
        # Пара «кандидат — вакансия» одна: повторный прогон по той же
        # вакансии счётчик не увеличивает.
        conn.execute(
            "INSERT INTO skill_candidate_hits (name_key, vacancy_id, employer, quote, created_at) VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT (name_key, vacancy_id) DO UPDATE SET quote = excluded.quote, employer = excluded.employer",
            (имя, str(вакансия), (работодатель or "").strip(), навык.как_в_тексте.strip()[:300], сейчас),
        )
        учтено += 1
    return учтено


def забыть_вакансию(conn: sqlite3.Connection, вакансия: str) -> None:
    """Убрать встречи вакансии: её разбирают заново, и прежние находки могут не повториться."""
    conn.execute("DELETE FROM skill_candidate_hits WHERE vacancy_id = ?", (str(вакансия),))


def совпадает(запрос: str, название: str) -> bool:
    """
    Подходит ли название под строку поиска.

    Короткий запрос ищется по началу слова, длинный — где угодно: иначе
    «ии» находит «Интеграции», а «ai» — «Rails» и «Tailwind».
    """
    запрос, название = ключ(запрос), ключ(название)
    if len(запрос) >= 3:
        return запрос in название
    return re.search(rf"(?<![a-zа-яё0-9]){re.escape(запрос)}", название) is not None


def _группы(
    conn: sqlite3.Connection,
    статус: str,
    порог: int,
    поиск: Optional[str] = None,
) -> List[tuple]:
    """
    Кандидаты состояния со встречами своей группы — все, без цитат.

    Требования к кандидату («Высшее образование»), записанные до появления
    проверки на них, отбрасываются здесь, а не при показе: иначе сводка
    считала бы их, а список — нет, и числа на экране расходились бы.
    """
    # Поиск — здесь же, а не условием в базе: подзапрос по слитым написаниям
    # перебирал все пары кандидатов и шёл тринадцать секунд. Ищется и по
    # слитым: «AI» находит канон «ИИ-инструменты».
    найденные = None
    if поиск and ключ(поиск):
        найденные = {к for (к,) in conn.execute("SELECT name_key FROM skill_candidates") if совпадает(поиск, к)}
        найденные |= {
            цель for к, цель in conn.execute("SELECT name_key, target FROM skill_candidates WHERE status = ?", (СЛИТ,))
            if к in найденные
        }
    # Итоги групп и кандидаты читаются двумя запросами и соединяются здесь,
    # словарём по ключу. Соединение в базе индекса не получало: план
    # показывал «SCAN итоги» на каждого кандидата, и запрос шёл шесть
    # секунд вместо десятой доли.
    итоги = {
        группа: (встреч, работодателей)
        for группа, встреч, работодателей in conn.execute(ВСТРЕЧИ_ГРУПП + "SELECT гр, встреч, работодателей FROM итоги")
    }
    нужно = порог if статус == НОВЫЙ else 0

    from src.ai.извлечение import похоже_на_требование

    строки = []
    for с in conn.execute(
        "SELECT name_key, name, kind, status, section, decided_at, target FROM skill_candidates WHERE status = ?",
        (статус,),
    ):
        if найденные is not None and с[0] not in найденные:
            continue
        встреч, работодателей = итоги.get(с[0], (0, 0))
        if работодателей < нужно or (с[3] == НОВЫЙ and похоже_на_требование(с[1])):
            continue
        строки.append((*с, встреч, работодателей))
    строки.sort(key=lambda с: (-с[8], -с[7], с[1]))
    return строки


def список(
    conn: sqlite3.Connection,
    статус: str = НОВЫЙ,
    порог: int = ПОРОГ_РАБОТОДАТЕЛЕЙ,
    предел: int = 200,
    смещение: int = 0,
    поиск: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """
    Кандидаты с числом встреч, числом работодателей и цитатами.

    Для новых применяется порог: опечатка одного объявления до человека
    не доходит. Для решённых порога нет — решение уже принято. Встречи
    и цитаты считаются вместе со слитыми в кандидата написаниями: «ИИ»,
    слитый в «ИИ-инструменты», прибавляет свои вакансии к канону.
    """
    итог = []
    for имя, название, вид, состояние, раздел, решён, цель, встреч, работодателей in \
            _группы(conn, статус, порог, поиск)[смещение:смещение + предел]:
        слитые = написания(conn, имя)
        ключи = [имя] + [с["ключ"] for с in слитые]
        цитаты = [
            {"цитата": цитата, "работодатель": работодатель, "вакансия": вакансия}
            for цитата, работодатель, вакансия in conn.execute(
                "SELECT quote, employer, vacancy_id FROM skill_candidate_hits "
                f"WHERE name_key IN ({','.join('?' * len(ключи))}) "
                "GROUP BY LOWER(TRIM(employer)) ORDER BY created_at DESC LIMIT ?",
                (*ключи, ЦИТАТ),
            )
        ]
        итог.append({
            "ключ": имя, "название": название, "вид": вид, "статус": состояние,
            "раздел": раздел or РАЗДЕЛ_ПО_ВИДУ.get(вид or "", "hard"),
            "встреч": встреч, "работодателей": работодателей, "цитаты": цитаты, "решён": решён,
            # Во что ушёл решённый как написание: канон словаря.
            "цель": цель if раздел == НАПИСАНИЕ else None,
            "написания": [с["название"] for с in слитые],
        })
    return итог


def написания(conn: sqlite3.Connection, имя: str) -> List[Dict[str, str]]:
    """Кандидаты, слитые в этого: его другие написания."""
    return [
        {"ключ": ключ_, "название": название}
        for ключ_, название in conn.execute(
            "SELECT name_key, name FROM skill_candidates WHERE status = ? AND target = ? ORDER BY name",
            (СЛИТ, ключ(имя)),
        )
    ]


def сколько(conn: sqlite3.Connection, статус: str = НОВЫЙ, порог: int = ПОРОГ_РАБОТОДАТЕЛЕЙ,
            поиск: Optional[str] = None) -> int:
    """Сколько кандидатов в списке без порций: для листания."""
    return len(_группы(conn, статус, порог, поиск))


def сводка(conn: sqlite3.Connection, порог: int = ПОРОГ_РАБОТОДАТЕЛЕЙ) -> Dict[str, int]:
    """
    Сколько кандидатов всего, сколько ждут решения и сколько решено.

    «Ждут решения» считается тем же правилом, что и список: до этого
    сводка говорила 81, а показывалось 76 (S10‑12h).
    """
    по_статусам = dict(conn.execute("SELECT status, COUNT(*) FROM skill_candidates GROUP BY status"))
    return {
        "новых": по_статусам.get(НОВЫЙ, 0), "ждут_решения": сколько(conn, НОВЫЙ, порог),
        "подтверждено": по_статусам.get(ПОДТВЕРЖДЁН, 0), "отклонено": по_статусам.get(ОТКЛОНЁН, 0),
        "слито": по_статусам.get(СЛИТ, 0),
    }


def отклонить(conn: sqlite3.Connection, имя: str) -> bool:
    """
    Отклонить кандидата: он запоминается и больше не предлагается.

    Слитые в него написания отклоняются вместе с ним: «не навык» про канон
    значит то же и про его другие написания.
    """
    принято = _решить(conn, имя, ОТКЛОНЁН, None)
    if принято:
        for слитый in написания(conn, имя):
            _решить(conn, слитый["ключ"], ОТКЛОНЁН, None, цель=ключ(имя))
    return принято


def подтвердить(
    conn: sqlite3.Connection,
    имя: str,
    раздел: Optional[str] = None,
    название: Optional[str] = None,
    файл_словаря: Optional[Path] = None,
) -> bool:
    """
    Подтвердить кандидата: навык уходит в словарь.

    Сначала словарь, потом отметка в базе: кандидат, помеченный
    подтверждённым, но не попавший в словарь, исчез бы из очереди и не
    стал бы находиться — худший из двух возможных обрывов.

    Слитые в кандидата написания уходят в словарь вместе с ним: в раздел —
    чтобы находиться в тексте, и под канон в `synonyms` — чтобы считаться
    одним навыком с ним.

    Args:
        раздел: hard / soft / tools; по умолчанию — по виду навыка
        название: как записать в словарь, если человек поправил написание
    """
    строка = conn.execute(
        "SELECT name, kind, status FROM skill_candidates WHERE name_key = ?", (ключ(имя),)
    ).fetchone()
    if not строка or строка[2] == СЛИТ:
        return False
    раздел = раздел or РАЗДЕЛ_ПО_ВИДУ.get(строка[1] or "", "hard")
    if раздел not in skills_store.РАЗДЕЛЫ:
        raise ValueError(f"Раздела «{раздел}» в словаре нет")

    канон = название or строка[0]
    слитые = написания(conn, имя)
    в_словарь(канон, раздел, файл_словаря)
    if слитые:
        for слитый in слитые:
            в_словарь(слитый["название"], раздел, файл_словаря)
        skills_store.в_синонимы(skills_store.для_показа(канон), [канон] + [с["название"] for с in слитые],
                                файл_словаря)
    принято = _решить(conn, имя, ПОДТВЕРЖДЁН, раздел)
    for слитый in слитые:
        _решить(conn, слитый["ключ"], ПОДТВЕРЖДЁН, раздел, цель=ключ(имя))
    return принято


def слить(conn: sqlite3.Connection, имя: str, в: str) -> bool:
    """
    Кандидат — другое написание кандидата `в`.

    Встречи обоих дальше считаются вместе, под каноном `в`; при
    подтверждении канона написание уходит в словарь вместе с ним.
    Цепочек не бывает: если `в` сам слит, цель — его канон; написания,
    слитые в `имя`, переезжают туда же.

    Returns:
        Слит ли кандидат (False — одного из двух нет, они совпадают или
        цель уже решена)
    """
    откуда, куда = ключ(имя), ключ(в)
    цель = conn.execute("SELECT name_key, status, target FROM skill_candidates WHERE name_key = ?", (куда,)).fetchone()
    исходный = conn.execute("SELECT status FROM skill_candidates WHERE name_key = ?", (откуда,)).fetchone()
    if not цель or not исходный or откуда == куда:
        return False
    if цель[1] == СЛИТ:
        куда = цель[2]
        цель = conn.execute("SELECT name_key, status, target FROM skill_candidates WHERE name_key = ?", (куда,)).fetchone()
    if not цель or цель[1] != НОВЫЙ or откуда == куда or исходный[0] != НОВЫЙ:
        return False
    сейчас = datetime.now().isoformat(sep=" ")
    conn.execute("UPDATE skill_candidates SET target = ? WHERE status = ? AND target = ?", (куда, СЛИТ, откуда))
    conn.execute(
        "UPDATE skill_candidates SET status = ?, target = ?, section = NULL, decided_at = ? WHERE name_key = ?",
        (СЛИТ, куда, сейчас, откуда),
    )
    return True


def написание_навыка(
    conn: sqlite3.Connection,
    имя: str,
    навык: str,
    файл_словаря: Optional[Path] = None,
) -> bool:
    """
    Кандидат — написание навыка, который словарь уже знает.

    Строка уходит в словарь не новой позицией, а написанием известного
    навыка: в его раздел — чтобы находиться в тексте, и под его канон в
    `synonyms` — чтобы считаться им. Слитые в кандидата написания уходят
    туда же.

    Raises:
        ValueError: навыка в словаре нет — тогда кандидата подтверждают
            своей позицией или сливают с другим кандидатом
    """
    строка = conn.execute(
        "SELECT name, status FROM skill_candidates WHERE name_key = ?", (ключ(имя),)
    ).fetchone()
    if not строка or строка[1] != НОВЫЙ:
        return False

    словарь = skills_store.загрузить(файл_словаря)
    цель = ключ(навык)
    раздел = next((р for р in skills_store.РАЗДЕЛЫ if цель in {ключ(н) for н in словарь.get(р) or []}), None)
    таблица = skills_store.таблица_синонимов(словарь)
    if раздел is None and цель in таблица:
        канон_ = таблица[цель]
        раздел = next((р for р in skills_store.РАЗДЕЛЫ if ключ(канон_) in {ключ(н) for н in словарь.get(р) or []}), None)
    if раздел is None:
        raise ValueError(f"Навыка «{навык}» в словаре нет")

    канон = skills_store.для_показа(навык, таблица)
    слитые = написания(conn, имя)
    названия = [строка[0]] + [с["название"] for с in слитые]
    for название in названия:
        в_словарь(название, раздел, файл_словаря)
    skills_store.в_синонимы(канон, названия, файл_словаря)
    сбросить_память_словаря()

    принято = _решить(conn, имя, ПОДТВЕРЖДЁН, НАПИСАНИЕ, цель=канон)
    for слитый in слитые:
        _решить(conn, слитый["ключ"], ПОДТВЕРЖДЁН, НАПИСАНИЕ, цель=канон)
    return принято


def _решить(conn: sqlite3.Connection, имя: str, статус: str, раздел: Optional[str],
            цель: Optional[str] = None) -> bool:
    курсор = conn.execute(
        "UPDATE skill_candidates SET status = ?, section = ?, target = COALESCE(?, target), decided_at = ? "
        "WHERE name_key = ?",
        (статус, раздел, цель, datetime.now().isoformat(sep=" "), ключ(имя)),
    )
    return курсор.rowcount > 0


def в_словарь(название: str, раздел: str, файл: Optional[Path] = None) -> bool:
    """
    Дописать навык в раздел словаря.

    Строка вставляется в конец раздела, а файл не переписывается целиком:
    словарь правят и руками, и перезапись через сериализатор поменяла бы
    в нём всё оформление разом — в истории изменений одна новая строка
    утонула бы в тысяче переформатированных.

    Returns:
        Добавлен ли навык (False — он там уже есть)
    """
    файл = файл or skills_store.ПУТЬ_СЛОВАРЯ
    запись = ключ(название)
    if not запись:
        raise ValueError("У навыка пустое название")

    словарь = skills_store.загрузить(файл)
    if запись in {ключ(имя) for имя in словарь.get(раздел) or []}:
        return False

    строки = файл.read_text(encoding="utf-8").split("\n")
    начало = next((i for i, строка in enumerate(строки) if строка.rstrip() == f"{раздел}:"), None)
    if начало is None:
        raise ValueError(f"В файле словаря нет раздела «{раздел}»")
    # Раздел кончается там, где начинается следующий ключ верхнего уровня.
    конец = next(
        (i for i in range(начало + 1, len(строки)) if строки[i] and not строки[i].startswith((" ", "-", "#"))),
        len(строки),
    )
    while конец > начало + 1 and not строки[конец - 1].strip():
        конец -= 1

    # Сериализатор нужен ради кавычек: «c#» и «1с: бухгалтерия» без них
    # читаются не как строка.
    новая = yaml.safe_dump([запись], allow_unicode=True, default_flow_style=False).rstrip("\n")
    строки.insert(конец, новая)
    файл.write_text("\n".join(строки), encoding="utf-8")

    сбросить_память_словаря()
    logger.info(f"Словарь навыков: в раздел {раздел} добавлено «{запись}»")
    return True


