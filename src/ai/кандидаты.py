# Слова, по которым похожесть не считается: они есть в половине названий
# и сводили бы «Работа с CRM» с «Работа в команде».
ОБЩИЕ_СЛОВА = {
    "работа", "работы", "опыт", "знание", "знания", "умение", "навык", "навыки", "владение",
    "and", "the", "for", "with", "для", "при", "над", "под", "или", "как",
}

# Одно и то же, написанное разными алфавитами. Не правило слияния — только
# подсказка: решает человек.
ЗАМЕНЫ = (("искусственный интеллект", "ai"), ("ии", "ai"), ("джава", "java"), ("питон", "python"))

СЛОВО = re.compile(r"[a-zа-яё0-9+#]+")


def скелет(название: str) -> str:
    """
    «ИИ-инструменты» → «aiинструменты»: без регистра, пробелов, дефисов и точек.

    Для подсказки, а не для слияния: у «C#» и «C++» скелет разный, но у
    «Vue.js» и «VueJS» одинаковый — то, что и нужно предложить человеку.
    """
    текст = ключ(название)
    for было, стало in ЗАМЕНЫ:
        текст = re.sub(rf"(?<![a-zа-яё]){было}(?![a-zа-яё])", стало, текст)
    return re.sub(r"[\s\-._/]+", "", текст)


def _слова(название: str) -> set:
    текст = ключ(название)
    for было, стало in ЗАМЕНЫ:
        текст = re.sub(rf"(?<![a-zа-яё]){было}(?![a-zа-яё])", стало, текст)
    return {с for с in СЛОВО.findall(текст) if len(с) >= 3 and с not in ОБЩИЕ_СЛОВА} | (
        {с for с in СЛОВО.findall(текст) if с in ("ai", "ml", "bi", "qa", "ux", "ui")}
    )


class Похожие:
    """
    Подсказки «это может быть то же самое» для экрана кандидатов.

    Индекс строится один раз на запрос: слово → названия. Похожими
    считаются названия с тем же скелетом («Vue.js» и «VueJS») и с общим
    значимым словом («Tool Calling» и «Tool use»). Первыми идут совпавшие
    по скелету, затем — по числу общих слов, затем более частые.
    """

    def __init__(self, словарь_навыков: Iterable[str], кандидаты_: Iterable[Dict[str, Any]]):
        self.записи: List[Dict[str, Any]] = []
        видели = set()
        for название in словарь_навыков:
            к = ключ(название)
            if к and к not in видели:
                видели.add(к)
                self.записи.append({"название": название, "ключ": к, "откуда": "словарь", "работодателей": None})
        for кандидат in кандидаты_:
            к = кандидат["ключ"]
            if к not in видели:
                видели.add(к)
                self.записи.append({"название": кандидат["название"], "ключ": к, "откуда": "кандидат",
                                    "работодателей": кандидат.get("работодателей")})
        self.по_скелету: Dict[str, List[int]] = {}
        self.по_слову: Dict[str, List[int]] = {}
        for номер, запись in enumerate(self.записи):
            запись["слова"] = _слова(запись["название"])
            self.по_скелету.setdefault(скелет(запись["название"]), []).append(номер)
            for слово in запись["слова"]:
                self.по_слову.setdefault(слово, []).append(номер)

    def для(self, название: str, предел: int = 6) -> List[Dict[str, Any]]:
        свой = ключ(название)
        слова = _слова(название)
        баллы: Dict[int, tuple] = {}
        for номер in self.по_скелету.get(скелет(название), []):
            баллы[номер] = (1, 0)
        for слово in слова:
            # Слово, общее для сотни названий, ничего не говорит о похожести.
            номера = self.по_слову.get(слово, [])
            if len(номера) > 60:
                continue
            for номер in номера:
                скел, общих = баллы.get(номер, (0, 0))
                баллы[номер] = (скел, общих + 1)
        итог = []
        for номер, (скел, общих) in баллы.items():
            запись = self.записи[номер]
            if запись["ключ"] == свой:
                continue
            итог.append((скел, общих, запись["работодателей"] or 0, запись))
        итог.sort(key=lambda т: (-т[0], -т[1], -т[2], т[3]["название"]))
        return [
            {"название": з["название"], "ключ": з["ключ"], "откуда": з["откуда"], "работодателей": з["работодателей"]}
            for _, _, _, з in итог[:предел]
        ]
