# Чем разбирать, пока выбор по замеру не записан настройкой.
# Выбор сделан замером на ста вакансиях эталона (data-issues.md, запись
# от 12.10.2026): тернарная модель нашла больше обеих моделей Qwen3,
# ошиблась реже и отвечает втрое быстрее — она целиком помещается на
# карту, а не делит себя с оперативной памятью.
ПО_УМОЛЧАНИЮ = "bonsai2-27b"


# Сколько памяти видеокарты должно быть свободно сверх размера самой
# модели, чтобы считать на карте: контекст и рабочая область рантайма.
# Меньше — модель ляжет в общую память карты и системы, и скорость
# упадёт в десять раз (так было 12.10.2026 под игрой).
ЗАПАС_КАРТЫ_МБ = 1500


def память_карты() -> Optional[tuple]:
    """
    Занято и всего на видеокарте, в мегабайтах. None — узнать не удалось.

    Спрашивается у `nvidia-smi`: ему видна память всех программ, а не
    только нашей.
    """
    try:
        ответ = subprocess.run(
            ["nvidia-smi", "--query-gpu=memory.used,memory.total", "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=15,
            # Без окна: прогон без консоли получал мелькающее окно
            # nvidia-smi перед каждой порцией, раз в три минуты.
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        занято, всего = (int(часть.strip()) for часть in ответ.stdout.strip().splitlines()[0].split(","))
    except (OSError, subprocess.SubprocessError, ValueError, IndexError):
        return None
    return занято, всего


def карта_свободна(кандидат: Optional[Кандидат] = None, память=память_карты) -> bool:
    """
    Поместится ли модель на видеокарту прямо сейчас.

    Если узнать не удалось, ответ «нет»: ошибиться в сторону процессора —
    потерять скорость, ошибиться в сторону карты — занять её у того, кто
    на ней сейчас работает или играет.
    """
    кандидат = кандидат or выбранный()
    замер = память()
    if замер is None:
        return False
    занято, всего = замер
    try:
        нужно = (папка_моделей() / кандидат.файл).stat().st_size / 1024 / 1024
    except OSError:
        return False
    return всего - занято >= нужно + ЗАПАС_КАРТЫ_МБ


def папка_рантайма(кандидат: Optional[Кандидат] = None) -> Path:
    """Где лежит рантайм: обычная сборка либо своя сборка кандидата — в папке рядом."""
    обычная = Path(os.getenv("AI_LLAMA_DIR", "F:/AI/llama.cpp"))
    if кандидат is not None and кандидат.рантайм:
        return обычная.with_name(f"{обычная.name}-{кандидат.рантайм}")
    return обычная


def папка_моделей() -> Path:
    return Path(os.getenv("AI_MODELS_DIR", "F:/AI/models"))


# Фоновый режим: слои модели считает процессор, видеокарте остаётся
# только короткое чтение текста. Нужен, когда карта занята не нами — на ней играют, — а очередь
# разбора стоит. Процессор при этом тоже делится: потоков меньше, чем
# ядер, и приоритет ниже обычного, чтобы игра получала своё первой.
# Скорость в фоне — цена режима, а не поломка; она названа замером
# (data-issues.md, запись от 13.10.2026).
#
# Ждать ответа в фоне приходится дольше: вакансия, которую карта читает
# за десять секунд, на процессоре занимает минуты, и принять это за
# отказ модели значило бы остановить прогон на третьей вакансии.
ОЖИДАНИЕ_В_ФОНЕ = 1800.0


def потоков_в_фоне() -> int:
    """Сколько потоков процессора отдать модели в фоне. Остальные — игре и системе."""
    return max(1, int(os.getenv("AI_BG_THREADS", "6")))


def порт(фон: bool = False) -> int:
    """
    Порт сервера модели. У фонового режима он свой.

    Иначе фоновый прогон принял бы за свой сервер, поднятый на карте, и
    занял бы её — ровно то, от чего режим должен уберечь.
    """
    if фон:
        return int(os.getenv("AI_PORT_BG", "8132"))
    return int(os.getenv("AI_PORT", "8131"))


def выбранный() -> Кандидат:
    имя = os.getenv("AI_MODEL", ПО_УМОЛЧАНИЮ)
    if имя not in КАНДИДАТЫ:
        raise KeyError(f"Модель «{имя}» не описана. Известны: {', '.join(КАНДИДАТЫ)}")
    return КАНДИДАТЫ[имя]


def версия_рантайма(кандидат: Optional[Кандидат] = None) -> str:
    """Номер сборки `llama.cpp` — из файла, который кладёт установка."""
    файл = папка_рантайма(кандидат) / "ВЕРСИЯ.txt"
    try:
        return файл.read_text(encoding="utf-8").strip() or "неизвестна"
    except OSError:
        return "неизвестна"


def команда_запуска(кандидат: Кандидат, потоков: int = 1, фон: bool = False) -> List[str]:
    """Команда `llama-server` под кандидата. Отдельно — чтобы её можно было проверить без запуска."""
    команда = [
        str(папка_рантайма(кандидат) / "llama-server.exe"),
        "--model", str(папка_моделей() / кандидат.файл),
        "--host", "127.0.0.1",
        "--port", str(порт(фон)),
        "--ctx-size", str(кандидат.контекст * потоков),
        "--parallel", str(потоков),
        "--n-gpu-layers", "0" if фон else str(кандидат.слоёв_на_карте),
        "--no-webui",
        "--jinja",
    ]
    if фон:
        команда += [
            "--threads", str(потоков_в_фоне()),
            "--threads-batch", str(потоков_в_фоне()),
            # Карта не отключается целиком (`--device none`), и это
            # замерено, а не забыто. При нуле слоёв рантайм всё равно
            # читает текст на карте: полгигабайта её памяти и около
            # двадцати секунд работы на вакансию. Без карты вовсе то же
            # чтение не кончилось за девять минут (13.10.2026) — режим,
            # который бережёт карту ценой двойного времени, никому не
            # нужен.
            # Потоки, ждущие работу, не крутятся вхолостую: иначе модель
            # занимает процессор и тогда, когда ничего не считает.
            "--poll", "0",
        ]
    elif кандидат.экспертов_в_память:
        команда += ["--n-cpu-moe", str(кандидат.экспертов_в_память)]
    return команда


def поставщик(кандидат: Optional[Кандидат] = None, фон: bool = False) -> LlamaСервер:
    """Поставщик для уже поднятого сервера."""
    кандидат = кандидат or выбранный()

    def словарём(пары):
        return {ключ: (словарём(значение) if isinstance(значение, tuple) else значение) for ключ, значение in пары}

    # Версия от режима не зависит: веса, квант, рантайм и промпт те же,
    # меняется только то, на чём считают. Разобранное в фоне поэтому не
    # разбирается заново на карте, и кэш у режимов общий.
    настройки = {"ожидание": ОЖИДАНИЕ_В_ФОНЕ} if фон else {}
    return LlamaСервер(
        f"http://127.0.0.1:{порт(фон)}", кандидат.версия(версия_рантайма(кандидат)),
        поля_запроса=словарём(кандидат.без_рассуждений), **настройки,
    )


def поднятая_модель(фон: bool = False) -> str:
    """Имя файла модели, которую держит сервер на нашем порту. Пусто — узнать не удалось."""
    import requests

    try:
        ответ = requests.get(f"http://127.0.0.1:{порт(фон)}/props", timeout=5, proxies={"http": None, "https": None})
        путь = ответ.json().get("model_path") or ""
    except (requests.RequestException, ValueError):
        return ""
    return Path(путь).name


def флаги_процесса(фон: bool) -> int:
    """
    Флаги запуска llama-server на Windows.

    Без окна — всегда. Пока прогон запускали из консоли, сервер делил её
    консоль и окна не было. Прогон, запущенный после сбора отдельным
    процессом, консоли не имеет, и Windows открывала серверу свою — окно
    выскакивало каждые три минуты, на каждой порции (15.10.2026).

    Приоритет ниже обычного — в фоне: когда процессор нужен игре или
    системе, модель ждёт. Вне Windows флагов нет, и функция даёт ноль.
    """
    без_окна = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    приоритет = getattr(subprocess, "BELOW_NORMAL_PRIORITY_CLASS", 0) if фон else 0
    return без_окна | приоритет


@contextmanager
def сервер(
    кандидат: Optional[Кандидат] = None, потоков: int = 1, ждать_секунд: int = 600, фон: bool = False
) -> Iterator[LlamaСервер]:
    """
    Поднять модель на время работы и погасить после.

    Сервер, который уже отвечает на этом порту, не трогается и не
    гасится: его подняли руками, и распоряжаться им не нам.

    Args:
        фон: Считать на процессоре, с приоритетом ниже обычного, не
            занимая видеокарту
    """
    кандидат = кандидат or выбранный()
    модель = поставщик(кандидат, фон)
    if модель.жив():
        # Сервер на порту может держать другую модель: его подняли руками
        # или соседний прогон. Принять его за свой значит записать ответы
        # одной модели под версией другой — так при первом замере два
        # кандидата и перемешались.
        поднята = поднятая_модель(фон)
        if поднята and поднята.lower() != кандидат.файл.lower():
            raise RuntimeError(
                f"На порту {порт(фон)} уже работает другая модель ({поднята}), а нужна {кандидат.файл}. "
                "Дождитесь её или остановите llama-server."
            )
        logger.info(f"Модель уже поднята на порту {порт(фон)} — используется она")
        yield модель
        return

    файл = папка_моделей() / кандидат.файл
    if not файл.exists():
        raise FileNotFoundError(f"Файл модели не найден: {файл}")

    журнал = папка_рантайма(кандидат) / f"сервер_{кандидат.имя}{'_фон' if фон else ''}.log"
    with open(журнал, "w", encoding="utf-8", errors="replace") as вывод:
        процесс = subprocess.Popen(
            команда_запуска(кандидат, потоков, фон), stdout=вывод, stderr=subprocess.STDOUT,
            creationflags=флаги_процесса(фон),
        )
        try:
            срок = time.monotonic() + ждать_секунд
            while not модель.жив():
                if процесс.poll() is not None:
                    raise RuntimeError(f"llama-server завершился при запуске, код {процесс.returncode}. Журнал: {журнал}")
                if time.monotonic() > срок:
                    raise TimeoutError(f"Модель не поднялась за {ждать_секунд} с. Журнал: {журнал}")
                time.sleep(1)
            logger.info(f"Модель поднята: {модель.версия}")
            yield модель
        finally:
            процесс.terminate()
            try:
                процесс.wait(timeout=20)
            except subprocess.TimeoutExpired:
                процесс.kill()
