"""
Кандидаты в модель слоя и запуск рантайма под них.

Модель выбирается замером на эталоне, а не по обзорам (S10‑3m), поэтому
кандидаты описаны здесь данными: что за файл, как его разместить между
видеокартой и оперативной памятью, какой контекст дать.

Два класса кандидатов, и они по-разному ложатся на железо станции
(RTX 4070 на 12 ГБ, 128 ГБ оперативной):

- плотная модель на 9–14 млрд параметров помещается на карту почти
  целиком;
- модель из смеси экспертов (MoE) втрое больше видеопамяти работает
  потому, что на каждый токен считается малая доля её весов: эксперты
  уходят в оперативную память (`--n-cpu-moe`), на карте остаются
  внимание и общие слои.
"""

from __future__ import annotations

import os
import subprocess
import time
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterator, List, Optional

from src.ai.поставщик import LlamaСервер
from src.utils import get_logger

logger = get_logger(__name__)


@dataclass(frozen=True)
class Кандидат:
    """Модель и то, как её запускать на этой станции."""

    имя: str
    файл: str
    квант: str
    описание: str
    # Сколько слоёв держать на видеокарте (`-ngl`): 99 — все, что влезут.
    слоёв_на_карте: int = 99
    # У скольких первых слоёв веса экспертов оставить в оперативной
    # памяти. Ноль — модель плотная либо помещается на карту целиком.
    экспертов_в_память: int = 0
    контекст: int = 8192

    def версия(self, рантайм: str) -> str:
        """Модель, квант и рантайм — тремя частями одной строки."""
        return f"{self.имя}:{self.квант}@llama.cpp-{рантайм}"


КАНДИДАТЫ: Dict[str, Кандидат] = {
    "qwen3-14b": Кандидат(
        имя="qwen3-14b",
        файл="Qwen3-14B-Q4_K_M.gguf",
        квант="Q4_K_M",
        описание="плотная, 14 млрд параметров, 9 ГБ",
    ),
    "qwen3-30b-a3b": Кандидат(
        имя="qwen3-30b-a3b",
        файл="Qwen3-30B-A3B-Instruct-2507-Q4_K_M.gguf",
        квант="Q4_K_M",
        описание="смесь экспертов, 30 млрд параметров, из них 3 млрд активных, 18,6 ГБ",
        # Сколько слоёв экспертов держать в оперативной памяти — подобрано
        # замером на этой карте (12 ГБ): 99 слоёв — 17 токенов в секунду,
        # 36 — 22, 30 — 25 при 10,4 ГБ на карте, 26 — 28, но карта занята
        # под край, 22 — память карты переполнена и скорость падает до 4.
        # Тридцать — быстрее не сделать, не рискуя переполнением, когда
        # на той же карте работает поиск по смыслу.
        экспертов_в_память=30,
    ),
}

# Чем разбирать, пока выбор по замеру не записан настройкой.
ПО_УМОЛЧАНИЮ = "qwen3-30b-a3b"


def папка_рантайма() -> Path:
    return Path(os.getenv("AI_LLAMA_DIR", "F:/AI/llama.cpp"))


def папка_моделей() -> Path:
    return Path(os.getenv("AI_MODELS_DIR", "F:/AI/models"))


def порт() -> int:
    return int(os.getenv("AI_PORT", "8131"))


def выбранный() -> Кандидат:
    имя = os.getenv("AI_MODEL", ПО_УМОЛЧАНИЮ)
    if имя not in КАНДИДАТЫ:
        raise KeyError(f"Модель «{имя}» не описана. Известны: {', '.join(КАНДИДАТЫ)}")
    return КАНДИДАТЫ[имя]


def версия_рантайма() -> str:
    """Номер сборки `llama.cpp` — из файла, который кладёт установка."""
    файл = папка_рантайма() / "ВЕРСИЯ.txt"
    try:
        return файл.read_text(encoding="utf-8").strip() or "неизвестна"
    except OSError:
        return "неизвестна"


def команда_запуска(кандидат: Кандидат, потоков: int = 1) -> List[str]:
    """Команда `llama-server` под кандидата. Отдельно — чтобы её можно было проверить без запуска."""
    команда = [
        str(папка_рантайма() / "llama-server.exe"),
        "--model", str(папка_моделей() / кандидат.файл),
        "--host", "127.0.0.1",
        "--port", str(порт()),
        "--ctx-size", str(кандидат.контекст * потоков),
        "--parallel", str(потоков),
        "--n-gpu-layers", str(кандидат.слоёв_на_карте),
        "--no-webui",
        "--jinja",
    ]
    if кандидат.экспертов_в_память:
        команда += ["--n-cpu-moe", str(кандидат.экспертов_в_память)]
    return команда


def поставщик(кандидат: Optional[Кандидат] = None) -> LlamaСервер:
    """Поставщик для уже поднятого сервера."""
    кандидат = кандидат or выбранный()
    return LlamaСервер(f"http://127.0.0.1:{порт()}", кандидат.версия(версия_рантайма()))


def поднятая_модель() -> str:
    """Имя файла модели, которую держит сервер на нашем порту. Пусто — узнать не удалось."""
    import requests

    try:
        ответ = requests.get(f"http://127.0.0.1:{порт()}/props", timeout=5, proxies={"http": None, "https": None})
        путь = ответ.json().get("model_path") or ""
    except (requests.RequestException, ValueError):
        return ""
    return Path(путь).name


@contextmanager
def сервер(кандидат: Optional[Кандидат] = None, потоков: int = 1, ждать_секунд: int = 600) -> Iterator[LlamaСервер]:
    """
    Поднять модель на время работы и погасить после.

    Сервер, который уже отвечает на этом порту, не трогается и не
    гасится: его подняли руками, и распоряжаться им не нам.
    """
    кандидат = кандидат or выбранный()
    модель = поставщик(кандидат)
    if модель.жив():
        # Сервер на порту может держать другую модель: его подняли руками
        # или соседний прогон. Принять его за свой значит записать ответы
        # одной модели под версией другой — так при первом замере два
        # кандидата и перемешались.
        поднята = поднятая_модель()
        if поднята and поднята.lower() != кандидат.файл.lower():
            raise RuntimeError(
                f"На порту {порт()} уже работает другая модель ({поднята}), а нужна {кандидат.файл}. "
                "Дождитесь её или остановите llama-server."
            )
        logger.info(f"Модель уже поднята на порту {порт()} — используется она")
        yield модель
        return

    файл = папка_моделей() / кандидат.файл
    if not файл.exists():
        raise FileNotFoundError(f"Файл модели не найден: {файл}")

    журнал = папка_рантайма() / f"сервер_{кандидат.имя}.log"
    with open(журнал, "w", encoding="utf-8", errors="replace") as вывод:
        процесс = subprocess.Popen(команда_запуска(кандидат, потоков), stdout=вывод, stderr=subprocess.STDOUT)
        try:
            срок = time.monotonic() + ждать_секунд
            while not модель.жив():
                if процесс.poll() is not None:
                    raise RuntimeError(f"llama-server завершился при запуске, код {процесс.returncode}. Журнал: {журнал}")
                if time.monotonic() > срок:
                    raise TimeoutError(f"Модель не поднялась за {ждать_секунд} с. Журнал: {журнал}")
                time.sleep(1)
            logger.info(f"Модель поднята: {модель.версия}")
            yield модель
        finally:
            процесс.terminate()
            try:
                процесс.wait(timeout=20)
            except subprocess.TimeoutExpired:
                процесс.kill()
