"""
Бюджет прогона: сколько вызовов и времени он может потратить.

Модель локальная и денег не стоит, но стоит времени и видеокарты:
полный проход по базе — часы, в которые карта не занята ничем другим.
Предел задаётся снаружи, на прогон. Достигнут — прогон останавливается
штатно: сделанное сохранено, следующий запуск продолжит с того же места
(разобранное лежит в кэше и в вакансиях).

Предела трат в деньгах нет намеренно: считать нечего. Появится платный
поставщик — предел добавится сюда третьей строкой.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Optional


@dataclass
class Бюджет:
    """Пределы одного прогона. None — без предела."""

    вызовов: Optional[int] = None
    минут: Optional[float] = None
    потрачено_вызовов: int = 0
    _начало: float = field(default_factory=time.monotonic)

    def исчерпан(self) -> str:
        """Причина остановки словами или пустая строка, если бюджет есть."""
        if self.вызовов is not None and self.потрачено_вызовов >= self.вызовов:
            return f"предел вызовов: {self.вызовов}"
        if self.минут is not None and self.прошло_минут() >= self.минут:
            return f"предел времени: {self.минут:g} мин"
        return ""

    def учесть_вызов(self) -> None:
        self.потрачено_вызовов += 1

    def прошло_минут(self) -> float:
        return (time.monotonic() - self._начало) / 60
