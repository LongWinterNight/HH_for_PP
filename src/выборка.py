"""
Отбор вакансий по фильтрам экрана — одна реализация на всех.

Зачем. Фильтры живут на экране «Вакансии», а отчёт собирался по всей
базе: человек настраивал выборку, нажимал «Собрать отчёт» и получал
файл про другое. Чтобы отчёт считал ровно то же, что показывает список,
отбор должен быть один и тот же кусок кода.

Второй реализации здесь быть не должно. Продукт это уже проходил: две
логики извлечения навыков разошлись и молча давали разные числа, и
кончилось удалением одной из них (S11). Фильтр — то же самое, только
заметить расхождение было бы ещё труднее: обе стороны показывают
правдоподобные цифры, просто разные.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional

import pandas as pd


@dataclass(frozen=True)
class Фильтры:
    """
    Условия отбора — ровно те, что есть на экране.

    Пустое значение означает «не фильтровать». Отдельным типом, а не
    словарём: так видно, какие условия существуют, и опечатка в имени
    поля обнаруживается сразу, а не пустой выборкой.
    """

    поиск: str = ""
    регион: str = ""
    опыт: str = ""
    навык: str = ""
    валюта: str = ""
    источник: str = ""
    только_с_зарплатой: bool = False
    включая_снятые: bool = False

    @property
    def пусты(self) -> bool:
        return not any([
            self.поиск, self.регион, self.опыт, self.навык,
            self.валюта, self.источник, self.только_с_зарплатой,
        ])


def отобрать(df: pd.DataFrame, ф: Фильтры) -> pd.DataFrame:
    """
    Применить фильтры к выборке.

    Порядок условий значения не имеет — каждое сужает независимо, — но
    поиск по навыку идёт по трём колонкам сразу: человек не обязан
    знать, куда продукт положил «Figma» — в инструменты или в жёсткие
    навыки.
    """
    if df.empty:
        return df

    if ф.регион:
        df = df[df["area"].str.contains(ф.регион, case=False, na=False)]

    if ф.опыт:
        df = df[df["experience"] == ф.опыт]

    if ф.источник and "source" in df.columns:
        df = df[df["source"] == ф.источник]

    if ф.навык:
        навык = ф.навык.lower()
        подходит = (
            df["hard_skills"].str.contains(навык, case=False, na=False)
            | df["tools"].str.contains(навык, case=False, na=False)
            | df["soft_skills"].str.contains(навык, case=False, na=False)
        )
        df = df[подходит]

    if ф.валюта and "salary_currency" in df.columns:
        df = df[df["salary_currency"] == ф.валюта]

    if ф.только_с_зарплатой:
        df = df[df["salary_from"].notna()]

    # Поиск — последним: остальные условия сужают то, из чего выбирают,
    # а не то, что уже выбрано. «Регион: Казань» и запрос «дизайнер»
    # должны дать лучших дизайнеров Казани, а не казанцев среди первых
    # двухсот дизайнеров страны.
    if ф.поиск:
        df = _по_запросу(df, ф.поиск)

    return df


def _по_запросу(df: pd.DataFrame, запрос: str) -> pd.DataFrame:
    """
    Вакансии выборки, отвечающие запросу, с местом в выдаче.

    Ищет гибридный поиск (`src/search`): слова со словоформами и
    синонимами плюс смысл. К строкам добавляются две колонки —
    `search_rank` (место, с единицы) и `search_why` (где найдено); по
    первой экран сортирует «по соответствию», вторую показывает.

    Если индекса поиска нет — база только что создана, тест работает на
    трёх строках, — остаётся прежний поиск подстрокой в названии. Пустой
    список в таком случае был бы ложью: вакансии есть, искать нечем.
    """
    from src.search import служба

    выдача = служба.найти(запрос, допустимые=set(df["vacancy_id"].astype(str)))
    if выдача is None:
        return df[df["vacancy_name"].str.contains(запрос, case=False, na=False, regex=False)]

    места = {строка.ид: место for место, строка in enumerate(выдача.строки, start=1)}
    почему = {строка.ид: строка.почему for строка in выдача.строки}

    иды = df["vacancy_id"].astype(str)
    найденное = df[иды.isin(места)].copy()
    найденное["search_rank"] = найденное["vacancy_id"].astype(str).map(места)
    найденное["search_why"] = найденное["vacancy_id"].astype(str).map(почему)
    # Что поиск сделал с запросом — экрану, чтобы он мог сказать об этом.
    найденное.attrs["поиск"] = {
        "замены": выдача.замены,
        "ослаблен": выдача.ослаблен,
        "способы": выдача.способы,
    }
    return найденное


def словами(ф: Фильтры, всего: Optional[int] = None) -> str:
    """
    Условия отбора человеческой фразой — для листа «Срез» в отчёте.

    Получатель файла не видел экрана, с которого отчёт собран. Строка
    «активные вакансии» была правдой, пока отчёт собирался по всей базе;
    теперь она врала бы про выборку. Здесь перечисляется то, что
    действительно применено.
    """
    куски: List[str] = []
    if ф.поиск:
        куски.append(f"поиск «{ф.поиск}»")
    if ф.регион:
        куски.append(f"регион: {ф.регион}")
    if ф.опыт:
        куски.append(f"опыт: {ф.опыт}")
    if ф.навык:
        куски.append(f"навык: {ф.навык}")
    if ф.валюта:
        куски.append(f"валюта: {ф.валюта}")
    if ф.источник:
        куски.append(f"источник: {ф.источник}")
    if ф.только_с_зарплатой:
        куски.append("только с указанной зарплатой")

    основа = ", ".join(куски) if куски else "вся база"
    состояние = "включая снятые" if ф.включая_снятые else "активные вакансии"
    итог = f"{основа} · {состояние}"
    return f"{итог} · {всего} вакансий" if всего is not None else итог
