"""
Справочник регионов источника.

Зачем. Источник отдаёт по запросу не больше 2000 вакансий: дальше
пагинация обрывается, сколько бы он ни «нашёл». По запросу «Рекрутер»
найдено 10 294 — мы видим пятую часть и не знаем, что в остальных
четырёх. Единственный способ достать больше — задать тот же запрос
по частям: у каждого региона своя выдача со своим пределом.

Живой замер (09.09.2026, запрос «Рекрутер»):

    без региона          10 294
    Москва (1)            2 043
    Санкт-Петербург (2)     645

Дерево регионов у hh.ru трёхуровневое: страны → регионы → города.
Россия — один узел из многих: в базе есть вакансии в тенге и сумах, и
резать только по российским областям значило бы потерять остальные
страны. Поэтому корни резки — страны верхнего уровня, а внутрь узла
спускаемся только там, где он сам упёрся в предел.

Справочник меняется в год по чайной ложке, а весит около мегабайта,
поэтому он кладётся на диск и берётся оттуда. Сеть спрашивается, лишь
когда файла нет или он старше `СРОК_ГОДНОСТИ_ДНЕЙ`.
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from src.config import PROJECT_ROOT
from src.utils import get_logger

logger = get_logger(__name__)

# Файл справочника. Лежит рядом с прочими данными сбора, а не в кэше
# ответов: тот чистится по сроку годности запросов, а справочник нужен
# и через месяц.
ПУТЬ_СПРАВОЧНИКА = PROJECT_ROOT / "data" / "areas.json"

# Через сколько дней справочник перечитывается из сети. Регионы меняются
# редко; лишний запрос в неделю ничего не стоит, ежедневный — расход
# лимита впустую.
СРОК_ГОДНОСТИ_ДНЕЙ = 30

# Россия в справочнике hh.ru. Нужна для человекочитаемых сообщений и
# тестов; резка её не выделяет — она такой же корень, как другие страны.
РОССИЯ = "113"


def _свежий(путь: Path) -> bool:
    """Файл существует и не старше срока годности."""
    if not путь.exists():
        return False
    возраст_дней = (time.time() - путь.stat().st_mtime) / 86400
    return возраст_дней < СРОК_ГОДНОСТИ_ДНЕЙ


def _устаревший() -> List[Dict[str, Any]]:
    """То, что лежит на диске, каким бы старым оно ни было."""
    if not ПУТЬ_СПРАВОЧНИКА.exists():
        return []
    try:
        дерево = json.loads(ПУТЬ_СПРАВОЧНИКА.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as ошибка:
        logger.warning(f"Устаревший справочник регионов не прочитан: {ошибка}")
        return []
    logger.warning("Работаем по устаревшему справочнику регионов: обновить не удалось")
    return дерево


def загрузить(клиент=None, обновить: bool = False) -> List[Dict[str, Any]]:
    """
    Дерево регионов: список стран, у каждой `areas` — регионы, у тех —
    города.

    Args:
        клиент: `HHAPIClient`. Нужен, только если справочника нет на
            диске или он устарел. Без клиента и без файла возвращается
            пустой список: выдумывать регионы неоткуда.
        обновить: Перечитать из сети, даже если файл свежий.

    Returns:
        Дерево как его отдаёт источник. Пустой список — «справочника
        нет», а не «регионов нет»: вызывающий код обязан различать эти
        случаи и не резать запрос вслепую.
    """
    if not обновить and _свежий(ПУТЬ_СПРАВОЧНИКА):
        try:
            return json.loads(ПУТЬ_СПРАВОЧНИКА.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as ошибка:
            logger.warning(f"Справочник регионов не прочитан: {ошибка}")

    if клиент is None:
        logger.warning("Справочника регионов нет, а клиент не передан — резать не по чему")
        return []

    # Устаревший справочник — не отсутствующий. Регионы меняются раз в
    # год, и файл месячной давности годится почти так же, как свежий.
    # Отказ сети при обновлении не должен стоить сбора: после месяца
    # простоя первым запросом шёл именно этот, и его отказ ронял запуск,
    # хотя пригодный справочник лежал на диске.
    try:
        дерево = клиент.get_areas()
    except Exception as ошибка:
        logger.warning(f"Справочник регионов не обновлён: {ошибка}")
        дерево = None

    if not дерево:
        return _устаревший()

    try:
        ПУТЬ_СПРАВОЧНИКА.parent.mkdir(parents=True, exist_ok=True)
        ПУТЬ_СПРАВОЧНИКА.write_text(
            json.dumps(дерево, ensure_ascii=False), encoding="utf-8"
        )
        logger.info(f"Справочник регионов сохранён: {ПУТЬ_СПРАВОЧНИКА}")
    except OSError as ошибка:
        # Не удалось сохранить — работать всё равно можно, просто
        # следующий запуск снова сходит в сеть.
        logger.warning(f"Справочник регионов не сохранён: {ошибка}")

    return дерево


def _обойти(узлы: List[Dict[str, Any]], родитель: Optional[str] = None):
    """Все узлы дерева подряд, вместе с идентификатором родителя."""
    for узел in узлы or []:
        yield узел, родитель
        yield from _обойти(узел.get("areas") or [], узел.get("id"))


def узел(дерево: List[Dict[str, Any]], area_id: str) -> Optional[Dict[str, Any]]:
    """Найти узел по идентификатору. None — такого региона нет."""
    if area_id is None:
        return None
    for текущий, _ in _обойти(дерево):
        if str(текущий.get("id")) == str(area_id):
            return текущий
    return None


def корни(дерево: List[Dict[str, Any]]) -> List[str]:
    """
    С чего начинается резка: страны верхнего уровня.

    Не «регионы России»: в базе есть вакансии в тенге, сумах и лари, и
    сузив резку до одной страны, мы потеряли бы остальные так же тихо,
    как раньше теряли всё за пределом выдачи.
    """
    return [str(с.get("id")) for с in дерево or [] if с.get("id")]


def дети(дерево: List[Dict[str, Any]], area_id: str) -> List[str]:
    """
    На что режется узел, когда он сам упёрся в предел.

    Пустой список означает, что резать дальше нечем: это лист дерева —
    город. Такой срез читается до предела, и остаток по нему честно
    попадает в недобор.
    """
    найденный = узел(дерево, area_id)
    if not найденный:
        return []
    return [str(р.get("id")) for р in найденный.get("areas") or [] if р.get("id")]


def имя(дерево: List[Dict[str, Any]], area_id: str) -> str:
    """Название региона для сообщений человеку. Неизвестный — свой же код."""
    найденный = узел(дерево, area_id)
    return найденный.get("name") if найденный else str(area_id)
