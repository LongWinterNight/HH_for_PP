"""
Журнал на диске: что продукт делал и на чём упал.

Сбор лежал месяц, и причину пришлось восстанавливать по записям
запусков в базе: журнала не было. Путь к файлу в настройках стоял с
первого дня, но обработчик подключался, только если путь передавали
аргументом, — а его не передавал никто.

**Один журнал на всё.** Обработчик висит на корневом логгере: всё, что
модули пишут в консоль, уходит и в файл, и ни один модуль об этом не
знает.

**Файл на день, без переименований.** Привычная схема — писать в один
файл и переименовывать его при переполнении. На Windows она ломается,
как только журнал открыт вторым процессом: сбор с экрана и сбор из
командной строки идут одновременно, и переименовать открытый файл
система не даёт. Здесь дата стоит в имени, и новый день — это просто
новый файл.

**Секреты в журнал не попадают.** Журнал читают, пересылают и
прикладывают к вопросам. Пароль стенда и токен источника заменяются
при записи — в сообщении и в трассировке одинаково.
"""

from __future__ import annotations

import logging
import os
import re
import sys
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import List, Optional

# Сколько дней хранится журнал. Месяц: столько же сбор однажды пролежал
# незамеченным, и короче этого срок быть не должен.
ХРАНИТЬ_ДНЕЙ = 30

# Имена переменных окружения, значения которых считаются секретами.
ПРИЗНАКИ_СЕКРЕТА = ("PASSWORD", "TOKEN", "SECRET", "API_KEY")

# Короче этого значение не скрывается: «1» или «true» нашлись бы в
# каждой второй строке журнала.
МИНИМУМ_СЕКРЕТА = 6

ЗАМЕНА = "***"

# Заголовок авторизации целиком, чей бы токен в нём ни стоял.
_НОСИТЕЛЬ = re.compile(r"(Bearer|Basic)\s+[A-Za-z0-9._~+/=\-]{8,}", re.IGNORECASE)

ФОРМАТ = "%(asctime)s | %(levelname)-8s | %(name)s | %(funcName)s:%(lineno)d | %(message)s"

_метка = "_журнал_basevacancy"


def секреты() -> List[str]:
    """Значения, которым в журнале не место, — из окружения процесса."""
    найденные = {
        значение
        for имя, значение in os.environ.items()
        if any(признак in имя.upper() for признак in ПРИЗНАКИ_СЕКРЕТА)
        and значение and len(значение) >= МИНИМУМ_СЕКРЕТА
    }
    # Длинные первыми: иначе секрет, содержащий другой секрет, скроется
    # наполовину и выдаст свой хвост.
    return sorted(найденные, key=len, reverse=True)


def скрыть(текст: str) -> str:
    """Тот же текст без секретов."""
    for секрет in секреты():
        if секрет in текст:
            текст = текст.replace(секрет, ЗАМЕНА)
    return _НОСИТЕЛЬ.sub(lambda совпадение: f"{совпадение.group(1)} {ЗАМЕНА}", текст)


class БезСекретов(logging.Formatter):
    """
    Запись журнала, из которой убраны секреты.

    Скрывает готовую строку, а не её части: трассировка исключения
    собирается из текста ошибки и локальных значений, и секрет может
    оказаться в любой из этих частей.
    """

    def format(self, record: logging.LogRecord) -> str:
        return скрыть(super().format(record))


class ДневнойЖурнал(logging.FileHandler):
    """
    Файл журнала с датой в имени: `имя_2026-10-10.log`.

    День проверяется при каждой записи. Приложение живёт неделями, и
    без этого оно продолжало бы писать в файл того дня, когда его
    запустили.
    """

    def __init__(self, образец: Path, хранить_дней: int = ХРАНИТЬ_ДНЕЙ) -> None:
        self.образец = Path(образец)
        self.хранить_дней = хранить_дней
        self._день = date.today()
        self.образец.parent.mkdir(parents=True, exist_ok=True)
        # Файл открывается при первой записи: процесс, который ничего не
        # написал, не оставляет после себя пустой файл.
        super().__init__(self._путь(self._день), encoding="utf-8", delay=True)
        self._убрать_старые()

    def _путь(self, день: date) -> Path:
        return self.образец.with_name(f"{self.образец.stem}_{день:%Y-%m-%d}{self.образец.suffix or '.log'}")

    def emit(self, record: logging.LogRecord) -> None:
        сегодня = date.today()
        if сегодня != self._день:
            self._день = сегодня
            self.close()
            self.baseFilename = os.fspath(self._путь(сегодня).resolve())
            self._убрать_старые()
        super().emit(record)

    def _убрать_старые(self) -> None:
        """Убрать файлы журнала старше срока хранения."""
        предел = datetime.now() - timedelta(days=self.хранить_дней)
        шаблон = f"{self.образец.stem}_*{self.образец.suffix or '.log'}"
        for файл in self.образец.parent.glob(шаблон):
            try:
                if datetime.fromtimestamp(файл.stat().st_mtime) < предел:
                    файл.unlink()
            except OSError:
                # Занятый или недоступный файл — не повод ронять запуск.
                continue


def _под_тестами() -> bool:
    """Идёт ли прогон тестов: он не должен писать в рабочий журнал."""
    return "pytest" in sys.modules or bool(os.getenv("PYTEST_CURRENT_TEST"))


def подключить(
    файл: Optional[Path] = None,
    уровень: int = logging.INFO,
    принудительно: bool = False,
) -> Optional[ДневнойЖурнал]:
    """
    Подключить журнал на диске к корневому логгеру.

    Вызов повторяемый: второй ничего не добавляет. Так его можно звать
    из любого места, где создаётся логгер, не следя за порядком.

    Args:
        файл: Образец имени. По умолчанию — из настроек (`LOG_FILE`)
        уровень: С какого уровня писать в файл
        принудительно: Подключить даже под тестами — для тестов самого
            журнала

    Returns:
        Подключённый обработчик либо None, если журнал выключен
        (`LOG_TO_FILE=0`) или идёт прогон тестов.
    """
    корень = logging.getLogger()
    for обработчик in корень.handlers:
        if getattr(обработчик, _метка, False):
            return обработчик  # type: ignore[return-value]

    if not принудительно and (_под_тестами() or os.getenv("LOG_TO_FILE", "1") in ("0", "false", "no")):
        return None

    if файл is None:
        from src.config import settings

        файл = settings.log_file

    try:
        обработчик = ДневнойЖурнал(Path(файл))
    except OSError as ошибка:
        # Папка недоступна — продукт работает без журнала и говорит об
        # этом один раз, а не падает на старте.
        print(f"Журнал на диске не подключён: {ошибка}", file=sys.stderr)
        return None

    обработчик.setLevel(уровень)
    обработчик.setFormatter(БезСекретов(ФОРМАТ, datefmt="%Y-%m-%d %H:%M:%S"))
    setattr(обработчик, _метка, True)
    корень.addHandler(обработчик)

    return обработчик


def подключить_сервер() -> None:
    """
    Направить сбои веб-сервера в тот же журнал.

    Сами до корня они не доходят: у логгера сервера распространение
    выключено. Вызывается при старте приложения, а не при импорте:
    сервер настраивает свои логгеры после загрузки приложения и снимает
    всё, что на них повесили раньше.

    Журнал запросов сюда не берётся — экран опрашивает состояние сбора
    раз в секунду, и за час это тысячи одинаковых строк поверх одной
    нужной.
    """
    обработчик = подключить()
    if обработчик is None:
        return
    ошибки_сервера = logging.getLogger("uvicorn.error")
    if обработчик not in ошибки_сервера.handlers:
        ошибки_сервера.addHandler(обработчик)


def текущий_файл() -> Optional[Path]:
    """Куда журнал пишет сейчас. None — журнал не подключён."""
    for обработчик in logging.getLogger().handlers:
        if getattr(обработчик, _метка, False):
            return Path(обработчик.baseFilename)
    return None
