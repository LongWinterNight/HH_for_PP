@dataclass
class Отказ:
    """Что случилось — в виде, который читается без журнала."""

    причина: str = "unknown"
    # Что сказала система: текст исключения. Идёт последней строкой и
    # только как подсказка тому, кто полезет разбираться.
    подробности: str = ""
    запуск: Optional[int] = None
    запросы: List[str] = field(default_factory=list)
    когда: str = field(default_factory=lambda: datetime.now().isoformat(timespec="seconds"))

    @property
    def заголовок(self) -> str:
        return ОБЪЯСНЕНИЯ.get(self.причина, ОБЪЯСНЕНИЯ["unknown"])["title"]

    @property
    def объяснение(self) -> str:
        return ОБЪЯСНЕНИЯ.get(self.причина, ОБЪЯСНЕНИЯ["unknown"])["text"]

    def текст(self) -> str:
        """Оповещение целиком: что, почему, что делать, и только потом — что сказала система."""
        строки = [f"BaseVacancy · {self.заголовок}", "", self.объяснение]
        if self.запросы:
            показать = ", ".join(self.запросы[:5])
            ещё = f" и ещё {len(self.запросы) - 5}" if len(self.запросы) > 5 else ""
            строки += ["", f"Запросы: {показать}{ещё}"]
        if self.запуск:
            строки.append(f"Запуск №{self.запуск} · {self.когда.replace('T', ' ')}")
        if self.подробности:
            строки += ["", f"Что сказала система: {self.подробности[:300]}"]
        return "\n".join(строки)


def _в_телеграм(текст: str) -> Dict[str, Any]:
    """
    Отправить сообщение в Telegram.

    Канал включается двумя переменными в `.env`: `TELEGRAM_BOT_TOKEN`
    и `TELEGRAM_CHAT_ID`. Без них он выключен, и это возвращается как
    исход, а не как ошибка.
    """
    токен = os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
    чат = os.getenv("TELEGRAM_CHAT_ID", "").strip()
    if not токен or not чат:
        return {"доставлено": False, "настроен": False,
                "почему": "не заданы TELEGRAM_BOT_TOKEN и TELEGRAM_CHAT_ID в .env"}

    ответ = requests.post(
        f"https://api.telegram.org/bot{токен}/sendMessage",
        json={"chat_id": чат, "text": текст, "disable_web_page_preview": True},
        timeout=ОЖИДАНИЕ_КАНАЛА,
    )
    if ответ.status_code == 200:
        return {"доставлено": True, "настроен": True}

    # Ответ канала в журнал не кладётся целиком: в адресе запроса стоит
    # токен, и библиотека повторяет его в тексте ошибки.
    try:
        описание = ответ.json().get("description", "")
    except ValueError:
        описание = ""
    return {"доставлено": False, "настроен": True,
            "почему": f"канал ответил {ответ.status_code}: {описание}"[:200]}


# Каналы оповещения. Словарь, а не цепочка условий: тест подменяет
# канал, не трогая сеть, а новый канал — это одна строка.
КАНАЛЫ: Dict[str, Callable[[str], Dict[str, Any]]] = {
    "telegram": _в_телеграм,
}


def файл_оповещений() -> Path:
    """Журнал оповещений лежит рядом с журналом работы."""
    from src.config import settings

    return settings.log_file.parent / "оповещения.jsonl"


def сообщить(отказ: Отказ, журнал: Optional[Path] = None) -> Dict[str, Any]:
    """
    Сообщить об отказе во все каналы и записать, что из этого вышло.

    Не бросает исключений: вызывается из обработчика отказа сбора, и
    второй отказ поверх первого скрыл бы первый.

    Returns:
        Запись журнала оповещений: событие и исход по каждому каналу.
    """
    logger.error(f"{отказ.заголовок}: {отказ.подробности or отказ.объяснение}")

    # Прогон тестов не пишет в рабочий журнал оповещений и не стучится в
    # настоящий канал. Тест самого оповещения передаёт журнал явно — и
    # получает полный путь, с каналами, которые он подменил.
    from src.journal import _под_тестами

    if журнал is None and _под_тестами():
        return {"событие": {**asdict(отказ), "заголовок": отказ.заголовок}, "каналы": {}, "доставлено": False}

    исходы: Dict[str, Dict[str, Any]] = {}
    for имя, отправить in КАНАЛЫ.items():
        try:
            исходы[имя] = отправить(отказ.текст())
        except Exception as ошибка:
            # Имя класса, а не текст: в тексте сетевой ошибки библиотека
            # повторяет адрес запроса вместе с токеном канала.
            исходы[имя] = {"доставлено": False, "настроен": True,
                           "почему": f"канал недоступен: {type(ошибка).__name__}"}
            logger.warning(f"Оповещение в канал «{имя}» не ушло: {type(ошибка).__name__}")

    запись = {
        "событие": {**asdict(отказ), "заголовок": отказ.заголовок},
        "каналы": исходы,
        "доставлено": any(исход.get("доставлено") for исход in исходы.values()),
    }

    if not запись["доставлено"]:
        logger.warning(
            "Оповещение об отказе никуда не доставлено: "
            + "; ".join(f"{имя} — {исход.get('почему', 'причина неизвестна')}" for имя, исход in исходы.items())
        )

    _записать(запись, журнал)
    return запись


def _записать(запись: Dict[str, Any], журнал: Optional[Path]) -> None:
    """Дописать строку в журнал оповещений. Сбой записи оповещение не отменяет."""
    try:
        путь = журнал or файл_оповещений()
        путь.parent.mkdir(parents=True, exist_ok=True)
        with путь.open("a", encoding="utf-8") as файл:
            файл.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError as ошибка:
        logger.warning(f"Журнал оповещений не записан: {ошибка}")


def последние(сколько: int = 20, журнал: Optional[Path] = None) -> List[Dict[str, Any]]:
    """Последние оповещения, свежие первыми."""
    путь = журнал or файл_оповещений()
    if not путь.exists():
        return []
    try:
        строки = путь.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []

    записи = []
    for строка in reversed(строки[-сколько:]):
        try:
            записи.append(json.loads(строка))
        except json.JSONDecodeError:
            # Оборванная строка — след прерванной записи; остальные целы.
            continue
    return записи
