"""
Оповещение об отказе: чтобы упавший сбор не лежал незамеченным.

Сбор лежал месяц. Отказ был виден только на экране «Сбор данных» и
только до перезапуска приложения: он жил в памяти процесса. Человек,
который не открывал этот экран, не узнавал ничего.

**Отказ — событие с причиной и следующим шагом.** «Python int too
large to convert to SQLite INTEGER» в оповещении бесполезно: по нему
нельзя понять ни что случилось, ни что делать. Причина приходит кодом,
а слова к ней — те же, что на экране (`collectionErrors.js`); тест
сверяет два списка, чтобы они не разошлись.

**Канал может не сработать — и это не теряется.** Каждое оповещение
пишется в журнал оповещений вместе с исходом по каждому каналу. Канал,
который не настроен, записывается как ненастроенный, а не пропускается
молча: иначе «оповещения включены» и «оповещения никуда не уходят»
выглядят одинаково.

**Оповещение — отчёт о работе, а не работа.** Отказ канала не роняет
сбор и не меняет его исход.
"""

from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

import requests

from src.utils import get_logger

logger = get_logger(__name__)

