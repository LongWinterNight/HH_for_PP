"""
Период выплаты: за месяц, за час, за смену.

Зачем. «1 000 ₽» и «1 000 ₽ за час» — разные величины, и до сих пор они
лежали в базе одинаково: мы брали поле `salary` и теряли период. Из-за
этого честная почасовая ставка получала красную пометку «слишком мало
для месячной оплаты», а вакансия за смену попадала в медиану рядом с
месячными окладами.

Источник период даёт — `salary_range.mode`, пять значений по справочнику
`salary_range_mode`. Поле приходит и в поисковой выдаче, поэтому при
сборе достаётся бесплатно, без запроса деталей по каждой вакансии.

Что мы с этим делаем: храним период, показываем его рядом с суммой и не
мешаем разные периоды в одном агрегате — по той же причине, по которой
не складываем рубли с тенге. Приводить час к месяцу не будем: для этого
пришлось бы угадать число рабочих часов, а догадка, выданная за факт, —
ровно то, из-за чего эта работа и появилась.
"""

from __future__ import annotations

from typing import Any, Dict, Optional

# Значения справочника hh.ru. Хранится код, а не перевод: название
# источник может изменить, а по коду мы принимаем решения.
МЕСЯЦ = "MONTH"
ЧАС = "HOUR"
СМЕНА = "SHIFT"
ВАХТА = "FLY_IN_FLY_OUT"
УСЛУГА = "SERVICE"

# Как период называется человеку. Формулировка совпадает с той, что
# видит человек на hh.ru: расхождение подписи с источником читается как
# ошибка продукта, даже когда число верное.
ПОДПИСИ = {
    МЕСЯЦ: "за месяц",
    ЧАС: "за час",
    СМЕНА: "за смену",
    ВАХТА: "за вахту",
    УСЛУГА: "за услугу",
}


def период_из_ответа(вакансия: Dict[str, Any]) -> Optional[str]:
    """
    Достать код периода из ответа источника.

    None — источник периода не назвал. Пустое значение честнее, чем
    «месяц по умолчанию»: месячность в этом случае была бы нашей
    выдумкой, и на ней строились бы расчёты.
    """
    диапазон = вакансия.get("salary_range") or {}
    режим = диапазон.get("mode") or {}
    код = режим.get("id")
    return код if код in ПОДПИСИ else None


def подпись(период: Optional[str]) -> Optional[str]:
    """Как назвать период рядом с суммой. None — говорить нечего."""
    return ПОДПИСИ.get(период) if период else None


def это_месячная(период: Optional[str]) -> bool:
    """
    Можно ли числу стоять рядом с месячными окладами.

    Неизвестный период считается месячным намеренно: подавляющее
    большинство вакансий — месячные, и выкинуть из статистики всё, что
    собрано до появления этой колонки, значило бы обрушить выборку с
    восьми тысяч записей до сотен. Риск обратный — несколько часовых
    ставок среди месячных — гасится правилом правдоподобия из E8.

    Пустое значение приходит в двух видах: None из базы и NaN из pandas.
    Сравнение `is None` второй вид пропускает, и однажды это уже выкинуло
    бы из агрегатов всю выборку, собранную до появления колонки.
    """
    if период is None or период != период:  # второе — проверка на NaN
        return True
    return период == МЕСЯЦ
