"""
Тексты описаний: хранение, дедупликация, отпечаток.

Зачем. Описание вакансии — единственное место, где живут навыки, не
названные работодателем в отдельном поле. До сих пор оно использовалось
на лету и выбрасывалось: в базе оставались только извлечённые навыки, а
сам текст — в сырых файлах сборов, 30 КБ на вакансию против 5,8 КБ
самого описания.

Четыре решения, принятые 10.09.2026 (запись «Текст описаний» в
`data-issues.md`), и здесь они воплощены:

**HTML, а не очищенный текст.** Секции описания разбираются по тегам
`<strong|b|h2|h3>`, подзаголовки есть у 95 % вакансий. Без разметки
переразобрать секции нельзя, а после сжатия она стоит 5 % объёма.

**Сжатым.** Замер на 444 описаниях: сжатие вчетверо, 5,8 КБ → 1,45 КБ.
Распаковка скрыта за методом чтения — вызывающий код о ней не знает.

**Один текст на группу совпадающих.** Ключ — хэш текста, а не
идентификатор вакансии: тридцать одна копия объявления по городам хранит
один текст. Тот же хэш нужен слою понимания как ключ кэша разбора.

**Отпечаток сразу.** `simhash` считается при записи, а не по всей базе
потом: он вход для сравнения объявлений между площадками (S12), где
точное совпадение хэша бесполезно — тексты перепечаток расходятся на
проценты.
"""

from __future__ import annotations

import hashlib
import re
import zlib
from typing import Optional, Tuple

# Уровень сжатия. Шестой — обычный компромисс zlib: девятый выигрывает
# проценты объёма за кратное время, а текст пишется на каждой вакансии.
СЖАТИЕ = 6

# Разрядность отпечатка. Шестьдесят четыре бита — столько, чтобы
# похожие тексты отличались единицами бит, и столько, чтобы отпечаток
# помещался в целое поле базы.
БИТ_ОТПЕЧАТКА = 64

# Сколько слов в цепочке, которая голосует за биты отпечатка. Четыре —
# по замеру: цепочки короче сливают разные вакансии на общей лексике,
# длиннее — расходятся на любой правке.
СЛОВ_В_ЦЕПОЧКЕ = 4

# Порог похожести в битах. До шестнадцати — один и тот же текст с
# правками; дальше — разные вакансии. На двухстах описаниях этот порог
# не слил ни одной чужой пары.
ПОХОЖИ_ДО = 16

РАЗМЕТКА = re.compile(r"<[^>]+>")
СЛОВА = re.compile(r"[a-zA-Zа-яёА-ЯЁ0-9]+")


def хэш(текст: str) -> str:
    """
    Ключ текста: sha256 от него самого.

    Считается по тексту как есть, без приведения: два описания,
    отличающиеся одним пробелом, — это два разных снимка, и притворяться,
    что они одно, значит потерять один из них.
    """
    return hashlib.sha256((текст or "").encode("utf-8")).hexdigest()


def сжать(текст: str) -> bytes:
    return zlib.compress((текст or "").encode("utf-8"), СЖАТИЕ)


def разжать(тело: bytes) -> str:
    return zlib.decompress(тело).decode("utf-8")


def отпечаток(текст: str) -> int:
    """
    Simhash описания: число, близкое у похожих текстов.

    Точный хэш для сравнения площадок бесполезен — перепечатка меняет
    проценты текста, и хэш расходится полностью. Simhash устроен иначе:
    каждый кусок текста голосует битами своего хэша, и правка нескольких
    слов сдвигает результат на единицы бит. Похожесть двух описаний —
    расстояние Хэмминга между их отпечатками.

    **Голосуют не слова, а цепочки из четырёх слов подряд.** Это не
    придирка: замер на двухстах живых описаниях показал, что по
    отдельным словам отпечаток почти не различает вакансии — разные
    сходились до шести бит при пороге похожести в двенадцать. Причина в
    общей лексике: «требования», «опыт», «команда», «оформление по ТК»
    есть почти везде, и по такому набору все вакансии похожи. Цепочки
    специфичны: те же двести описаний разошлись минимум на восемнадцать
    бит, и порог в шестнадцать не слил ни одной пары.

    Считается по тексту без разметки: теги одинаковы у всех вакансий
    одного источника и только размывают отпечаток.
    """
    слова = СЛОВА.findall(РАЗМЕТКА.sub(" ", текст or "").lower())
    if not слова:
        return 0

    цепочки = [
        " ".join(слова[i:i + СЛОВ_В_ЦЕПОЧКЕ])
        for i in range(max(1, len(слова) - СЛОВ_В_ЦЕПОЧКЕ + 1))
    ]

    веса = [0] * БИТ_ОТПЕЧАТКА
    for цепочка in цепочки:
        h = int.from_bytes(
            hashlib.blake2b(цепочка.encode("utf-8"), digest_size=8).digest(), "big"
        )
        for бит in range(БИТ_ОТПЕЧАТКА):
            веса[бит] += 1 if (h >> бит) & 1 else -1

    итог = 0
    for бит, вес in enumerate(веса):
        if вес > 0:
            итог |= 1 << бит
    return итог


# Все биты отпечатка единицами: маска, по которой знаковый вид числа
# сводится к беззнаковому и обратно.
_МАСКА = (1 << БИТ_ОТПЕЧАТКА) - 1


def в_поле(число: int) -> int:
    """
    Отпечаток в том виде, в котором его принимает целое поле базы.

    Отпечаток беззнаковый, поле знаковое: число со старшим битом в него
    не помещается, и запись падает с «Python int too large to convert
    to SQLite INTEGER». Старший бит стоит у половины описаний — сбор
    падал на первой же партии текстов. Биты при переводе те же, меняется
    только чтение старшего: расстояние между отпечатками от этого не
    зависит.
    """
    число &= _МАСКА
    return число - (1 << БИТ_ОТПЕЧАТКА) if число >> (БИТ_ОТПЕЧАТКА - 1) else число


def из_поля(число: int) -> int:
    """Отпечаток из базы — тем же числом, каким он был посчитан."""
    return число & _МАСКА


def расстояние(первый: int, второй: int) -> int:
    """
    Сколько бит различается: мера непохожести двух отпечатков.

    Маска обязательна: отпечаток из базы знаковый, и без неё разность
    двух отрицательных чисел считалась бы по их записи со знаком, а не
    по битам.
    """
    return bin((первый ^ второй) & _МАСКА).count("1")


def подготовить(текст: str) -> Optional[Tuple[str, bytes, int, int]]:
    """
    Всё, что нужно записать про один текст.

    Returns:
        `(хэш, сжатое тело, отпечаток, размер до сжатия)` либо None,
        если текста нет. None, а не пустая запись: вакансия без описания
        — обычное дело, и заводить ей пустой текст незачем.
    """
    if not текст or not текст.strip():
        return None
    сырой = текст.encode("utf-8")
    return хэш(текст), сжать(текст), отпечаток(текст), len(сырой)
