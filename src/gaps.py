def _таблица(conn: sqlite3.Connection) -> None:
    conn.execute(
        "CREATE TABLE IF NOT EXISTS query_suggestions ("
        "query_key VARCHAR(200) PRIMARY KEY, query VARCHAR(200) NOT NULL, reason TEXT, vacancies INTEGER, "
        "employers INTEGER, status VARCHAR(20) NOT NULL DEFAULT 'new', suggested_at DATETIME NOT NULL, decided_at DATETIME)"
    )


def обновить(conn: sqlite3.Connection, запросы: List[str], предел: int = 12) -> List[Dict[str, Any]]:
    """
    Пересчитать пробелы и записать новые предложения.

    Решённое не трогается: отклонённое не возвращается, принятое остаётся
    в истории. У ещё не решённых обновляются числа и основание — база с
    прошлого раза выросла.
    """
    _таблица(conn)
    сейчас = datetime.now().isoformat(sep=" ")
    for пробел in найти(conn, запросы)["профессии"]:
        conn.execute(
            "INSERT INTO query_suggestions (query_key, query, reason, vacancies, employers, status, suggested_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?) ON CONFLICT (query_key) DO UPDATE SET "
            "query = CASE WHEN status = 'new' THEN excluded.query ELSE query END, "
            "reason = CASE WHEN status = 'new' THEN excluded.reason ELSE reason END, "
            "vacancies = excluded.vacancies, employers = excluded.employers",
            (пробел["ключ"], пробел["запрос"], пробел["основание"], пробел["вакансий"], пробел["работодателей"], НОВОЕ, сейчас),
        )
    conn.commit()
    return предложения(conn, запросы, предел=предел)


def предложения(conn: sqlite3.Connection, запросы: Optional[List[str]] = None, статус: str = НОВОЕ, предел: int = 12) -> List[Dict[str, Any]]:
    """Предложения в заданном состоянии, от больших выборок к малым."""
    _таблица(conn)
    строки = conn.execute(
        "SELECT query_key, query, reason, vacancies, employers, status, suggested_at, decided_at FROM query_suggestions "
        "WHERE status = ? ORDER BY vacancies DESC, query LIMIT ?",
        (статус, предел * 3),
    ).fetchall()
    итог = []
    for ключ, запрос, основание, вакансий, работодателей, состояние, предложено, решено in строки:
        # Запрос уже добавили в список руками — предлагать его поздно.
        if статус == НОВОЕ and запросы and _покрыто(ключ, запросы):
            continue
        итог.append({
            "ключ": ключ, "запрос": запрос, "основание": основание, "вакансий": вакансий, "работодателей": работодателей,
            "статус": состояние, "предложено": предложено, "решено": решено,
        })
    return итог[:предел]


def решить(conn: sqlite3.Connection, ключ: str, принять: bool) -> Optional[str]:
    """
    Записать решение человека.

    Returns:
        Запрос, который принят (его нужно дописать в список), пустая
        строка при отклонении, None — такого предложения нет.
    """
    _таблица(conn)
    строка = conn.execute("SELECT query FROM query_suggestions WHERE query_key = ? AND status = ?", (ключ, НОВОЕ)).fetchone()
    if not строка:
        return None
    conn.execute(
        "UPDATE query_suggestions SET status = ?, decided_at = ? WHERE query_key = ?",
        (ПРИНЯТО if принять else ОТКЛОНЕНО, datetime.now().isoformat(sep=" "), ключ),
    )
    conn.commit()
    return строка[0] if принять else ""
