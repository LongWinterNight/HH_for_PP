"""
Пробелы базы и предложения запросов на следующий сбор.

Зачем. Что собирать, решает человек, глядя на список запросов. Но база
сама показывает, чего в ней не хватает: по запросу «3dsmax» попутно
пришли шестьдесят «дизайнеров интерьеров» и столько же «архитекторов» —
профессии, которые в базе есть случайно и неполно. Прямой запрос по
ним дал бы полную картину; пока его нет, медиана по «дизайнеру
интерьеров» посчитана по тем, кто упомянул 3ds Max.

Здесь эти пробелы находятся и превращаются в предложения. Модель для
этого не нужна: предложение строится подсчётом по базе, одинаково при
каждом запуске, и у каждого названо основание — сколько вакансий, у
скольких работодателей и по каким запросам они пришли.

Сбор сам не начинается. Предложение — строка на экране; принятое
дописывается в список запросов, и собирать по нему или нет, человек
решает кнопкой, как и раньше. Предложенное, принятое и отклонённое
сохраняется: отклонённое не предлагается снова, а по принятому видно,
что советовали и что взяли.
"""

from __future__ import annotations

import re
import sqlite3
from collections import Counter, defaultdict
from datetime import datetime
from typing import Any, Dict, Iterable, List, Optional

from src.utils import get_logger

logger = get_logger(__name__)

# Сколько вакансий и у скольких работодателей должно набраться, чтобы
# название профессии стало предложением. Десять вакансий одной фирмы —
# её штатное расписание, а не профессия на рынке.
МИН_ВАКАНСИЙ = 10
МИН_РАБОТОДАТЕЛЕЙ = 5

# Меньше скольких активных вакансий по запросу — выборка тонкая: числа
# по ней ненадёжны. Порог тот же, что у графиков.
ТОНКАЯ_ВЫБОРКА = 30

НОВОЕ, ПРИНЯТО, ОТКЛОНЕНО = "new", "accepted", "rejected"

СКОБКИ = re.compile(r"\([^)]*\)|\[[^\]]*\]")
ХВОСТ = re.compile(r"[/|,;—–]| в | на | для | по | с | от ")
СЛОВО = re.compile(r"[a-zа-яё0-9+#]+(?:-[a-zа-яё0-9+#]+)*")
КИРИЛЛИЦА = re.compile(r"[а-яё]")

# Ступени должности: «ведущий архитектор» и «архитектор» — одна профессия.
СТУПЕНИ = {
    "ведущий", "старший", "главный", "младший", "senior", "junior", "middle", "lead", "помощник", "стажер", "стажёр",
}

# Слова, которые сами по себе профессию не называют: запрос «менеджер»
# принёс бы весь рынок.
ОБЩИЕ = {
    "менеджер", "специалист", "директор", "инженер", "оператор", "дизайнер", "руководитель", "сотрудник",
    "консультант", "администратор", "эксперт", "мастер", "работник", "ассистент", "аналитик", "разработчик",
    "manager", "specialist", "engineer", "designer", "developer", "hr",
}


def название_профессии(название: str) -> str:
    """
    Название вакансии, приведённое к названию профессии.

    «Ведущий архитектор (жилые комплексы) в Москве» и «Архитектор» — одна
    профессия. Отбрасываются скобки, уточнения после предлога и ступень
    должности; дефис и пробел не различаются («HR-менеджер», «HR менеджер»).
    """
    текст = СКОБКИ.sub(" ", (название or "").lower().replace("ё", "е"))
    текст = ХВОСТ.split(f" {текст} ")[0]
    слова = [слово for слово in СЛОВО.findall(текст.replace("-", " ")) if слово not in СТУПЕНИ]
    # Слова — в начальной форме: «дизайнер интерьеров» и «дизайнер
    # интерьера» иначе считались бы двумя профессиями по тридцать
    # вакансий вместо одной на шестьдесят.
    from src.morphology import начальная_форма

    return " ".join(начальная_форма(слово) if КИРИЛЛИЦА.search(слово) else слово for слово in слова[:4])


def _чистое(написание: str) -> bool:
    """Название без ступени должности, скобок и уточнений — такое годится в запрос."""
    слова = СЛОВО.findall(написание.lower().replace("ё", "е").replace("-", " "))
    if not слова or len(слова) > 4 or any(слово in СТУПЕНИ for слово in слова):
        return False
    return len(написание) <= 40 and not СКОБКИ.search(написание) and not ХВОСТ.search(f" {написание.lower()} ")


def _покрыто(профессия: str, запросы: Iterable[str]) -> bool:
    """Уже ли собирается профессия одним из запросов."""
    слитно = профессия.replace(" ", "")
    for запрос in запросы:
        ключ = название_профессии(запрос).replace(" ", "") or запрос.lower().replace(" ", "").replace("-", "")
        if ключ and (ключ in слитно or слитно in ключ):
            return True
    return False


def найти(conn: sqlite3.Connection, запросы: List[str]) -> Dict[str, Any]:
    """
    Пробелы базы относительно списка запросов.

    Returns:
        {"профессии": [...], "тонкие_запросы": [...]}

        Профессия — та, что набралась в базе попутно и ни одним запросом
        не собирается. Тонкий запрос — тот, по которому активных
        вакансий меньше порога: предлагать тут нечего, но знать надо.
    """
    строки = conn.execute(
        "SELECT vacancy_name, employer_name, source_keyword FROM vacancies "
        "WHERE COALESCE(is_active, 1) = 1 AND COALESCE(off_query, 0) = 0"
    ).fetchall()

    счёт: Counter = Counter()
    фирмы: Dict[str, set] = defaultdict(set)
    откуда: Dict[str, Counter] = defaultdict(Counter)
    как_пишут: Dict[str, Counter] = defaultdict(Counter)
    по_запросам: Counter = Counter()

    for название, фирма, слова in строки:
        пришла_по = [слово.strip() for слово in (слова or "").split(",") if слово.strip()]
        for слово in пришла_по:
            по_запросам[слово.lower()] += 1
        профессия = название_профессии(название)
        if not профессия:
            continue
        счёт[профессия] += 1
        фирмы[профессия].add((фирма or "").strip().lower())
        for слово in пришла_по:
            откуда[профессия][слово] += 1
        как_пишут[профессия][(название or "").strip()] += 1

    профессии = []
    for профессия, вакансий in счёт.most_common():
        if вакансий < МИН_ВАКАНСИЙ:
            break
        работодателей = len(фирмы[профессия] - {""})
        if работодателей < МИН_РАБОТОДАТЕЛЕЙ or профессия in ОБЩИЕ or _покрыто(профессия, запросы):
            continue
        источники = [слово for слово, _ in откуда[профессия].most_common(2)]
        # Запросом становится самое частое настоящее написание: оно
        # сохраняет регистр и дефисы, как их пишут работодатели.
        # Со ступенью должности или уточнением в скобках написание не
        # годится: «Ведущий архитектор (жилые комплексы)» — не запрос.
        написание = next(
            (вариант for вариант, _ in как_пишут[профессия].most_common() if _чистое(вариант)),
            профессия.capitalize(),
        )
        профессии.append({
            "ключ": профессия,
            "запрос": написание,
            "вакансий": вакансий,
            "работодателей": работодателей,
            "источники": источники,
            "основание": (
                f"В базе {вакансий} активных вакансий у {работодателей} работодателей — они пришли попутно, "
                f"по {'запросу' if len(источники) == 1 else 'запросам'} "
                f"{' и '.join(f'«{слово}»' for слово in источники)}. Прямой запрос соберёт профессию целиком."
            ),
        })

    тонкие = [
        {"запрос": запрос, "вакансий": по_запросам.get(запрос.lower(), 0)}
        for запрос in запросы if по_запросам.get(запрос.lower(), 0) < ТОНКАЯ_ВЫБОРКА
    ]
    return {"профессии": профессии, "тонкие_запросы": тонкие}


