"""
Копии одной вакансии по городам.

Работодатель размещает одну вакансию в десятках городов; у каждой копии
свой идентификатор, и для базы это разные записи. На живой базе таких
15 % активных строк, рекорд — 31 копия одной вакансии.

Дедупликация по идентификатору этого не ловит и не должна: копии
действительно разные записи источника, и человеку, который ищет работу
в Самаре, нужна именно его строка. Но в зарплатных числах одна вакансия
весит как тридцать:

    медиана по строкам   81 500 ₽
    медиана по вакансиям 90 000 ₽

В топе работодателей то же самое: Самокат с двенадцатью вакансиями в
шестидесяти двух городах обгонял СБЕР с тридцатью тремя разными.

**Решение (S5‑1b).** Копии считаются за одну вакансию там, где число
описывает рынок труда: медиана зарплаты, квартили, гистограмма, топ
работодателей. Там, где число описывает предложения — «вакансий в
базе», «вакансии по регионам», список на экране, — считаются все
строки: в каждом городе предложение действительно есть.

**Ключ группы — название и работодатель.** Зарплата в ключ не входит:
она различается внутри группы у 6 случаев из 83 (одна вакансия с разной
ставкой по регионам), и добавление зарплаты разбивало бы настоящие
группы.
"""

from __future__ import annotations

from typing import List, Optional

import numpy as np
import pandas as pd

# Поля, по которым копии одной вакансии узнаются друг в друге.
КЛЮЧ_КОПИИ = ["vacancy_name", "employer_name"]


def ключ_доступен(df: pd.DataFrame) -> bool:
    """Есть ли по чему группировать: у старых выборок полей может не быть."""
    return all(поле in df.columns for поле in КЛЮЧ_КОПИИ)


def без_копий(df: pd.DataFrame, поле_суммы: Optional[str] = None) -> pd.DataFrame:
    """
    Одна строка на вакансию вместо одной на город.

    Args:
        df: Выборка вакансий
        поле_суммы: Колонка, по которой выбирается представитель группы.
            Берётся строка с медианной зарплатой — не первая попавшаяся:
            у шести групп из восьмидесяти трёх ставка различается по
            регионам, и брать первую значило бы отдать результат на волю
            порядка строк.

    Returns:
        Выборка, где каждая группа копий представлена одной строкой.
        Порядок и остальные поля сохраняются.
    """
    if df is None or df.empty or not ключ_доступен(df):
        return df

    if поле_суммы and поле_суммы in df.columns:
        # Представитель группы — строка, ближайшая к медиане по сумме.
        #
        # Считается по всей выборке разом, а не циклом по группам. Цикл
        # собирал по объекту на группу, и на десяти тысячах вакансий это
        # восемь секунд на вызов — а экран «Аналитика» вызывает отсев
        # десять раз на один ответ. Выбор тот же: сверено на живой базе,
        # те же вакансии в том же порядке.
        группы = df.groupby(КЛЮЧ_КОПИИ, dropna=False, sort=False).ngroup()
        суммы = pd.to_numeric(df[поле_суммы], errors="coerce")
        отклонение = (суммы - суммы.groupby(группы).transform("median")).abs()

        порядок = pd.DataFrame({
            "группа": группы.to_numpy(),
            # Строка без суммы представителем не становится, пока в
            # группе есть хоть одна с суммой; если нет ни одной — берётся
            # первая, как и раньше.
            "отклонение": отклонение.fillna(np.inf).to_numpy(),
            "место": np.arange(len(df)),
        })
        выбор = (
            порядок.sort_values(["группа", "отклонение", "место"], kind="stable")
            .drop_duplicates("группа")["место"]
        )
        return df.iloc[выбор.to_numpy()]

    return df.drop_duplicates(subset=КЛЮЧ_КОПИИ, keep="first")


def размеры_групп(df: pd.DataFrame) -> pd.Series:
    """Сколько строк в каждой группе копий. Ключ — название и компания."""
    if df is None or df.empty or not ключ_доступен(df):
        return pd.Series(dtype="int64")
    return df.groupby(КЛЮЧ_КОПИИ, dropna=False).size()


def сколько_копий(df: pd.DataFrame) -> int:
    """Сколько строк исчезнет при схлопывании копий — для подписи на экране."""
    размеры = размеры_групп(df)
    if размеры.empty:
        return 0
    return int((размеры - 1).clip(lower=0).sum())


def города_групп(вся: pd.DataFrame, ключи: List[tuple]) -> dict:
    """
    Где размещена каждая вакансия: {(название, компания): [город, …]}.

    Список нужен строке списка («Москва и ещё 10») и панели вакансии
    («Где размещена»). Берётся из всей базы, а не из выборки: при фильтре
    по Самаре человеку всё равно полезно знать, что та же вакансия есть
    ещё в десяти городах.

    Каждый город — с номером своего объявления и ссылкой на него: у копий
    разные адреса на источнике, и откликаться нужно на объявление своего
    города. Города идут по алфавиту.
    """
    if вся is None or вся.empty or not ключ_доступен(вся) or not ключи:
        return {}
    нужные = pd.MultiIndex.from_tuples(ключи, names=КЛЮЧ_КОПИИ)
    строки = вся[pd.MultiIndex.from_frame(вся[КЛЮЧ_КОПИИ]).isin(нужные)]
    итог: dict = {}
    for ключ, группа in строки.groupby(КЛЮЧ_КОПИИ, dropna=False, sort=False):
        города = []
        for _, строка in группа.iterrows():
            города.append({
                "area": строка.get("area") or "",
                "vacancy_id": str(строка.get("vacancy_id") or ""),
                "vacancy_url": строка.get("vacancy_url") or "",
            })
        города.sort(key=lambda г: (г["area"].lower(), г["vacancy_id"]))
        итог[ключ if isinstance(ключ, tuple) else (ключ,)] = города
    return итог