"""
Недобор выдачи: сколько вакансий мы по запросу не увидели.

Источник отдаёт не всю выдачу. hh.ru жёстко обрывает пагинацию на 2000
записях, а наш предел ещё ниже — `max_pages` страниц по сотне. По
запросу «Рекрутер», где источник знает несколько тысяч вакансий, мы
читаем первую тысячу и молчим об этом: в истории сбора стоит число
собранного, и оно выглядит как весь рынок.

Разрыв между «найдено» (`found` — что источник обещал) и «взято»
(`taken` — сколько записей выдачи мы прочитали) и есть то, чего мы не
увидели. Он считается только по запросам, где выдача читалась не до
конца: у полного обхода `found` больше `taken` по другой причине —
часть вакансий отсеялась по возрасту, и это не потеря.

Числа здесь ничего не чинят. Они называют вслух то, что раньше
происходило молча: пока недобор не виден, любой вывод по базе — вывод
по неизвестно какой её части. Резка запроса на срезы (S4‑2, S4‑3) — уже
лечение; это — диагноз.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

# Запрос считается упёршимся в потолок, если выдача читалась не до
# конца. Статус приходит из разбивки сбора: complete — дочитали,
# partial — предел страниц, остановка или ошибка.
СТАТУС_ПОЛНЫЙ = "complete"

# Жёсткий предел источника: сколько вакансий по одному запросу вообще
# можно прочитать, сколько бы он ни «нашёл». Проверено живым ответом
# (09.09.2026): по «Рекрутеру» найдено 10 294, а страниц по сто отдаётся
# ровно двадцать.
ПРЕДЕЛ_ИСТОЧНИКА = 2000


def доступная_глубина(ответ: Optional[Dict[str, Any]],
                      max_pages: int,
                      per_page: int = 100) -> int:
    """
    Сколько вакансий по этому запросу мы вообще можем прочитать.

    Меньшее из трёх: предел источника, число страниц, которое он сам
    назвал, и наш собственный предел страниц. Последний — не свойство
    источника, а наша настройка, но для вопроса «упёрлись ли» разницы
    нет: непрочитанное остаётся непрочитанным по любой из причин.
    """
    страниц = None
    if isinstance(ответ, dict):
        значение = ответ.get("pages")
        if isinstance(значение, int) and значение >= 0:
            страниц = значение

    пределы = [ПРЕДЕЛ_ИСТОЧНИКА, max(0, max_pages) * per_page]
    if страниц is not None:
        пределы.append(страниц * per_page)
    return min(пределы)


def упёрся(ответ: Optional[Dict[str, Any]],
           max_pages: int,
           per_page: int = 100) -> bool:
    """
    Правда ли, что за прочитанным осталось непрочитанное.

    Считается по одному ответу — первой странице: `found` источник
    называет сразу, и решать, резать ли запрос, надо до того, как
    потрачены двадцать запросов на страницы.

    Отсутствие `found` — не повод резать: без числа судить не о чем, а
    лишняя резка стоит десятков запросов к источнику.
    """
    if not isinstance(ответ, dict):
        return False
    найдено = ответ.get("found")
    if not isinstance(найдено, int):
        return False
    return найдено > доступная_глубина(ответ, max_pages, per_page)


def недобор_запроса(запрос: Dict[str, Any]) -> Optional[int]:
    """
    Сколько вакансий не увидели по одному запросу.

    Возвращает None, когда судить не по чему: нет «найдено» или «взято»
    (старые сборы, до того как эти числа стали записываться), либо
    выдача прочитана до конца.
    """
    if запрос.get("status") == СТАТУС_ПОЛНЫЙ:
        return None

    найдено = запрос.get("found")
    взято = запрос.get("taken")
    if not isinstance(найдено, int) or not isinstance(взято, int):
        return None

    return max(0, найдено - взято)


def склонение(n: int, одна: str, две: str, много: str) -> str:
    """Русское склонение после числительного."""
    сотня = abs(n) % 100
    последняя = сотня % 10
    if 10 < сотня < 20:
        return много
    if 1 < последняя < 5:
        return две
    if последняя == 1:
        return одна
    return много


def _число(n: int) -> str:
    """Число с неразрывными пробелами между разрядами: 2 412."""
    return f"{n:,}".replace(",", " ")


def сводка_недобора(запросы: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Что сбор не увидел — числами и словами.

    Args:
        запросы: Разбивка сбора по запросам (`storage.get_run_queries`)

    Returns:
        {
            "запросов": сколько запросов уперлись в потолок выдачи,
            "вакансий": сколько записей суммарно не прочитано,
            "фраза": та же мысль словами, для показа человеку,
            "по_запросам": [{"запрос", "найдено", "взято", "не_увидели"}],
        }

        Когда судить не по чему, «вакансий» равно нулю, а «фраза» пуста:
        отсутствие данных не то же самое, что отсутствие недобора, и
        придумывать успокоительную надпись здесь нельзя.
    """
    по_запросам: List[Dict[str, Any]] = []
    всего = 0

    for запрос in запросы or []:
        сколько = недобор_запроса(запрос)
        if not сколько:
            continue
        всего += сколько
        по_запросам.append({
            "запрос": запрос.get("keyword"),
            "найдено": запрос.get("found"),
            "взято": запрос.get("taken"),
            "не_увидели": сколько,
        })

    if not по_запросам:
        return {"запросов": 0, "вакансий": 0, "фраза": "", "по_запросам": []}

    # Порядок по величине потери: первым идёт запрос, где мы видим
    # меньшую долю рынка — с него и начнётся резка на срезы.
    по_запросам.sort(key=lambda з: з["не_увидели"], reverse=True)

    запросов = len(по_запросам)
    фраза = (
        f"{_число(всего)} {склонение(всего, 'вакансия', 'вакансии', 'вакансий')} "
        f"осталось за пределом выдачи "
        f"по {_число(запросов)} {склонение(запросов, 'запросу', 'запросам', 'запросам')}: "
        f"источник не отдаёт больше, чем помещается в прочитанные страницы."
    )

    return {
        "запросов": запросов,
        "вакансий": всего,
        "фраза": фраза,
        "по_запросам": по_запросам,
    }
