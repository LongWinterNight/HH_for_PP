"""
Поиск как служба продукта: одна точка для экрана, отчёта и сбора.

Модули поиска ничего не знают о приложении: им дают соединение,
синонимы и модель. Здесь это собрано вместе — где база, какой словарь,
поднята ли модель, — чтобы экран и сбор не решали это каждый по-своему.

**Модель одна на процесс и поднимается один раз.** Загрузка — секунды и
больше гигабайта памяти видеокарты. Если поднять её не удалось, отказ
запоминается: иначе каждый запрос ждал бы той же неудачи заново.

**Смысл можно выключить** переменной `SEARCH_VECTORS=0` — на машине,
где видеокарта нужна другому, поиск остаётся на словах.
"""

from __future__ import annotations

import os
import sqlite3
import threading
from typing import Dict, Iterable, Optional

from src.search import hybrid, lexical, vectors, индексация
from src.utils import get_logger

logger = get_logger(__name__)

_замок = threading.Lock()
_модель: Optional[vectors.ЛокальнаяМодель] = None
# Почему модель не поднялась. Пока причина записана, новых попыток нет.
_отказ_модели: Optional[str] = None
_синонимы: Optional[Dict[str, str]] = None


def смысл_включён() -> bool:
    return os.getenv("SEARCH_VECTORS", "1").lower() not in ("0", "false", "no")


def _под_тестами() -> bool:
    from src.journal import _под_тестами as под_тестами

    return под_тестами()


def кодировщик() -> Optional[vectors.ЛокальнаяМодель]:
    """
    Модель векторов либо None, если её нет.

    Под тестами модель не поднимается никогда: тест не должен занимать
    видеокарту и зависеть от того, скачана ли модель на этой машине.
    Тесты самого поиска передают подставной кодировщик явно.
    """
    global _модель, _отказ_модели
    if not смысл_включён() or _отказ_модели or _под_тестами():
        return None
    with _замок:
        if _модель is None and _отказ_модели is None:
            модель = vectors.ЛокальнаяМодель()
            try:
                модель(["прогрев"], True)
                _модель = модель
            except vectors.МодельНедоступна as ошибка:
                _отказ_модели = str(ошибка)
                logger.info(f"Поиск по смыслу выключен: {ошибка}. Поиск идёт по словам.")
            except Exception as ошибка:
                _отказ_модели = f"{type(ошибка).__name__}: {ошибка}"
                logger.exception("Модель векторов не поднялась, поиск идёт по словам")
    return _модель


def прогреть() -> None:
    """
    Поднять модель заранее, в стороне от запросов.

    Первый поиск иначе ждал бы загрузки модели несколько секунд — и
    человек видел бы зависший экран там, где привык к мгновенному
    списку.
    """
    if not смысл_включён() or _под_тестами():
        return
    threading.Thread(target=кодировщик, name="прогрев-поиска", daemon=True).start()


def состояние() -> Dict[str, object]:
    """Чем поиск располагает прямо сейчас — для экрана и для проверки."""
    return {
        "смысл_включён": смысл_включён(),
        "модель": vectors.имя_модели(),
        "модель_поднята": _модель is not None,
        "отказ_модели": _отказ_модели,
    }


def синонимы() -> Dict[str, str]:
    global _синонимы
    if _синонимы is None:
        from src.skills_store import таблица_синонимов

        _синонимы = таблица_синонимов()
    return _синонимы


def _соединение() -> sqlite3.Connection:
    from src.config import settings

    return sqlite3.connect(settings.db_path)


def _знает(conn: sqlite3.Connection, идентификаторы: set) -> bool:
    """Есть ли в индексе хоть одна из этих вакансий. Проверяется на выборке."""
    образец = list(идентификаторы)[:50]
    строка = conn.execute(
        f"SELECT 1 FROM search_docs WHERE vacancy_id IN ({','.join('?' * len(образец))}) LIMIT 1", образец
    ).fetchone()
    return строка is not None


def найти(запрос: str, допустимые: Optional[set] = None) -> Optional[hybrid.Выдача]:
    """
    Найти вакансии по запросу.

    Returns:
        Выдачу либо None, если индекса нет. None — не «ничего не
        найдено», а «искать нечем»: вызывающий код обязан различать эти
        случаи и во втором вернуться к простому поиску по названию, а
        не показать пустой список.
    """
    conn = _соединение()
    try:
        if lexical.размер(conn) == 0:
            return None
        if допустимые and not _знает(conn, допустимые):
            # Индекс есть, но про эти вакансии он не слышал: выборка
            # пришла не из той базы, по которой он построен, либо её
            # ещё не индексировали. Ответить «ничего не найдено» значило
            # бы соврать — искать по ним нечем.
            return None
        return hybrid.найти(conn, запрос, синонимы(), кодировщик(), vectors.имя_модели(), допустимые)
    finally:
        conn.close()


def обновить(идентификаторы: Optional[Iterable[str]] = None) -> Dict[str, int]:
    """
    Записать вакансии в индексы поиска. Вызывается сбором.

    Ничего не бросает: индекс — способ находить собранное, а не условие
    сбора. Сбор, который упал из-за поиска, потерял бы данные ради
    удобства.
    """
    try:
        conn = _соединение()
        try:
            return индексация.обновить(conn, идентификаторы, кодировщик(), vectors.имя_модели())
        finally:
            conn.close()
    except Exception:
        logger.exception("Индексы поиска не обновлены")
        return {"по_словам": 0, "векторов": 0}
