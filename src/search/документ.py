"""
Документ поиска: что из вакансии участвует в поиске.

Четыре поля, и вес у них разный. Слово в названии значит «это такая
вакансия»; слово в описании — «в ней об этом упомянуто». Запрос
«арт-директор» должен ставить арт-директора выше дизайнера, который
ему подчиняется.

**Название компании в смысловой поиск не входит.** По запросу
«Арт-директор» источник отдавал 331 вакансию ресторанов работодателя
«АРТ РЕСТ» ровно потому, что искал и по компании. В поиске по словам
компания остаётся отдельным полем с наименьшим весом: человек вправе
искать «Яндекс», но совпадение в названии компании не должно
перевешивать совпадение в названии вакансии.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from typing import Optional

from src import morphology

РАЗМЕТКА = re.compile(r"<[^>]+>")
ПРОБЕЛЫ = re.compile(r"\s+")
СЛОВО = re.compile(r"[a-zа-я0-9]+(?:[+#][+#]?)?")

# Сколько знаков описания уходит в модель смысла. Модель читает около
# пятисот частей слова; остальное она отбросит сама, но готовить и
# передавать лишнее незачем.
ЗНАКОВ_ДЛЯ_СМЫСЛА = 2500


def чистый_текст(текст: Optional[str]) -> str:
    """Текст без разметки и лишних пробелов."""
    return ПРОБЕЛЫ.sub(" ", РАЗМЕТКА.sub(" ", текст or "")).strip()


def слова(текст: Optional[str]) -> list:
    """
    Слова текста: нижний регистр, «е» вместо «ё».

    «C++» и «C#» остаются целыми: без знаков это одна буква, по которой
    нашлось бы всё подряд.
    """
    return СЛОВО.findall(чистый_текст(текст).lower().replace("ё", "е"))


def привести(текст: Optional[str]) -> str:
    """
    Текст в том виде, в котором он лежит в индексе и приходит в запросе.

    Одна функция на обе стороны: если индекс и запрос приводятся разным
    кодом, «дизайнера» в запросе и «дизайнер» в индексе не встретятся —
    и узнать об этом можно будет только по пустой выдаче.
    """
    return " ".join(_для_индекса(слово) for слово in слова(текст))


def _для_индекса(слово: str) -> str:
    # Индекс разбивает текст по знакам, и «c++» распался бы на «c».
    # Знаки заменяются буквами — одинаково в индексе и в запросе.
    слово = слово.replace("++", "plusplus").replace("+", "plus").replace("#", "sharp")
    # Разборщик возвращает начальную форму с «ё» («удалённый»), а текст
    # до него приведён к «е». Без второй замены одно и то же слово
    # лежало бы в индексе в двух видах.
    return morphology.начальная_форма(слово).replace("ё", "е")


@dataclass(frozen=True)
class Документ:
    """Вакансия в виде, пригодном для обоих способов поиска."""

    ид: str
    название: str
    навыки: str
    описание: str
    компания: str

    def для_смысла(self) -> str:
        """Текст, который читает модель: кто нужен, что уметь, что делать."""
        части = [self.название]
        if self.навыки:
            части.append(f"Навыки: {self.навыки}")
        if self.описание:
            части.append(self.описание[:ЗНАКОВ_ДЛЯ_СМЫСЛА])
        return ". ".join(части)

    def отпечаток(self) -> str:
        """
        Изменился ли документ с прошлого раза.

        По нему векторы пересчитываются только у тех вакансий, чей текст
        действительно стал другим, а не у всей базы после каждого сбора.
        """
        return hashlib.sha1(self.для_смысла().encode("utf-8")).hexdigest()


def собрать_документ(
    ид,
    название: Optional[str],
    навыки: Optional[str] = None,
    навыки_работодателя: Optional[str] = None,
    описание: Optional[str] = None,
    компания: Optional[str] = None,
) -> Документ:
    """Документ поиска из полей вакансии."""
    все_навыки = ", ".join(
        dict.fromkeys(  # порядок сохраняется, повторы уходят
            часть.strip()
            for источник in (навыки, навыки_работодателя)
            for часть in (источник or "").split(",")
            if часть.strip()
        )
    )
    return Документ(
        ид=str(ид),
        название=чистый_текст(название),
        навыки=все_навыки,
        описание=чистый_текст(описание),
        компания=чистый_текст(компания),
    )
