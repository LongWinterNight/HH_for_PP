"""
Слияние двух списков: найденное по словам и найденное по смыслу.

Оценки двух способов несравнимы: у слов это BM25, у смысла — близость
векторов, и ни складывать, ни взвешивать их нельзя без подгонки под
конкретные данные. Сравнимо другое — место в списке. Правило слияния по
местам (reciprocal rank fusion) берёт от каждого списка 1 / (k + место)
и складывает: вакансия, которую нашли оба способа, оказывается выше
найденной одним, и ни один способ не может задавить другой величиной
своих чисел.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence

from src.search import lexical, vectors
from src.utils import get_logger

logger = get_logger(__name__)

# Постоянная слияния. Шестьдесят — значение из работы, где правило
# предложено; оно сглаживает разницу между первым и вторым местом так,
# чтобы одно первое место не перевешивало два вторых.
K_СЛИЯНИЯ = 60

# Сколько ближайших по смыслу берётся в слияние. Больше — длиннее хвост
# выдачи из вакансий, которые «немного похожи»: на первые позиции он не
# влияет, а счётчик найденного раздувает.
ИЗ_СМЫСЛА = 100

# Вес списков при слиянии — равный. Замер на эталоне показывал лучший
# результат при весе смысла 2 (0,854 против 0,840), но соседние значения
# 1,5 и 3 были не лучше единицы: это всплеск на восемнадцати запросах,
# а не закономерность, и подгонять под него нечего.


@dataclass
class Строка:
    """Одна найденная вакансия и то, как она найдена."""

    ид: str
    оценка: float
    место_по_словам: Optional[int] = None
    место_по_смыслу: Optional[int] = None
    близость: Optional[float] = None
    # «в названии», «в навыках», «по смыслу» — для подписи в списке.
    почему: str = ""


@dataclass
class Выдача:
    """Итог гибридного поиска."""

    строки: List[Строка] = field(default_factory=list)
    # Что заменено в запросе: «дизайнр» → «дизайнер».
    замены: Dict[str, str] = field(default_factory=dict)
    # Совпали не все слова запроса.
    ослаблен: bool = False
    # Какие способы участвовали. Смысла может не быть — модель не
    # поднята, — и экран вправе об этом сказать.
    способы: List[str] = field(default_factory=list)

    @property
    def порядок(self) -> List[str]:
        return [строка.ид for строка in self.строки]


def слить(списки: Sequence[Sequence[str]], k: int = K_СЛИЯНИЯ) -> Dict[str, float]:
    """Оценка слияния по местам для каждого идентификатора."""
    оценки: Dict[str, float] = {}
    for список in списки:
        for место, ид in enumerate(список, start=1):
            оценки[ид] = оценки.get(ид, 0.0) + 1.0 / (k + место)
    return оценки


def найти(
    conn: sqlite3.Connection,
    запрос: str,
    синонимы: Optional[Dict[str, str]] = None,
    кодировщик: Optional[vectors.Кодировщик] = None,
    модель: Optional[str] = None,
    допустимые: Optional[set] = None,
    порог_смысла: Optional[float] = None,
) -> Выдача:
    """
    Гибридный поиск.

    Args:
        conn: Соединение с базой, где лежат индексы
        запрос: Что набрал человек
        синонимы: Таблица «написание → канон» из словаря навыков
        кодировщик: Модель векторов. Без неё поиск идёт только по словам
        модель: Имя модели — по нему выбираются её векторы
        допустимые: Идентификаторы, прошедшие фильтры экрана. Фильтр
            применяется до ранжирования: «регион: Казань» сужает то, из
            чего выбирают, а не то, что уже выбрали
        порог_смысла: Наименьшая близость, с которой вакансия считается
            найденной по смыслу. По умолчанию — порог модели
    """
    итог = Выдача()
    if not (запрос or "").strip():
        return итог

    по_словам = lexical.найти(conn, запрос, синонимы, сколько=2000)
    слова = [ид for ид in по_словам.порядок if допустимые is None or ид in допустимые]
    итог.замены = по_словам.запрос.замены
    итог.ослаблен = по_словам.ослаблен
    if слова:
        итог.способы.append("слова")

    смысл: List[str] = []
    близости: Dict[str, float] = {}
    if кодировщик is not None:
        модель = модель or vectors.имя_модели()
        if порог_смысла is None:
            порог_смысла = vectors.порог_близости(модель)
        try:
            хранилище = vectors.индекс(conn, модель)
            if len(хранилище):
                вектор = кодировщик([запрос], True)[0]
                for ид, близость in хранилище.ближайшие(вектор, ИЗ_СМЫСЛА, допустимые):
                    if близость >= порог_смысла:
                        смысл.append(ид)
                        близости[ид] = близость
        except vectors.МодельНедоступна as ошибка:
            # Обычный исход на машине без модели, а не сбой: поиск
            # продолжается по словам.
            logger.info(f"Поиск по смыслу пропущен: {ошибка}")
        except Exception:
            logger.exception("Поиск по смыслу не удался, продолжаем по словам")
        if смысл:
            итог.способы.append("смысл")

    оценки = слить([слова, смысл])
    места_слов = {ид: место for место, ид in enumerate(слова, start=1)}
    места_смысла = {ид: место for место, ид in enumerate(смысл, start=1)}

    for ид, оценка in sorted(оценки.items(), key=lambda пара: -пара[1]):
        итог.строки.append(Строка(
            ид=ид,
            оценка=оценка,
            место_по_словам=места_слов.get(ид),
            место_по_смыслу=места_смысла.get(ид),
            близость=близости.get(ид),
            почему=по_словам.где.get(ид) or "по смыслу",
        ))
    return итог
