"""
Поиск по словам: FTS5 со словоформами, синонимами и опечатками.

Три вещи, которых не умела подстрока в названии.

**Словоформы.** Текст в индексе и слова запроса приводятся к начальной
форме одним и тем же кодом (`документ.привести`): «дизайнера» в запросе
встречает «дизайнер» в индексе.

**Синонимы.** «3dsmax», «3ds Max» и «3д макс» — одно и то же, и словарь
навыков это уже знает. Запрос расширяется его вариантами: искать навык
в написании, которое выбрал автор вакансии, человек не обязан.

**Опечатки и раскладка.** Слово, которого нет в индексе, не означает,
что вакансий нет: чаще человек ошибся буквой («дизайнр») или написал
латинское название кириллицей («фигма»). Такое слово заменяется
ближайшим известным, и замена называется в ответе — молча подменять
запрос нельзя.

Порядок выдачи — по BM25 с весами полей: совпадение в названии весит
больше совпадения в описании.
"""

from __future__ import annotations

import re
import sqlite3
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

from src.search.документ import Документ, привести, слова

# Вес поля в BM25. Название — «это такая вакансия», описание — «в ней
# об этом упомянуто». Компания ищется, но не перевешивает.
ВЕСА = {"title": 8.0, "skills": 4.0, "body": 1.0, "company": 0.5}

ПОЛЯ = {"title": "в названии", "skills": "в навыках", "body": "в описании", "company": "в названии компании"}

# Сколько слов подряд может быть одним названием из словаря навыков.
СЛОВ_В_НАЗВАНИИ = 4

# Насколько слово должно быть похоже на известное, чтобы считаться его
# опечаткой. Ниже — начинаются подмены одного слова другим.
ПОРОГ_ОПЕЧАТКИ = 0.42

# Короче этого слово не исправляется: у трёх букв слишком мало
# признаков, и «фар» превращалось бы в «бар».
МИНИМУМ_ДЛЯ_ОПЕЧАТКИ = 4

# Латинские названия, записанные кириллицей на слух.
_ТРАНСЛИТ = str.maketrans({
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ж": "zh", "з": "z", "и": "i",
    "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r", "с": "s",
    "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ы": "y", "э": "e", "ю": "yu", "я": "ya", "ь": "", "ъ": "",
})

_КИРИЛЛИЦА = re.compile(r"[а-я]")

# Единица запроса: слово либо несколько слов через дефис.
_СОСТАВНОЕ = re.compile(r"[a-zа-я0-9+#]+(?:-[a-zа-я0-9+#]+)*")

# Слово, встреченное реже этого, считается подозрительным: возможно,
# это опечатка, которую кто-то уже допустил в вакансии.
РЕДКОЕ_СЛОВО = 3

СХЕМА = """
CREATE TABLE IF NOT EXISTS search_docs (
    rowid       INTEGER PRIMARY KEY,
    vacancy_id  TEXT NOT NULL UNIQUE
);
CREATE VIRTUAL TABLE IF NOT EXISTS search_fts USING fts5(
    title, skills, body, company,
    tokenize = "unicode61 remove_diacritics 2"
);
CREATE VIRTUAL TABLE IF NOT EXISTS search_vocab USING fts5vocab(search_fts, 'row');
"""


def создать(conn: sqlite3.Connection) -> None:
    """Таблицы индекса. Повторный вызов ничего не меняет."""
    conn.executescript(СХЕМА)


def записать(conn: sqlite3.Connection, документы: Iterable[Документ]) -> int:
    """
    Записать документы в индекс; известные — заменить.

    Ключ строки индекса — номер из `search_docs`, а не идентификатор
    вакансии: удалить строку полнотекстовой таблицы по её номеру —
    мгновенно, по значению поля — просмотр всего индекса.
    """
    создать(conn)
    записано = 0
    for документ in документы:
        строка = conn.execute("SELECT rowid FROM search_docs WHERE vacancy_id = ?", (документ.ид,)).fetchone()
        if строка:
            номер = строка[0]
            conn.execute("DELETE FROM search_fts WHERE rowid = ?", (номер,))
        else:
            номер = conn.execute("INSERT INTO search_docs (vacancy_id) VALUES (?)", (документ.ид,)).lastrowid
        conn.execute(
            "INSERT INTO search_fts (rowid, title, skills, body, company) VALUES (?, ?, ?, ?, ?)",
            (номер, привести(документ.название), привести(документ.навыки),
             привести(документ.описание), привести(документ.компания)),
        )
        записано += 1
    _сбросить_словарь(conn)
    return записано


def убрать(conn: sqlite3.Connection, идентификаторы: Iterable[str]) -> None:
    """Убрать вакансии из индекса."""
    for ид in идентификаторы:
        строка = conn.execute("SELECT rowid FROM search_docs WHERE vacancy_id = ?", (str(ид),)).fetchone()
        if строка:
            conn.execute("DELETE FROM search_fts WHERE rowid = ?", (строка[0],))
            conn.execute("DELETE FROM search_docs WHERE rowid = ?", (строка[0],))
    _сбросить_словарь(conn)


def размер(conn: sqlite3.Connection) -> int:
    """Сколько вакансий в индексе. Ноль — индекса нет или он пуст."""
    try:
        return conn.execute("SELECT COUNT(*) FROM search_docs").fetchone()[0]
    except sqlite3.OperationalError:
        return 0


