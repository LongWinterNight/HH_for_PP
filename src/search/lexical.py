@dataclass
class Найденное:
    """Итог поиска по словам."""

    запрос: Запрос
    # Идентификаторы вакансий, от лучшего совпадения к худшему.
    порядок: List[str] = field(default_factory=list)
    # Где совпало: идентификатор → «в названии», «в навыках»…
    где: Dict[str, str] = field(default_factory=dict)
    # Совпали не все слова запроса: точных совпадений не нашлось.
    ослаблен: bool = False


def найти(
    conn: sqlite3.Connection,
    запрос: str,
    синонимы: Optional[Dict[str, str]] = None,
    сколько: int = 500,
) -> Найденное:
    """
    Вакансии, отвечающие запросу, от лучшей к худшей.

    Сначала ищутся вакансии со всеми словами запроса. Если таких нет,
    условие ослабляется до «любое из слов», и это отмечается в ответе:
    выдача «по одному слову из трёх» не должна выглядеть точной.
    """
    разобранный = разобрать(запрос, словарь(conn), синонимы)
    итог = Найденное(запрос=разобранный)
    if разобранный.пуст or размер(conn) == 0:
        return итог

    веса = ", ".join(str(ВЕСА[поле]) for поле in ("title", "skills", "body", "company"))
    выборка = (
        "SELECT d.vacancy_id FROM search_fts JOIN search_docs d ON d.rowid = search_fts.rowid "
        f"WHERE search_fts MATCH ? ORDER BY bm25(search_fts, {веса}) LIMIT ?"
    )

    строки = _выполнить(conn, выборка, (разобранный.выражение(), сколько))
    if not строки and len(разобранный.группы) > 1:
        строки = _выполнить(conn, выборка, (разобранный.выражение(все_группы=False), сколько))
        итог.ослаблен = bool(строки)

    итог.порядок = [строка[0] for строка in строки]
    итог.где = _где_совпало(conn, разобранный, set(итог.порядок), все_группы=not итог.ослаблен)
    return итог


def _выполнить(conn: sqlite3.Connection, запрос: str, параметры: Sequence) -> list:
    try:
        return conn.execute(запрос, параметры).fetchall()
    except sqlite3.OperationalError:
        # Запрос, который FTS5 не смог разобрать, — не повод ронять
        # экран: поиск просто ничего не находит.
        return []


def _где_совпало(
    conn: sqlite3.Connection, запрос: Запрос, найденные: Set[str], все_группы: bool
) -> Dict[str, str]:
    """
    В каком поле вакансии нашёлся запрос.

    Называется самое значимое поле: если запрос есть и в названии, и в
    описании, человеку важно первое.
    """
    где: Dict[str, str] = {}
    if not найденные:
        return где
    for поле in ("title", "skills", "company", "body"):
        строки = _выполнить(
            conn,
            "SELECT d.vacancy_id FROM search_fts JOIN search_docs d ON d.rowid = search_fts.rowid "
            "WHERE search_fts MATCH ?",
            # Достаточно части запроса: «3д макс визуализатор» находит
            # вакансию визуализатора с 3ds Max в навыках — запрос
            # целиком не лежит ни в одном поле, а самое значимое
            # совпадение всё равно в названии.
            (запрос.выражение(все_группы=False, поле=поле),),
        )
        for (ид,) in строки:
            if ид in найденные:
                где.setdefault(ид, ПОЛЯ[поле])
    return где
