@dataclass
class Запрос:
    """Запрос, разобранный на группы взаимозаменяемых вариантов."""

    исходный: str
    # Каждая группа — варианты одного и того же: достаточно любого.
    # Между группами — «и»: вакансия должна отвечать каждой.
    группы: List[List[str]] = field(default_factory=list)
    # Что было заменено и на что: «дизайнр» → «дизайнер».
    замены: Dict[str, str] = field(default_factory=dict)

    @property
    def пуст(self) -> bool:
        return not self.группы

    def выражение(self, все_группы: bool = True, поле: Optional[str] = None) -> str:
        """Запрос на языке FTS5."""
        части = []
        for группа in self.группы:
            варианты = " OR ".join(_фраза(вариант) for вариант in группа)
            часть = f"({варианты})"
            части.append(f"{{{поле}}} : {часть}" if поле else часть)
        return (" AND " if все_группы else " OR ").join(части)


def _фраза(вариант: str) -> str:
    # Звёздочка в конце — «слово начинается так»; она стоит вне кавычек.
    if вариант.endswith("*"):
        return '"' + вариант[:-1].replace('"', '""') + '"*'
    return '"' + вариант.replace('"', '""') + '"'


def _варианты_синонимов(синонимы: Dict[str, str]) -> Tuple[Dict[str, str], Dict[str, List[str]]]:
    """
    Таблица синонимов в виде, удобном для разбора запроса.

    Returns:
        (написание → канон, канон → все написания). Написания приведены
        так же, как слова запроса, и дополнительно склеены: «3ds max» и
        «3dsmax» должны узнаваться друг в друге.
    """
    к_канону: Dict[str, str] = {}
    написания: Dict[str, List[str]] = {}
    for вариант, канон in синонимы.items():
        приведённый = " ".join(слова(вариант))
        if not приведённый:
            continue
        for ключ in (приведённый, приведённый.replace(" ", "")):
            к_канону.setdefault(ключ, канон)
        написания.setdefault(канон, [])
        if приведённый not in написания[канон]:
            написания[канон].append(приведённый)
    return к_канону, написания


def разобрать(
    запрос: str,
    известные: Optional[Словарь] = None,
    синонимы: Optional[Dict[str, str]] = None,
) -> Запрос:
    """
    Разобрать запрос на группы вариантов.

    Args:
        запрос: Что набрал человек
        известные: Словарь индекса. Без него опечатки не исправляются
        синонимы: Таблица «написание → канон» из словаря навыков
    """
    итог = Запрос(исходный=запрос)
    # Слова через дефис — одно название: «арт-директор» не равно «арт»
    # и «директор» по отдельности. Без этого по запросу находился
    # «директор ресторана, любит арт».
    единицы = [единица for единица in _СОСТАВНОЕ.findall((запрос or "").lower().replace("ё", "е")) if слова(единица)]
    if not единицы:
        return итог

    к_канону, написания = _варианты_синонимов(синонимы or {})
    набранное = [слово for единица in единицы for слово in слова(единица)]
    # Где в набранном начинается и кончается каждая составная единица.
    границы, начало = {}, 0
    for единица in единицы:
        части = слова(единица)
        if len(части) > 1:
            границы[начало] = len(части)
        начало += len(части)

    i = 0
    while i < len(набранное):
        # Самое длинное название из словаря, начинающееся с этого слова.
        найдено = False
        for длина in range(min(СЛОВ_В_НАЗВАНИИ, len(набранное) - i), 0, -1):
            окно = набранное[i:i + длина]
            канон = к_канону.get(" ".join(окно)) or к_канону.get("".join(окно))
            if канон and (длина > 1 or len(написания.get(канон, [])) > 1):
                варианты = list(dict.fromkeys(привести(написание) for написание in написания[канон]))
                итог.группы.append([вариант for вариант in варианты if вариант])
                i += длина
                найдено = True
                break
        if найдено:
            continue

        if i in границы:
            # Составное слово, которого словарь не знает: слова подряд
            # либо слитно — «арт директор» и «артдиректор».
            части = набранное[i:i + границы[i]]
            подряд = привести(" ".join(части))
            итог.группы.append(list(dict.fromkeys([подряд, привести("".join(части))])))
            i += границы[i]
            continue

        сырое = набранное[i]
        слово = привести(сырое)
        последнее = i == len(набранное) - 1
        i += 1
        if not слово:
            continue

        варианты = [слово]
        if известные is not None:
            частота = известные.частоты.get(слово, 0)
            латиницей = сырое.translate(_ТРАНСЛИТ) if _КИРИЛЛИЦА.search(сырое) else None

            def заметно_чаще(кандидат: str) -> bool:
                return известные.частоты.get(кандидат, 0) > max(частота, 1) * 3

            # Латинское название, записанное кириллицей буква в букву:
            # «фигма». Само слово в индексе встречается — так пишут и в
            # вакансиях, — но в разы реже латинского, и искать только по
            # нему значит показать одну вакансию из сотни.
            if латиницей and латиницей in известные and заметно_чаще(латиницей):
                варианты.append(латиницей)
                итог.замены[сырое] = латиницей

            elif частота < РЕДКОЕ_СЛОВО:
                # Порядок догадок — от самой вероятной. Человек ещё
                # печатает: «дизай» — начало слова, а не опечатка. Берётся
                # набранное, а не его начальная форма: разборщик делает из
                # «дизай» глагол «дизать».
                if последнее and len(сырое) >= 3 and известные.есть_с_началом(сырое):
                    варианты.append(сырое + "*")
                else:
                    # Опечатка в русском слове: «дизайнр», «проэктировщик».
                    похожие = [похожее for похожее in известные.ближайшие(слово) if похожее != слово]
                    # И только если русского слова не нашлось — название,
                    # записанное на слух с ошибкой. В обратном порядке
                    # «дизайнр» превращался в узбекское «dizayn».
                    if not похожие and латиницей:
                        похожие = [похожее for похожее in известные.ближайшие(латиницей, сколько=1)]
                    if похожие:
                        варианты.extend(похожие)
                        итог.замены[сырое] = ", ".join(похожие)

            elif латиницей:
                # Слово известное, но латинское название может быть в
                # разы чаще: «фотошоп» — двенадцать вакансий, Photoshop —
                # сотни.
                for похожее in известные.ближайшие(латиницей, сколько=1):
                    if заметно_чаще(похожее):
                        варианты.append(похожее)
                        итог.замены[сырое] = похожее

        итог.группы.append(list(dict.fromkeys(варианты)))

    return итог


