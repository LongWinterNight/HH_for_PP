# Словарь индекса: какие слова в нём вообще есть
# ---------------------------------------------------------------------------

class Словарь:
    """Слова индекса и их частота — по ним узнаются опечатки."""

    def __init__(self, частоты: Dict[str, int]) -> None:
        self.частоты = частоты
        self._по_триграммам: Optional[Dict[str, Set[str]]] = None

    def __contains__(self, слово: str) -> bool:
        return слово in self.частоты

    def есть_с_началом(self, начало: str) -> bool:
        return any(слово.startswith(начало) for слово in self.частоты)

    def ближайшие(self, слово: str, сколько: int = 2) -> List[str]:
        """
        Известные слова, на которые это похоже, от самого похожего.

        Возвращается не одно слово, а до двух: «дизайнр» одинаково
        близок к «дизайн» и к «дизайнер», и выбрать за человека значит
        в половине случаев выбрать не то.
        """
        if len(слово) < МИНИМУМ_ДЛЯ_ОПЕЧАТКИ:
            return []
        if self._по_триграммам is None:
            self._по_триграммам = {}
            for известное, частота in self.частоты.items():
                # Слово, встреченное в одной вакансии, само может быть
                # опечаткой: исправлять на него нельзя.
                if частота >= 2 and len(известное) >= МИНИМУМ_ДЛЯ_ОПЕЧАТКИ:
                    for часть in _триграммы(известное):
                        self._по_триграммам.setdefault(часть, set()).add(известное)

        части = _триграммы(слово)
        общих: Dict[str, int] = {}
        for часть in части:
            for известное in self._по_триграммам.get(часть, ()):
                общих[известное] = общих.get(известное, 0) + 1

        # Триграммы только отбирают кандидатов; решает число правок,
        # которыми одно слово получается из другого. По одним триграммам
        # «дизайнр» оказывался ближе к обрывку «дизай», чем к «дизайнер»,
        # хотя до «дизайнер» одна вставка, а до «дизай» — две правки.
        оценки = []
        for известное, число in общих.items():
            if abs(len(известное) - len(слово)) > 2:
                continue
            сходство = число / (len(части) + len(_триграммы(известное)) - число)
            if сходство >= ПОРОГ_ОПЕЧАТКИ:
                оценки.append((_правок(слово, известное), -self.частоты[известное], известное))
        if not оценки:
            return []

        оценки.sort()
        наименьшее = оценки[0][0]
        # Все слова на том же расстоянии — равноправные догадки.
        return [найденное for правок, _, найденное in оценки if правок == наименьшее][:сколько]

    def ближайшее(self, слово: str) -> Optional[str]:
        """Самое похожее известное слово либо None."""
        найденные = self.ближайшие(слово, сколько=1)
        return найденные[0] if найденные else None


def _правок(первое: str, второе: str) -> int:
    """
    Сколько правок превращают одно слово в другое.

    Правка — вставка, удаление, замена буквы или перестановка двух
    соседних: «дизанйер» — одна опечатка, а не две.
    """
    прошлая2: List[int] = []
    прошлая = list(range(len(второе) + 1))
    for i, буква in enumerate(первое, start=1):
        текущая = [i]
        for j, другая in enumerate(второе, start=1):
            цена = 0 if буква == другая else 1
            значение = min(прошлая[j] + 1, текущая[j - 1] + 1, прошлая[j - 1] + цена)
            if i > 1 and j > 1 and буква == второе[j - 2] and первое[i - 2] == другая:
                значение = min(значение, прошлая2[j - 2] + 1)
            текущая.append(значение)
        прошлая2, прошлая = прошлая, текущая
    return прошлая[-1]


def _триграммы(слово: str) -> Set[str]:
    обрамлённое = f"  {слово} "
    return {обрамлённое[i:i + 3] for i in range(len(обрамлённое) - 2)}


# Словари по базам: путь файла → (штамп индекса, словарь).
_словари: Dict[str, Tuple[tuple, Словарь]] = {}


def _база(conn: sqlite3.Connection) -> str:
    """Файл базы за соединением: по нему словарь узнаёт свой индекс."""
    строка = conn.execute("PRAGMA database_list").fetchone()
    return строка[2] or f"память:{id(conn)}"


def _сбросить_словарь(conn: sqlite3.Connection) -> None:
    _словари.pop(_база(conn), None)


def словарь(conn: sqlite3.Connection) -> Словарь:
    """
    Словарь индекса.

    Читается один раз на состояние индекса. Состояние узнаётся по числу
    документов и последнему номеру: индекс пишет не только этот процесс
    — сбор из командной строки идёт рядом с открытым экраном, и словарь,
    прочитанный до него, не знал бы слов из новых вакансий.
    """
    try:
        штамп = tuple(conn.execute("SELECT COUNT(*), COALESCE(MAX(rowid), 0) FROM search_docs").fetchone())
    except sqlite3.OperationalError:
        return Словарь({})

    ключ = _база(conn)
    запомненное = _словари.get(ключ)
    if запомненное is None or запомненное[0] != штамп:
        строки = conn.execute("SELECT term, doc FROM search_vocab").fetchall()
        _словари[ключ] = (штамп, Словарь({слово: частота for слово, частота in строки}))
    return _словари[ключ][1]


