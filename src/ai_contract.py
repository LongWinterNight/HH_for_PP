"""
Контракт ответа модели: что она обязана вернуть и чему мы верим.

Зачем. Модель отвечает текстом, а в базу должна попасть структура. Между
одним и другим — место, где ошибка стоит дороже всего: неверно разобранный
ответ не падает, а тихо превращается в навык, которого в вакансии нет.
Продукт уже убирал среднюю зарплату за то, что её нельзя объяснить;
выдуманный навык — та же болезнь, только незаметнее, потому что выглядит
правдоподобно.

Три защиты, и каждая закрывает свой способ соврать:

1. **Схема целиком.** Ответ либо разбирается весь, либо отбрасывается
   весь. Половина разобранного ответа хуже отсутствующего: она выглядит
   как результат работы.
2. **Цитата обязательна.** У каждого навыка есть поле «как в тексте» —
   то, из чего он получен. Без него человек, подтверждающий кандидата,
   принимает решение вслепую.
3. **Цитата проверяется по описанию.** Модель может сослаться на слова,
   которых в вакансии нет. Такой навык отбрасывается: это единственный
   способ отличить находку от выдумки, не читая вакансию самому.

Этот модуль не ходит в сеть и не знает, какая модель отвечает. Он про
границу: что мы принимаем, а что нет.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Any, Dict, List, Optional, Tuple

from src.normalize import без_гомоглифов

# Виды навыков из § 11.4 разбора: по ним видно, что перед нами —
# инструмент, который ставят, или умение, которому учатся.
ВИДЫ = ("инструмент", "технология", "метод", "язык", "компетенция")

# Ниже этого порога навык не идёт даже в кандидаты. Порог намеренно
# низкий: отсев по уверенности — грубая мера, а тонкая работа делается
# порогом «три работодателя» и подтверждением человеком.
МИН_УВЕРЕННОСТЬ = 0.3


class ОтветСломан(ValueError):
    """
    Ответ модели не разобран.

    Отдельный тип, а не голый ValueError: вызывающий код обязан отличать
    «модель ответила ерундой» от собственных ошибок — первое ожидаемо и
    лечится повторным проходом, второе нет.
    """


@dataclass(frozen=True)
class ИзвлечённыйНавык:
    """Навык, названный моделью, вместе с основанием."""

    название: str
    как_в_тексте: str
    вид: str
    уверенность: float
    родитель: Optional[str] = None

    def __post_init__(self) -> None:
        if not self.название.strip():
            raise ОтветСломан("у навыка пустое название")
        # Цитата обязательна именно здесь, а не при проверке ответа:
        # объект без неё не должен существовать вовсе, иначе он утечёт
        # в базу через любой обходной путь.
        if not self.как_в_тексте.strip():
            raise ОтветСломан(f"навык «{self.название}» без цитаты из текста")
        if self.вид not in ВИДЫ:
            raise ОтветСломан(f"навык «{self.название}»: неизвестный вид «{self.вид}»")
        if not 0.0 <= self.уверенность <= 1.0:
            raise ОтветСломан(
                f"навык «{self.название}»: уверенность {self.уверенность} вне 0…1"
            )


@dataclass(frozen=True)
class ОтветИзвлечения:
    """Разобранный ответ модели по одной вакансии."""

    навыки: List[ИзвлечённыйНавык]
    язык_текста: str
    версия_модели: str
    версия_промпта: str

    def __post_init__(self) -> None:
        # Версии обязательны: без них прошлые числа нечем объяснить после
        # смены модели или промпта. Это то же правило, по которому
        # рублёвый эквивалент хранится вместе с датой курса.
        for поле in ("версия_модели", "версия_промпта"):
            if not getattr(self, поле).strip():
                raise ОтветСломан(f"в ответе нет поля «{поле}»")


def _строка(данные: Dict[str, Any], ключ: str, где: str) -> str:
    значение = данные.get(ключ)
    if not isinstance(значение, str) or not значение.strip():
        raise ОтветСломан(f"{где}: поле «{ключ}» отсутствует или не строка")
    return значение.strip()


def разобрать_ответ(данные: Any) -> ОтветИзвлечения:
    """
    Превратить ответ модели в структуру или отказаться целиком.

    Частичный разбор запрещён намеренно. Модель, сбившаяся на одном
    навыке, обычно сбита и на остальных, а половина ответа неотличима на
    вид от полного — и именно поэтому опаснее пустого.
    """
    if not isinstance(данные, dict):
        raise ОтветСломан(f"ответ не объект, а {type(данные).__name__}")

    сырые = данные.get("навыки")
    if not isinstance(сырые, list):
        raise ОтветСломан("в ответе нет списка «навыки»")

    навыки = []
    for i, сырой in enumerate(сырые):
        if not isinstance(сырой, dict):
            raise ОтветСломан(f"навык №{i + 1} не объект")
        где = f"навык №{i + 1}"
        уверенность = сырой.get("уверенность", 1.0)
        if not isinstance(уверенность, (int, float)):
            raise ОтветСломан(f"{где}: уверенность не число")
        родитель = сырой.get("родитель")
        if родитель is not None and not isinstance(родитель, str):
            raise ОтветСломан(f"{где}: родитель не строка")
        навыки.append(
            ИзвлечённыйНавык(
                название=_строка(сырой, "название", где),
                как_в_тексте=_строка(сырой, "как_в_тексте", где),
                вид=_строка(сырой, "вид", где),
                уверенность=float(уверенность),
                родитель=(родитель or None),
            )
        )

    return ОтветИзвлечения(
        навыки=навыки,
        язык_текста=_строка(данные, "язык_текста", "ответ"),
        версия_модели=_строка(данные, "версия_модели", "ответ"),
        версия_промпта=_строка(данные, "версия_промпта", "ответ"),
    )


def _подготовить(текст: str) -> str:
    """
    Текст в виде, пригодном для сверки цитаты.

    Регистр и лишние пробелы не считаются расхождением: модель цитирует
    смысл, а не байты. Гомоглифы чинятся тем же способом, что и при
    поиске навыков, — иначе цитата «Exсel» с русской «с» не найдётся в
    тексте, где стоит ровно она же.
    """
    return " ".join(без_гомоглифов((текст or "").lower()).split())


def без_выдуманного(
    ответ: ОтветИзвлечения,
    описание: str,
) -> Tuple[ОтветИзвлечения, List[ИзвлечённыйНавык]]:
    """
    Оставить навыки, чья цитата действительно есть в описании.

    Returns:
        Пара: очищенный ответ и список отброшенных навыков. Отброшенные
        возвращаются, а не теряются: их число — мера того, насколько
        модели можно верить, и оно попадает в лог прогона.
    """
    текст = _подготовить(описание)
    оставлены, отброшены = [], []
    for навык in ответ.навыки:
        цитата = _подготовить(навык.как_в_тексте)
        if цитата and цитата in текст and навык.уверенность >= МИН_УВЕРЕННОСТЬ:
            оставлены.append(навык)
        else:
            отброшены.append(навык)
    return replace(ответ, навыки=оставлены), отброшены
