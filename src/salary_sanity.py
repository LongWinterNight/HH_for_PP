"""
Правдоподобие зарплаты: одно место, где решается, верить ли числу.

Зачем. В данных источника встречаются зарплаты, которых не бывает:
«Structural Steel Supervisor, 18 EUR», «HR Assistant, 400 UZS»,
«менеджер по подбору, от 50 до 100 000 ₽». Причины две — часовая ставка, попавшая в
поле месячной, и потерянные при наборе нули, — и первая из них не
догадка: hh.ru отдаёт период выплаты в `salary_range.mode`. Пока это
поле не собрано по всей базе, правило работает по величине; там, где
период известен, решает он (см. `src/salary_mode.py`).

Что с этим делаем (решение записано в `docs/data-issues.md`, запись 13).
Запись не удаляем: она настоящая, а правило основано на догадке — всё,
что стоит на догадке, обязано быть обратимым и видимым. Вместо этого
помечаем причину сомнения; агрегаты считаются без помеченных, а сама
вакансия остаётся в списке и в выгрузке.

Почему это отдельный модуль. Агрегаты в хранилище пишутся сырым SQL и
живут в нескольких местах. Правило, размазанное по запросам, однажды
будет забыто в новом — и число снова начнёт врать, но уже только на
одном экране, что хуже всего.
"""

from __future__ import annotations

from typing import Optional

import pandas as pd

from src.salary_mode import это_месячная

# Нижняя граница правдоподобной месячной оплаты по валютам.
#
# Числа не взяты из МРОТ: подработка и неполный день законны, и порог по
# минимальной оплате отсёк бы настоящие вакансии. Порог примерно
# вдвадцатеро ниже медианы своей валюты — на замере 08.09.2026 это
# отсекает весь известный мусор и не задевает массу: у рубля первый
# перцентиль равен 20 000, то есть до порога 5 000 остаётся четырёхкратный
# запас.
#
# Пороги — договорённость, а не факт, и пересматриваются вручную. После
# правки признак у накопленных записей переставляется прогоном
# `python scripts/migrations/008_salary_doubt.py --пересчитать --yes`.
ПОРОГ_МЕСЯЧНОЙ_ОПЛАТЫ = {
    "RUB": 5_000,       # медиана 91 000, первый перцентиль 20 000
    "KZT": 20_000,      # медиана 350 000
    "UZS": 300_000,     # медиана 6 000 000
    "KGS": 3_000,       # медиана 60 000
    "BYR": 300,         # медиана 2 000; ниже — оплата за смену, не за месяц
    "BYN": 300,         # то же в новом коде валюты
    "USD": 100,         # медиана 1 300
    "EUR": 100,         # медиана 1 100
    "AZN": 100,
    "GEL": 100,
}

# Во сколько раз верхняя граница вилки может превышать нижнюю. «От 50 до
# 100 000 ₽» — это разрыв в две тысячи раз, и он означает не широкую
# вилку, а потерянные в нижней границе нули. Двадцатикратный разрыв ещё
# встречается у настоящих вакансий («от 30 000 до 600 000» у продавцов на
# проценте), поэтому предел взят с запасом.
ПРЕДЕЛЬНЫЙ_РАЗРЫВ_ВИЛКИ = 20

# Причины сомнения. Хранится причина, а не голый признак: человеку,
# увидевшему пометку, нужно понимать, что именно с числом не так.
МАЛО = "слишком мало для месячной оплаты"
РАЗРЫВ = "разрыв вилки: похоже на потерянные нули"


def причина_сомнения(
    salary_from: Optional[float],
    salary_to: Optional[float],
    currency: Optional[str],
    salary_mode: Optional[str] = None,
) -> Optional[str]:
    """
    Почему зарплате нельзя верить. None — с числом всё в порядке.

    Порог применяется только к месячной оплате. «1 000 ₽ за час» — не
    опечатка, а честная ставка, и красная пометка «слишком мало для
    месячной оплаты» под ней была враньём: так продукт и опозорился на
    вакансии Full-stack Developer (`docs/data-issues.md`, запись 15).
    Проверка семи помеченных записей показала, что пять из них — часовые
    и сменные ставки, а не ошибки.

    Валюта без известного порога сомнительной не считается: молчаливое
    отсеивание незнакомой валюты означало бы, что при выходе на новый
    рынок половина вакансий тихо исчезнет из статистики.
    """
    if not currency:
        return None

    порог = ПОРОГ_МЕСЯЧНОЙ_ОПЛАТЫ.get(currency.upper())
    if порог is None:
        return None

    # Проверяем ту границу, которая указана: у половины вакансий задана
    # только одна из двух.
    известная = salary_from if salary_from else salary_to
    if известная and известная < порог and это_месячная(salary_mode):
        return МАЛО

    if salary_from and salary_to and salary_from > 0:
        if salary_to / salary_from > ПРЕДЕЛЬНЫЙ_РАЗРЫВ_ВИЛКИ:
            return РАЗРЫВ

    return None


def зарплата_правдоподобна(
    salary_from: Optional[float],
    salary_to: Optional[float],
    currency: Optional[str],
) -> bool:
    """Короткая форма для мест, где причина не нужна."""
    return причина_сомнения(salary_from, salary_to, currency) is None


def только_правдоподобные(df):
    """
    Строки, чья зарплата участвует в расчётах.

    Отдельная функция, а не условие по месту: зарплатные числа считаются
    в доброй десятке мест — дашборд, аналитика, гистограмма, динамика,
    отчёт. Правило, переписанное в каждом из них, однажды будет забыто в
    новом, и число начнёт врать на одном экране из десяти — это хуже, чем
    если бы врало везде: расхождение никто не заметит.

    Пометка берётся из колонки, если она есть; иначе считается на месте —
    выборка может прийти не из базы, а из разбора файлов сбора.

    Не-месячная оплата отсеивается здесь же, даже когда с числом всё в
    порядке: «1 000 ₽ за час» — честная ставка, но в медиане месячных
    окладов ей делать нечего. Это то же правило, по которому не
    складываются рубли с тенге, только про время, а не про валюту.
    """
    if df is None or len(df) == 0 or "salary_from" not in df.columns:
        return df

    с_зарплатой = df[df["salary_from"].notna()]

    if "salary_mode" in с_зарплатой.columns:
        месячные = с_зарплатой["salary_mode"].apply(это_месячная)
        с_зарплатой = с_зарплатой[месячные]

    if "salary_doubt" in с_зарплатой.columns:
        return с_зарплатой[с_зарплатой["salary_doubt"].isna()]

    сомнение = с_зарплатой.apply(
        lambda строка: причина_сомнения(
            строка.get("salary_from"),
            строка.get("salary_to"),
            строка.get("salary_currency"),
            строка.get("salary_mode"),
        ),
        axis=1,
    )
    return с_зарплатой[pd.isna(сомнение)]
