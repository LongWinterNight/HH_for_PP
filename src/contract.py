"""
Контракт ответа источника: что обязано быть в его данных.

Зачем. Поля источника читаются напрямую, и пропажа поля выглядит как
пустое значение, а не как ошибка. Так уже случилось: hh.ru перенёс
зарплату из `salary` в `salary_range`, добавив туда период выплаты, — и
сбор месяцами писал в базу зарплаты без периода, считая часовые ставки
месячными. Никто ничего не заметил, потому что заметить было нечем:
пустое поле от исчезнувшего поля неотличимо.

Контракт называет минимум, без которого запись бесполезна, и отделяет
его от того, что «хорошо бы иметь». Нарушение — не повод уронить сбор:
вакансия без описания всё равно даёт название, зарплату и работодателя.
Но нарушение обязано быть посчитано и названо вслух.

Проверка дешёвая и выборочная: смотрится первая страница каждого
запроса. Схема меняется у источника целиком, а не у отдельной вакансии,
и сотня проверок на страницу ничего не добавит к одной.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

# Без этого ответ поиска не ответ: по нему нельзя ни прочитать вакансии,
# ни понять, сколько их всего и есть ли следующая страница.
ПОЛЯ_ОТВЕТА_ПОИСКА = ["items", "found", "pages", "page"]

# Минимум вакансии в выдаче. Идентификатор — то, чем она отличается от
# других; название и работодатель — то, ради чего она в базе; дата
# публикации решает, войдёт ли она в срез по возрасту.
ПОЛЯ_ВАКАНСИИ = ["id", "name", "employer", "published_at", "area"]

# Минимум карточки. Описание — единственное место, где живут навыки,
# не названные работодателем в отдельном поле.
ПОЛЯ_КАРТОЧКИ = ["id", "name", "employer", "description"]

# Поля, без которых работать можно, но хуже. Их пропажа — повод
# посмотреть, не сменилась ли схема: так уходила зарплата в
# `salary_range`, и это стоило месяцев неверных чисел.
# `schedule` и `employment` источник убрал: вместо них `work_format`,
# `work_schedule_by_days` и `employment_form`. Ждать исчезнувшее значило
# предупреждать на каждом запросе о том, что уже не изменится, — и за
# этим шумом не заметить следующую настоящую перемену.
ЖЕЛАТЕЛЬНЫЕ_ПОЛЯ_ВАКАНСИИ = ["salary", "salary_range", "experience", "work_format", "employment_form"]


def _нет_полей(данные: Optional[Dict[str, Any]], поля: List[str]) -> List[str]:
    """Каких полей не хватает. Значение None считается отсутствием."""
    if not isinstance(данные, dict):
        return list(поля)
    return [поле for поле in поля if данные.get(поле) is None]


def проверить_ответ_поиска(ответ: Optional[Dict[str, Any]]) -> List[str]:
    """Чего не хватает в ответе поиска. Пустой список — ответ годен."""
    return _нет_полей(ответ, ПОЛЯ_ОТВЕТА_ПОИСКА)


def проверить_вакансию(вакансия: Optional[Dict[str, Any]]) -> List[str]:
    """Чего не хватает в вакансии из выдачи."""
    return _нет_полей(вакансия, ПОЛЯ_ВАКАНСИИ)


def проверить_карточку(карточка: Optional[Dict[str, Any]]) -> List[str]:
    """Чего не хватает в карточке вакансии."""
    return _нет_полей(карточка, ПОЛЯ_КАРТОЧКИ)


def подозрительные_пропажи(вакансия: Optional[Dict[str, Any]]) -> List[str]:
    """
    Желательные поля, которых нет ни в одном виде.

    Зарплата считается на месте, если есть хотя бы одно из `salary` и
    `salary_range`: источник перенёс её из первого во второе, и требовать
    оба — значит объявить нарушением нормальную работу.
    """
    if not isinstance(вакансия, dict):
        return list(ЖЕЛАТЕЛЬНЫЕ_ПОЛЯ_ВАКАНСИИ)

    пропало = []
    if вакансия.get("salary") is None and вакансия.get("salary_range") is None:
        пропало.append("salary/salary_range")
    for поле in ЖЕЛАТЕЛЬНЫЕ_ПОЛЯ_ВАКАНСИИ:
        if поле in ("salary", "salary_range"):
            continue
        if вакансия.get(поле) is None:
            пропало.append(поле)
    return пропало


def проверить_страницу(ответ: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Проверить ответ поиска целиком: сам ответ и первую вакансию в нём.

    Returns:
        {
            "ответ": чего не хватает в ответе,
            "вакансия": чего не хватает в первой вакансии,
            "подозрительно": желательные поля, которых нет,
            "нарушен": правда ли нарушен обязательный минимум,
        }

        Пустая выдача нарушением не считается: «ничего не нашлось» —
        честный ответ источника, а не поломка схемы.
    """
    нет_в_ответе = проверить_ответ_поиска(ответ)

    items = (ответ or {}).get("items") or []
    первая = items[0] if items else None

    нет_в_вакансии = проверить_вакансию(первая) if первая else []
    подозрительно = подозрительные_пропажи(первая) if первая else []

    return {
        "ответ": нет_в_ответе,
        "вакансия": нет_в_вакансии,
        "подозрительно": подозрительно,
        "нарушен": bool(нет_в_ответе or нет_в_вакансии),
    }
