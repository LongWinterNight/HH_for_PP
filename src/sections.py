# Слова, которыми описывают соцпакет, а не требования к человеку.
#
# Нужны для разделов с авторскими заголовками: «праздничные сюрпризы»,
# «думаем о каждом», «заботимся о здоровье», «почему мы» — перечислить
# их в чёрном списке нельзя, а «Подарки» в топе навыков приходили именно
# оттуда. Такой раздел узнаётся по содержимому.
#
# Список нарочно узкий. «Зарплата» сюда не входит: «расчёт зарплаты» —
# настоящий навык бухгалтера. «Питание», «кофе» и «чай» тоже: для повара
# и бариста это предметная область, а не плюшки.
МАРКЕРЫ_УСЛОВИЙ = (
    "дмс",
    "тк рф",
    "трудовой кодекс",
    "официальное трудоустройство",
    "белая зарплата",
    "«белая» зарплата",
    "оклад",
    "испытательный срок",
    "корпоратив",
    "печеньк",
    "спортзал",
    "фитнес",
    "массаж",
    "страховка",
    "медицинская страховка",
    "подарки",
    "компенсация проезда",
    "оплачиваемый отпуск",
    "больничные",
)

# Сколько маркеров должно совпасть, чтобы счесть раздел условиями.
#
# Хватает одного. Разделы с плюшками короткие — «мы подготовим приятные
# подарки на праздники», — и трёх маркеров в них не набирается, а
# порог 3 пропускал их целиком. Риск ошибиться мал: правило работает
# только для авторских заголовков, знакомые разделы с требованиями
# берутся всегда и что бы в них ни стояло, а сами маркеры узкие —
# «ДМС», «корпоратив», «печеньки», «спортзал», а не «зарплата» или
# «питание», которые бывают предметом работы.
ПОРОГ_УСЛОВИЙ = 1


def похоже_на_условия(текст: str) -> bool:
    """Раздел с авторским заголовком, но с содержимым про соцпакет."""
    чистый = РАЗМЕТКА.sub(" ", текст).lower()
    совпало = sum(1 for маркер in МАРКЕРЫ_УСЛОВИЙ if маркер in чистый)
    return совпало >= ПОРОГ_УСЛОВИЙ


def _ключ(текст: str) -> str:
    """Заголовок в виде, пригодном для сравнения со списком."""
    без_разметки = РАЗМЕТКА.sub(" ", текст)
    только_буквы = re.sub(r"[^а-яёa-z ]", " ", без_разметки.lower())
    return re.sub(r"\s+", " ", только_буквы).strip()


def есть_текст(кусок: str) -> bool:
    """В куске есть слова, а не только разметка.

    Между закрывающим тегом абзаца и следующим заголовком остаётся
    «</p><p>» — обрывок, в котором нет ни одного слова. Пока он считался
    содержимым, описание из одних условий возвращало эту разметку вместо
    честного отказа отбирать разделы, и вакансия молча лишалась навыков.
    """
    return bool(РАЗМЕТКА.sub(" ", кусок or "").strip())


def похож_на_заголовок(ключ: str) -> bool:
    """Короткая фраза, а не выделенное жирным предложение.

    Работодатели выделяют полужирным и обычный текст — «мы ищем именно
    вас, если вы готовы работать в команде». Такое за заголовок не
    считается: иначе разделом станет каждое второе предложение.
    """
    return 4 <= len(ключ) <= 45 and len(ключ.split()) <= 5


def разделы(описание: str) -> List[Tuple[str, str]]:
    """
    Описание, разбитое на пары «заголовок, текст».

    Текст до первого заголовка возвращается с пустым заголовком: это
    вводная часть, и навыки там бывают.
    """
    if not описание:
        return []

    куски: List[Tuple[str, str]] = []
    позиция = 0
    текущий = ""

    for совпадение in ЗАГОЛОВОК.finditer(описание):
        ключ = _ключ(совпадение.group(2))
        if not похож_на_заголовок(ключ):
            continue

        кусок = описание[позиция:совпадение.start()]
        if есть_текст(кусок):
            куски.append((текущий, кусок))

        текущий = ключ
        позиция = совпадение.end()

    хвост = описание[позиция:]
    if есть_текст(хвост):
        куски.append((текущий, хвост))

    return куски


def текст_для_навыков(описание: str) -> str:
    """
    Часть описания, по которой имеет смысл искать навыки.

    Вакансия без узнаваемых заголовков разбирается целиком — так же, как
    раньше: у 5 % описаний структуры нет вовсе, и терять их нельзя.
    """
    куски = разделы(описание)
    if not куски:
        return описание or ""

    подходящие = []
    for заголовок, текст in куски:
        # Знакомый раздел с требованиями берётся всегда, что бы в нём ни
        # было написано: «опыт работы с ДМС» у кадровика — это навык.
        if заголовок in ПОЛЕЗНЫЕ_РАЗДЕЛЫ:
            подходящие.append(текст)
            continue

        # Знакомый раздел с условиями не берётся никогда.
        if заголовок in ШУМНЫЕ_РАЗДЕЛЫ:
            continue

        # Заголовок авторский — решает содержимое.
        if not похоже_на_условия(текст):
            подходящие.append(текст)

    # Всё отсеялось — берём описание целиком: пустой текст означал бы,
    # что вакансия молча лишилась навыков.
    return " ".join(подходящие) if подходящие else описание


def статистика_разделов(описание: str) -> Dict[str, int]:
    """Сколько символов в полезных разделах и сколько в отброшенных."""
    куски = разделы(описание)
    полезно = шум = 0

    for заголовок, текст in куски:
        длина = len(РАЗМЕТКА.sub(" ", текст).strip())
        if заголовок in ШУМНЫЕ_РАЗДЕЛЫ:
            шум += длина
        else:
            полезно += длина

    return {"полезно": полезно, "шум": шум, "разделов": len(куски)}
