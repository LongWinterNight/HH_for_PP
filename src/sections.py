"""
Разделы описания вакансии.

Зачем. Навыки искались по всему тексту разом, и в статистику попадало
то, что стоит в разделе «Условия»: «Подарки» у 70 вакансий, «Развитие» у
260, «Мотивация» у 129, «Больничные» у 26. «Подарки» дошли до топ‑10
навыков на дашборде — корпоративные подарки, засчитанные как
профессиональный навык.

Описания hh структурированы: подзаголовки есть у 95 % вакансий. Отделив
«Требования» и «Обязанности» от «Условий» и «Мы предлагаем», мы убираем
этот класс ошибок целиком — и это дешевле любого улучшения самого
поиска.

Правило отбора двухступенчатое, и одной ступени тут мало.

Чёрного списка не хватает: работодатели придумывают свои заголовки —
«праздничные сюрпризы», «думаем о каждом», «корпоративы и мероприятия»,
«наше предложение». Перечислить их нельзя, а «Подарки» приходили именно
оттуда.

Белого списка одного тоже мало: узнаваемый раздел с требованиями есть у
78 % описаний, у остальных структура своя или её нет вовсе.

Поэтому: если в описании нашёлся хотя бы один узнаваемый раздел с
требованиями — берутся только такие разделы, и вся авторская фантазия
остаётся за бортом. Если не нашёлся — берётся всё, кроме известного
шума. Так 78 % разбираются строго, а остальные не теряют навыки из-за
незнакомого заголовка.
"""

from __future__ import annotations

import re
from typing import Dict, List, Tuple

# Теги, которыми hh выделяет подзаголовки. Порядок не важен: ищется
# любой из них, вместе с вложенной разметкой внутри.
ЗАГОЛОВОК = re.compile(r"<(strong|b|h2|h3)[^>]*>(.*?)</\1>", re.S | re.I)

РАЗМЕТКА = re.compile(r"<[^>]+>")

# Разделы, где навыков не бывает. Список собран по живым данным: это
# самые частые подзаголовки из 9240 описаний.
#
