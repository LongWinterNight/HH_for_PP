# тестирования работает со следующим стеком: MS SQL, ClickHouse,
# RabbitMQ». Раздел выглядит рассказом о компании, а несёт половину
# технических навыков вакансии.
# Разделы, где кандидату говорят, что от него нужно. Список собран по
