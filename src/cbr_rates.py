"""
Официальные курсы валют ЦБ РФ.

Зачем. Зарплаты в выборке идут в девяти валютах, и сравнить их человеку
нечем: 19 000 000 сум и 300 000 рублей стоят в списке рядом, а какая
вакансия выгоднее — не поймёт никто. Рублёвый эквивалент отвечает на
этот вопрос, но только если курс настоящий: до этого модуля в коде
лежал словарь, набитый руками, с долларом по 92 при живых 86,47.

Источник — `cbr.ru/scripts/XML_daily.asp`: официальный, без ключа и без
лимитов, 54 валюты. Проверен живьём 08.09.2026.

Три вещи, которые видны только в настоящем ответе и стоят ошибки в сто
раз, если их не знать:

    номинал      курс даётся за 100 тенге, за 100 сомов и за 10 000
                 сумов, а не за единицу
    запятая      значения приходят как «86,4730» — float() без замены
                 падает
    код валюты   hh.ru отдаёт устаревший BYR, ЦБ котирует BYN; суммы при
                 этом соответствуют новому рублю, поэтому нужна
                 сопоставка кодов, а пересчёта номинала — нет

Дата курса берётся из ответа, а не из запроса: в выходной ЦБ отдаёт
последний рабочий день, и подпись «по курсу на 6 сентября» под
пятничным курсом была бы неправдой.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from datetime import date, datetime
from typing import Dict, Optional

import requests

from src.utils import get_logger

logger = get_logger(__name__)

АДРЕС = "https://www.cbr.ru/scripts/XML_daily.asp"

# Отдельная страница ЦБ на каждый запрос — небольшой XML, но источник
# чужой и бесплатный: ходить к нему чаще раза в сутки незачем, курс за
# день не меняется.
СРОК_ОЖИДАНИЯ = 15

# Коды валют, которые источник вакансий называет по-своему. hh.ru всё
# ещё пишет BYR — код белорусского рубля до деноминации 2016 года, — но
# суммы в объявлениях соответствуют нынешнему BYN (медиана 2 000).
СОПОСТАВКА_КОДОВ = {
    "BYR": "BYN",
    "RUR": "RUB",
}


@dataclass(frozen=True)
class Курсы:
    """
    Курсы на одну дату: сколько рублей стоит единица валюты.

    Номинал уже учтён — значения приведены к одной единице, чтобы
    пересчёт был обычным умножением и о номинале больше никто не помнил.
    """

    на_дату: date
    значения: Dict[str, float]

    def рублей_за(self, валюта: Optional[str]) -> Optional[float]:
        """
        Курс валюты. None — валюты в котировках нет.

        Пустой ответ важнее нуля: незнакомая валюта должна остаться без
        эквивалента и сказать об этом, а не превратиться в 0 ₽.
        """
        if not валюта:
            return None
        код = валюта.upper()
        код = СОПОСТАВКА_КОДОВ.get(код, код)
        if код == "RUB":
            return 1.0
        return self.значения.get(код)


def разобрать(xml: bytes) -> Курсы:
    """
    Разобрать ответ ЦБ.

    Отдельно от запроса, чтобы проверять на записанном ответе и не
    зависеть в тестах от сети и от того, работает ли сегодня ЦБ.
    """
    корень = ET.fromstring(xml)

    строка_даты = корень.get("Date") or ""
    try:
        на_дату = datetime.strptime(строка_даты, "%d.%m.%Y").date()
    except ValueError as e:
        raise ValueError(f"ЦБ вернул непонятную дату: {строка_даты!r}") from e

    значения: Dict[str, float] = {"RUB": 1.0}
    for валюта in корень:
        код = валюта.findtext("CharCode")
        сырое = валюта.findtext("Value")
        номинал = валюта.findtext("Nominal")
        if not (код and сырое and номинал):
            continue
        try:
            # Запятая как разделитель дробной части и номинал за сотню
            # или за десять тысяч — обе ловушки снимаются здесь, чтобы
            # дальше по коду курс был просто числом.
            значения[код] = float(сырое.replace(",", ".")) / float(номинал.replace(",", "."))
        except (ValueError, ZeroDivisionError):
            logger.warning(f"Курс {код} не разобран: значение {сырое!r}, номинал {номинал!r}")

    if len(значения) <= 1:
        raise ValueError("В ответе ЦБ не оказалось ни одной валюты")

    return Курсы(на_дату=на_дату, значения=значения)


def запросить(на: Optional[date] = None) -> Курсы:
    """
    Сходить в ЦБ за курсами.

    Args:
        на: дата курса. Без неё — последние опубликованные. В выходной и
            праздник ЦБ сам отдаёт последний рабочий день, поэтому
            календарь здесь не нужен — нужна лишь честность в подписи,
            а её обеспечивает дата из ответа.

    Raises:
        requests.RequestException: источник недоступен
        ValueError: ответ не разобран
    """
    параметры = {"date_req": на.strftime("%d/%m/%Y")} if на else None

    ответ = requests.get(
        АДРЕС,
        params=параметры,
        timeout=СРОК_ОЖИДАНИЯ,
        # Латиница не для красоты: заголовки HTTP кодируются latin-1,
        # и кириллица в User-Agent роняет запрос ещё до отправки.
        headers={"User-Agent": "BaseVacancy/1.0 (labour market analytics)"},
    )
    ответ.raise_for_status()

    курсы = разобрать(ответ.content)
    logger.info(f"Курсы ЦБ на {курсы.на_дату:%d.%m.%Y}: {len(курсы.значения)} валют")
    return курсы
