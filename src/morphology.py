"""
Морфология русских навыков.

Зачем. Словарь ищет точную форму, а работодатели пишут естественным
языком: в словаре «переговоры» и «презентации», в тексте — «ведение
переговоров», «проведение презентаций». Замер по эталону показал, где
это больнее всего: полнота по продажам 27 % против 91 % по
ИТ-разработке. В ИТ навыки — термины, которые не склоняют; в продажах,
HR и услугах навыки называют обычными словами, и они склоняются.

Что делается. Текст и навык приводятся к начальным формам, и сравнение
идёт по ним: «переговоров» → «переговоры» находит навык «переговоры».

Чего не делается. Латиница не трогается вовсе — `python`, `c#`,
`node.js` остаются как есть. pymorphy3 к английским словам применять
нельзя: он разбирает их как русские и портит («cache» превращается в
неведомое), а в ИТ-выдаче латиницы половина.
"""

from __future__ import annotations

import re
from functools import lru_cache
from typing import Optional

import pymorphy3

# Слово для разбора: буквы, цифры и символы, из которых состоят названия
# технологий. Точка, решётка и плюс внутри слова сохраняются — иначе
# «node.js» и «c#» распадутся на части.
СЛОВО = re.compile(r"[а-яёa-z0-9#+./_-]+", re.I)

КИРИЛЛИЦА = re.compile(r"[а-яё]", re.I)

_анализатор: Optional[pymorphy3.MorphAnalyzer] = None


def анализатор() -> pymorphy3.MorphAnalyzer:
    """Разборщик создаётся один раз: его инициализация — секунды."""
    global _анализатор
    if _анализатор is None:
        _анализатор = pymorphy3.MorphAnalyzer()
    return _анализатор


@lru_cache(maxsize=100_000)
def начальная_форма(слово: str) -> str:
    """
    Слово в начальной форме. Латиница возвращается как есть.

    Кэш обязателен: одни и те же слова повторяются в каждой вакансии
    тысячи раз, а разбор стоит примерно столько же, сколько всё
    остальное сопоставление.
    """
    if not КИРИЛЛИЦА.search(слово):
        return слово
    return анализатор().parse(слово)[0].normal_form


def привести(текст: str) -> str:
    """Текст, в котором русские слова стоят в начальной форме."""
    if not текст:
        return ""
    return " ".join(начальная_форма(с) for с in СЛОВО.findall(текст.lower()))


# Части речи, при которых начальная форма навыка достоверна.
#
# Навык — это предмет или действие, то есть существительное или
# отглагольное существительное. Когда разборщик считает слово
# прилагательным или местоимением, он ошибся насчёт того, что это за
# слово, и его «начальная форма» уводит в сторону: «ту» (технические
# условия) он приводит к «тот», а «гибка» (гибка металла) — к «гибкий»,
# после чего навык находится в «работать в ту же смену» и «гибкий
# график». На живой базе это дало 620 ложных «ТУ» и 209 ложных «Гибка».
ЧАСТИ_РЕЧИ_НАВЫКА = {"NOUN", "INFN"}


def нужна_ли(навык: str) -> bool:
    """Есть ли смысл приводить навык к начальной форме.

    Латинским названиям морфология не нужна и вредна. Русским — нужна,
    но только если разборщик видит в них существительное: иначе он
    нормализует не то слово (см. ЧАСТИ_РЕЧИ_НАВЫКА).
    """
    if not КИРИЛЛИЦА.search(навык):
        return False

    слова = СЛОВО.findall(навык.lower())
    if not слова:
        return False

    русские = [с for с in слова if КИРИЛЛИЦА.search(с)]
    if not русские:
        return False

    части = [str(анализатор().parse(с)[0].tag.POS) for с in русские]

    # Однословный навык обязан быть существительным сам: у «гибка» и
    # «ту» разборщик видит прилагательное и местоимение — значит понял
    # слово не так, как мы, и его начальная форма уведёт не туда.
    if len(русские) == 1:
        return части[0] in ЧАСТИ_РЕЧИ_НАВЫКА

    # У составного достаточно одного существительного: «активные
    # продажи» начинается с прилагательного, но говорит о продажах, и
    # склоняется целиком — «опыт активных продаж».
    return any(часть in ЧАСТИ_РЕЧИ_НАВЫКА for часть in части)
