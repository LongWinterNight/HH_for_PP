"""
География зарплат: страны, регионы и города одной выборки.

Зачем. Окно «Медиана по регионам» показывало города и называло их
регионами, а стран не знало вовсе — хотя в базе вакансии шести стран.
В записи вакансии лежит только название места; страну и регион ему
даёт справочник источника (`data/areas.json`): дерево «страна → регион →
город», которым до сих пор пользовался только сбор.

Окно отвечает на вопросы географии и только на них: где платят больше,
насколько страна или регион отличается от соседей, из чего территория
состоит. Опыт, формат работы и сферы сюда не входят — у них свои окна.

Правила чисел те же, что везде: только правдоподобные зарплаты,
средней нет, выборка меньше пяти чисел не даёт.

Копии одной вакансии по городам считаются по-разному на разных уровнях,
и это следует из решения S5‑1b. В городе копий нет: там вакансия одна.
В регионе и в стране одна вакансия, размещённая в двадцати городах,
весила бы как двадцать — поэтому на этих уровнях копии сводятся к одной
внутри своей территории. Счёт вакансий («сколько предложений») копии не
сводит нигде: в каждом городе предложение действительно есть.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

from src import regions
from src.copies import без_копий
from src.salary_sanity import только_правдоподобные
from src.utils import get_logger

logger = get_logger(__name__)

МАЛО = 5

# Корень справочника, под которым лежат не регионы одной страны, а
# остальные страны мира.
ДРУГИЕ = "Другие регионы"

_привязка_память: Dict[str, Any] = {"отметка": None, "значение": {}}


def привязка(дерево: List[Dict[str, Any]]) -> Dict[str, Tuple[str, str]]:
    """
    Место → (страна, регион) по дереву справочника.

    Регион — второй уровень дерева: область, край, республика. Город
    федерального значения сам себе регион. Под корнем «Другие регионы»
    лежат страны, поэтому там вторым уровнем считается страна.
    """
    где: Dict[str, Tuple[str, str]] = {}
    for корень in дерево or []:
        название = корень.get("name") or ""
        дети = корень.get("areas") or []
        if not дети:
            где.setdefault(название, (название, название))
            continue
        for второй in дети:
            страна = второй["name"] if название == ДРУГИЕ else название
            регион = второй["name"]
            где.setdefault(регион, (страна, регион))
            for город in второй.get("areas") or []:
                где.setdefault(город["name"], (страна, регион))
                # Глубже третьего уровня справочник почти не идёт, но
                # если идёт — место остаётся в том же регионе.
                for глубже in город.get("areas") or []:
                    где.setdefault(глубже["name"], (страна, регион))
    return где


def привязка_с_диска() -> Dict[str, Tuple[str, str]]:
    """
    Привязка по справочнику на диске, какой бы давности он ни был.

    Сбор требует свежего справочника: по нему режется запрос. Здесь нужен
    только ответ «в какой стране Казань», а он не меняется годами — ходить
    за ним в сеть при открытии экрана незачем.
    """
    путь = regions.ПУТЬ_СПРАВОЧНИКА
    try:
        отметка = путь.stat().st_mtime
    except OSError:
        return {}
    if _привязка_память["отметка"] != отметка:
        try:
            дерево = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as ошибка:
            logger.warning(f"Справочник регионов не прочитан: {ошибка}")
            return {}
        _привязка_память["значение"] = привязка(дерево)
        _привязка_память["отметка"] = отметка
    return _привязка_память["значение"]


def _числа(суммы: pd.Series) -> Dict[str, Any]:
    объём = int(len(суммы))
    if объём < МАЛО:
        return {"sample": объём, "weak": True, "q1": None, "median": None, "q3": None}
    return {
        "sample": объём, "weak": False,
        "q1": float(суммы.quantile(0.25)), "median": float(суммы.median()), "q3": float(суммы.quantile(0.75)),
    }


def собрать(
    df: pd.DataFrame,
    вид: str = "currency",
    валюта: str = "RUB",
    где: Optional[Dict[str, Tuple[str, str]]] = None,
) -> Dict[str, Any]:
    """
    Три уровня географии одним ответом.

    Все уровни приезжают сразу: их вместе меньше пятисот строк, а экран
    переходит от страны к её регионам и городам без запроса к серверу.

    Территория, где вакансий с зарплатой меньше пяти, чисел не получает,
    но остаётся: «в Грузии 55 вакансий, зарплата указана у трёх» — тоже
    сведение о географии.
    """
    в_рублях = вид in ("rub", "equivalent")
    колонка = "salary_from_rub" if в_рублях else "salary_from"
    пусто = {
        "basis": "equivalent" if в_рублях else "currency", "currency": "RUB" if в_рублях else валюта,
        "total": 0, "overall": {}, "countries": [], "regions": [], "cities": [], "unknown": 0,
    }
    if df is None or df.empty or "area" not in df.columns:
        return пусто

    где = привязка_с_диска() if где is None else где
    места = df["area"].map(lambda место: где.get(место) if isinstance(место, str) else None)
    df = df.assign(
        _страна=места.map(lambda пара: пара[0] if пара else None),
        _регион=места.map(lambda пара: пара[1] if пара else None),
    )
    # Место, которого нет в справочнике, не выдумывается: оно выпадает из
    # стран и регионов, а сколько таких вакансий — говорится вслух.
    неизвестных = int(df["_страна"].isna().sum())
    всего = int(len(df))

    считаемые = только_правдоподобные(df)
    if not в_рублях and "salary_currency" in считаемые.columns:
        считаемые = считаемые[считаемые["salary_currency"] == валюта]
    считаемые = считаемые[считаемые[колонка].notna()] if колонка in считаемые.columns else считаемые.iloc[0:0]

    def уровень(ключи: List[str], сводить_копии: bool) -> List[Dict[str, Any]]:
        объёмы = df[df[ключи[-1]].notna()].groupby(ключи).size()
        зарплаты = {}
        for ключ, группа in считаемые[считаемые[ключи[-1]].notna()].groupby(ключи):
            if сводить_копии:
                группа = без_копий(группа, колонка)
            зарплаты[ключ if isinstance(ключ, tuple) else (ключ,)] = группа[колонка]
        строки = []
        for ключ, объём in объёмы.items():
            ключ = ключ if isinstance(ключ, tuple) else (ключ,)
            строки.append({"ключ": ключ, "total": int(объём), **_числа(зарплаты.get(ключ, pd.Series(dtype=float)))})
        строки.sort(key=lambda с: (-с["total"], с["ключ"]))
        return строки

    страны = [
        {"label": с["ключ"][0], **{к: з for к, з in с.items() if к != "ключ"}}
        for с in уровень(["_страна"], сводить_копии=True)
    ]
    области = [
        {"label": с["ключ"][1], "country": с["ключ"][0], **{к: з for к, з in с.items() if к != "ключ"}}
        for с in уровень(["_страна", "_регион"], сводить_копии=True)
    ]
    города = [
        {"label": с["ключ"][2], "country": с["ключ"][0], "region": с["ключ"][1],
         **{к: з for к, з in с.items() if к != "ключ"}}
        for с in уровень(["_страна", "_регион", "area"], сводить_копии=False)
    ]

    # В какой валюте платят в стране. Нужно, чтобы объяснить пустоту:
    # в валютном виде у Казахстана почти нет чисел не потому, что там не
    # платят, а потому, что платят в тенге.
    if "salary_currency" in df.columns:
        for страна in страны:
            свои = df[(df["_страна"] == страна["label"]) & df["salary_currency"].notna()]["salary_currency"]
            счёт = свои.value_counts()
            страна["main_currency"] = str(счёт.index[0]) if len(счёт) else None
            страна["with_salary"] = int(len(свои))

    общие = без_копий(считаемые, колонка)[колонка] if not считаемые.empty else pd.Series(dtype=float)
    return {
        **пусто,
        "total": всего,
        "unknown": неизвестных,
        "overall": _числа(общие),
        "countries": страны,
        "regions": области,
        "cities": города,
    }
