"""
Сборка отчёта XLSX по правилам дизайн-системы.

Файл уходит наружу и живёт без продукта: его открывают люди, которые
экрана не видели, и открывают в редакторе таблиц, где нет ни наших
гарнитур, ни радиусов, ни границ через тень. Поэтому система переносится
не оформлением, а решениями:

    данные, а не картинка   числа числами, даты датами, ни одной
                            объединённой ячейки — получатель обязан иметь
                            возможность отфильтровать, отсортировать и
                            построить свою сводную
    файл объясняет себя     первый лист — срез: период, фильтры, дата
                            сбора, объём выборки. Через месяц никто не
                            помнит, откуда взялись числа
    валюты не складываются  строка на каждую валюту, итоговой строки
                            «всего» нет вообще
    оформление минимально   заливка только у шапки, линия только под ней

Четыре листа в порядке чтения: Срез, Вакансии, Сводка, Навыки. Порядок не
произвольный — сначала читатель узнаёт, откуда числа, и только потом
видит их.
"""

from __future__ import annotations

from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

import pandas as pd
from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

from src.config import settings
from src.salary_sanity import только_правдоподобные
from src.utils import get_logger, ensure_dir

logger = get_logger(__name__)

# Гарнитура файла — стандартная для редактора таблиц. Наши Geologica и
# Martian Mono у получателя не установлены: файл подставил бы что попало
# и разъехался по ширине колонок.
ШРИФТ = "Aptos Narrow"
КЕГЛЬ = 10
КЕГЛЬ_ШАПКИ = 11

# Цвета из дизайн-системы, приведённые к тому, что понимает редактор.
ЧЕРНИЛА = "FF050038"
СЕРЫЙ = "FF6E6C86"
СИНИЙ = "FF2B3ECC"
КРАСНЫЙ = "FF96271F"
ПОДЛОЖКА_ШАПКИ = "FFF2F1F6"

# Приставка в имени файла отчёта. По ней файл узнаётся своим: в папке
# лежат ещё экспорты и выгрузки прежних анализаторов.
ИМЯ_ОТЧЁТА = "basevacancy_"

# Девять колонок листа «Вакансии»: порядок неизменный, ширины заданы
# явно. Автоподбор ширины не используется — он ломается на длинных
# названиях вакансий и делает файл нечитаемым.
КОЛОНКИ = [
    {"поле": "vacancy_id", "заголовок": "ID", "ширина": 10, "формат": "@"},
    {"поле": "vacancy_name", "заголовок": "Вакансия", "ширина": 42, "формат": "@"},
    {"поле": "employer_name", "заголовок": "Компания", "ширина": 28, "формат": "@"},
    {"поле": "area", "заголовок": "Регион", "ширина": 18, "формат": "@"},
    {"поле": "salary_from", "заголовок": "Зарплата от", "ширина": 14, "формат": "# ##0"},
    {"поле": "salary_to", "заголовок": "Зарплата до", "ширина": 14, "формат": "# ##0"},
    {"поле": "salary_currency", "заголовок": "Валюта", "ширина": 9, "формат": "@"},
    {"поле": "experience", "заголовок": "Опыт", "ширина": 13, "формат": "@"},
    {"поле": "published_at", "заголовок": "Опубликована", "ширина": 14, "формат": "DD.MM.YYYY"},
    # Эквивалент стоит последним, а не рядом с суммой: колонки A–I
    # зафиксированы спекой, и сдвиг «Опыта» с «Опубликована» сломал бы
    # формулы и привычки у тех, кто уже работает с прежними файлами.
    # Внутри файла получатель переключателя не имеет — без этой колонки
    # он не может сравнить 19 000 000 сум с 300 000 рублей. Курс, по
    # которому она посчитана, назван строкой на листе «Срез».
    {"поле": "salary_from_rub", "заголовок": "В рублях", "ширина": 14, "формат": "# ##0"},
]

# Ниже этого объёма выборки медиана не показатель рынка: число остаётся,
# но подаётся серым — то же правило, что на экране.
МАЛАЯ_ВЫБОРКА = 10

АДРЕС_ПРОДУКТА = "basevacancy.ru"


def _шрифт(**kwargs) -> Font:
    return Font(name=ШРИФТ, size=kwargs.pop("size", КЕГЛЬ), **kwargs)


def _оформить_лист(ws: Worksheet) -> None:
    """
    Колонтитул и сетка.

    Колонтитул повторяется на каждом листе бумаги: без него распечатанная
    страница не говорит, откуда она.
    """
    ws.oddHeader.left.text = f"BaseVacancy · {АДРЕС_ПРОДУКТА}"
    ws.oddHeader.left.size = 9
    ws.oddHeader.right.text = "Страница &P из &N"
    ws.oddHeader.right.size = 9
    ws.sheet_view.showGridLines = False


def _шапка(ws: Worksheet, заголовки: List[str], ширины: List[int]) -> None:
    """
    Строка заголовков: единственное место с заливкой и границей.

    Файл, раскрашенный как экран, неудобен в работе: заливка мешает
    читать, а при копировании фрагмента в другой файл теряется.
    """
    линия = Border(bottom=Side(style="thin", color="FFD8D6E0"))
    заливка = PatternFill("solid", fgColor=ПОДЛОЖКА_ШАПКИ)

    for i, (текст, ширина) in enumerate(zip(заголовки, ширины), start=1):
        ячейка = ws.cell(row=1, column=i, value=текст)
        ячейка.font = _шрифт(bold=True, size=КЕГЛЬ_ШАПКИ, color=ЧЕРНИЛА)
        ячейка.fill = заливка
        ячейка.border = линия
        ws.column_dimensions[get_column_letter(i)].width = ширина


def лист_срез(wb: Workbook, срез: Dict[str, Any]) -> None:
    """
    Лист «Срез»: откуда взялись числа.

    Две колонки, ключ и значение. Ни одной объединённой ячейки: они
    ломают фильтр, сортировку и сводные таблицы, а получатель обязан
    иметь возможность работать дальше.
    """
    ws = wb.create_sheet("Срез")
    _оформить_лист(ws)
    _шапка(ws, ["Что", "Значение"], [28, 52])

    строки = [
        ("Отчёт", срез.get("название", "Выгрузка вакансий"), ЧЕРНИЛА, False),
        ("Отчёт собран в", "BaseVacancy · аналитика рынка труда", ЧЕРНИЛА, False),
        ("Адрес продукта", АДРЕС_ПРОДУКТА, СИНИЙ, True),
        ("Данные предоставил", "hh.ru · публичный API", ЧЕРНИЛА, False),
        ("Собран", срез.get("собран", ""), ЧЕРНИЛА, False),
        ("Данные собраны", срез.get("данные_собраны", "—"), ЧЕРНИЛА, False),
        ("Период публикаций", срез.get("период", "—"), ЧЕРНИЛА, False),
        ("Фильтры", срез.get("фильтры", "без фильтров"), ЧЕРНИЛА, False),
        ("Вакансий в выборке", срез.get("объём", ""), ЧЕРНИЛА, False),
        # Колонка «В рублях» без курса и даты ничем не подтверждена:
        # получатель должен видеть, по какому курсу и на какой день
        # посчитан эквивалент, — иначе число нечем проверить.
        ("Курс ЦБ на", срез.get("курс_на", "—"), ЧЕРНИЛА, False),
    ]

    # Две последние строки — самые важные и самые непривычные: сколько
    # вакансий без зарплаты и какая доля данных поэтому не участвует в
    # расчётах. Без этой оговорки отчёт вводит в заблуждение.
    оговорки = [
        ("Без указанной зарплаты", срез.get("без_зарплаты", ""), КРАСНЫЙ, False),
        ("Зарплатные числа считаны по", срез.get("с_зарплатой", ""), КРАСНЫЙ, False),
    ]

    for номер, (ключ, значение, цвет, ссылка) in enumerate(строки + оговорки, start=2):
        ws.cell(row=номер, column=1, value=ключ).font = _шрифт(color=СЕРЫЙ)
        ячейка = ws.cell(row=номер, column=2, value=значение)
        ячейка.font = _шрифт(color=цвет, underline="single" if ссылка else None)
        if ссылка:
            ячейка.hyperlink = f"https://{значение}"


def лист_вакансии(wb: Workbook, df: pd.DataFrame) -> None:
    """
    Лист «Вакансии»: сами данные, одна вакансия — одна строка.

    Числа записываются числами, даты датами. Пустая ячейка вместо «не
    указана»: текст в числовой колонке ломает и сортировку, и суммы, и
    весь смысл выгрузки.
    """
    ws = wb.create_sheet("Вакансии")
    _оформить_лист(ws)
    _шапка(ws, [к["заголовок"] for к in КОЛОНКИ], [к["ширина"] for к in КОЛОНКИ])

    for номер, (_, запись) in enumerate(df.iterrows(), start=2):
        for столбец, колонка in enumerate(КОЛОНКИ, start=1):
            значение = запись.get(колонка["поле"])

            if pd.isna(значение) or значение == "":
                значение = None
            elif колонка["формат"] == "# ##0":
                значение = float(значение)
            elif колонка["формат"] == "DD.MM.YYYY":
                разобранная = pd.to_datetime(значение, errors="coerce", utc=True)
                # До календарного дня: время публикации в отчёте не нужно, а
                # с ним ломается группировка по дате в сводной таблице.
                значение = разобранная.date() if pd.notna(разобранная) else None
            else:
                значение = str(значение)

            ячейка = ws.cell(row=номер, column=столбец, value=значение)
            ячейка.number_format = колонка["формат"]
            ячейка.font = _шрифт(color=ЧЕРНИЛА)
            if колонка["формат"] in ("# ##0", "DD.MM.YYYY"):
                ячейка.alignment = Alignment(horizontal="right")

        # ID ведёт на вакансию у источника: получатель проверяет данные
        # в один клик, а не ищет её поиском по названию.
        адрес = запись.get("vacancy_url")
        if isinstance(адрес, str) and адрес.startswith("http"):
            ссылка = ws.cell(row=номер, column=1)
            ссылка.hyperlink = адрес
            ссылка.font = _шрифт(color=СИНИЙ, underline="single")

    # Шапка закреплена и снабжена автофильтром: работать с файлом можно
    # сразу после открытия, не настраивая его.
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(КОЛОНКИ))}{max(2, len(df) + 1)}"


def лист_сводка(wb: Workbook, df: pd.DataFrame) -> None:
    """
    Лист «Сводка»: статистика по валютам, строка на валюту.

    Итоговой строки «всего» нет вообще: сумма разных валют — то самое
    число, из-за которого прежний интерфейс переделывали. Сложить рубли
    с тенге здесь нельзя даже формулой.
    """
    ws = wb.create_sheet("Сводка")
    _оформить_лист(ws)
    _шапка(ws, ["Валюта", "Минимум", "Медиана", "Средняя", "Максимум", "Вакансий"],
           [10, 14, 14, 14, 14, 11])

    # Без сомнительных: минимум по валюте — то самое число, которое они
    # рушат сильнее всего («от 7 ₽», «от 18 €»). Сами вакансии из листа
    # «Вакансии» никуда не деваются (src/salary_sanity.py).
    с_зарплатой = только_правдоподобные(df) if "salary_from" in df.columns else pd.DataFrame()
    if с_зарплатой.empty:
        return

    номер = 2
    группы = с_зарплатой.groupby("salary_currency")["salary_from"]
    for валюта, значения in sorted(группы, key=lambda пара: -len(пара[1])):
        # Объём выборки меньше десяти — медиана не показатель рынка.
        # Число остаётся, но подаётся серым: то же правило, что на экране.
        цвет_объёма = СЕРЫЙ if len(значения) < МАЛАЯ_ВЫБОРКА else ЧЕРНИЛА

        ws.cell(row=номер, column=1, value=str(валюта)).font = _шрифт(color=ЧЕРНИЛА)
        for столбец, число in enumerate(
            [значения.min(), значения.median(), средняя_по_валюте(значения), значения.max()], start=2
        ):
            ячейка = ws.cell(row=номер, column=столбец, value=float(число))
            ячейка.number_format = "# ##0"
            ячейка.font = _шрифт(color=ЧЕРНИЛА)
            ячейка.alignment = Alignment(horizontal="right")

        объём = ws.cell(row=номер, column=6, value=int(len(значения)))
        объём.font = _шрифт(color=цвет_объёма)
        объём.alignment = Alignment(horizontal="right")
        номер += 1


def средняя_по_валюте(значения: pd.Series) -> float:
    """Средняя по валюте.

    На экране средняя не показывается — её тянут выбросы. В файле она
    остаётся: получатель считает по-своему, и отсутствие колонки он
    воспримет как пропажу данных, а не как позицию.
    """
    return float(значения.mean())


def лист_навыки(wb: Workbook, df: pd.DataFrame, предел: int = 40) -> None:
    """
    Лист «Навыки»: частота навыков в выборке.

    Категория записана словом, а не заливкой: цвет в файле не переживает
    копирования фрагмента в чужую книгу, а текст переживает.
    """
    ws = wb.create_sheet("Навыки")
    _оформить_лист(ws)
    _шапка(ws, ["Навык", "Категория", "Вакансий", "Доля"], [30, 18, 12, 10])

    категории = [
        ("hard_skills", "Профессиональные"),
        ("soft_skills", "Личные"),
        ("tools", "Инструменты"),
    ]

    счётчик: Counter = Counter()
    к_категории: Dict[str, str] = {}
    for поле, подпись in категории:
        if поле not in df.columns:
            continue
        for строка in df[поле].dropna():
            for навык in str(строка).split(","):
                навык = навык.strip()
                if навык:
                    счётчик[навык] += 1
                    к_категории.setdefault(навык, подпись)

    всего = max(1, len(df))
    for номер, (навык, сколько) in enumerate(счётчик.most_common(предел), start=2):
        ws.cell(row=номер, column=1, value=навык).font = _шрифт(color=ЧЕРНИЛА)
        ws.cell(row=номер, column=2, value=к_категории.get(навык, "—")).font = _шрифт(color=СЕРЫЙ)

        число = ws.cell(row=номер, column=3, value=int(сколько))
        число.font = _шрифт(color=ЧЕРНИЛА)
        число.alignment = Alignment(horizontal="right")

        доля = ws.cell(row=номер, column=4, value=сколько / всего)
        доля.number_format = "0.0%"
        доля.font = _шрифт(color=ЧЕРНИЛА)
        доля.alignment = Alignment(horizontal="right")


def состав_файла(df: pd.DataFrame, предел_навыков: int = 40) -> Dict[str, Any]:
    """
    Что окажется в файле, посчитанное без сборки.

    Экран показывает это до того, как человек нажмёт кнопку: собранный
    впустую отчёт по трём вакансиям — потраченное время и файл, который
    стыдно отправить.

    Считается здесь, а не на экране, ровно теми же выражениями, что
    наполняют листы. Второй подсчёт «примерно так же» разошёлся бы с
    файлом при первой же правке одного из них, и экран начал бы обещать
    сорок навыков там, где их двенадцать.
    """
    вакансий = int(len(df))

    навыки: Counter = Counter()
    for поле in ("hard_skills", "soft_skills", "tools"):
        if поле not in df.columns:
            continue
        for строка in df[поле].dropna():
            for навык in str(строка).split(","):
                навык = навык.strip()
                if навык:
                    навыки[навык] += 1

    с_зарплатой = только_правдоподобные(df) if "salary_from" in df.columns else pd.DataFrame()
    валют = int(с_зарплатой["salary_currency"].nunique()) if not с_зарплатой.empty else 0

    return {
        "вакансий": вакансий,
        "навыков": min(len(навыки), предел_навыков),
        "навыков_всего": len(навыки),
        "валют": валют,
        "с_зарплатой": int(len(с_зарплатой)),
        "малая_выборка": вакансий < МАЛАЯ_ВЫБОРКА,
    }


def описать_срез(
    df: pd.DataFrame,
    фильтры: str = "без фильтров",
    данные_собраны: Optional[str] = None,
    название: Optional[str] = None,
    курс_на: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Собрать описание выборки для первого листа.

    Период считается по самим данным, а не по заданным фильтрам: получатель
    должен видеть, что в файле на самом деле, а не что просили собрать.
    Вызывается и из веба, и из командной строки, чтобы срез в обоих случаях
    описывался одинаково.
    """
    период = "—"
    if "published_at" in df.columns:
        даты = pd.to_datetime(df["published_at"], errors="coerce", utc=True).dropna()
        if not даты.empty:
            период = f"{даты.min():%d.%m.%Y} — {даты.max():%d.%m.%Y}"

    # Дата курса берётся из самих данных, если её не передали: эквивалент
    # считается при сохранении вакансии, и её день лежит рядом с числом.
    if not курс_на and "rate_date" in df.columns:
        даты_курса = pd.to_datetime(df["rate_date"], errors="coerce").dropna()
        if not даты_курса.empty:
            курс_на = f"{даты_курса.max():%d.%m.%Y}"

    return {
        "название": название or "Выгрузка вакансий",
        "период": период,
        "фильтры": фильтры,
        "данные_собраны": данные_собраны or "—",
        "курс_на": курс_на or "—",
    }


def собрать_отчёт(
    df: pd.DataFrame,
    путь: Optional[Path] = None,
    срез: Optional[Dict[str, Any]] = None,
) -> Path:
    """
    Собрать файл отчёта.

    Args:
        df: Вакансии выборки
        путь: Куда сохранить. Если не задан, имя составляется по дате
        срез: Описание выборки для первого листа

    Returns:
        Путь к сохранённому файлу
    """
    if df.empty:
        raise ValueError("Пустая выборка: отчёт собирать не из чего")

    срез = dict(срез or {})
    указана = int(df["salary_from"].notna().sum()) if "salary_from" in df.columns else 0
    без_зарплаты = len(df) - указана
    # Считаны числа по тем, чьей зарплате можно верить, — их и называем.
    # Иначе доли на листе не сходятся с выборкой, и человек считает, что
    # ошиблись мы, а не источник.
    в_расчёте = len(только_правдоподобные(df)) if "salary_from" in df.columns else 0
    сомнительных = указана - в_расчёте
    доля = round(в_расчёте / len(df) * 100) if len(df) else 0

    основание = f"{в_расчёте} вакансиям · {доля} %"
    if сомнительных:
        основание += f" (ещё {сомнительных} с неправдоподобной зарплатой исключены)"

    срез.setdefault("собран", datetime.now().strftime("%d.%m.%Y, %H:%M"))
    срез.setdefault("объём", f"{len(df)}")
    срез.setdefault("без_зарплаты", f"{без_зарплаты} из {len(df)}")
    срез.setdefault("с_зарплатой", основание)

    wb = Workbook()
    wb.remove(wb.active)  # лист по умолчанию: свои создаём в нужном порядке

    # Порядок листов — порядок чтения. Сначала читатель узнаёт, откуда
    # числа, и только потом видит их.
    лист_срез(wb, срез)
    лист_вакансии(wb, df)
    лист_сводка(wb, df)
    лист_навыки(wb, df)

    if путь is None:
        ensure_dir(settings.reports_dir)
        путь = settings.reports_dir / f"{ИМЯ_ОТЧЁТА}{datetime.now():%Y-%m-%d_%H%M}.xlsx"

    wb.save(путь)
    logger.info(f"Отчёт собран: {путь} · {len(df)} вакансий, четыре листа")
    return Path(путь)

# Что список отчётов на экране спрашивает у готового файла и под каким
# именем это лежит на листе «Срез».
ЧИТАЕМОЕ_ИЗ_СРЕЗА = {
    "Вакансий в выборке": "вакансий",
    "Фильтры": "срез",
    "Данные собраны": "данные_собраны",
    "Период публикаций": "период",
}


def прочитать_срез(путь: Path) -> Dict[str, Any]:
    """
    Чем готовый файл себя называет: объём выборки, условия, дата данных.

    Экрану нужно показать, по какой выборке собран каждый файл, а имя
    файла об этом не говорит. Второй экземпляр этих чисел в базе
    разошёлся бы с файлом при первой правке сборки, и файлы, собранные
    до появления такой таблицы, остались бы без них навсегда. Поэтому
    источник один — лист «Срез» внутри самого файла.

    Файл, которого продукт не собирал (выгрузка старого анализатора,
    чужой xlsx, битая половина недописанного файла), молчит: возвращается
    пустой ответ, а не выдуманные числа. Список из-за такого файла не
    пропадает — это единственное, что здесь важно.
    """
    путь = Path(путь)
    if путь.suffix.lower() != ".xlsx":
        return {}

    wb = None
    try:
        wb = load_workbook(путь, read_only=True, data_only=True)
        if "Срез" not in wb.sheetnames:
            return {}

        найденное: Dict[str, Any] = {}
        for ключ, значение in wb["Срез"].iter_rows(min_col=1, max_col=2, values_only=True):
            поле = ЧИТАЕМОЕ_ИЗ_СРЕЗА.get(str(ключ).strip() if ключ else "")
            if поле and значение not in (None, ""):
                найденное[поле] = значение

        объём = найденное.get("вакансий")
        if объём is not None:
            найденное["вакансий"] = _числом(объём)

        return найденное
    except Exception as e:
        # Нечитаемый файл — обычное дело: сборка могла прерваться на
        # записи. Список важнее одной строки в нём.
        logger.debug(f"Срез файла {путь.name} не прочитан: {e}")
        return {}
    finally:
        if wb is not None:
            try:
                wb.close()
            except Exception:
                pass


def _числом(значение: Any) -> Optional[int]:
    """Объём выборки числом: на листе он лежит текстом."""
    if isinstance(значение, (int, float)):
        return int(значение)
    цифры = "".join(с for с in str(значение) if с.isdigit())
    return int(цифры) if цифры else None

# Срок хранения отчётов, названный на экране. Уборка касается только
# файлов, собранных этим экраном: их продукт пересоберёт той же кнопкой
# по тем же фильтрам. Экспорт с «Вакансий» и выгрузки старых
# анализаторов лежат в той же папке, пересобрать их нечем, и
# автоматическая уборка унесла бы единственную копию — их убирает
# человек кнопкой в строке.
СРОК_ХРАНЕНИЯ_ДНЕЙ = 30

# За сколько дней до срока файл помечается истекающим: чтобы «ещё есть»
# и «уже нет» не оказались одним и тем же днём.
ПРЕДУПРЕДИТЬ_ЗА_ДНЕЙ = 3


def собран_продуктом(имя: str) -> bool:
    """Наш отчёт или чужой файл, оказавшийся в той же папке."""
    return имя.lower().startswith(ИМЯ_ОТЧЁТА)


def убрать_устаревшие(папка: Optional[Path] = None, срок: int = СРОК_ХРАНЕНИЯ_ДНЕЙ) -> List[str]:
    """
    Убрать свои отчёты старше срока. Возвращает имена убранных.

    Привязано к обращению к списку, а не к таймеру в процессе:
    приложение живёт на одном компьютере и перезапускается когда угодно,
    и уборка по расписанию внутри процесса пропускалась бы ровно тогда,
    когда его не запускали месяц — то есть когда она и нужна.
    """
    папка = Path(папка or settings.reports_dir)
    if not папка.exists():
        return []

    предел = datetime.now().timestamp() - срок * 86400
    убранные = []
    for файл in папка.iterdir():
        if not файл.is_file() or not собран_продуктом(файл.name):
            continue
        try:
            if файл.stat().st_ctime >= предел:
                continue
            файл.unlink()
        except OSError as e:
            # Занятый или недоступный файл — не повод валить список.
            logger.warning(f"Отчёт {файл.name} не убран по сроку: {e}")
            continue
        убранные.append(файл.name)

    if убранные:
        logger.info(f"Убрано по сроку хранения ({срок} дней): {len(убранные)} шт.")
    return убранные
