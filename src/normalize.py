# Слой источника: перевод его полей в общую запись. Импортируется
# отложенно внутри функции — модуль источника сам пользуется
# разбором разделов из `sections`, и прямой импорт замкнул бы круг.

logger = get_logger(__name__)

# Коды валют источника к общепринятым. Источник обозначает рубль как RUR,
# остальные коды совпадают со стандартом.
CURRENCY_MAP = {
    "RUR": "RUB",
    "KZT": "KZT",
    "UZS": "UZS",
    "BYN": "BYN",
    "USD": "USD",
    "EUR": "EUR",
}

# Односимвольные «навыки» вроде «r» или «c» ловятся в любом тексте и
# засоряют статистику: язык R не отличить от предлога.
EXCLUDED_SKILLS = set("abcdefghijklmnopqrstuvwxyz")

# Двухсимвольные навыки ищутся, а не отбрасываются.
#
# Раньше порог был три символа, и вместе с шумом он выбрасывал целый
# класс настоящих навыков: Go, C#, QA, UX, UI, ML, BI, JS. Они есть в
# словаре, но до поиска не доходили — на замере это первая по величине
# группа пропусков.
#
# Порог заменён двумя защитами. Первая — границы слова со спецсимволами
# (см. PreparedSkill): «Go» в «алгоритм» не найдётся. Вторая — короткий
# навык требует, чтобы рядом стояло слово из его окружения: «go» в
# «go-разработчик» и «опыт go» засчитывается, «go» в «go home» — нет.
MIN_SKILL_LENGTH = 2

# Слова, рядом с которыми короткий навык — действительно навык.
#
# Список не про конкретные технологии, а про то, как о них говорят:
# «опыт go», «знание qa», «на c#», «go разработчик». Одного соседа
# достаточно — требовать больше значило бы терять «стек: go, kafka».
СОСЕДИ_НАВЫКА = (
    "опыт", "знание", "знания", "владение", "уверенн", "разработ", "инженер",
    "программирован", "стек", "технологи", "язык", "фреймворк", "библиотек",
    "навык", "умение", "работа с", "работал", "писал", "пишем", "используем",
    "плюс", "преимущест", "требован", "обязанност", "проект",
)

# Сколько символов вокруг короткого навыка считать его окружением.
ОКНО_КОНТЕКСТА = 60


# Как текст и навык разбиваются на слова для быстрого отсева.
#
# Символы «#» и «+» входят в слово: «c#» и «c++» — это названия, а не
# буква с пунктуацией. Точка и дефис, наоборот, разделяют: в тексте
# «node.js» и «machine-learning» пишут и слитно, и раздельно, и обе
# записи должны давать одинаковый набор слов — иначе отсев начнёт
# выбрасывать навыки, которые поиск нашёл бы.
СЛОВО_ДЛЯ_ОТСЕВА = re.compile(r"[\w#+]+")


def слова_для_отсева(текст: str) -> Set[str]:
    """Слова текста в том же виде, в каком они берутся у навыка."""
    return set(СЛОВО_ДЛЯ_ОТСЕВА.findall(текст)) if текст else set()


class PreparedSkill:
    """
    Навык вместе с готовыми к поиску формами.

    Регулярные выражения компилируются один раз на весь разбор. Без
    этого поиск упирается во внутренний кэш `re`: он держит 512
    выражений, а словари дают около тысячи навыков и втрое больше
    вариантов написания — кэш переполняется, и каждое выражение
    компилируется заново на каждой вакансии. Разбор восьми тысяч
    вакансий в таком виде не заканчивается за разумное время.
    """

    __slots__ = ("name", "title", "word", "parts", "variants", "lemma", "lemma_word", "якорь")

    def __init__(self, skill: str, показ: Optional[str] = None) -> None:
        self.name = skill
        # Как навык выглядит в списках и топах. Прежде здесь стоял
        # `skill.title()`, и он дробил статистику: словарный «Оценка
        # Персонала» и названный работодателем «Оценка персонала»
        # считались разными навыками, каждый занижен вдвое. Аббревиатуры
        # он превращал в слова — «Llm», «Api», «Sql».
        self.title = показ if показ is not None else skills_store.для_показа(skill)
        # Границы слова проверяются вручную, а не через \b: «#», «+» и
        # «.» не буквы, и граница оказывалась не там, где нужно, —
        # «C#» и «Node.js» не находились вовсе. Здесь условие прямое:
        # рядом не должно быть буквы, цифры или того же спецсимвола.
        # «C#» в «C#» находится, в «C##» — нет.
        # Косая черта справа намеренно разрешена.
        #
        # Соблазн запретить её велик: «access» в «access/refresh tokens»
        # — часть чужого термина, а не Microsoft Access. Но замер на
        # девяти тысячах описаний показал цену: таких ловушек 2, а
        # перечислений стека через слэш — «React/JS/Express»,
        # «Python/Django» — 206. Запрет отнимал бы в сто раз больше, чем
        # спасал: полнота падала с 81,3 % до 79,4 %.
        self.word = re.compile(
            r"(?<![\w#+.])" + re.escape(skill) + r"(?![\w#+])",
            re.IGNORECASE,
        )

        # Составные навыки ищутся ещё и по словам: «управление
        # проектами» встречается как «управление проектной работой».
        # Начальная форма — для русских навыков, которые в тексте
        # склоняются: «переговоры» ищется в «ведение переговоров».
        # Латинским она не нужна и вредна.
        self.lemma = привести(skill) if нужна_ли(skill) else None
        # Выражение строится и тогда, когда начальная форма навыка
        # совпадает с ним самим: меняется-то текст. «Переговоры» в
        # словаре и «переговоров» в тексте сойдутся только через леммы
        # текста, хотя сам навык при этом не изменился.
        self.lemma_word = (
            re.compile(
                r"(?<![\w#+.])" + re.escape(self.lemma) + r"(?![\w#+])",
                re.IGNORECASE,
            )
            if self.lemma
            else None
        )

        # Слова, хотя бы одно из которых обязано встретиться в тексте,
        # чтобы навык вообще мог быть найден. Проверка пересечения
        # множеств отбрасывает почти весь словарь за доли миллисекунды —
        # дешевле, чем тысяча поисков подстроки.
        #
        # Сюда входит не только само название: навык находят ещё и по
        # начальной форме («аукционы» в тексте — «аукционах») и по
        # вариантам написания («Next.js» — «nextjs»). Якорь из одного
        # названия отбрасывал такие навыки до проверки: на пятистах
        # живых описаниях это теряло навыки в 111 случаях.
        self.якорь: Set[str] = слова_для_отсева(skill)
        if self.lemma:
            self.якорь |= слова_для_отсева(self.lemma)

        self.parts = [
            (part, re.compile(
                r"(?<![\w#+.])" + re.escape(part) + r"(?![\w#+])", re.IGNORECASE
            ))
            for part in skill.split()
            if len(part) > 2
        ]

        # Варианты написания: «C++» в тексте бывает «C plus plus»,
        # «CI/CD» — «CI CD», «ASP.NET» — «ASP NET».
        variants = {
            skill.replace("+", " plus").replace(".", ""),
            skill.replace("-", " ").replace(".", ""),
            skill.replace("_", " "),
            skill.replace("/", " "),
        } - {skill}
        self.variants = [
            (v, re.compile(
                r"(?<![\w#+.])" + re.escape(v) + r"(?![\w#+])", re.IGNORECASE
            ))
            for v in variants
            if len(v) > 2
        ]

        for вариант, _ in self.variants:
            self.якорь |= слова_для_отсева(вариант)


class SkillDictionaries:
    """Словари навыков, подготовленные к поиску."""

    def __init__(self, hard: List[str], soft: List[str], tools: List[str]) -> None:
        # Таблица написаний читается один раз на весь словарь: она нужна
        # каждому навыку, а тысяча чтений файла на разбор — это минуты.
        таблица = skills_store.таблица_синонимов()
        известные = {s.lower() for s in hard + soft + tools}

        def готовые(значения: List[str]) -> List["PreparedSkill"]:
            return [
                PreparedSkill(s, skills_store.для_показа(s, таблица, известные))
                for s in значения if len(s) >= MIN_SKILL_LENGTH
            ]

        self.hard = готовые(hard)
        self.soft = готовые(soft)
        self.tools = готовые(tools)

    @classmethod
    def from_config(cls) -> "SkillDictionaries":
        """
        Словари из файла данных `data/skills.yaml`.

        Название метода оставлено прежним: его знает весь код сбора, а
        источник словаря — деталь загрузки. Пока файла данных нет,
        `skills_store` читает конфиг, как раньше.
        """
        def clean(values: Iterable[str]) -> List[str]:
            prepared = [
                v.lower().strip() for v in values
                if len(v.strip()) >= MIN_SKILL_LENGTH
            ]
            return [v for v in prepared if v not in EXCLUDED_SKILLS]

        словарь = skills_store.загрузить()

        dictionaries = cls(
            hard=clean(словарь["hard"]),
            soft=clean(словарь["soft"]),
            tools=clean(словарь["tools"]),
        )
        logger.info(
            f"Словари навыков: hard={len(dictionaries.hard)}, "
            f"soft={len(dictionaries.soft)}, tools={len(dictionaries.tools)}, "
            f"синонимов={len(словарь.get('synonyms') or {})}"
        )
        return dictionaries


def подтверждён_контекстом(skill: "PreparedSkill", text: str) -> bool:
    """Рядом с коротким навыком стоит слово, говорящее о навыке.

    Двухсимвольные названия — Go, QA, UX, C# — встречаются и как обычные
    слова: «go home», «ui» внутри английского текста. Смотрим окно вокруг
    совпадения: если там есть «опыт», «стек», «разработчик» и подобное,
    это навык.
    """
    for совпадение in skill.word.finditer(text):
        начало = max(0, совпадение.start() - ОКНО_КОНТЕКСТА)
        окно = text[начало:совпадение.end() + ОКНО_КОНТЕКСТА]
        if any(сосед in окно for сосед in СОСЕДИ_НАВЫКА):
            return True
    return False


def find_skills(
    text: str,
    skills: Iterable[PreparedSkill],
    леммы: Optional[str] = None,
) -> Set[str]:
    """
    Найти навыки в тексте.

    Три способа, от строгого к свободному: целое слово, большинство слов
    составного навыка, вариант написания. Границы слова обязательны —
    иначе «Go» находится в «алгоритм», а «R» в каждом слове с этой буквой.

    Args:
        text: Где искать (уже приведён к нижнему регистру)
        skills: Что искать — подготовленные навыки

    Returns:
        Найденные навыки в виде, пригодном для показа

    Note:
        Перед каждой регуляркой стоит проверка обычным вхождением
        подстроки. Она ничего не отсеивает сверх нужного — совпадение по
        границам слова невозможно там, где нет самой подстроки, — но
        отбрасывает почти весь словарь ценой сравнения строк, которое
        на порядок дешевле разбора выражения.

        Перед этим стоит ещё более дешёвый отсев: слова текста
        сравниваются со словами навыка одним пересечением множеств.
        Навык, ни одно слово которого в тексте не встречается, не может
        быть найден ни одним из способов ниже — ни целиком, ни по
        частям, ни вариантом написания, ни через начальную форму.
        На живых описаниях это отбрасывает 96 % словаря: 45 навыков из
        1079 доходят до сопоставления.
    """
    found: Set[str] = set()
    if not text:
        return found

    # Леммы входят в отсев наравне с текстом: навык «переговоры»
    # находится в «ведение переговоров» только через начальную форму, и
    # без лемм отсев выбросил бы его до проверки.
    слова_текста = слова_для_отсева(text)
    if леммы:
        слова_текста |= слова_для_отсева(леммы)

    for skill in skills:
        if not (skill.якорь & слова_текста):
            continue

        # Точное совпадение целым словом.
        if skill.name in text and skill.word.search(text):
            # Короткий навык подтверждается окружением: «Go» рядом со
            # словом «опыт», «стек» или «разработчик» — это язык, «go»
            # посреди английской фразы — нет. Длинные навыки в
            # подтверждении не нуждаются: «PostgreSQL» ни с чем не
            # спутать.
            if len(skill.name) > 2 or подтверждён_контекстом(skill, text):
                found.add(skill.title)
            continue

        # Составной навык: засчитываем, если нашлись хотя бы два слова.
        if len(skill.parts) >= 2:
            matched = 0
            for part, pattern in skill.parts:
                if part in text and pattern.search(text):
                    matched += 1
                    if matched >= 2:
                        break
            if matched >= 2:
                found.add(skill.title)
                continue

        # Варианты написания.
        нашёлся = False
        for variant, pattern in skill.variants:
            if variant in text and pattern.search(text):
                found.add(skill.title)
                нашёлся = True
                break
        if нашёлся:
            continue

        # Начальные формы: «переговоров» → «переговоры».
        #
        # Идёт последним и только для русских навыков: латинские
        # названия морфология портит, а точное совпадение уже проверено
        # выше. Текст приводится к начальным формам один раз на вакансию
        # и передаётся сюда готовым — разбор дороже всего остального
        # сопоставления вместе взятого.
        if леммы and skill.lemma_word and skill.lemma in леммы:
            if skill.lemma_word.search(леммы):
                found.add(skill.title)

    return found


# Кириллические буквы, неотличимые на вид от латинских. Работодатель
# пишет «Exсel» с русской «с», и такой навык не находится никогда:
# глазами разницы нет, поиском есть. На живой базе так испорчены слова в
# 2 % описаний — среди них Excel, Word и Confluence.
ГОМОГЛИФЫ = str.maketrans("асеорхукмтнвіj", "aceopxykmthbij")
ЛАТИНСКАЯ = re.compile(r"[a-z]")
КИРИЛЛИЧЕСКАЯ = re.compile(r"[а-яё]")


def _починить_слово(слово: str) -> str:
    """
    Кириллица в слове чинится, только если это вкрапление в латинское.

    Переводить кириллицу в латиницу подряд нельзя: «типографика»
    превратится в набор букв. Смешанное слово смешанному рознь —
    «UX-метрики» и «SMM-менеджер» законны, а «Exсel» с одной русской
    буквой почти всегда описка. Отсюда три условия: латинских букв
    большинство, кириллических одна-две, дефиса нет.
    """
    латинских = len(ЛАТИНСКАЯ.findall(слово))
    кириллических = len(КИРИЛЛИЧЕСКАЯ.findall(слово))
    вкрапление = (
        латинских >= 3
        and 0 < кириллических <= max(2, латинских // 4)
        and "-" not in слово
    )
    return слово.translate(ГОМОГЛИФЫ) if вкрапление else слово


БУКВЫ = re.compile(r"[a-zA-Zа-яёА-ЯЁ]+")


def без_гомоглифов(текст: str) -> str:
    """
    Текст, в котором испорченные латинские слова написаны латиницей.

    Разбор идёт по буквенным последовательностям, а не по словам через
    пробел: в описании остаётся разметка, и «<p><strong>мы» — это одно
    «слово», в котором латинских букв больше, чем кириллических. Деля по
    пробелам, починка превращала русское «мы» в «mы» и ломала поиск.
    """
    if not текст:
        return текст
    return БУКВЫ.sub(lambda м: _починить_слово(м.group()), текст)


def searchable_text(vacancy: Dict[str, Any]) -> str:
    """
    Текст, по которому ищутся навыки.

    Собирается из краткой выжимки поиска, полного описания и названия.
    Больше ниоткуда: поля работодателя дают ложные совпадения.

    Из описания берутся не все разделы. «Условия», «Мы предлагаем» и
    «О компании» рассказывают о работодателе, а не о кандидате, и поиск
    по ним давал «Подарки» у 70 вакансий, «Развитие» у 260 и «Мотивацию»
    у 129 — «Подарки» дошли до топ‑10 навыков на дашборде. Выжимки из
    поиска остаются целиком: они и есть требования с обязанностями.
    """
    snippet = vacancy.get("snippet") or {}
    parts = [
        snippet.get("requirement") or "",
        snippet.get("responsibility") or "",
        текст_для_навыков(vacancy.get("description") or ""),
        vacancy.get("name") or "",
    ]
    return без_гомоглифов(" ".join(part.lower() for part in parts if part))


def навыки_работодателя(vacancy: Dict[str, Any]) -> List[str]:
    """
    Навыки, которые работодатель назвал сам, в поле `key_skills`.

    Это лучший источник навыков, какой бывает: не догадка по тексту, а
    прямое утверждение. Через словарь они не проходят намеренно — 77 %
    из них в словаре отсутствуют, и фильтрация по нему выбрасывала бы
    ровно то, ради чего поле и читается.

    Порядок сохраняется в том виде, в каком его задал работодатель:
    первым он обычно называет главное.

    Написание приводится к канону: работодатели пишут одно и то же
    по-разному, и «3ds Max» с «3D Max» стояли в топе двумя строками,
    деля между собой 221 упоминание. Таблица синонимов — проверенный
    список, а не правило: у «C#» и «C++» написание без пробелов и
    регистра совпадает.
    """
    сырые = vacancy.get("key_skills") or []
    таблица = skills_store.таблица_синонимов()
    навыки, видели = [], set()

    for запись in сырые:
        имя = (запись.get("name") if isinstance(запись, dict) else запись) or ""
        имя = skills_store.привести_к_канону(имя.strip(), таблица)
        ключ = имя.lower()
        if имя and ключ not in видели:
            видели.add(ключ)
            навыки.append(имя)

    return навыки


def _без_повторов(навыки: List[str]) -> List[str]:
    """Один навык — одна запись, порядок работодателя сохранён."""
    видели, итог = set(), []
    for навык in навыки:
        ключ = (навык or "").strip().lower()
        if ключ and ключ not in видели:
            видели.add(ключ)
            итог.append(навык.strip())
    return итог


def normalize_vacancy(
    vacancy: Dict[str, Any],
    dictionaries: Optional[SkillDictionaries] = None,
) -> Dict[str, Any]:
    """
    Превратить вакансию из ответа источника в строку базы.

    Args:
        vacancy: Сырая вакансия — из поиска, из карточки или из файла
            прошлого сбора
        dictionaries: Словари навыков. Если не переданы, читаются из
            конфига (дорого для каждой вакансии — передавайте готовые)

    Returns:
        Словарь с полями таблицы vacancies

    Note:
        Служебные пометки сбора `_source_keyword` и `_has_details`
        переносятся в поля записи. Для старых файлов, где пометок нет,
        наличие описания определяется по самим данным — так же, как это
        делает живой сбор.
    """
    dictionaries = dictionaries or SkillDictionaries.from_config()
    таблица_написаний = skills_store.таблица_синонимов()

    # Имена полей источника сюда не доходят: перевод делает его слой
    # (`src/sources/`). Здесь и ниже — только общие поля, одинаковые для
    # любого сайта вакансий.
    from src.sources import hh as hh_источник

    запись = (
        vacancy
        if vacancy.get("источник")
        else hh_источник.в_общую_запись(vacancy)
    )

    text = запись["текст"]
    # Начальные формы считаются один раз на вакансию и переиспользуются
    # тремя поисками: разбор текста дороже самого сопоставления.
    леммы = привести(text)
    hard = sorted(find_skills(text, dictionaries.hard, леммы))
    soft = sorted(find_skills(text, dictionaries.soft, леммы))
    tools = sorted(find_skills(text, dictionaries.tools, леммы))

    # Навыки от работодателя идут в общий список, но не в категории:
    # категорию мы знаем только для тех, что есть в словарях, а таких
    # среди них меньше четверти. Отнести остальные к hard или soft
    # значило бы придумать за источник.
    от_работодателя = [
        skills_store.привести_к_канону(н, таблица_написаний)
        for н in запись["навыки_работодателя"]
    ]
    от_работодателя = _без_повторов(от_работодателя)

    # Один навык, названный дважды — словарём и работодателем, — остаётся
    # одним. Сравнение по нижнему регистру: «PostgreSQL» от источника и
    # «postgresql» из словаря — это одно и то же.
    словарные = hard + soft + tools
    известные = {н.lower() for н in словарные}
    только_от_работодателя = [н for н in от_работодателя if н.lower() not in известные]

    все_навыки = словарные + только_от_работодателя

    # Полное описание, как пришло от источника. Оно не колонка вакансии,
    # а отдельная запись: аналитика текст не читает никогда, а таскать
    # шесть килобайт в каждом сканировании таблицы незачем. Хранилище
    # заберёт его по служебному ключу и положит в свою таблицу, оставив
    # у вакансии только ссылку.
    описание = vacancy.get("description") or ""

    return {
        "_описание": описание,
        "text_hash": хэш_текста(описание) if описание.strip() else None,
        # Источник — часть ключа записи: идентификаторы разных сайтов
        # совпадают, и без имени источника «137176862» с hh.ru затёрло
        # бы «137176862» с любого другого.
        "source": запись["источник"],
        "vacancy_id": запись["идентификатор"],
        "vacancy_name": запись["название"] or "",
        "published_at": запись["опубликовано"],
        "salary_from": запись["зарплата_от"],
        "salary_to": запись["зарплата_до"],
        "salary_currency": запись["валюта"],
        "salary_gross": bool(запись["до_вычета"]),
        # Период выплаты: «1 000 ₽» и «1 000 ₽ за час» — разные величины,
        # и без этого поля вторая ложилась в базу как месячный оклад.
        "salary_mode": запись["период"],
        "employer_name": запись["работодатель"] or "",
        "employer_id": запись["работодатель_ид"] or "",
        "employer_url": запись["работодатель_ссылка"] or "",
        "vacancy_url": запись["ссылка"] or "",
        "experience": запись["опыт"] or "",
        "employment": запись["занятость"] or "",
        "schedule": запись["график"] or "",
        "area": запись["регион"] or "",
        "all_skills": ", ".join(все_навыки),
        "hard_skills": ", ".join(hard),
        "soft_skills": ", ".join(soft),
        "tools": ", ".join(tools),
        # Что назвал работодатель — целиком, включая то, что нашлось и
        # словарём: поле отвечает на вопрос «что сказал источник», а не
        # «что он сказал сверх наших знаний».
        "employer_skills": ", ".join(от_работодателя),
        "skill_count": len(все_навыки),
        "hard_skill_count": len(hard),
        "soft_skill_count": len(soft),
        "tools_count": len(tools),
        "source_keyword": запись["запрос"],
        "has_details": bool(запись["есть_карточка"]),
    }


def normalize_many(
    vacancies: Iterable[Dict[str, Any]],
    dictionaries: Optional[SkillDictionaries] = None,
) -> List[Dict[str, Any]]:
    """
    Нормализовать список вакансий.

    Словари читаются один раз на весь список: чтение конфига на каждую
    вакансию — самая дорогая часть разбора при тысячах записей.
    """
    dictionaries = dictionaries or SkillDictionaries.from_config()
    return [normalize_vacancy(vacancy, dictionaries) for vacancy in vacancies]
