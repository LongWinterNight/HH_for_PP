"""
Приведение вакансии из ответа источника к строке базы.

Единственное место, где сырой JSON превращается в запись. Раньше эта
работа была скопирована в два коллектора, и копии разошлись: одна искала
навыки с вариациями написания и вдобавок в поле работодателя, вторая — ни
того, ни другого. Какие навыки окажутся в базе, зависело от флагов
запуска, а не от данных. Восстановление истории из старых файлов сборов
требует ровно той же логики, что и живой сбор, — иначе восстановленные
записи отличались бы от собранных сегодня, и разница легла бы в
статистику как настоящая.

Правила, принятые при слиянии копий:

- поиск с вариациями написания остаётся: без него «C++», «ASP.NET» и
  «CI/CD» не находятся, потому что в тексте пишутся иначе;
- поиск личных качеств в поле работодателя убран. Там лежат название
  компании и ссылка, описания качеств в них нет, а совпадения бывают —
  «Ответственный» в названии организации становился личным качеством
  вакансии;
- повторный проход по названию вакансии убран как лишний: название уже
  входит в общий текст поиска.
"""

