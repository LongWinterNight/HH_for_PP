"""
Качество сбора: годятся ли собранные записи для аналитики.

«Собрано 1 891» не отвечает на вопрос, можно ли по этим записям
считать. Вакансия без карточки несёт 2,4 навыка против 14,7 у вакансии
с карточкой, и пятая часть базы когда-то оставалась вовсе без навыков —
но узнать это можно было только запросом к базе руками, задним числом.

Три числа после каждого сбора:

- **с карточкой** — сколько записей получили отдельный запрос за полным
  описанием. Без карточки у вакансии есть название и зарплата, но почти
  нет навыков;
- **без навыков** — сколько записей не дали ни одного навыка. Это прямая
  мера того, сколько собранного бесполезно для аналитики;
- **неполных обходов** — сколько запросов не дочитаны до конца. По ним
  нельзя гасить пропавшие вакансии, и именно они дают недобор.

Числа считаются по записям этого сбора, а не по всей базе: качество
базы меняется медленно и прячет ухудшение сегодняшнего запуска.
"""

from __future__ import annotations

from typing import Any, Dict, Optional

import pandas as pd


def пустая_сводка() -> Dict[str, int]:
    """Ноль по всем числам — с этого начинается накопление."""
    return {"всего": 0, "с_карточкой": 0, "без_навыков": 0}


def метрики(df: Optional[pd.DataFrame]) -> Dict[str, int]:
    """
    Три числа по разобранным записям одной порции сбора.

    Args:
        df: Разобранные вакансии — то, что уходит в базу

    Returns:
        Сколько всего, сколько с карточкой, сколько без единого навыка.
        Отсутствующая колонка считается нулём, а не пропускается: сводка
        обязана сходиться, а не молчать о том, чего не смогла измерить.
    """
    if df is None or len(df) == 0:
        return пустая_сводка()

    с_карточкой = 0
    if "has_details" in df.columns:
        с_карточкой = int(df["has_details"].fillna(0).astype(bool).sum())

    без_навыков = len(df)
    if "skill_count" in df.columns:
        без_навыков = int((df["skill_count"].fillna(0) == 0).sum())

    return {
        "всего": len(df),
        "с_карточкой": с_карточкой,
        "без_навыков": без_навыков,
    }


def сложить(накоплено: Dict[str, int], добавка: Dict[str, int]) -> Dict[str, int]:
    """Сложить сводки порций: сбор идёт запросами, а числа нужны общие."""
    итог = dict(накоплено or пустая_сводка())
    for поле, значение in (добавка or {}).items():
        итог[поле] = итог.get(поле, 0) + значение
    return итог


def неполных_обходов(by_keyword: Dict[str, Dict[str, Any]]) -> int:
    """
    Сколько запросов не дочитаны до конца.

    Запрос без отметки о полноте считается неполным: по нему нельзя
    утверждать, что выдача прочитана, а осторожная ошибка здесь дешевле
    смелой — по «полному» обходу сбор гасит вакансии, которых в нём не
    оказалось.
    """
    return sum(1 for stats in (by_keyword or {}).values() if not stats.get("complete"))


def сводка(накоплено: Dict[str, int], by_keyword: Dict[str, Dict[str, Any]]) -> Dict[str, int]:
    """Итог качества сбора: три числа, которые уходят в историю запусков."""
    итог = dict(накоплено or пустая_сводка())
    итог["неполных_запросов"] = неполных_обходов(by_keyword)
    return итог
