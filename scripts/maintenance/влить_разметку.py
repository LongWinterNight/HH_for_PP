"""
Влить размеченную партию в эталонный набор.

Зачем. Эталон растёт партиями по рынку, и каждая партия должна попадать
в файл сразу после разметки, а не копиться «до конца»: набор из двухсот
вакансий размечается не за один заход, и незафиксированная работа
теряется вместе с сессией. Так уже терялась подзадача, которая была в
плане, но не в коде.

Скрипт берёт партию — список `{"id": ..., "навыки": [...]}` — достаёт
текст и остальные поля из очереди (`data/очередь_эталона.json`) и
дописывает в `tests/fixtures/private/эталон_навыков.json`.

Проверяется три вещи, каждая из которых уже ломала наборы:
- вакансии нет в эталоне (иначе одна вакансия весит вдвое);
- навыки непусты (пустая разметка занижает полноту молча);
- каждый размеченный навык встречается в тексте или в `key_skills`
  (иначе эталон требует находить то, чего в вакансии нет).

Запуск:
    python scripts/maintenance/влить_разметку.py партия.json
    python scripts/maintenance/влить_разметку.py партия.json --проверить
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЭТАЛОН = КОРЕНЬ / "tests" / "fixtures" / "private" / "эталон_навыков.json"
ОЧЕРЕДЬ = КОРЕНЬ / "data" / "очередь_эталона.json"
sys.path.insert(0, str(КОРЕНЬ))

РАЗМЕТКА = re.compile(r"<[^>]+>")

# Кириллические буквы, неотличимые на вид от латинских. Работодатели
# пишут «Confluenсe» с русской «с» — глазами не видно, поиском не
#найти. Проверка не должна из-за этого браковать верную разметку.
ГОМОГЛИФЫ = str.maketrans("асеорхукмтнвіј", "aceopxykmthbij")


def выровнять(текст: str) -> str:
    """
    Текст, в котором навык можно искать так же, как его ищет продукт.

    Три приведения, и каждое отвечает на свой случай из живых описаний:
    русские слова к начальной форме («типографикой» → «типографика»),
    гомоглифы к латинице («Confluenсe» → «Confluence»), перечисления
    через слэш к пробелам («Substance Painter/Designer»).
    """
    from src.morphology import привести  # локально: инициализация — секунды

    чистый = re.sub(r"[/|]", " ", РАЗМЕТКА.sub(" ", текст or "").lower())
    # Точка и запятая, приклеенные к слову, ломают морфологию: «верстке.»
    # она не разбирает вовсе и оставляет как есть. Убираются только
    # завершающие знаки — точка внутри слова значима («Draw.IO», «Node.js»).
    чистый = re.sub(r"(?<=[\wа-яё])[.,;:!?»)(«\[\]]+(?=\s|$)", " ", чистый)
    return привести(" ".join(_разгомоглифить(с) for с in чистый.split()))


ЛАТИНИЦА = re.compile(r"[a-z]")
КИРИЛЛИЦА = re.compile(r"[а-яё]")


def _разгомоглифить(слово: str) -> str:
    """
    Кириллица в слове чинится только тогда, когда слово смешанное.

    Переводить кириллицу в латиницу подряд нельзя: «типографикой»
    превратится в набор букв, и морфология после этого не работает.
    Смешанное же слово — «Confluenсe» с русской «с» — почти всегда
    описка работодателя в латинском термине, и её стоит починить.
    """
    латинских = len(ЛАТИНИЦА.findall(слово))
    кириллических = len(КИРИЛЛИЦА.findall(слово))
    если_вкрапление = (
        латинских >= 3
        and 0 < кириллических <= max(2, латинских // 4)
        and "-" not in слово
    )
    # Составные термины — «UX-метрики», «SMM-менеджер» — смешанные
    # законно, и чинить их нельзя: получится мусор вместо русского
    # слова. Чинится только вкрапление: пара кириллических букв внутри
    # латинского слова, и без дефиса.
    return слово.translate(ГОМОГЛИФЫ) if если_вкрапление else слово


def без_тегов(html: str) -> str:
    return выровнять(html)


def проверить(запись: Dict[str, Any], навыки: List[str]) -> List[str]:
    """
    Замечания к разметке одной вакансии. Пустой список — всё чисто.

    Навык, которого нет ни в тексте, ни в `key_skills`, — почти всегда
    описка или домысел разметчика. Он опаснее пропуска: пропуск занижает
    полноту, а выдуманный навык требует от поиска находить то, чего в
    вакансии не написано, и правка пойдёт не туда.
    """
    замечания = []
    if not навыки:
        замечания.append("навыков ноль")
    if len(навыки) != len(set(навыки)):
        замечания.append("есть повторы")
    текст = без_тегов(запись.get("описание", ""))
    поле = выровнять(" ".join(запись.get("key_skills") or []))
    for навык in навыки:
        if не_из_текста(выровнять(навык), текст, поле):
            замечания.append(f"нет в тексте: {навык}")
    return замечания


def _варианты(канон: str) -> list:
    """Все написания навыка, известные словарю синонимов."""
    from src import skills_store

    # Сюда приходит уже выровненный навык, поэтому и канон из таблицы
    # выравнивается тем же способом: иначе «программа лояльность» никогда
    # не совпадёт с записанным в словаре «Программы лояльности».
    таблица = skills_store.таблица_синонимов()
    return [выровнять(вариант) for вариант, к_канон in таблица.items()
            if выровнять(к_канон) == канон]


def не_из_текста(навык: str, текст: str, поле: str) -> bool:
    """
    Навыка нет в вакансии ни целиком, ни по словам.

    Проверять фразу целиком нельзя: навык пишется в каноничной форме
    («Адаптивный дизайн»), а в тексте стоит как придётся — «адаптивный и
    responsive дизайн». Требуя точного вхождения, проверка заставила бы
    разметчика писать не канон, а цитату, и замер начал бы считать
    промахом верную находку словаря.

    Поэтому по словам: каждое значимое слово навыка должно встретиться в
    вакансии. Домысел разметчика это ловит («3D-моделирование» там, где
    сказано только «создание 3D-моделей»), а канон не ломает.
    """
    где = текст + " " + поле
    if навык in где:
        return False
    # Навык мог быть написан в вакансии на другом языке или в другом
    # написании: эталон хранит канон («Типографика»), а в англоязычном
    # описании стоит «typography». Синонимы словаря — то самое место,
    # где эта связь уже описана, и проверка обязана её знать.
    for вариант in _варианты(навык):
        if вариант in где:
            return False
    слова = [с for с in re.split(r"[^\w#+.]+", навык) if len(с) > 2]
    # По основе, а не по слову целиком: морфология на неологизмах
    # расходится сама с собой — «гайдлайны» она приводит к «гайдлайна», а
    # «гайдлайнов» к «гайдлайн», и точное сравнение забракует верное.
    return not слова or any(с[:max(5, len(с) - 2)] not in где for с in слова)


def main() -> int:
    parser = argparse.ArgumentParser(description="Влить партию разметки в эталон")
    parser.add_argument("партия", help="JSON: [{id, навыки}, ...]")
    parser.add_argument("--проверить", action="store_true", help="только проверить, не писать")
    parser.add_argument("--всё-равно", action="store_true",
                        help="влить, несмотря на замечания: разметчик настаивает, и это видно в записи")
    args = parser.parse_args()

    партия = json.loads(Path(args.партия).read_text(encoding="utf-8"))
    очередь = {в["id"]: в for в in json.loads(ОЧЕРЕДЬ.read_text(encoding="utf-8"))["вакансии"]}
    набор = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    уже = {str(в["id"]) for в in набор["вакансии"]}

    новые, ошибки = [], []
    for пункт in партия:
        ид = str(пункт["id"])
        навыки = sorted(set(пункт["навыки"]), key=str.lower)
        if ид in уже:
            ошибки.append(f"{ид}: уже в эталоне")
            continue
        if ид not in очередь:
            ошибки.append(f"{ид}: нет в очереди")
            continue
        исходная = очередь[ид]
        замечания = проверить(исходная, навыки)
        if замечания and not args.всё_равно:
            ошибки.append(f"{ид} ({исходная['name'][:40]}): " + "; ".join(замечания))
            continue
        if замечания:
            print(f"  ! {ид}: влито с замечаниями — " + "; ".join(замечания))
        новые.append({
            "id": ид,
            "name": исходная["name"],
            # Рынок можно поправить прямо в партии: отбор ставит его по
            # названию и роли, и на смешанных случаях ошибается —
            # «BIM-менеджер» и «Верстальщик» попадали в «Дизайн».
            "рынок": пункт.get("рынок") or исходная["рынок"],
            "employer": исходная["employer"],
            "описание": исходная["описание"],
            "key_skills": исходная["key_skills"],
            "навыки": навыки,
            **({"замечания_проверки": замечания} if замечания else {}),
        })

    for строка in ошибки:
        print("  ✗", строка)
    if args.проверить:
        print(f"\nГотово к вливанию: {len(новые)}, с замечаниями: {len(ошибки)}")
        return 1 if ошибки else 0
    if ошибки:
        print("\nНичего не записано: сначала разберись с замечаниями.")
        return 1

    набор["вакансии"].extend(новые)
    набор["собран"] = "2026-09-10"
    ЭТАЛОН.write_text(json.dumps(набор, ensure_ascii=False, indent=1), encoding="utf-8")

    from collections import Counter
    свод = Counter(в.get("рынок", "—") for в in набор["вакансии"])
    print(f"Влито: {len(новые)}. В наборе стало: {len(набор['вакансии'])} из {набор['объём_план']}")
    for рынок, n in sorted(свод.items(), key=lambda x: -x[1]):
        print(f"   {рынок:<28}{n:>4}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
