"""
Приведение навыков в базе к каноническому написанию.

Зачем. Работодатели пишут одно и то же по-разному, и для продукта это
разные навыки. По базе на 09.09.2026:

    3ds Max 131 · 3D Max 90 · 3dmax 1 · 3DsMax 1 · 3D-max 1
    JavaScript 103 · Java Script 2
    VueJS 12 · Vue.js 9

В топе навыков «3ds Max» и «3D Max» стоят двумя строками, деля между
собой 221 упоминание, — то есть каждая занижена вдвое. Живой сбор
приводит написание к канону сам (`skills_store`), но записи, собранные
раньше, остались как есть.

**Почему не пересчёт по файлам сборов.** Напрашивается запустить
`пересчёт_навыков.py` — он умеет переразбирать сохранённые ответы. Но в
файлах `key_skills` есть только у 6 562 записей из 22 710, а в базе
навыки работодателя проставлены у 7 400: часть восстановлена скриптом
обогащения из более поздних сборов. Пересчёт стёр бы разницу — почти
десять тысяч упоминаний. Поэтому здесь только переименование: ни одна
запись не пересчитывается, ни один навык не исчезает.

Тем же проходом чинится написание, испорченное `str.title()`:
«Оценка Персонала» и «Оценка персонала» были двумя навыками по 237 и
154 упоминания, а «LLM» показывался как «Llm».

Запуск:
    python scripts/maintenance/канон_навыков.py --сухой-прогон
    python scripts/maintenance/канон_навыков.py --yes
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.config import PROJECT_ROOT  # noqa: E402
from src.skills_store import для_показа, известные_названия, таблица_синонимов  # noqa: E402

# Колонки, где лежат названия навыков через запятую.
КОЛОНКИ = ["all_skills", "hard_skills", "soft_skills", "tools", "employer_skills"]


def канон_списка(строка: str, таблица: dict, известные: set) -> str:
    """
    Строка навыков с приведёнными названиями и без повторов.

    Повторы появляются именно здесь: после приведения «3D Max» и «3ds
    Max» в одной вакансии становятся одним и тем же навыком, названным
    дважды. Порядок сохраняется — первым работодатель называет главное.
    """
    if not строка:
        return строка

    итог, видели = [], set()
    for кусок in строка.split(","):
        навык = для_показа(кусок.strip(), таблица, известные)
        ключ = навык.lower()
        if навык and ключ not in видели:
            видели.add(ключ)
            итог.append(навык)

    return ", ".join(итог)


def main() -> int:
    разбор = argparse.ArgumentParser(description="Канон написания навыков в базе")
    разбор.add_argument("--db", default=str(PROJECT_ROOT / "data" / "hh_vacancies.db"))
    разбор.add_argument("--сухой-прогон", action="store_true", dest="сухой")
    разбор.add_argument("--yes", action="store_true")
    аргументы = разбор.parse_args()

    путь = Path(аргументы.db)
    if not путь.exists():
        print(f"База не найдена: {путь}")
        return 1

    таблица = таблица_синонимов()
    известные = известные_названия()
    if not таблица:
        print("Таблица синонимов пуста — приводить нечего.")
        return 0

    conn = sqlite3.connect(путь)
    conn.row_factory = sqlite3.Row

    try:
        строки = conn.execute(
            f"SELECT id, {', '.join(КОЛОНКИ)} FROM vacancies"
        ).fetchall()

        правки = []
        переименовано = Counter()

        for строка in строки:
            новые = {}
            for колонка in КОЛОНКИ:
                было = строка[колонка]
                стало = канон_списка(было, таблица, известные)
                if стало != было:
                    новые[колонка] = стало
                    # Считаем по одной колонке, иначе одно и то же
                    # переименование посчитается пять раз.
                    #
                    # Каждое название сверяется со своим каноном, а не с
                    # тем, что оказалось на его месте в новой строке:
                    # приведение схлопывает дубли, списки расходятся по
                    # длине, и сравнение по позиции давало пары вроде
                    # «Презентации → 3ds Max» — сдвиг, а не правку.
                    if колонка == "all_skills":
                        for кусок in (было or "").split(","):
                            старое_имя = кусок.strip()
                            новое_имя = для_показа(старое_имя, таблица, известные)
                            if старое_имя and старое_имя != новое_имя:
                                переименовано[f"{старое_имя} → {новое_имя}"] += 1

            if новые:
                правки.append((строка["id"], новые))

        print(f"База: {путь}")
        print(f"  записей в базе: {len(строки)}")
        print(f"  изменится записей: {len(правки)}")
        print(f"  синонимов в таблице: {len(таблица)}")

        if переименовано:
            print("\nЧто во что переходит (топ-15):")
            for пара, сколько in переименовано.most_common(15):
                print(f"  {сколько:>5} × {пара}")

        if аргументы.сухой:
            print("\nСухой прогон. Данные не изменены.")
            return 0

        if not аргументы.yes:
            print("\nЗапустите с --yes, чтобы применить.")
            return 1

        for ид, новые in правки:
            присвоения = ", ".join(f"{к} = ?" for к in новые)
            conn.execute(
                f"UPDATE vacancies SET {присвоения} WHERE id = ?",
                (*новые.values(), ид),
            )
        conn.commit()

        print(f"\nГотово: приведено записей {len(правки)}.")
        return 0

    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
