"""
Сверка справочника профессий с базой.

Зачем. Справочник перечисляет профессии рынка, база наполняется сборами
по конкретным запросам, и расходятся они молча. Человек выбирает
профессию, попадает в пустоту и решает, что сломан продукт, — а сломано
только соответствие между двумя списками.

Скрипт печатает обе стороны расхождения:

- профессии, по которым в базе нет ни одной вакансии;
- ключевые слова сборов, которым в справочнике не нашлось профессии.

Второе важнее первого: если собранное не попадает ни в одну профессию,
раздел «Профессии» не покажет самые свежие данные вовсе.

Запуск после каждого сбора:
    python scripts/maintenance/сверка_профессий.py
    python scripts/maintenance/сверка_профессий.py --подробно
    python scripts/maintenance/сверка_профессий.py --предел 40
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.storage import VacancyStorage  # noqa: E402
from web.app.main import (  # noqa: E402
    _load_professions_catalog,
    _счёт_вакансий_по_профессиям,
)


def ключевые_слова(df) -> set:
    """Запросы, по которым собирались вакансии, по одному на строку."""
    слова = set()
    for строка in df["source_keyword"].dropna():
        слова.update(часть.strip() for часть in str(строка).split(",") if часть.strip())
    return слова


def main() -> int:
    разбор = argparse.ArgumentParser(description="Сверка справочника профессий с базой")
    разбор.add_argument("--подробно", action="store_true",
                        help="печатать списки целиком, а не первые строки")
    разбор.add_argument("--предел", type=int, default=15,
                        help="сколько строк показывать в кратком виде")
    аргументы = разбор.parse_args()

    каталог = _load_professions_catalog()
    профессии = list(каталог.get("professions", {}).values())
    if not профессии:
        print("Справочник пуст: data/professions_catalog.json не найден или без профессий.")
        return 1

    склад = VacancyStorage()
    try:
        df = склад.get_all_vacancies()
    finally:
        склад.close()

    if df.empty:
        print("База пуста — сверять не с чем. Сначала запустите сбор.")
        return 0

    счёт = _счёт_вакансий_по_профессиям(df, профессии)
    пустые = sorted(п["name"] for п in профессии if not счёт.get(п["key"]))
    с_данными = len(профессии) - len(пустые)

    имена = [(п.get("name") or "").lower() for п in профессии]
    слова = ключевые_слова(df)
    вне = sorted(с for с in слова
                 if not any(с.lower() in имя or имя in с.lower() for имя in имена if имя))

    маска = df["source_keyword"].fillna("").apply(
        lambda строка: any(с in строка for с in вне)
    )

    def печать(заголовок, строки):
        сколько = len(строки) if аргументы.подробно else аргументы.предел
        print(f"\n{заголовок}")
        for значение in строки[:сколько]:
            print(f"  · {значение}")
        если_ещё = len(строки) - сколько
        if если_ещё > 0:
            print(f"  … и ещё {если_ещё}. Полный список: --подробно")

    print(f"Профессий в справочнике: {len(профессии)}")
    print(f"  с вакансиями в базе:   {с_данными}")
    print(f"  ведут в пустоту:       {len(пустые)}"
          f"  ({len(пустые) / len(профессии) * 100:.0f} %)")
    print(f"\nЗапросов, по которым собирали: {len(слова)}")
    print(f"  вне справочника:            {len(вне)}")
    print(f"  вакансий по ним:            {int(маска.sum())} из {len(df)}"
          f"  ({маска.sum() / len(df) * 100:.0f} %)")

    if вне:
        печать("Запросы, которым не нашлось профессии:", вне)
    if пустые:
        печать("Профессии без вакансий в базе:", пустые)

    print("\nЧто с этим делать. Раздел «Профессии» показывает справочник "
          "целиком — это навигатор по направлениям, и пустые профессии в нём "
          "остаются намеренно, с пометкой «не собирали» и объяснением. "
          "Смотреть стоит на вторую цифру: запросы вне справочника значат, "
          "что собранное не попадает ни в одну профессию и в разделе не "
          "показывается вовсе.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
