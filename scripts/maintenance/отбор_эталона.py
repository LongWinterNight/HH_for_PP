РАЗМЕТКА = re.compile(r"<[^>]+>")

# Границы длины описания. Короче — размечать нечего; длиннее — вакансия
# читается полчаса, а навыков в ней не больше, чем в обычной.
МИН_ДЛИНА, МАКС_ДЛИНА = 900, 12000


def рынок_вакансии(v: Dict[str, Any]) -> str:
    """Рынок по названию, а если оно молчит — по роли источника."""
    имя = (v.get("name") or "").lower()
    for образец, рынок in УТОЧНЕНИЯ:
        if re.search(образец, имя):
            return рынок
    роли = v.get("professional_roles") or []
    роль = роли[0].get("name") if роли and isinstance(роли[0], dict) else ""
    return РОЛЬ_РЫНОК.get(роль, "—")


def сырьё() -> Dict[str, Dict[str, Any]]:
    """Уникальные вакансии с описанием из всех файлов сборов."""
    уник: Dict[str, Dict[str, Any]] = {}
    for файл in sorted(СЫРЬЁ.glob("*.json")):
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(данные, dict):
            данные = данные.get("vacancies") or данные.get("items") or []
        for v in данные:
            if isinstance(v, dict) and v.get("description") and v.get("id"):
                уник.setdefault(str(v["id"]), v)
    return уник


def размеченные() -> set:
    if not ЭТАЛОН.exists():
        return set()
    набор = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    return {str(в.get("id")) for в in набор.get("вакансии", [])}


def пригодна(v: Dict[str, Any]) -> bool:
    текст = РАЗМЕТКА.sub(" ", v.get("description") or "")
    return МИН_ДЛИНА <= len(текст) <= МАКС_ДЛИНА


def по_рынкам(уник: Dict[str, Dict[str, Any]], пропустить: set) -> Dict[str, List[Dict]]:
    """
    Разложить вакансии по рынкам, отбросив копии одной вакансии.

    Ключ копии тот же, что в `src/copies.py`: название и работодатель.
    Тридцать одна копия объявления по городам дала бы тридцать одну
    одинаковую разметку и перекос набора в сторону массовых профессий.
    """
    видели = set()
    корзины: Dict[str, List[Dict]] = defaultdict(list)
    for ид, v in уник.items():
        if ид in пропустить or not пригодна(v):
            continue
        ключ = ((v.get("name") or "").strip().lower(),
                ((v.get("employer") or {}).get("name") or "").strip().lower())
        if ключ in видели:
            continue
        видели.add(ключ)
        корзины[рынок_вакансии(v)].append(v)
    return корзины


def очередь(корзины: Dict[str, List[Dict]], на_рынок: int) -> List[Dict[str, Any]]:
    """
    Квота с чередованием работодателей.

    Внутри рынка вакансии одного работодателя идут подряд — он
    выкладывает их пачкой. Взяв первые двадцать, набор получил бы один
    работодатель вместо двадцати, поэтому кандидаты чередуются: сначала
    по одной от каждого, потом по второй.
    """
    отобрано = []
    for рынок in РЫНКИ:
        по_работодателям: Dict[str, List[Dict]] = defaultdict(list)
        for v in корзины.get(рынок, []):
            по_работодателям[((v.get("employer") or {}).get("name") or "—")].append(v)
        очередь_рынка = []
        круг = 0
        while len(очередь_рынка) < на_рынок:
            добавили = False
            for список in по_работодателям.values():
                if круг < len(список):
                    очередь_рынка.append(список[круг])
                    добавили = True
                    if len(очередь_рынка) >= на_рынок:
                        break
            if not добавили:
                break
            круг += 1
        for v in очередь_рынка:
            отобрано.append({
                "id": str(v["id"]),
                "name": v.get("name"),
                "рынок": рынок,
                "employer": ((v.get("employer") or {}).get("name") or ""),
                "описание": v.get("description"),
                "key_skills": [k.get("name") for k in (v.get("key_skills") or [])],
            })
    return отобрано


def main() -> int:
    parser = argparse.ArgumentParser(description="Очередь на разметку эталона")
    parser.add_argument("--собрать", action="store_true", help="записать очередь в файл")
    parser.add_argument("--на-рынок", type=int, default=22, help="сколько вакансий на рынок")
    args = parser.parse_args()

    уник = сырьё()
    пропустить = размеченные()
    корзины = по_рынкам(уник, пропустить)

    print(f"Уникальных вакансий с описанием: {len(уник)}")
    print(f"Уже размечено: {len(пропустить)}\n")
    print(f"{'рынок':<28}{'доступно':>10}{'работодателей':>15}")
    for рынок in РЫНКИ:
        список = корзины.get(рынок, [])
        работодателей = len({((v.get('employer') or {}).get('name') or '') for v in список})
        пометка = "  ← мало" if len(список) < args.на_рынок else ""
        print(f"{рынок:<28}{len(список):>10}{работодателей:>15}{пометка}")
    неразобранные = корзины.get("—", [])
    if неразобранные:
        роли = Counter(
            (v.get("professional_roles") or [{}])[0].get("name", "?")
            for v in неразобранные
        )
        print(f"\nБез рынка: {len(неразобранные)} — роли не разнесены:")
        for роль, n in роли.most_common(10):
            print(f"   {n:>4}  {роль}")

    if not args.собрать:
        print("\nЗапуск с --собрать запишет очередь.")
        return 0

    отобрано = очередь(корзины, args.на_рынок)
    ОЧЕРЕДЬ.write_text(
        json.dumps(
            {"собрана": "2026-09-10", "на_рынок": args.на_рынок,
             "всего": len(отобрано), "вакансии": отобрано},
            ensure_ascii=False, indent=1),
        encoding="utf-8")
    свод = Counter(в["рынок"] for в in отобрано)
    print(f"\nОчередь записана: {ОЧЕРЕДЬ.relative_to(КОРЕНЬ)}, вакансий {len(отобрано)}")
    for рынок in РЫНКИ:
        print(f"   {рынок:<28}{свод.get(рынок, 0):>4}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
