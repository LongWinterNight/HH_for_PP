ИЗ_КАЖДОГО = 12


def допустимые(conn: sqlite3.Connection) -> set:
    """Вакансии, которые видит экран: активные и найденные по запросу."""
    return {строка[0] for строка in conn.execute(
        "SELECT vacancy_id FROM vacancies WHERE COALESCE(is_active, 1) = 1 AND COALESCE(off_query, 0) = 0"
    )}


def способы(conn, синонимы, кодировщики, кого) -> Dict[str, callable]:
    """Все сравниваемые способы поиска: имя → функция «запрос → список идентификаторов»."""
    def по_словам(запрос):
        return [ид for ид in lexical.найти(conn, запрос, синонимы, сколько=2000).порядок if ид in кого]

    итог = {"слова": по_словам}
    for модель, кодировщик in кодировщики.items():
        короткое = модель.split("/")[-1]

        def по_смыслу(запрос, модель=модель, кодировщик=кодировщик):
            вектор = кодировщик([запрос], True)[0]
            return [ид for ид, _ in vectors.индекс(conn, модель).ближайшие(вектор, 200, кого)]

        def вместе(запрос, модель=модель, кодировщик=кодировщик):
            return hybrid.найти(conn, запрос, синонимы, кодировщик, модель, кого).порядок

        итог[f"смысл · {короткое}"] = по_смыслу
        итог[f"слова + {короткое}"] = вместе
    return итог


def собрать_пул(conn) -> int:
    синонимы = таблица_синонимов()
    кого = допустимые(conn)
    кодировщики = {модель: vectors.ЛокальнаяМодель(модель) for модель in МОДЕЛИ}
    набор = способы(conn, синонимы, кодировщики, кого)

    размечено = json.loads(ЭТАЛОН.read_text(encoding="utf-8")) if ЭТАЛОН.exists() else {}
    случай = random.Random(20261011)

    for запрос in ЗАПРОСЫ:
        пул: List[str] = []
        for найти in набор.values():
            for ид in найти(запрос)[:ИЗ_КАЖДОГО]:
                if ид not in пул:
                    пул.append(ид)
        новые = [ид for ид in пул if ид not in размечено.get(запрос, {})]
        if not новые:
            continue
        случай.shuffle(новые)

        print(f"\n### {запрос}  ({len(новые)} к разметке)")
        for ид in новые:
            строка = conn.execute(
                "SELECT v.vacancy_name, COALESCE(v.all_skills, ''), COALESCE(v.employer_skills, ''), t.body "
                "FROM vacancies v LEFT JOIN vacancy_texts t ON t.text_hash = v.text_hash WHERE v.vacancy_id = ?",
                (ид,),
            ).fetchone()
            название, навыки, навыки_работодателя, тело = строка
            описание = чистый_текст(zlib.decompress(тело).decode("utf-8"))[:170] if тело else "—"
            все_навыки = ", ".join(list(dict.fromkeys((навыки + ", " + навыки_работодателя).split(", ")))[:9]).strip(", ")
            print(f"{ид} | {название[:70]} | {все_навыки[:110]} | {описание}")
    return 0


