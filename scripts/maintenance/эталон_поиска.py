def ndcg(порядок: List[str], оценки: Dict[str, int], сколько: int = 10) -> float:
    """Качество первых позиций: высокая оценка наверху стоит больше, чем внизу."""
    def выигрыш(список):
        return sum((2 ** оценка - 1) / math.log2(место + 1) for место, оценка in enumerate(список, start=1))

    полученное = [оценки.get(ид, 0) for ид in порядок[:сколько]]
    лучшее = sorted(оценки.values(), reverse=True)[:сколько]
    return выигрыш(полученное) / выигрыш(лучшее) if any(лучшее) else 0.0


def замерить(conn, показать_запросы: bool = False, сохранить: bool = False) -> int:
    if not ЭТАЛОН.exists():
        print(f"Эталона нет: {ЭТАЛОН}")
        return 1
    размечено: Dict[str, Dict[str, int]] = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    синонимы = таблица_синонимов()
    кого = допустимые(conn)
    # Сравниваются модели, чьи векторы лежат в базе. Чтобы добавить
    # кандидата: python scripts/построить_поиск.py --модель <имя>.
    посчитанные = [строка[0] for строка in conn.execute("SELECT DISTINCT model FROM search_vectors")]
    кодировщики = {модель: vectors.ЛокальнаяМодель(модель) for модель in посчитанные}
    набор = способы(conn, синонимы, кодировщики, кого)

    пар = sum(len(оценки) for оценки in размечено.values())
    print(f"Эталон: {len(размечено)} запросов, {пар} пар; подходящих (оценка 2) — "
          f"{sum(1 for о in размечено.values() for в in о.values() if в == 2)}\n")
    print(f"{'способ':34}{'nDCG@10':>9}{'точность@10':>13}{'полнота@20':>12}{'не размечено@10':>17}")

    по_запросам: Dict[str, Dict[str, float]] = {}
    итоги: Dict[str, Dict[str, float]] = {}
    for имя, найти in набор.items():
        суммы = {"ndcg": 0.0, "точность": 0.0, "полнота": 0.0, "неизвестно": 0.0}
        for запрос, оценки in размечено.items():
            порядок = найти(запрос)
            подходящие = {ид for ид, оценка in оценки.items() if оценка == 2}
            значение = ndcg(порядок, оценки)
            суммы["ndcg"] += значение
            суммы["точность"] += sum(1 for ид in порядок[:10] if оценки.get(ид, 0) == 2) / 10
            суммы["полнота"] += (len(подходящие & set(порядок[:20])) / len(подходящие)) if подходящие else 0
            суммы["неизвестно"] += sum(1 for ид in порядок[:10] if ид not in оценки) / 10
            по_запросам.setdefault(запрос, {})[имя] = значение
        n = len(размечено)
        итоги[имя] = {
            "ndcg": round(суммы["ndcg"] / n, 3),
            "точность": round(суммы["точность"] / n, 3),
            "полнота": round(суммы["полнота"] / n, 3),
        }
        print(f"{имя:34}{суммы['ndcg'] / n:>9.3f}{суммы['точность'] / n:>13.3f}"
              f"{суммы['полнота'] / n:>12.3f}{суммы['неизвестно'] / n:>17.3f}")

    if сохранить:
        # Экран «Как устроено» читает числа отсюда, а не из разметки:
        # переписанное число перестаёт быть правдой при смене модели.
        from datetime import date

        from src.system_state import файл_замера

        файл_замера().write_text(json.dumps({
            "когда": date.today().isoformat(),
            "запросов": len(размечено),
            "пар": пар,
            "способы": итоги,
            "разметка": "вслепую, без перепроверки человеком",
        }, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"\nЗамер сохранён: {файл_замера()}")

    if показать_запросы:
        имена = list(набор)
        print("\nnDCG@10 по запросам:\n" + f"{'запрос':34}" + "".join(f"{имя[:15]:>17}" for имя in имена))
        for запрос, значения in по_запросам.items():
            print(f"{запрос[:33]:34}" + "".join(f"{значения[имя]:>17.2f}" for имя in имена))
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(description="Эталон релевантности для поиска")
    разбор.add_argument("--пул", action="store_true", help="напечатать неразмеченные пары")
    разбор.add_argument("--замер", action="store_true", help="сравнить способы поиска на эталоне")
    разбор.add_argument("--по-запросам", action="store_true", dest="по_запросам", help="показать замер по каждому запросу")
    разбор.add_argument("--сохранить", action="store_true", help="записать итог замера для экрана «Как устроено»")
    аргументы = разбор.parse_args()

    conn = sqlite3.connect(f"file:{settings.db_path}?mode=ro", uri=True)
    try:
        if аргументы.пул:
            return собрать_пул(conn)
        if аргументы.замер:
            return замерить(conn, аргументы.по_запросам, аргументы.сохранить)
        разбор.print_help()
        return 2
    finally:
        conn.close()


if __name__ == "__main__":
    sys.exit(main())
