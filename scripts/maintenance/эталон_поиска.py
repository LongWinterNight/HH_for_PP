"""
Эталон релевантности для поиска: пул кандидатов и замер.

Зачем. Три способа поиска и две модели векторов нельзя сравнить на
глаз: на одном запросе лучше один, на другом другой, и «кажется, стало
лучше» ничего не стоит. Нужны запросы с известными ответами.

Как собран пул. По каждому запросу берутся первые вакансии от каждого
способа и объединяются. Размечается объединение — вслепую: в списке для
разметки не сказано, какой способ что нашёл, и порядок перемешан.
Иначе разметчик невольно подтверждал бы выдачу того способа, который
видит первым.

Оценки: 2 — вакансия отвечает запросу; 1 — отчасти (смежная профессия,
нужный навык упомянут вскользь); 0 — не отвечает.

Ограничение метода. Вакансия, которую не нашёл ни один способ, в пул не
попадает, и полнота считается относительно пула, а не всей базы. Для
сравнения способов между собой этого достаточно; абсолютной полноты
замер не даёт.

Запуск:
    python scripts/maintenance/эталон_поиска.py --пул            # список для разметки
    python scripts/maintenance/эталон_поиска.py --замер          # сравнить способы
"""

