"""
Замер: по запросу ли собранные вакансии.

Зачем. Источник ищет слова запроса во всех полях вакансии, включая
название компании. По запросу «Арт-директор» так пришла 331 вакансия
ресторанов работодателя «АРТ РЕСТ», и все они вошли в медианы зарплат
и частоты навыков профессии. Прежде чем сужать поиск, нужно знать, что
каждое сужение отрежет: мусор или настоящие вакансии, где профессия
названа иначе.

Что меряется. Для каждой вакансии с сохранённым текстом описания — где
встречаются слова запроса: в названии, в описании, среди навыков, в
названии компании. Это те же поля, по которым источник умеет
ограничивать поиск, поэтому замер отвечает на вопрос «что останется,
если искать только здесь».

Сопоставление нестрогое намеренно: «рендеринг» совпадает с «рендер»,
«3ds Max» — с «3dsmax». Строгое сравнение объявило бы мусором
вакансии, где слово стоит в другой форме или написано раздельно.

Чего замер не видит. Источник расширяет запрос синонимами: вакансия
«Креативный директор» приходит по «Арт-директор» законно, а здесь
попадёт в «нигде». Поэтому «нигде» — верхняя граница мусора, а не его
точная доля; точную даёт только разметка глазами.

Запуск:
    python scripts/maintenance/замер_профильности.py
    python scripts/maintenance/замер_профильности.py --от 100
"""

from __future__ import annotations

import argparse
import re
import sqlite3
import sys
import zlib
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.config import settings  # noqa: E402

РАЗМЕТКА = re.compile(r"<[^>]+>")
СЛОВА = re.compile(r"[a-zа-я0-9]+")


def _слова(текст: str) -> List[str]:
    return СЛОВА.findall((текст or "").lower().replace("ё", "е"))


def _основа(слово: str) -> str:
    """Слово без окончания: «дизайнера» и «дизайнер» должны совпасть."""
    return слово[:-2] if len(слово) > 5 else слово


def встречается(запрос: str, текст: str) -> bool:
    """
    Есть ли запрос в тексте.

    Два способа, достаточно любого. По словам: каждое слово запроса
    начинает какое-то слово текста («рендер» — «рендеринг»). Слитно:
    запрос без пробелов есть в тексте без пробелов («3dsmax» — «3ds
    max», «арт-директор» — «артдиректор»).
    """
    слова_запроса = _слова(запрос)
    слова_текста = _слова(текст)
    if not слова_запроса or not слова_текста:
        return False

    if all(any(слово.startswith(_основа(з)) for слово in слова_текста) for з in слова_запроса):
        return True

    слитно = "".join(слова_запроса)
    return len(слитно) >= 4 and слитно in "".join(слова_текста)


def замерить(путь_базы: Path) -> Dict[str, Counter]:
    база = sqlite3.connect(f"file:{путь_базы}?mode=ro", uri=True)
    try:
        строки = база.execute(
            """
            SELECT v.source_keyword, v.vacancy_name, COALESCE(v.employer_name, ''),
                   COALESCE(v.all_skills, '') || ' ' || COALESCE(v.employer_skills, ''), t.body
            FROM vacancies v JOIN vacancy_texts t ON t.text_hash = v.text_hash
            WHERE v.source_keyword NOT LIKE '%,%'
            """
        ).fetchall()
    finally:
        база.close()

    по_запросам: Dict[str, Counter] = defaultdict(Counter)
    for запрос, название, компания, навыки, тело in строки:
        описание = РАЗМЕТКА.sub(" ", zlib.decompress(тело).decode("utf-8"))
        в_названии = встречается(запрос, название)
        в_описании = встречается(запрос, описание)
        в_навыках = встречается(запрос, навыки)
        в_компании = встречается(запрос, компания) or any(
            слово.startswith(_основа(з)) for з in _слова(запрос) for слово in _слова(компания)
        )

        п = по_запросам[запрос]
        п["всего"] += 1
        п["название"] += в_названии
        п["название_описание"] += в_названии or в_описании or в_навыках
        нигде = not (в_названии or в_описании or в_навыках)
        п["нигде"] += нигде
        п["только_компания"] += нигде and в_компании
    return по_запросам


def main() -> int:
    разбор = argparse.ArgumentParser(description="Замер: по запросу ли собранные вакансии")
    разбор.add_argument("--от", type=int, default=30, help="показывать запросы с выборкой не меньше")
    аргументы = разбор.parse_args()

    по_запросам = замерить(settings.db_path)
    if not по_запросам:
        print("Вакансий с сохранённым текстом описания нет — мерить не по чему.")
        return 0

    доля = lambda часть, целое: f"{round(часть / целое * 100):>3} %" if целое else "   —"  # noqa: E731
    print(f"{'запрос':26}{'вакансий':>9}{'в названии':>12}{'назв.+описание':>16}{'нигде':>8}{'из них по компании':>20}")
    итог: Counter = Counter()
    for запрос, п in sorted(по_запросам.items(), key=lambda пара: -пара[1]["всего"]):
        итог.update(п)
        if п["всего"] < аргументы.от:
            continue
        print(
            f"{запрос[:25]:26}{п['всего']:>9}{доля(п['название'], п['всего']):>12}"
            f"{доля(п['название_описание'], п['всего']):>16}{доля(п['нигде'], п['всего']):>8}{п['только_компания']:>20}"
        )
    print(
        f"\n{'ВСЕГО':26}{итог['всего']:>9}{доля(итог['название'], итог['всего']):>12}"
        f"{доля(итог['название_описание'], итог['всего']):>16}{доля(итог['нигде'], итог['всего']):>8}{итог['только_компания']:>20}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
