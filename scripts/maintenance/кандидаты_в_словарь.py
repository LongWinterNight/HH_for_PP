"""
Кандидаты в словарь навыков.

Зачем. Словарь пополняется руками, а рынок меняется быстрее, чем его
успевают дописывать: замер показал, что 89 базовых терминов в нём
отсутствовали, и каждый пропуск — это навык, которого для продукта не
существует. Тексты вакансий при этом полны названий, которых мы не
знаем.

Скрипт ищет их сам: собирает то, что стоит в позиции навыка — после
«знание», «владение», «опыт работы с», в перечислении стека, — и чего
нет в словаре.

Кандидат не становится навыком автоматически. Он копится с частотой,
числом работодателей и примерами, а решение принимает человек: словарь,
пополняемый машиной без надзора, за месяц превращается в свалку
опечаток и обрывков фраз.

Решения хранятся в `data/кандидаты_навыков.json` и переживают повторные
запуски: отклонённый кандидат больше не предлагается.

Запуск:
    python scripts/maintenance/кандидаты_в_словарь.py                 # собрать и показать
    python scripts/maintenance/кандидаты_в_словарь.py --принять "микросервисная архитектура" "брокеры сообщений"
    python scripts/maintenance/кандидаты_в_словарь.py --отклонить "читать" "четко"
    python scripts/maintenance/кандидаты_в_словарь.py --в-словарь     # записать принятых в config.yaml
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import yaml  # noqa: E402

from src.morphology import анализатор, привести  # noqa: E402
from src.normalize import SkillDictionaries  # noqa: E402
from src.sections import текст_для_навыков  # noqa: E402

РАЗМЕТКА = re.compile(r"<[^>]+>")

# Обороты, после которых работодатель называет навык. Список короткий и
# намеренно строгий: чем свободнее шаблон, тем больше мусора, а разбирать
# мусор руками дороже, чем пропустить редкий навык — он всё равно
# встретится ещё раз.
ПОЗИЦИЯ_НАВЫКА = re.compile(
    r"(?:знание|знания|владение|уверенное владение|опыт работы с|опыт с|"
    r"умение|навыки|стек[а-я]*\s*:|используем|работа с)\s+"
    r"([a-zа-яё0-9#+.\- ]{3,40})",
    re.I,
)

РАЗДЕЛИТЕЛЬ = re.compile(r"\s*[,;/]\s*|\s+и\s+")

# Слова, которые сами по себе навык не составляют.
СЛИШКОМ_ОБЩИЕ = {
    "работы", "опыт", "работа", "знание", "умение", "понимание", "навыки",
    "задач", "задачи", "решения", "данных", "данные", "компании", "команде",
    "людьми", "клиентами", "инструментами", "инструмент", "сбора", "четко",
    "чётко", "коммуникации", "процессов", "процессы", "документации",
    "требований", "системами", "системы", "проектов", "продукта",
}

# Части речи, с которых навык не начинается: «читать», «работать»,
# «быстро» — это не названия умений, а глаголы и наречия рядом с ними.
НЕ_НАЧАЛО_НАВЫКА = {"INFN", "VERB", "ADVB", "PRED", "CONJ", "PREP", "PRCL"}

ФАЙЛ_РЕШЕНИЙ = Path("data/кандидаты_навыков.json")


def похоже_на_навык(фраза: str) -> bool:
    """Отсев очевидного мусора до того, как его увидит человек.

    Короче четырёх символов кандидаты не рассматриваются вовсе. Это
    осознанная потеря: «Go», «QA», «1С» так не найдутся — но короткие
    сочетания букв встречаются в текстах постоянно и по любому поводу,
    и автоотбор по ним даёт больше мусора, чем пользы. Такие навыки
    добавляются в словарь руками.
    """
    if len(фраза) < 4 or len(фраза.split()) > 3:
        return False
    if фраза in СЛИШКОМ_ОБЩИЕ:
        return False
    if re.fullmatch(r"[\d\s.,%-]+", фраза):
        return False

    # «3 лет», «5 месяцев» — обрывок требования к стажу, а не навык.
    # Отсекается именно эта форма: число, пробел и слово. Навыки,
    # начинающиеся с цифры без пробела, — «1С», «3ds max», «3d-печать» —
    # проходят.
    if re.match(r"^\d+\s+[а-яёa-z]", фраза):
        return False

    первое = фраза.split()[0]
    if re.search(r"[а-яё]", первое):
        разбор = анализатор().parse(первое)[0]
        if str(разбор.tag.POS) in НЕ_НАЧАЛО_НАВЫКА:
            return False

    return True


def ключ(фраза: str) -> str:
    """Фраза в виде, пригодном для сравнения с уже решённым.

    Кандидат приходит из текста в косвенном падеже — «базами данных», —
    а в словарь его записывают каноническим — «базы данных». Сравнение
    по буквам предлагало бы один и тот же навык бесконечно.
    """
    return привести(фраза.lower())


def собрать(папка: Path, известно: set) -> tuple:
    """Кандидаты с частотой, работодателями и примерами."""
    частота = Counter()
    работодатели = defaultdict(set)
    примеры = defaultdict(list)

    for файл in sorted(папка.glob("*.json")):
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(данные, dict):
            данные = данные.get("vacancies") or данные.get("items") or []

        for вакансия in данные:
            if not isinstance(вакансия, dict):
                continue
            описание = вакансия.get("description") or ""
            if not описание:
                continue

            наниматель = ((вакансия.get("employer") or {}).get("name") or "")[:60]
            текст = РАЗМЕТКА.sub(" ", текст_для_навыков(описание)).lower()

            for кусок in ПОЗИЦИЯ_НАВЫКА.findall(текст):
                for часть in РАЗДЕЛИТЕЛЬ.split(кусок):
                    фраза = часть.strip(" .:;-—")
                    if ключ(фраза) in известно or not похоже_на_навык(фраза):
                        continue
                    частота[фраза] += 1
                    работодатели[фраза].add(наниматель)
                    if len(примеры[фраза]) < 3:
                        примеры[фраза].append(вакансия.get("name") or "")

    return частота, работодатели, примеры


def читать_решения() -> dict:
    if ФАЙЛ_РЕШЕНИЙ.exists():
        return json.loads(ФАЙЛ_РЕШЕНИЙ.read_text(encoding="utf-8"))
    return {"принято": [], "отклонено": []}


def записать_решения(решения: dict) -> None:
    ФАЙЛ_РЕШЕНИЙ.parent.mkdir(parents=True, exist_ok=True)
    ФАЙЛ_РЕШЕНИЙ.write_text(
        json.dumps(решения, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def main() -> int:
    разбор = argparse.ArgumentParser(description="Кандидаты в словарь навыков")
    разбор.add_argument("--raw", default="data/raw")
    разбор.add_argument("--работодателей", type=int, default=3,
                        help="минимум разных работодателей у кандидата")
    разбор.add_argument("--сколько", type=int, default=40)
    разбор.add_argument("--принять", nargs="*", default=[])
    разбор.add_argument("--отклонить", nargs="*", default=[])
    разбор.add_argument("--в-словарь", action="store_true", dest="в_словарь")
    аргументы = разбор.parse_args()

    решения = читать_решения()

    if аргументы.принять or аргументы.отклонить:
        for фраза in аргументы.принять:
            if фраза not in решения["принято"]:
                решения["принято"].append(фраза)
        for фраза in аргументы.отклонить:
            if фраза not in решения["отклонено"]:
                решения["отклонено"].append(фраза)
        записать_решения(решения)
        print(f"Принято: {len(решения['принято'])}, отклонено: {len(решения['отклонено'])}")
        return 0

    if аргументы.в_словарь:
        принятые = решения["принято"]
        if not принятые:
            print("Принятых кандидатов нет. Сначала: --принять «навык»")
            return 0

        конфиг = Path("config.yaml")
        данные = yaml.safe_load(конфиг.read_text(encoding="utf-8"))
        известно = {
            s.lower()
            for к in ("hard_skills", "soft_skills", "tools")
            for s in данные.get(к, [])
        }
        новые = [ф for ф in принятые if ф.lower() not in известно]
        данные["hard_skills"] = данные.get("hard_skills", []) + новые
        конфиг.write_text(
            yaml.safe_dump(данные, allow_unicode=True, sort_keys=False, width=100),
            encoding="utf-8",
        )
        print(f"В словарь добавлено: {len(новые)}")
        for ф in новые:
            print(f"  + {ф}")
        print("\nПересчитать базу: python scripts/maintenance/пересчёт_навыков.py --yes")
        return 0

    папка = Path(аргументы.raw)
    if not папка.exists():
        print(f"Папка сборов не найдена: {папка}")
        return 1

    словари = SkillDictionaries.from_config()
    # Сравнение идёт по начальным формам: словарь и решения записаны
    # каноническими, а текст даёт косвенные падежи.
    известно = {ключ(s.name) for s in (словари.hard + словари.soft + словари.tools)}
    известно |= {ключ(ф) for ф in решения["принято"] + решения["отклонено"]}

    частота, работодатели, примеры = собрать(папка, известно)

    годные = [
        (ф, c) for ф, c in частота.most_common()
        if len(работодатели[ф]) >= аргументы.работодателей
    ]

    print(f"Кандидатов найдено: {len(частота)}")
    print(f"Из них у {аргументы.работодателей}+ работодателей: {len(годные)}")
    print(f"Уже решено: принято {len(решения['принято'])}, "
          f"отклонено {len(решения['отклонено'])}\n")

    for фраза, счёт in годные[:аргументы.сколько]:
        где = "; ".join(примеры[фраза][:2])
        print(f"  {счёт:>4} × {фраза}")
        print(f"        работодателей: {len(работодатели[фраза])} · {где[:70]}")

    print("\nРешение принимает человек:")
    print('  --принять "навык" "навык"     — в очередь на добавление')
    print('  --отклонить "мусор"           — больше не предлагать')
    print("  --в-словарь                   — записать принятых в config.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
