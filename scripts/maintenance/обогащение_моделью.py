"""
Прогон обогащения: модель разбирает вакансии, которым не хватило словаря.

Зачем. У половины вакансий словарь находит меньше трёх навыков. Модель
читает их тексты, её находки ложатся рядом с навыками словаря (в
аналитику не идут), а найденное вне словаря копится кандидатами на его
пополнение.

Прогон идёт по базе и долго — часы на весь массив, — поэтому у него
есть сухой прогон и бюджет. Прерванный прогон продолжается с того же
места: разобранное не разбирается заново.

Запуск:
    python scripts/maintenance/обогащение_моделью.py --сухой-прогон
    python scripts/maintenance/обогащение_моделью.py --вызовов 200
    python scripts/maintenance/обогащение_моделью.py --минут 120
    python scripts/maintenance/обогащение_моделью.py --модель qwen3-14b --вызовов 50

Слой включается настройкой AI_LAYER=1 в .env. Выключенный слой прогон
не запускает: выключение должно выключать всё, а не только показ.
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))


def main() -> int:
    разбор = argparse.ArgumentParser(description="Прогон обогащения вакансий моделью")
    разбор.add_argument("--сухой-прогон", action="store_true", help="показать, сколько вакансий в очереди и сколько это займёт")
    разбор.add_argument("--вызовов", type=int, default=None, help="предел вызовов модели за прогон")
    разбор.add_argument("--минут", type=float, default=None, help="предел времени прогона")
    разбор.add_argument("--вакансий", type=int, default=None, help="взять из очереди не больше стольких вакансий")
    разбор.add_argument("--модель", default="", help="кандидат из src/ai/модели.py (по умолчанию — выбранный)")
    разбор.add_argument("--db", default="", help="путь к базе (по умолчанию — рабочая)")
    разбор.add_argument("--несмотря-на-выключение", action="store_true", help="запустить при AI_LAYER=0 — для проб до решения о включении")
    аргументы = разбор.parse_args()

    from src import ai, schema_check
    from src.ai import кандидаты, модели, прогон
    from src.ai.бюджет import Бюджет
    from src.config import settings

    путь = Path(аргументы.db) if аргументы.db else settings.db_path
    if schema_check.недостающие(путь):
        print(schema_check.объяснение(schema_check.недостающие(путь), путь))
        return 2

    кандидат = модели.КАНДИДАТЫ[аргументы.модель] if аргументы.модель else модели.выбранный()
    версия = f"{кандидат.версия(модели.версия_рантайма())}|{прогон.ВЕРСИЯ_ПРОМПТА}"

    conn = sqlite3.connect(путь, timeout=60)
    try:
        ждёт = прогон.сколько_ждёт(conn, версия)
        print(f"Модель: {кандидат.имя} ({кандидат.описание})")
        print(f"Версия разбора: {версия}")
        print(f"В очереди: {ждёт} вакансий с текстом, где словарь нашёл меньше {прогон.МАЛО_НАВЫКОВ} навыков")

        if аргументы.сухой_прогон:
            # Оценка времени — по последнему замеру этой модели: число,
            # взятое с потолка, хуже отсутствующего.
            оценка = _секунд_на_вакансию(кандидат.имя)
            if оценка and ждёт:
                часов = ждёт * оценка / 3600
                print(f"Оценка: около {оценка:g} с на вакансию — {часов:.1f} ч на всю очередь (по замеру на эталоне)")
            else:
                print("Оценки времени нет: замер этой модели не сохранён (замер_извлечения.py --эталон --режим модель --сохранить)")
            print("Сухой прогон: модель не вызвана, база не тронута.")
            return 0

        if not ai.включён() and not аргументы.несмотря_на_выключение:
            print("Слой выключен (AI_LAYER=0). Включите его в .env либо добавьте --несмотря-на-выключение для пробы.")
            return 2
        if not ждёт:
            print("Очередь пуста — разбирать нечего.")
            return 0

        def ход(номер, всего, итог):
            if номер % 10 == 0 or номер == всего:
                print(f"  [{номер}/{всего}] вызовов {итог.вызовов}, из кэша {итог.из_кэша}, "
                      f"навыков {итог.навыков}, кандидатов {итог.кандидатов}", flush=True)

        with модели.сервер(кандидат) as модель:
            итог = прогон.провести(
                conn, модель, Бюджет(вызовов=аргументы.вызовов, минут=аргументы.минут),
                предел=аргументы.вакансий, ход=ход,
            )

        print(f"\nРазобрано {итог.разобрано} из {итог.отобрано}: вызовов модели {итог.вызовов}, из кэша {итог.из_кэша}")
        print(f"Навыков найдено {итог.навыков}; с цитатой не из текста отброшено {итог.отброшено}")
        print(f"Кандидатов в словарь учтено {итог.кандидатов}; ответов отброшено целиком {итог.сломанных}; отказов модели {итог.отказов}")
        print(f"Время: {итог.секунд / 60:.1f} мин; токенов {итог.токенов_вход} + {итог.токенов_выход}")
        if итог.остановка:
            print(f"Остановлен: {итог.остановка}. Следующий запуск продолжит с этого места.")
        с = кандидаты.сводка(conn)
        print(f"Кандидатов всего {с['новых']}, из них ждут решения (три работодателя и больше) — {с['ждут_решения']}")
        print(f"Осталось в очереди: {прогон.сколько_ждёт(conn, версия)}")
        return 0
    finally:
        conn.close()


def _секунд_на_вакансию(имя_модели: str):
    import json

    файл = Path("data/замер_навыков.json")
    if not файл.exists():
        return None
    try:
        замеры = json.loads(файл.read_text(encoding="utf-8")).get("замеры", {})
    except (OSError, ValueError):
        return None
    for запись in замеры.values():
        if (запись.get("версия") or "").startswith(имя_модели + ":") and запись.get("вакансий_в_час"):
            return round(3600 / запись["вакансий_в_час"], 1)
    return None


if __name__ == "__main__":
    sys.exit(main())
