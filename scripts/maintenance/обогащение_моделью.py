"""
Прогон обогащения: модель разбирает вакансии, которым не хватило словаря.

Зачем. У половины вакансий словарь находит меньше трёх навыков. Модель
читает их тексты, её находки ложатся рядом с навыками словаря (в
аналитику не идут), а найденное вне словаря копится кандидатами на его
пополнение.

Прогон идёт по базе и долго — часы на весь массив, — поэтому у него
есть сухой прогон и бюджет. Прерванный прогон продолжается с того же
места: разобранное не разбирается заново.

Запуск:
    python scripts/maintenance/обогащение_моделью.py --сухой-прогон
    python scripts/maintenance/обогащение_моделью.py --вызовов 200
    python scripts/maintenance/обогащение_моделью.py --минут 120
    python scripts/maintenance/обогащение_моделью.py --модель qwen3-14b --вызовов 50
    python scripts/maintenance/обогащение_моделью.py --фон --навыков-меньше 1000

Фон — режим для занятой видеокарты: модель считает на процессоре с
пониженным приоритетом. Результат тот же, что на карте, и версия разбора
та же; отличается только скорость.

Слой включается настройкой AI_LAYER=1 в .env. Выключенный слой прогон
не запускает: выключение должно выключать всё, а не только показ.
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))


def main() -> int:
    разбор = argparse.ArgumentParser(description="Прогон обогащения вакансий моделью")
    разбор.add_argument("--сухой-прогон", action="store_true", help="показать, сколько вакансий в очереди и сколько это займёт")
    разбор.add_argument("--вызовов", type=int, default=None, help="предел вызовов модели за прогон")
    разбор.add_argument("--минут", type=float, default=None, help="предел времени прогона")
    разбор.add_argument("--вакансий", type=int, default=None, help="взять из очереди не больше стольких вакансий")
    разбор.add_argument("--модель", default="", help="кандидат из src/ai/модели.py (по умолчанию — выбранный)")
    разбор.add_argument("--навыков-меньше", type=int, default=None,
                        help="брать вакансии, где словарь нашёл меньше стольких навыков (по умолчанию 3; 1000 — все с текстом)")
    разбор.add_argument("--фон", action="store_true",
                        help="считать на процессоре с пониженным приоритетом, почти не занимая видеокарту: около десяти минут на вакансию, зато не мешает играм")
    разбор.add_argument("--сам", action="store_true",
                        help="идти до конца очереди, перед каждой порцией выбирая: карта свободна — на ней, занята — в фоне")
    разбор.add_argument("--db", default="", help="путь к базе (по умолчанию — рабочая)")
    разбор.add_argument("--несмотря-на-выключение", action="store_true", help="запустить при AI_LAYER=0 — для проб до решения о включении")
    аргументы = разбор.parse_args()

    from src import ai, schema_check
    from src.ai import кандидаты, модели, прогон
    from src.ai.бюджет import Бюджет
    from src.config import settings

    путь = Path(аргументы.db) if аргументы.db else settings.db_path
    if schema_check.недостающие(путь):
        print(schema_check.объяснение(schema_check.недостающие(путь), путь))
        return 2

    кандидат = модели.КАНДИДАТЫ[аргументы.модель] if аргументы.модель else модели.выбранный()
    версия = f"{кандидат.версия(модели.версия_рантайма(кандидат))}|{прогон.ВЕРСИЯ_ПРОМПТА}"

    conn = sqlite3.connect(путь, timeout=60)
    try:
        порог = аргументы.навыков_меньше if аргументы.навыков_меньше is not None else прогон.МАЛО_НАВЫКОВ
        ждёт = прогон.сколько_ждёт(conn, версия, порог)
        print(f"Модель: {кандидат.имя} ({кандидат.описание})")
        print(f"Версия разбора: {версия}")
        print(f"В очереди: {ждёт} вакансий с текстом, где словарь нашёл меньше {порог} навыков")
        if аргументы.фон:
            print(f"Режим: фон — процессор, потоков {модели.потоков_в_фоне()}, приоритет ниже обычного; карте остаётся только чтение текста")

        if аргументы.сухой_прогон:
            # Оценка времени — по последнему замеру этой модели: число,
            # взятое с потолка, хуже отсутствующего.
            оценка = _секунд_на_вакансию(кандидат.имя)
            if аргументы.фон:
                # Замер на эталоне сделан на видеокарте; выдать его за
                # скорость процессора значило бы пообещать десять часов
                # там, где выйдут сотни.
                print("Оценки времени для фона нет: сохранённый замер сделан на видеокарте. Скорость фона — в data-issues.md.")
            elif оценка and ждёт:
                часов = ждёт * оценка / 3600
                print(f"Оценка: около {оценка:g} с на вакансию — {часов:.1f} ч на всю очередь (по замеру на эталоне)")
            else:
                print("Оценки времени нет: замер этой модели не сохранён (замер_извлечения.py --эталон --режим модель --сохранить)")
            print("Сухой прогон: модель не вызвана, база не тронута.")
            return 0

        if not ai.включён() and not аргументы.несмотря_на_выключение:
            print("Слой выключен (AI_LAYER=0). Включите его в .env либо добавьте --несмотря-на-выключение для пробы.")
            return 2
        if not ждёт:
            print("Очередь пуста — разбирать нечего.")
            return 0

        if аргументы.сам:
            return _сам(conn, кандидат, версия, порог, аргументы.минут)

        # В фоне вакансия идёт минуты: строка раз в десять вакансий
        # молчала бы по часу и выглядела зависанием.
        шаг = 1 if аргументы.фон else 10

        def ход(номер, всего, итог):
            if номер % шаг == 0 or номер == всего:
                print(f"  [{номер}/{всего}] вызовов {итог.вызовов}, из кэша {итог.из_кэша}, "
                      f"навыков {итог.навыков}, кандидатов {итог.кандидатов}", flush=True)

        with модели.сервер(кандидат, фон=аргументы.фон) as модель:
            итог = прогон.провести(
                conn, модель, Бюджет(вызовов=аргументы.вызовов, минут=аргументы.минут),
                предел=аргументы.вакансий, навыков_меньше=порог, ход=ход,
            )

        print(f"\nРазобрано {итог.разобрано} из {итог.отобрано}: вызовов модели {итог.вызовов}, из кэша {итог.из_кэша}")
        print(f"Навыков найдено {итог.навыков}; с цитатой не из текста отброшено {итог.отброшено}")
        print(f"Кандидатов в словарь учтено {итог.кандидатов}; ответов отброшено целиком {итог.сломанных}; отказов модели {итог.отказов}")
        print(f"Время: {итог.секунд / 60:.1f} мин; токенов {итог.токенов_вход} + {итог.токенов_выход}")
        if итог.остановка:
            print(f"Остановлен: {итог.остановка}. Следующий запуск продолжит с этого места.")
        с = кандидаты.сводка(conn)
        print(f"Кандидатов всего {с['новых']}, из них ждут решения (три работодателя и больше) — {с['ждут_решения']}")
        print(f"Осталось в очереди: {прогон.сколько_ждёт(conn, версия, порог)}")
        return 0
    finally:
        conn.close()


# Порция на карте ограничена временем, а не числом вакансий: если карту
# заняли посреди порции, медленными окажутся минуты, а не час. В фоне
# порция — одна вакансия: она и так идёт минуты, и после каждой стоит
# заново посмотреть, не освободилась ли карта.
МИНУТ_НА_КАРТЕ = 3
ВАКАНСИЙ_В_ФОНЕ = 1

# Файл-просьба остановиться. Проверяется между порциями: прогон идёт в
# своём окне, и дотянуться до него иначе можно только закрыв окно.
СТОП = Path("data") / "стоп_разбора"


def _сам(conn, кандидат, версия: str, порог: int, минут) -> int:
    """
    Идти по очереди до конца, выбирая режим перед каждой порцией.

    Видеокарта одна на всё: модель, поиск по смыслу и то, чем занят
    владелец. Ждать свободной карты значит разбирать только по ночам;
    считать только на процессоре — в десятки раз медленнее. Здесь оба
    режима работают по очереди: свободна карта — быстро на ней, занята —
    медленно в фоне, не трогая её.
    """
    import time
    from datetime import datetime

    from src.ai import модели, прогон
    from src.ai.бюджет import Бюджет

    начало = time.monotonic()
    сделано = {"карта": [0, 0.0], "фон": [0, 0.0]}
    пропустить: set = set()
    исход = "очередь пуста"

    while True:
        if СТОП.exists():
            СТОП.unlink()
            исход = "остановлен по просьбе (файл data/стоп_разбора)"
            break
        if минут and (time.monotonic() - начало) / 60 >= минут:
            исход = f"предел времени: {минут:g} мин"
            break
        осталось = прогон.сколько_ждёт(conn, версия, порог) - len(пропустить)
        if осталось <= 0:
            break

        фон = not модели.карта_свободна(кандидат)
        режим = "фон" if фон else "карта"
        try:
            with модели.сервер(кандидат, фон=фон) as модель:
                итог = прогон.провести(
                    conn, модель, Бюджет() if фон else Бюджет(минут=МИНУТ_НА_КАРТЕ),
                    предел=ВАКАНСИЙ_В_ФОНЕ if фон else None, навыков_меньше=порог, кроме=пропустить,
                )
        except (RuntimeError, TimeoutError, OSError) as ошибка:
            исход = f"модель не поднялась ({режим}): {ошибка}"
            break

        пропустить.update(итог.отказавшие)
        сделано[режим][0] += итог.разобрано
        сделано[режим][1] += итог.секунд
        print(f"{datetime.now():%d.%m %H:%M} | {режим:5} | разобрано {итог.разобрано}, навыков {итог.навыков}, "
              f"отказов {итог.отказов}, {итог.секунд:.0f} с | осталось {осталось - итог.разобрано}", flush=True)

        if "модель не отвечает" in итог.остановка:
            исход = итог.остановка
            break
        if not итог.разобрано and not итог.отказов:
            # Порция ничего не взяла и ни на чём не споткнулась: идти
            # дальше значило бы крутиться на месте.
            исход = "порция пуста при непустой очереди"
            break

    print(f"\nПрогон кончился: {исход}.")
    for режим, (вакансий, секунд) in сделано.items():
        if вакансий:
            print(f"  {режим}: {вакансий} вакансий за {секунд / 60:.0f} мин — {секунд / вакансий:.0f} с на вакансию")
    if пропустить:
        print(f"  модель не ответила на {len(пропустить)} вакансиях — они остались в очереди")
    print(f"Осталось в очереди: {прогон.сколько_ждёт(conn, версия, порог)}")
    return 0


def _секунд_на_вакансию(имя_модели: str):
    import json

    файл = Path("data/замер_навыков.json")
    if not файл.exists():
        return None
    try:
        замеры = json.loads(файл.read_text(encoding="utf-8")).get("замеры", {})
    except (OSError, ValueError):
        return None
    for запись in замеры.values():
        if (запись.get("версия") or "").startswith(имя_модели + ":") and запись.get("вакансий_в_час"):
            return round(3600 / запись["вакансий_в_час"], 1)
    return None


if __name__ == "__main__":
    sys.exit(main())
