РАЗМЕТКА = re.compile(r"<[^>]+>")


def стоит_в_тексте(навык: str, текст: str) -> bool:
    """Навык присутствует как отдельное слово, а не как часть чужого.

    Без этого эталон завышается и цель становится неверной: «Git»
    считался бы обязательным к находке в тексте, где есть только
    «github.com» и «gitlab», а «R» — в каждом слове с этой буквой.
    Требовать от поиска находить такое нельзя — он и не должен.
    """
    шаблон = r"(?<![\w#+.])" + re.escape(навык.lower()) + r"(?![\w#+])"
    return re.search(шаблон, текст) is not None


def пары_для_замера(папка: Path, предел: int):
    """Вакансии, где есть и описание, и названные работодателем навыки."""
    пары = []
    for файл in sorted(папка.glob("*.json")):
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(данные, dict):
            данные = данные.get("vacancies") or данные.get("items") or []
        for вакансия in данные:
            if not isinstance(вакансия, dict):
                continue
            описание = вакансия.get("description") or ""
            навыки = [
                (s.get("name") or "").strip()
                for s in (вакансия.get("key_skills") or [])
                if (s.get("name") or "").strip()
            ]
            if описание and навыки:
                пары.append((вакансия, описание, навыки))
            if len(пары) >= предел:
                return пары
    return пары


РЕЖИМЫ = ("словарь", "модель", "вместе")
ФАЙЛ_ЗАМЕРА = Path("data/замер_навыков.json")
КЭШ_ЗАМЕРА = Path("data/ai_замер.db")


def _канон(название: str, таблица: dict) -> str:
    """Название в том виде, в каком его сравнивает замер: канон словаря, нижний регистр."""
    ключ = " ".join(название.lower().split())
    return str(таблица.get(ключ, ключ)).lower()


def навыки_модели(вакансии: list, имя_модели: str, потоков: int, уверенность: float = 0.0, отбор: bool = True) -> tuple:
    """
    Что модель нашла в каждой вакансии эталона.

    Returns:
        ({ид вакансии: множество названий}, сводка о вызовах, версия разбора)
    """
    import sqlite3
    from concurrent.futures import ThreadPoolExecutor

    from src.ai import кэш, модели
    from src.ai.извлечение import ВЕРСИЯ_ПРОМПТА, ГРАММАТИКА, СХЕМА_ОТВЕТА, вход, достойные, из_сырого, промпт
    from src.ai.поставщик import МодельНедоступна
    from src.ai_contract import ОтветСломан
    from src import skills_store

    кандидат = модели.КАНДИДАТЫ[имя_модели]
    таблица = skills_store.таблица_синонимов()

    КЭШ_ЗАМЕРА.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(КЭШ_ЗАМЕРА)
    conn.execute(
        "CREATE TABLE IF NOT EXISTS ai_extractions (id INTEGER PRIMARY KEY AUTOINCREMENT, text_hash VARCHAR(64) NOT NULL, "
        "model_version VARCHAR(200) NOT NULL, prompt_version VARCHAR(100) NOT NULL, response TEXT NOT NULL, "
        "tokens_in INTEGER DEFAULT 0, tokens_out INTEGER DEFAULT 0, duration_ms INTEGER DEFAULT 0, "
        "skills_count INTEGER DEFAULT 0, rejected_count INTEGER DEFAULT 0, run_tag VARCHAR(40), created_at DATETIME NOT NULL, "
        "UNIQUE (text_hash, model_version, prompt_version))"
    )

    версия = кандидат.версия(модели.версия_рантайма())
    тексты = {str(в["id"]): вход(в["name"], в["описание"]) for в in вакансии}
    сырые = {ид: кэш.найти(conn, текст, версия, ВЕРСИЯ_ПРОМПТА) for ид, текст in тексты.items()}
    ждут = [ид for ид, сырой in сырые.items() if сырой is None]
    # Время ответов, уже лежащих в кэше: пересчёт без вызовов модели
    # иначе терял бы скорость, которая в нём измерена.
    из_кэша_мс = [
        строка[0] for строка in conn.execute(
            "SELECT duration_ms FROM ai_extractions WHERE model_version = ? AND prompt_version = ? AND duration_ms > 0",
            (версия, ВЕРСИЯ_ПРОМПТА),
        )
    ] if len(ждут) < len(сырые) else []

    сводка = {"вызовов": 0, "из_кэша": len(сырые) - len(ждут), "отказов": 0, "сломанных": 0, "отброшено_цитат": 0,
              "мс": list(из_кэша_мс), "токенов_вход": 0, "токенов_выход": 0, "секунд_всего": 0.0}

    if ждут:
        import time

        инструкция = промпт()
        with модели.сервер(кандидат, потоков=потоков) as модель:
            начало = time.monotonic()

            def вызвать(ид):
                try:
                    return ид, модель.ответить(инструкция, тексты[ид], СХЕМА_ОТВЕТА, ГРАММАТИКА)
                except МодельНедоступна as e:
                    return ид, e

            with ThreadPoolExecutor(max_workers=потоков) as пул:
                for номер, (ид, ответ) in enumerate(пул.map(вызвать, ждут), 1):
                    if isinstance(ответ, Exception):
                        сводка["отказов"] += 1
                        print(f"  [{номер}/{len(ждут)}] отказ: {ответ}", flush=True)
                        continue
                    сырые[ид] = ответ.текст
                    сводка["вызовов"] += 1
                    сводка["мс"].append(ответ.мс)
                    сводка["токенов_вход"] += ответ.токенов_вход
                    сводка["токенов_выход"] += ответ.токенов_выход
                    кэш.записать(conn, тексты[ид], версия, ВЕРСИЯ_ПРОМПТА, ответ.текст, токенов_вход=ответ.токенов_вход,
                                 токенов_выход=ответ.токенов_выход, мс=ответ.мс, прогон="замер")
                    conn.commit()
                    if номер % 10 == 0:
                        print(f"  [{номер}/{len(ждут)}] {ответ.мс} мс", flush=True)
            сводка["секунд_всего"] = round(time.monotonic() - начало, 1)

    найдено = {}
    по_описаниям = {str(в["id"]): в["описание"] for в in вакансии}
    for ид, сырой in сырые.items():
        if сырой is None:
            найдено[ид] = set()
            continue
        try:
            ответ, отброшены = из_сырого(сырой, по_описаниям[ид], версия, ВЕРСИЯ_ПРОМПТА)
        except ОтветСломан:
            сводка["сломанных"] += 1
            найдено[ид] = set()
            continue
        сводка["отброшено_цитат"] += len(отброшены)
        принятые = достойные(ответ.навыки) if отбор else ответ.навыки
        сводка["недоверено"] = сводка.get("недоверено", 0) + len(ответ.навыки) - len(принятые)
        найдено[ид] = {_канон(н.название, таблица) for н in принятые if н.уверенность >= уверенность}
    conn.close()
    return найдено, сводка, f"{версия}|{ВЕРСИЯ_ПРОМПТА}"


def замер_по_эталону(путь: Path, подробно: bool, режим: str = "словарь", имя_модели: str = "",
                     потоков: int = 1, предел: int = 0, сохранить: bool = False,
                     каждую: int = 1, уверенность: float = 0.0, отбор: bool = True) -> int:
    """Полнота и точность по вакансиям, размеченным руками."""
    if not путь.exists():
        print(f"Эталон не найден: {путь}")
        return 1

    from src import skills_store

    эталон = json.loads(путь.read_text(encoding="utf-8"))
    # Каждая N-я вакансия, а не первые N: набор сложен по рынкам, и
    # первые пятьдесят — это один рынок, а не срез всех десяти.
    вакансии = эталон["вакансии"][::max(1, каждую)]
    вакансии = вакансии[:предел] if предел else вакансии
    словари = SkillDictionaries.from_config()
    все = list(словари.hard) + list(словари.soft) + list(словари.tools)
    таблица = skills_store.таблица_синонимов()

    от_модели, сводка, версия = {}, None, ""
    if режим in ("модель", "вместе"):
        from src.ai import модели

        имя_модели = имя_модели or модели.выбранный().имя
        от_модели, сводка, версия = навыки_модели(вакансии, имя_модели, потоков, уверенность, отбор)

    должно = нашли = лишних = 0
    пропуски, лишнее = Counter(), Counter()
    по_рынкам = {}

    for вакансия in вакансии:
        размечено = {_канон(н, таблица) for н in вакансия["навыки"]}
        найдено = set()
        if режим in ("словарь", "вместе"):
            текст = РАЗМЕТКА.sub(" ", текст_для_навыков(вакансия["описание"])).lower()
            найдено |= {_канон(н, таблица) for н in find_skills(текст, все, привести(текст))}
        if режим in ("модель", "вместе"):
            найдено |= от_модели.get(str(вакансия["id"]), set())

        # Навыки работодателя система берёт как есть, без поиска: в
        # замере они учитываются так же, иначе он мерил бы не то, что
        # видит человек на экране.
        найдено |= {_канон(н, таблица) for н in вакансия.get("key_skills") or []}

        совпало = размечено & найдено
        должно += len(размечено)
        нашли += len(совпало)
        лишних += len(найдено - размечено)

        for н in размечено - найдено:
            пропуски[н] += 1
        for н in найдено - размечено:
            лишнее[н] += 1

        рынок = вакансия.get("рынок", "прочее")
        было = по_рынкам.setdefault(рынок, [0, 0])
        было[0] += len(размечено)
        было[1] += len(совпало)

    полнота = нашли / должно * 100 if должно else 0.0
    точность = нашли / (нашли + лишних) * 100 if (нашли + лишних) else 0.0

    print(f"Режим: {режим}" + (f" · {версия}" if версия else "")
          + (f" · уверенность от {уверенность:g}" if уверенность else "")
          + ("" if отбор or режим == "словарь" else " · без правила доверия"))
    print(f"Эталон: {len(вакансии)} вакансий, {должно} размеченных навыков")
    print(f"Найдено из размеченных: {нашли}")
    print(f"Найдено сверх разметки: {лишних}")
    print(f"\nПОЛНОТА:  {полнота:.1f} %")
    print(f"ТОЧНОСТЬ: {точность:.1f} %")

    print("\nПо рынкам:")
    for рынок, (всего, найдено_тут) in sorted(по_рынкам.items()):
        доля = найдено_тут / всего * 100 if всего else 0
        print(f"  {рынок:<16} {найдено_тут:>3} из {всего:<3} ({доля:.0f} %)")

    сколько = None if подробно else 15
    print("\nНе найдено:")
    for навык, счёт in пропуски.most_common(сколько):
        print(f"  {счёт:>3} × {навык}")

    print("\nНайдено сверх разметки (это либо ошибка, либо пробел разметки):")
    for навык, счёт in лишнее.most_common(сколько):
        print(f"  {счёт:>3} × {навык}")

    if сводка:
        мс = sorted(сводка["мс"])
        print(f"\nМодель: вызовов {сводка['вызовов']}, из кэша {сводка['из_кэша']}, отказов {сводка['отказов']}, "
              f"сломанных ответов {сводка['сломанных']}, навыков с цитатой не из текста {сводка['отброшено_цитат']}, "
              f"не прошло правило доверия {сводка.get('недоверено', 0)}")
        if мс:
            в_час = round(3600 / (мс[len(мс) // 2] / 1000))
            print(f"Время ответа: медиана {мс[len(мс) // 2] / 1000:.1f} с, наибольшее {мс[-1] / 1000:.1f} с; "
                  f"пропускная способность {в_час} вакансий в час в {потоков} потока")
            print(f"Токенов: вход {сводка['токенов_вход']}, выход {сводка['токенов_выход']}")

    if сохранить:
        from datetime import date

        записи = json.loads(ФАЙЛ_ЗАМЕРА.read_text(encoding="utf-8")) if ФАЙЛ_ЗАМЕРА.exists() else {"замеры": {}}
        отпечаток = None
        if режим != "словарь":
            from src.ai.извлечение import отпечаток_промпта

            отпечаток = отпечаток_промпта()
        мс = sorted((сводка or {}).get("мс") or [])
        ключ = режим if режим == "словарь" else f"{режим}|{версия}|{уверенность:g}|{'отбор' if отбор else 'всё'}"
        записи["замеры"][ключ] = {
            "режим": режим, "версия": версия, "когда": date.today().isoformat(), "уверенность_от": уверенность,
            "отпечаток_промпта": отпечаток,
            "вакансий": len(вакансии), "размечено": должно,
            "полнота": round(полнота, 1), "точность": round(точность, 1),
            "секунд_на_вакансию": round(мс[len(мс) // 2] / 1000, 1) if мс else None,
            # По медиане времени ответа: она есть и у замера,
            # пересчитанного из кэша, а прогон идёт в один поток.
            "вакансий_в_час": round(3600 / (мс[len(мс) // 2] / 1000)) if мс else None,
            "потоков": потоков if сводка else None,
            "сломанных": (сводка or {}).get("сломанных"), "отброшено_цитат": (сводка or {}).get("отброшено_цитат"),
            "по_рынкам": {рынок: round(найдено_тут / всего * 100) if всего else 0
                          for рынок, (всего, найдено_тут) in sorted(по_рынкам.items())},
        }
        ФАЙЛ_ЗАМЕРА.write_text(json.dumps(записи, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"\nЗамер записан: {ФАЙЛ_ЗАМЕРА}")

    if len(эталон["вакансии"]) < эталон.get("объём_план", 0):
        print(f"\nНабор пока меньше запланированного: "
              f"{len(эталон['вакансии'])} из {эталон['объём_план']}. "
              "Числа выше — ориентир, а не приговор.")
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(description="Замер извлечения навыков")
    разбор.add_argument("--raw", default="data/raw")
    разбор.add_argument("--вакансий", type=int, default=600)
    разбор.add_argument("--подробно", action="store_true")
    разбор.add_argument("--эталон", action="store_true",
                        help="считать по размеченному набору, с точностью")
    разбор.add_argument("--файл-эталона", default="tests/fixtures/эталон_навыков.json")
    разбор.add_argument("--режим", choices=РЕЖИМЫ, default="словарь", help="чем извлекать: словарь, модель или вместе")
    разбор.add_argument("--модель", default="", help="кандидат из src/ai/модели.py (по умолчанию — выбранный)")
    разбор.add_argument("--потоков", type=int, default=1, help="сколько вакансий модель разбирает одновременно")
    разбор.add_argument("--каждую", type=int, default=1, help="взять каждую N-ю вакансию эталона — срез по всем рынкам")
    разбор.add_argument("--уверенность", type=float, default=0.0, help="учитывать навыки модели с уверенностью не ниже этой")
    разбор.add_argument("--первых", type=int, default=0, help="взять только первые N вакансий эталона")
    разбор.add_argument("--сохранить", action="store_true", help="записать числа в data/замер_навыков.json")
    разбор.add_argument("--без-отбора", action="store_true", help="взять у модели всё, без правила доверия по виду навыка")
    аргументы = разбор.parse_args()

    if аргументы.эталон:
        return замер_по_эталону(
            Path(аргументы.файл_эталона), аргументы.подробно, аргументы.режим, аргументы.модель,
            аргументы.потоков, аргументы.первых, аргументы.сохранить, аргументы.каждую, аргументы.уверенность,
            not аргументы.без_отбора,
        )

    папка = Path(аргументы.raw)
    if not папка.exists():
        print(f"Папка сборов не найдена: {папка}")
        return 1

    словари = SkillDictionaries.from_config()
    все = list(словари.hard) + list(словари.soft) + list(словари.tools)

    пары = пары_для_замера(папка, аргументы.вакансий)
    если_нет = 0
    должно, нашли = 0, 0
    пропуски = Counter()

    for _, описание, эталон in пары:
        текст = РАЗМЕТКА.sub(" ", текст_для_навыков(описание)).lower()
        полный = РАЗМЕТКА.sub(" ", описание).lower()
        найденные = {н.lower() for н in find_skills(текст, все, привести(текст))}

        для_этой = 0
        for навык in эталон:
            # Эталон — только то, что буквально есть в тексте: чего в
            # тексте нет, поиск по тексту найти и не мог.
            if not стоит_в_тексте(навык, полный):
                continue
            должно += 1
            для_этой += 1
            if навык.lower() in найденные:
                нашли += 1
            else:
                пропуски[навык] += 1
        если_нет += 1 if для_этой == 0 else 0

    полнота = нашли / должно * 100 if должно else 0.0

    print(f"Вакансий в замере: {len(пары)}")
    print(f"Навыков, которые обязаны найтись: {должно}")
    print(f"Найдено: {нашли}")
    print(f"ПОЛНОТА: {полнота:.1f} %")

    сколько = len(пропуски) if аргументы.подробно else 20
    print(f"\nЧаще всего пропускается:")
    for навык, счёт in пропуски.most_common(сколько):
        print(f"  {счёт:>4} × {навык}")

    return 0


