"""
Полнота и точность извлечения навыков.

Зачем. Любая правка словаря или правил меняет числа на экранах, и без
замера «стало лучше» недоказуемо: «Подарки» тоже прибавляют полноту.

Замер идёт в двух режимах, и они отвечают на разные вопросы.

**Черновой** (по умолчанию): навыки, которые работодатель назвал в
`key_skills` и которые буквально присутствуют в тексте описания. Такие
мы обязаны находить — это нижняя граница полноты, посчитанная на
сотнях вакансий бесплатно. Точность по нему не считается: навыки,
которых нет в `key_skills`, эталоном не покрыты, и найденное сверх него
не обязательно ошибка.

**Эталонный** (`--эталон`): вакансии, прочитанные и размеченные руками,
`tests/fixtures/эталон_навыков.json`. Здесь считаются обе метрики —
полнота и точность, — потому что размечено всё, что есть в тексте, и
найденное сверх разметки действительно лишнее.

Одна метрика без другой ничего не значит: «Подарки» тоже прибавляют
полноту.

Запуск:
    python scripts/maintenance/замер_извлечения.py
    python scripts/maintenance/замер_извлечения.py --вакансий 800
    python scripts/maintenance/замер_извлечения.py --эталон
    python scripts/maintenance/замер_извлечения.py --эталон --подробно
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.normalize import SkillDictionaries, find_skills  # noqa: E402
from src.morphology import привести  # noqa: E402
from src.sections import текст_для_навыков  # noqa: E402

РАЗМЕТКА = re.compile(r"<[^>]+>")


def стоит_в_тексте(навык: str, текст: str) -> bool:
    """Навык присутствует как отдельное слово, а не как часть чужого.

    Без этого эталон завышается и цель становится неверной: «Git»
    считался бы обязательным к находке в тексте, где есть только
    «github.com» и «gitlab», а «R» — в каждом слове с этой буквой.
    Требовать от поиска находить такое нельзя — он и не должен.
    """
    шаблон = r"(?<![\w#+.])" + re.escape(навык.lower()) + r"(?![\w#+])"
    return re.search(шаблон, текст) is not None


def пары_для_замера(папка: Path, предел: int):
    """Вакансии, где есть и описание, и названные работодателем навыки."""
    пары = []
    for файл in sorted(папка.glob("*.json")):
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(данные, dict):
            данные = данные.get("vacancies") or данные.get("items") or []
        for вакансия in данные:
            if not isinstance(вакансия, dict):
                continue
            описание = вакансия.get("description") or ""
            навыки = [
                (s.get("name") or "").strip()
                for s in (вакансия.get("key_skills") or [])
                if (s.get("name") or "").strip()
            ]
            if описание and навыки:
                пары.append((вакансия, описание, навыки))
            if len(пары) >= предел:
                return пары
    return пары


def замер_по_эталону(путь: Path, подробно: bool) -> int:
    """Полнота и точность по вакансиям, размеченным руками."""
    if not путь.exists():
        print(f"Эталон не найден: {путь}")
        return 1

    эталон = json.loads(путь.read_text(encoding="utf-8"))
    словари = SkillDictionaries.from_config()
    все = list(словари.hard) + list(словари.soft) + list(словари.tools)

    должно = нашли = лишних = 0
    пропуски, лишнее = Counter(), Counter()
    по_рынкам = {}

    for вакансия in эталон["вакансии"]:
        размечено = {н.lower() for н in вакансия["навыки"]}
        текст = РАЗМЕТКА.sub(" ", текст_для_навыков(вакансия["описание"])).lower()
        найдено = {н.lower() for н in find_skills(текст, все, привести(текст))}

        # Навыки работодателя система берёт как есть, без поиска: в
        # замере они учитываются так же, иначе он мерил бы не то, что
        # видит человек на экране.
        найдено |= {н.lower() for н in вакансия.get("key_skills") or []}

        совпало = размечено & найдено
        должно += len(размечено)
        нашли += len(совпало)
        лишних += len(найдено - размечено)

        for н in размечено - найдено:
            пропуски[н] += 1
        for н in найдено - размечено:
            лишнее[н] += 1

        рынок = вакансия.get("рынок", "прочее")
        было = по_рынкам.setdefault(рынок, [0, 0])
        было[0] += len(размечено)
        было[1] += len(совпало)

    полнота = нашли / должно * 100 if должно else 0.0
    точность = нашли / (нашли + лишних) * 100 if (нашли + лишних) else 0.0

    print(f"Эталон: {len(эталон['вакансии'])} вакансий, {должно} размеченных навыков")
    print(f"Найдено из размеченных: {нашли}")
    print(f"Найдено сверх разметки: {лишних}")
    print(f"\nПОЛНОТА:  {полнота:.1f} %")
    print(f"ТОЧНОСТЬ: {точность:.1f} %")

    print("\nПо рынкам:")
    for рынок, (всего, найдено_тут) in sorted(по_рынкам.items()):
        доля = найдено_тут / всего * 100 if всего else 0
        print(f"  {рынок:<16} {найдено_тут:>3} из {всего:<3} ({доля:.0f} %)")

    сколько = None if подробно else 15
    print("\nНе найдено:")
    for навык, счёт in пропуски.most_common(сколько):
        print(f"  {счёт:>3} × {навык}")

    print("\nНайдено сверх разметки (это либо ошибка, либо пробел разметки):")
    for навык, счёт in лишнее.most_common(сколько):
        print(f"  {счёт:>3} × {навык}")

    if len(эталон["вакансии"]) < эталон.get("объём_план", 0):
        print(f"\nНабор пока меньше запланированного: "
              f"{len(эталон['вакансии'])} из {эталон['объём_план']}. "
              "Числа выше — ориентир, а не приговор.")
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(description="Замер извлечения навыков")
    разбор.add_argument("--raw", default="data/raw")
    разбор.add_argument("--вакансий", type=int, default=600)
    разбор.add_argument("--подробно", action="store_true")
    разбор.add_argument("--эталон", action="store_true",
                        help="считать по размеченному набору, с точностью")
    разбор.add_argument("--файл-эталона", default="tests/fixtures/эталон_навыков.json")
    аргументы = разбор.parse_args()

    if аргументы.эталон:
        return замер_по_эталону(Path(аргументы.файл_эталона), аргументы.подробно)

    папка = Path(аргументы.raw)
    if not папка.exists():
        print(f"Папка сборов не найдена: {папка}")
        return 1

    словари = SkillDictionaries.from_config()
    все = list(словари.hard) + list(словари.soft) + list(словари.tools)

    пары = пары_для_замера(папка, аргументы.вакансий)
    если_нет = 0
    должно, нашли = 0, 0
    пропуски = Counter()

    for _, описание, эталон in пары:
        текст = РАЗМЕТКА.sub(" ", текст_для_навыков(описание)).lower()
        полный = РАЗМЕТКА.sub(" ", описание).lower()
        найденные = {н.lower() for н in find_skills(текст, все, привести(текст))}

        для_этой = 0
        for навык in эталон:
            # Эталон — только то, что буквально есть в тексте: чего в
            # тексте нет, поиск по тексту найти и не мог.
            if not стоит_в_тексте(навык, полный):
                continue
            должно += 1
            для_этой += 1
            if навык.lower() in найденные:
                нашли += 1
            else:
                пропуски[навык] += 1
        если_нет += 1 if для_этой == 0 else 0

    полнота = нашли / должно * 100 if должно else 0.0

    print(f"Вакансий в замере: {len(пары)}")
    print(f"Навыков, которые обязаны найтись: {должно}")
    print(f"Найдено: {нашли}")
    print(f"ПОЛНОТА: {полнота:.1f} %")

    сколько = len(пропуски) if аргументы.подробно else 20
    print(f"\nЧаще всего пропускается:")
    for навык, счёт in пропуски.most_common(сколько):
        print(f"  {счёт:>4} × {навык}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
