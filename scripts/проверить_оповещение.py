"""
Проверить, что оповещение об отказе дойдёт.

Зачем. Узнать, что канал не работает, в момент настоящего отказа —
значит не узнать об отказе вовсе. Эта команда шлёт пробное сообщение
тем же путём, что и сбор, и печатает исход по каждому каналу: дошло,
не настроен или отказал — и почему.

Запуск:
    python scripts/проверить_оповещение.py
    python scripts/проверить_оповещение.py --журнал     # последние оповещения
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.alerts import Отказ, последние, сообщить, файл_оповещений  # noqa: E402
from src.journal import текущий_файл  # noqa: E402

КАК_НАСТРОИТЬ_TELEGRAM = """
Как включить Telegram:
  1. В Telegram напишите @BotFather, команда /newbot — он выдаст токен бота.
  2. Напишите своему новому боту любое сообщение.
  3. Откройте в браузере https://api.telegram.org/bot<ТОКЕН>/getUpdates
     и найдите в ответе "chat":{"id": ЧИСЛО} — это идентификатор чата.
  4. Добавьте в файл .env две строки:
       TELEGRAM_BOT_TOKEN=<ТОКЕН>
       TELEGRAM_CHAT_ID=<ЧИСЛО>
  5. Запустите эту команду ещё раз и перезапустите приложение.
"""


def показать_журнал() -> int:
    записи = последние(10)
    if not записи:
        print(f"Оповещений ещё не было. Журнал: {файл_оповещений()}")
        return 0
    for запись in записи:
        событие = запись["событие"]
        исход = "доставлено" if запись["доставлено"] else "НЕ доставлено"
        print(f"{событие['когда'].replace('T', ' ')} · {событие['заголовок']} · {исход}")
        for канал, итог in запись["каналы"].items():
            if not итог.get("доставлено"):
                print(f"    {канал}: {итог.get('почему', 'причина неизвестна')}")
    return 0


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверить, что оповещение об отказе дойдёт")
    разбор.add_argument("--журнал", action="store_true", help="показать последние оповещения и их исход")
    аргументы = разбор.parse_args()

    if аргументы.журнал:
        return показать_журнал()

    запись = сообщить(
        Отказ(проба=True),
        журнал=файл_оповещений(),
    )

    print()
    не_настроено = False
    for канал, итог in запись["каналы"].items():
        if итог.get("доставлено"):
            print(f"  {канал}: доставлено — проверьте сообщение")
        elif not итог.get("настроен", True):
            не_настроено = True
            print(f"  {канал}: не настроен — {итог.get('почему')}")
        else:
            print(f"  {канал}: НЕ доставлено — {итог.get('почему')}")

    print(f"\nЖурнал оповещений: {файл_оповещений()}")
    print(f"Журнал работы:     {текущий_файл() or 'не подключён'}")
    if не_настроено:
        print(КАК_НАСТРОИТЬ_TELEGRAM)
    # Код выхода — для расписания и сценариев: ноль только когда дошло.
    return 0 if запись["доставлено"] else 1


if __name__ == "__main__":
    sys.exit(main())
