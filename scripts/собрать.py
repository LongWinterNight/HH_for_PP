"""
Сбор вакансий без экрана — тем же путём и по тем же запросам, что с него.

Зачем. Сбор запускался только руками, и история копилась, когда о нём
вспоминали. Эта команда — то, что запускает планировщик: берёт запросы,
почту и паузу из настроек экрана «Сбор данных», проводит сбор, пишет его
в историю и завершается кодом, по которому виден исход.

Сбор всегда дописывает к базе и никогда её не перезаписывает: запуск,
который никто не видит, не должен уметь стереть собранное. Перед сбором
снимается копия базы.

Запуск:
    python scripts/собрать.py
    python scripts/собрать.py --проверить     # что будет собрано, без сбора

Коды выхода:
    0 — сбор прошёл
    1 — сбор не удался (об этом уже сообщено)
    2 — собирать нечем: нет запросов или почты
    3 — сбор уже идёт
    4 — сбор остановлен человеком
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

УСПЕХ, ОТКАЗ, НЕ_НАСТРОЕНО, ЗАНЯТО, ОСТАНОВЛЕН = 0, 1, 2, 3, 4


def main(аргументы: list | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Сбор вакансий без экрана")
    разбор.add_argument("--проверить", action="store_true", help="показать, что будет собрано, и выйти")
    разбор.add_argument("--страниц", type=int, default=None, help="страниц выдачи на запрос (по умолчанию из настроек)")
    разбор.add_argument("--дней", type=int, default=None, help="глубина поиска в днях (по умолчанию из настроек)")
    разбор.add_argument("--без-копии", action="store_true", help="не снимать копию базы перед сбором")
    разбор.add_argument("--ждать", type=float, default=20, help="сколько минут ждать недоступный источник (по умолчанию 20)")
    параметры = разбор.parse_args(аргументы)

    from src import collection_run, schedule
    from src.alerts import Отказ, сообщить
    from src.config import settings
    from src.storage import VacancyStorage
    from src.utils import get_logger

    logger = get_logger("сбор_по_расписанию")

    storage = VacancyStorage()
    try:
        настройки = storage.get_collection_settings()
        запросы = [запрос for запрос in (настройки.get("search_queries") or []) if запрос and запрос.strip()]
        почта = (настройки.get("email") or "").strip()

        if not запросы or not почта:
            чего_нет = "запросов" if not запросы else "почты для hh.ru"
            logger.error(f"Сбор по расписанию не начат: в настройках нет {чего_нет}")
            if not параметры.проверить:
                # Расписание стоит, а собирать нечем — это отказ, и
                # самый тихий: каждую ночь задание будет честно
                # завершаться, ничего не собрав.
                сообщить(Отказ(
                    причина="no_queries" if not запросы else "no_email",
                    подробности=f"сбор по расписанию: в настройках нет {чего_нет}",
                    запросы=запросы,
                ))
            print(f"Собирать нечем: на экране «Сбор данных» нет {чего_нет}.")
            return НЕ_НАСТРОЕНО

        страниц = параметры.страниц or settings.max_pages
        дней = параметры.дней or settings.days_back

        if параметры.проверить:
            print(f"Запросы ({len(запросы)}): {', '.join(запросы)}")
            print(f"Страниц на запрос: {страниц}, глубина: {дней} дн., пауза: {настройки['request_delay']} с")
            print("Сбор дописывает к базе. Проверка: сбор не запущен.")
            return УСПЕХ

        другой = collection_run.идёт_другой_сбор(storage)
        if другой:
            # Не отказ: человек собирает руками в то же время.
            logger.warning(f"Сбор по расписанию пропущен: уже идёт сбор №{другой['id']}")
            print(f"Сбор уже идёт (№{другой['id']}) — этот запуск пропущен.")
            return ЗАНЯТО
    finally:
        storage.close()

    # Сбор догоняет пропущенный запуск сразу после включения компьютера,
    # когда сеть или прокси ещё не поднялись. Переждать дешевле, чем
    # потерять день; отказ по ключу или почте ждать бессмысленно.
    from src.api_client import HHAPIClient

    проверка = collection_run.дождаться_источника(
        HHAPIClient(email=почта, delay=настройки["request_delay"]),
        ждать_минут=параметры.ждать,
    )
    if not проверка["доступно"]:
        logger.error(f"Сбор по расписанию не начат: {проверка['причина']} — {проверка['подробности']}")
        # Попытка записывается в историю: «сбора не было» и «сбор не
        # смог начаться» — разные вещи, и вторую видно только так.
        storage = VacancyStorage()
        try:
            запуск = storage.create_parser_run(
                запросы, max_pages=страниц, days_back=дней, is_incremental=True, use_cache=True,
                source=collection_run.РАСПИСАНИЕ,
            )
            storage.complete_parser_run(
                запуск, status=collection_run.ОТКАЗ,
                error_message=проверка["подробности"], error_type=проверка["причина"],
            )
        finally:
            storage.close()
        сообщить(Отказ(
            причина=проверка["причина"], подробности=проверка["подробности"], запуск=запуск, запросы=запросы,
        ))
        print(f"Сбор №{запуск} не начат: источник недоступен ({проверка['причина']}).")
        return ОТКАЗ

    if not параметры.без_копии:
        try:
            копия = schedule.копия_базы(settings.db_path)
            if копия:
                logger.info(f"Копия базы перед сбором: {копия.name}")
        except Exception:
            # Копия — страховка, а не условие: сбор дописывает к базе, и
            # отказываться от него из-за нехватки места незачем. Но
            # сказать об этом нужно.
            logger.exception("Копия базы перед сбором не снята")

    исход = collection_run.провести(
        запросы,
        email=почта,
        пауза=настройки["request_delay"],
        max_pages=страниц,
        days_back=дней,
        # Только дописывание: сбор, который никто не видит, не должен
        # уметь перезаписать базу.
        incremental=True,
        use_cache=True,
        глубоко=settings.резать_упёршиеся,
        источник=collection_run.РАСПИСАНИЕ,
    )

    if исход.статус == collection_run.ЗАВЕРШЁН:
        logger.info(
            f"Сбор по расписанию №{исход.запуск} прошёл: собрано {исход.собрано}, "
            f"новых {исход.новых}, обновлено {исход.обновлено}"
        )
        print(f"Сбор №{исход.запуск}: собрано {исход.собрано}, новых {исход.новых}, обновлено {исход.обновлено}.")
        return УСПЕХ
    if исход.статус == collection_run.ОСТАНОВЛЕН:
        logger.warning(f"Сбор по расписанию №{исход.запуск} остановлен человеком")
        print(f"Сбор №{исход.запуск} остановлен.")
        return ОСТАНОВЛЕН

    print(f"Сбор №{исход.запуск} не удался: {исход.причина}. Подробности — в журнале.")
    return ОТКАЗ


if __name__ == "__main__":
    sys.exit(main())
