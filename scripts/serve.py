"""
Запуск сервера с перезагрузкой, которая ждёт, пока он освободится.

Зачем не `uvicorn --reload`. Сбор данных идёт фоновым потоком внутри
процесса сервера и живёт десятки минут. Обычная перезагрузка убивает
процесс при первой же правке файла — вместе со сбором: запись пометится
`interrupted`, а час работы источника пропадёт. Вторая беда тише, но
случается чаще: перезапуск в тот момент, когда кто-то смотрит на
страницу, даёт ему ошибку сети на ровном месте.

Что делает этот надзор. Следит за исходниками; заметив правку, не
перезапускает сразу, а ждёт, пока сервер освободится: закончится сбор и
пройдёт несколько секунд без запросов. Занятость спрашивается у самого
сервера (`/api/health/idle`) — если он не отвечает, значит перезапускать
нечего и можно поднимать сразу.

Запуск:
    python scripts/serve.py
    python scripts/serve.py --порт 8001 --тишина 10
"""

from __future__ import annotations

import argparse
import json
import os
import signal
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

from watchfiles import watch

КОРЕНЬ = Path(__file__).resolve().parents[1]

# За чем следим. Фронт собирается своим сборщиком и к серверу отношения
# не имеет; база, отчёты и логи меняются во время работы постоянно — от
# записи в базу сервер перезапускаться не должен.
ЗА_ЧЕМ_СЛЕДИМ = [КОРЕНЬ / "src", КОРЕНЬ / "web", КОРЕНЬ / "main.py"]

# Сколько ждать тишины, прежде чем перезапускать. Пять секунд — это
# заметно больше паузы между кликами и заметно меньше, чем терпение
# разработчика, ждущего свою правку.
ТИШИНА_ПО_УМОЛЧАНИЮ = 5.0

# Как часто переспрашивать сервер, освободился ли он.
ШАГ_ОЖИДАНИЯ = 2.0

# Сколько ждать, пока сервер закончит начатое и погаснет сам.
СРОК_МЯГКОЙ_ОСТАНОВКИ = 10.0

# Как часто напоминать в логе, чего мы ждём. Без напоминания долгое
# ожидание сбора неотличимо от зависшего надзора.
ШАГ_НАПОМИНАНИЯ = 30.0


def это_исходник(путь: str) -> bool:
    """Правка кода, а не данных.

    Кэш байт-кода отсеиваем отдельно: он меняется при каждом запуске и
    вызвал бы перезапуск сам от себя.
    """
    return путь.endswith(".py") and "__pycache__" not in путь


def сказать(текст: str) -> None:
    print(f"[надзор {time.strftime('%H:%M:%S')}] {текст}", flush=True)


class Сервер:
    """Дочерний процесс uvicorn: запуск, мягкая остановка, перезапуск."""

    def __init__(self, хост: str, порт: int) -> None:
        self.хост = хост
        self.порт = порт
        self.процесс: subprocess.Popen | None = None

    def запустить(self) -> None:
        команда = [
            sys.executable, "-m", "uvicorn", "web.app.main:app",
            "--host", self.хост, "--port", str(self.порт),
        ]
        # Своя группа процессов нужна, чтобы сигнал остановки достался
        # серверу, а не прилетел заодно и надзору.
        флаги = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
        self.процесс = subprocess.Popen(команда, cwd=КОРЕНЬ, creationflags=флаги)
        сказать(f"сервер поднят на {self.хост}:{self.порт} (pid {self.процесс.pid})")

    def остановить(self) -> None:
        """
        Мягко: дать серверу доработать начатое.

        Сначала сигнал завершения — uvicorn закрывает приём новых
        соединений и дорабатывает текущие запросы. Жёсткое добивание
        только по сроку: процесс, оставшийся висеть, займёт порт, и
        следующий запуск упадёт.
        """
        if not self.процесс or self.процесс.poll() is not None:
            return

        сигнал = signal.CTRL_BREAK_EVENT if os.name == "nt" else signal.SIGTERM
        try:
            self.процесс.send_signal(сигнал)
        except (OSError, ValueError):
            pass

        try:
            self.процесс.wait(timeout=СРОК_МЯГКОЙ_ОСТАНОВКИ)
            сказать("сервер остановлен")
        except subprocess.TimeoutExpired:
            сказать(f"сервер не погас за {СРОК_МЯГКОЙ_ОСТАНОВКИ:.0f} с — останавливаю жёстко")
            self.процесс.kill()
            self.процесс.wait(timeout=5)

    def перезапустить(self) -> None:
        self.остановить()
        self.запустить()

    def жив(self) -> bool:
        return bool(self.процесс) and self.процесс.poll() is None


def занятость(порт: int) -> dict | None:
    """
    Спросить у сервера, занят ли он.

    Возвращает None, если сервер не ответил: он либо ещё поднимается,
    либо уже упал — в обоих случаях беречь нечего.
    """
    адрес = f"http://127.0.0.1:{порт}/api/health/idle"
    try:
        with urllib.request.urlopen(адрес, timeout=3) as ответ:
            return json.loads(ответ.read().decode("utf-8"))
    except (urllib.error.URLError, OSError, ValueError, json.JSONDecodeError):
        return None


def дождаться_покоя(сервер: Сервер, тишина: float) -> None:
    """
    Ждать, пока сервер освободится.

    Два условия, и оба обязательны: сбор должен закончиться и запросы
    должны прекратиться. Ожидание не ограничено по времени намеренно —
    сбор длиной в час это нормальная работа, и обрывать его ради правки
    в коде нельзя. Чтобы ожидание не выглядело зависанием, каждые
    полминуты в логе появляется, чего мы ждём.
    """
    начало = time.monotonic()
    последнее_напоминание = 0.0

    while True:
        состояние = занятость(сервер.порт)

        # Сервер молчит: перезапускать нечего, поднимаем немедленно.
        if состояние is None:
            return

        если_ждём = None
        if состояние.get("сбор_идёт"):
            если_ждём = "идёт сбор данных"
        elif состояние.get("секунд_тишины", 0) < тишина:
            если_ждём = f"пользователь работает (тишина {состояние['секунд_тишины']:.0f} с из {тишина:.0f})"

        if если_ждём is None:
            прошло = time.monotonic() - начало
            if прошло > ШАГ_ОЖИДАНИЯ:
                сказать(f"сервер свободен, ждали {прошло:.0f} с")
            return

        сейчас = time.monotonic() - начало
        if сейчас - последнее_напоминание >= ШАГ_НАПОМИНАНИЯ or последнее_напоминание == 0.0:
            сказать(f"перезапуск отложен: {если_ждём}")
            последнее_напоминание = сейчас

        time.sleep(ШАГ_ОЖИДАНИЯ)


def main() -> int:
    разбор = argparse.ArgumentParser(description="Сервер с бережной перезагрузкой")
    разбор.add_argument("--хост", default="0.0.0.0")
    разбор.add_argument("--порт", type=int, default=8000)
    разбор.add_argument("--тишина", type=float, default=ТИШИНА_ПО_УМОЛЧАНИЮ,
                        help="секунд без запросов перед перезапуском")
    аргументы = разбор.parse_args()

    сервер = Сервер(аргументы.хост, аргументы.порт)
    сервер.запустить()
    сказать(f"слежу за правками: {', '.join(p.name for p in ЗА_ЧЕМ_СЛЕДИМ)}")

    сообщили_о_падении = False

    try:
        # Ожидание прерывается по сроку даже без правок: иначе падение
        # сервера осталось бы незамеченным до следующего изменения файла,
        # и надзор молча смотрел бы на мёртвый порт.
        поток = watch(
            *ЗА_ЧЕМ_СЛЕДИМ,
            watch_filter=lambda _, путь: это_исходник(путь),
            rust_timeout=2000,
            yield_on_timeout=True,
        )

        for изменения in поток:
            if not изменения:
                if not сервер.жив() and not сообщили_о_падении:
                    # Поднимать самим нельзя: если причина в ошибке кода,
                    # надзор уйдёт в бесконечный круг перезапусков.
                    сказать("сервер остановился сам — жду правку в коде")
                    сообщили_о_падении = True
                continue

            файлы = sorted({Path(путь).name for _, путь in изменения})
            сказать(f"правка: {', '.join(файлы[:3])}{' …' if len(файлы) > 3 else ''}")

            дождаться_покоя(сервер, аргументы.тишина)
            сервер.перезапустить()
            сообщили_о_падении = False
    except KeyboardInterrupt:
        сказать("остановка по Ctrl+C")
    finally:
        # Дочерний процесс, переживший надзор, займёт порт: следующий
        # запуск упадёт с «адрес уже используется».
        сервер.остановить()

    return 0


if __name__ == "__main__":
    sys.exit(main())
