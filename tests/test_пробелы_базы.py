"""
Пробелы базы и предложения запросов.

Предложение строится подсчётом по базе: что набралось попутно и ни
одним запросом не собирается. Проверяется, что общие слова и уже
собираемые профессии не предлагаются, что у предложения названо
основание, что сбор сам не начинается, а решение человека запоминается.
"""

from __future__ import annotations

import sqlite3

import pandas as pd
import pytest

from src import gaps
from src.config import settings

ЗАПРОСЫ = ["3dsmax", "Арт-директор"]


def _вакансии(название: str, сколько: int, запрос: str = "3dsmax", фирма: str = "Фирма", с: int = 0):
    return [
        {"vacancy_id": f"{название}-{с + i}", "vacancy_name": название, "employer_name": f"{фирма} {с + i}",
         "source_keyword": запрос}
        for i in range(сколько)
    ]


@pytest.fixture
def база():
    from src.storage import VacancyStorage

    строки = [
        # Одна профессия в трёх написаниях: число, ступень, уточнение.
        *_вакансии("Дизайнер интерьеров", 6),
        *_вакансии("Дизайнер интерьера", 4, с=10),
        *_вакансии("Ведущий дизайнер интерьеров (жилые комплексы)", 2, с=20),
        # Слишком общее слово: запрос «менеджер» принёс бы весь рынок.
        *_вакансии("Менеджер", 30, запрос="Арт-директор"),
        # Уже собирается своим запросом.
        *_вакансии("Арт-директор", 15, запрос="Арт-директор"),
        *_вакансии("3D-визуализатор 3dsmax", 12),
        # Много вакансий, но одна фирма — это её штат, а не рынок.
        *[{"vacancy_id": f"оператор-{i}", "vacancy_name": "Оператор станка", "employer_name": "Завод", "source_keyword": "3dsmax"}
          for i in range(14)],
        # Мало вакансий.
        *_вакансии("Ландшафтный архитектор", 3),
    ]
    хранилище = VacancyStorage(db_path=settings.db_path)
    хранилище.save_vacancies_incremental(pd.DataFrame(строки))
    хранилище.save_collection_settings(email="человек@example.com", request_delay=0.2, search_queries=ЗАПРОСЫ)
    хранилище.close()
    conn = sqlite3.connect(settings.db_path)
    yield conn
    conn.close()


class TestНазваниеПрофессии:

    @pytest.mark.parametrize("название, профессия", [
        ("Дизайнер интерьеров", "дизайнер интерьер"),
        ("Дизайнер интерьера", "дизайнер интерьер"),
        ("Ведущий дизайнер интерьеров (жилые комплексы)", "дизайнер интерьер"),
        ("HR-менеджер", "hr менеджер"),
        ("HR менеджер в Москве", "hr менеджер"),
        ("Senior AI Engineer / LLM", "ai engineer"),
        ("", ""),
    ])
    def test_написания_сводятся_к_одной_профессии(self, название, профессия):
        assert gaps.название_профессии(название) == профессия


class TestПробелы:

    def test_профессия_набравшаяся_попутно_предложена_с_основанием(self, база):
        профессии = gaps.найти(база, ЗАПРОСЫ)["профессии"]

        assert [п["ключ"] for п in профессии] == ["дизайнер интерьер"]
        пробел = профессии[0]
        assert (пробел["вакансий"], пробел["работодателей"]) == (12, 12), "три написания — одна профессия"
        assert пробел["запрос"] == "Дизайнер интерьеров", "запрос — как пишут чаще всего, без ступени и скобок"
        assert "12 активных вакансий у 12 работодателей" in пробел["основание"] and "«3dsmax»" in пробел["основание"]

    def test_общее_слово_не_предлагается(self, база):
        assert "менеджер" not in {п["ключ"] for п in gaps.найти(база, ЗАПРОСЫ)["профессии"]}

    def test_уже_собираемое_не_предлагается(self, база):
        ключи = {п["ключ"] for п in gaps.найти(база, ЗАПРОСЫ)["профессии"]}
        assert not {"арт директор", "3d визуализатор 3dsmax"} & ключи

    def test_штат_одной_фирмы_не_профессия_на_рынке(self, база):
        assert "оператор станок" not in {п["ключ"] for п in gaps.найти(база, ЗАПРОСЫ)["профессии"]}

    def test_запрос_с_малой_выборкой_назван(self, база):
        тонкие = gaps.найти(база, [*ЗАПРОСЫ, "рендер"])["тонкие_запросы"]
        assert тонкие == [{"запрос": "рендер", "вакансий": 0}]

    def test_снятые_и_найденные_не_по_запросу_не_считаются(self, база):
        база.execute("UPDATE vacancies SET is_active = 0 WHERE vacancy_name = 'Дизайнер интерьеров'")
        база.commit()
        assert gaps.найти(база, ЗАПРОСЫ)["профессии"] == [], "шесть вакансий — меньше порога"


class TestРешение:

    def test_предложение_сохраняется_и_повтор_его_не_плодит(self, база):
        первые = gaps.обновить(база, ЗАПРОСЫ)
        вторые = gaps.обновить(база, ЗАПРОСЫ)

        assert [п["ключ"] for п in первые] == [п["ключ"] for п in вторые] == ["дизайнер интерьер"]
        assert база.execute("SELECT COUNT(*) FROM query_suggestions").fetchone()[0] == 1

    def test_отклонённое_больше_не_предлагается(self, база):
        gaps.обновить(база, ЗАПРОСЫ)
        assert gaps.решить(база, "дизайнер интерьер", принять=False) == ""

        assert gaps.обновить(база, ЗАПРОСЫ) == []
        assert [п["ключ"] for п in gaps.предложения(база, статус=gaps.ОТКЛОНЕНО)] == ["дизайнер интерьер"]

    def test_принятое_возвращает_запрос_и_остаётся_в_истории(self, база):
        gaps.обновить(база, ЗАПРОСЫ)

        assert gaps.решить(база, "дизайнер интерьер", принять=True) == "Дизайнер интерьеров"
        принятые = gaps.предложения(база, статус=gaps.ПРИНЯТО)
        assert [п["запрос"] for п in принятые] == ["Дизайнер интерьеров"] and принятые[0]["решено"]

    def test_решить_дважды_нельзя(self, база):
        gaps.обновить(база, ЗАПРОСЫ)
        gaps.решить(база, "дизайнер интерьер", принять=True)
        assert gaps.решить(база, "дизайнер интерьер", принять=False) is None
        assert gaps.решить(база, "такого нет", принять=True) is None


class TestЭкран:

    def test_принятый_запрос_дописан_в_список_а_сбор_не_начат(self, база):
        import web.app.main as api
        from src.storage import VacancyStorage

        база.close()
        ответ = api.предложения_запросов()
        assert [п["запрос"] for п in ответ["предложения"]] == ["Дизайнер интерьеров"]

        решение = api.решить_предложение({"ключ": "дизайнер интерьер", "решение": "accept"})

        assert решение["search_queries"] == [*ЗАПРОСЫ, "Дизайнер интерьеров"]
        хранилище = VacancyStorage(db_path=settings.db_path)
        try:
            assert хранилище.get_collection_settings()["search_queries"] == [*ЗАПРОСЫ, "Дизайнер интерьеров"]
            assert хранилище.get_parser_runs_history() == [], "сбор сам не начинается"
        finally:
            хранилище.close()
        assert api.предложения_запросов()["предложения"] == [], "принятое больше не предлагается"

    def test_отклонение_список_запросов_не_меняет(self, база):
        import web.app.main as api

        база.close()
        api.предложения_запросов()
        решение = api.решить_предложение({"ключ": "дизайнер интерьер", "решение": "reject"})

        assert решение["принято"] is False and решение["search_queries"] == ЗАПРОСЫ

    @pytest.mark.parametrize("тело, код", [
        ({"ключ": "", "решение": "accept"}, 400),
        ({"ключ": "дизайнер интерьер", "решение": "собрать"}, 400),
        ({"ключ": "такого нет", "решение": "accept"}, 404),
    ])
    def test_негодное_решение_отказ(self, база, тело, код):
        from fastapi import HTTPException

        import web.app.main as api

        база.close()
        api.предложения_запросов()
        with pytest.raises(HTTPException) as отказ:
            api.решить_предложение(тело)
        assert отказ.value.status_code == код
