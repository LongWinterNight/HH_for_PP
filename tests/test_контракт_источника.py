"""
Контракт ответа источника (S6‑3a, S6‑3b).

Проверка идёт на настоящих ответах hh.ru, сохранённых в фикстурах, а не
на выдуманных словарях: смысл контракта в том, чтобы поймать смену
схемы источника, и проверять его на данных, которые мы же и придумали,
значило бы проверять собственную фантазию.

Отдельно проверяется, что контракт не придирается: у вакансии сотни
полей, и требовать их все — верный способ объявить нарушением обычную
работу.
"""

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.contract import (  # noqa: E402
    ПОЛЯ_ВАКАНСИИ,
    подозрительные_пропажи,
    проверить_вакансию,
    проверить_карточку,
    проверить_ответ_поиска,
    проверить_страницу,
)

ФИКСТУРЫ = Path(__file__).parent / "fixtures"


@pytest.fixture(scope="module")
def ответ_поиска():
    return json.loads((ФИКСТУРЫ / "ответ_поиска.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def ответ_карточки():
    return json.loads((ФИКСТУРЫ / "ответ_карточки.json").read_text(encoding="utf-8"))


class TestНастоящийОтвет:

    def test_ответ_поиска_выполняет_контракт(self, ответ_поиска):
        assert проверить_ответ_поиска(ответ_поиска) == []

    def test_вакансия_из_выдачи_выполняет_контракт(self, ответ_поиска):
        assert проверить_вакансию(ответ_поиска["items"][0]) == []

    def test_карточка_выполняет_контракт(self, ответ_карточки):
        assert проверить_карточку(ответ_карточки) == []

    def test_страница_целиком_не_нарушена(self, ответ_поиска):
        итог = проверить_страницу(ответ_поиска)

        assert итог["нарушен"] is False
        assert итог["ответ"] == []
        assert итог["вакансия"] == []

    def test_зарплата_на_месте_хотя_бы_в_одном_виде(self, ответ_поиска):
        # Источник перенёс зарплату из `salary` в `salary_range`.
        # Требовать оба поля — значит объявить нарушением норму.
        вакансия = ответ_поиска["items"][0]

        assert "salary/salary_range" not in подозрительные_пропажи(вакансия)


class TestСменаСхемы:

    def test_пропажа_обязательного_поля_ловится(self, ответ_поиска):
        испорченный = json.loads(json.dumps(ответ_поиска))
        del испорченный["items"][0]["published_at"]

        итог = проверить_страницу(испорченный)

        assert итог["нарушен"] is True
        assert "published_at" in итог["вакансия"]

    def test_пропажа_поля_ответа_ловится(self, ответ_поиска):
        испорченный = dict(ответ_поиска)
        del испорченный["found"]

        assert "found" in проверить_ответ_поиска(испорченный)

    def test_переезд_зарплаты_замечен(self, ответ_поиска):
        # Ровно то, что случилось на самом деле: зарплата уехала, а сбор
        # молча писал пустоту.
        испорченный = json.loads(json.dumps(ответ_поиска))
        испорченный["items"][0]["salary"] = None
        испорченный["items"][0]["salary_range"] = None

        итог = проверить_страницу(испорченный)

        # Это не поломка: вакансия без зарплаты — обычное дело. Но повод
        # посмотреть, не сменилась ли схема.
        assert итог["нарушен"] is False
        assert "salary/salary_range" in итог["подозрительно"]

    def test_пустое_значение_считается_пропажей(self):
        # Поле есть, но пустое, — для нас это то же самое, что его нет.
        assert "name" in проверить_вакансию({"id": "1", "name": None})


class TestНеПридирается:

    def test_пустая_выдача_не_нарушение(self):
        # «Ничего не нашлось» — честный ответ источника, а не поломка.
        итог = проверить_страницу({"items": [], "found": 0, "pages": 0, "page": 0})

        assert итог["нарушен"] is False

    def test_контракт_короткий(self):
        # У вакансии больше сорока полей. Контракт требует минимум, без
        # которого запись бесполезна, — иначе он ловил бы не смену схемы,
        # а любое изменение у источника.
        assert len(ПОЛЯ_ВАКАНСИИ) <= 6

    def test_ответа_нет_вовсе(self):
        итог = проверить_страницу(None)

        assert итог["нарушен"] is True
