"""
Состав файла считается до сборки — и теми же выражениями, что листы.

Экран показывает, что попадёт в отчёт, прежде чем человек нажмёт
кнопку. Ценность здесь в совпадении: если подсчёт разойдётся с
наполнением листов, экран начнёт обещать сорок навыков там, где их
двенадцать, и заметить это можно будет только открыв файл.
"""

from __future__ import annotations

import pandas as pd
import pytest
from openpyxl import Workbook

from src.report_xlsx import МАЛАЯ_ВЫБОРКА, лист_навыки, состав_файла

ВЫБОРКА = pd.DataFrame([
    {
        "vacancy_id": "1", "vacancy_name": "UX-дизайнер", "area": "Москва",
        "hard_skills": "figma, типографика", "tools": "sketch", "soft_skills": "внимательность",
        "salary_from": 150000, "salary_currency": "RUB",
    },
    {
        "vacancy_id": "2", "vacancy_name": "Графический дизайнер", "area": "Казань",
        "hard_skills": "photoshop", "tools": "figma", "soft_skills": "",
        "salary_from": None, "salary_currency": "RUB",
    },
    {
        "vacancy_id": "3", "vacancy_name": "Python разработчик", "area": "Москва",
        "hard_skills": "python, django", "tools": "", "soft_skills": "",
        "salary_from": 300000, "salary_currency": "USD",
    },
])


class TestСостав:

    def test_считает_вакансии(self):
        assert состав_файла(ВЫБОРКА)["вакансий"] == 3

    def test_навыки_собираются_из_трёх_колонок(self):
        """
        Лист «Навыки» складывает жёсткие, личные и инструменты в один
        список — предпросмотр обязан считать так же.
        """
        # figma, типографика, sketch, внимательность, photoshop, python, django
        assert состав_файла(ВЫБОРКА)["навыков_всего"] == 7

    def test_навык_из_разных_колонок_не_задваивается(self):
        """«Figma» стоит у первой в жёстких, у второй в инструментах."""
        состав = состав_файла(ВЫБОРКА)
        assert состав["навыков_всего"] == 7, "figma посчитана дважды"

    def test_предел_листа_учтён(self):
        """
        В файл попадают первые сорок навыков. Обещать больше нельзя:
        человек откроет лист и не найдёт остальных.
        """
        много = pd.DataFrame([
            {"vacancy_id": str(i), "hard_skills": f"навык-{i}", "tools": "", "soft_skills": "",
             "salary_from": None, "salary_currency": "RUB"}
            for i in range(60)
        ])
        состав = состав_файла(много)
        assert состав["навыков"] == 40
        assert состав["навыков_всего"] == 60

    def test_валюты_считаются_по_правдоподобным(self):
        assert состав_файла(ВЫБОРКА)["валют"] == 2

    def test_малая_выборка_помечена(self):
        assert состав_файла(ВЫБОРКА)["малая_выборка"] is True
        assert состав_файла(ВЫБОРКА.loc[ВЫБОРКА.index.repeat(5)])["малая_выборка"] is False

    def test_пустая_выборка_не_ломается(self):
        пусто = pd.DataFrame(columns=ВЫБОРКА.columns)
        состав = состав_файла(пусто)
        assert состав["вакансий"] == 0
        assert состав["навыков"] == 0


def test_обещание_совпадает_с_листом():
    """
    Главная проверка: сколько навыков обещал экран, столько строк в
    листе. Расхождение между подсчётом и наполнением — то, ради чего
    подсчёт живёт рядом с генератором, а не на экране.
    """
    состав = состав_файла(ВЫБОРКА)

    wb = Workbook()
    лист_навыки(wb, ВЫБОРКА)
    ws = wb["Навыки"]

    строк = ws.max_row - 1  # без шапки
    assert строк == состав["навыков"], (
        f"экран обещает {состав['навыков']} навыков, в листе {строк}"
    )


