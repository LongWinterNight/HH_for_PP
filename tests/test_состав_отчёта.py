    """
    Порог берётся из генератора, а не задаётся на экране заново: серый
    цвет объёма в «Сводке» и предупреждение на экране должны включаться
    в одной и той же точке.
    """
    from web.app.main import МАЛАЯ_ВЫБОРКА_ОТЧЁТА

    assert МАЛАЯ_ВЫБОРКА_ОТЧЁТА == МАЛАЯ_ВЫБОРКА
