"""
Кандидаты в словарь навыков.

Словарь пополняется руками, а рынок меняется быстрее: замер показал, что
89 базовых терминов в нём отсутствовали. Скрипт ищет пропущенное сам —
но словарь, который машина пополняет без надзора, за месяц превращается
в свалку обрывков фраз. Поэтому кандидат копится, а решение принимает
человек.

Здесь закрепляются оба свойства: что скрипт отсеивает сам и что он не
решает за человека.

Запуск: pytest tests/test_кандидаты_словаря.py -v
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

спец = importlib.util.spec_from_file_location(
    "кандидаты", project_root / "scripts" / "maintenance" / "кандидаты_в_словарь.py"
)
кандидаты = importlib.util.module_from_spec(спец)
спец.loader.exec_module(кандидаты)


class TestОтсевМусора:
    def test_глагол_не_навык(self):
        """«Читать», «работать» — то, что стоит рядом с навыком."""
        assert not кандидаты.похоже_на_навык("читать")
        assert not кандидаты.похоже_на_навык("работать самостоятельно")

    def test_наречие_не_навык(self):
        assert not кандидаты.похоже_на_навык("чётко")

    def test_слишком_общее_не_навык(self):
        for слово in ("опыт", "знание", "данные", "задачи"):
            assert not кандидаты.похоже_на_навык(слово), слово

    def test_числа_и_обрывки_отсеиваются(self):
        assert not кандидаты.похоже_на_навык("3 лет")
        assert not кандидаты.похоже_на_навык("от")

    def test_длинная_фраза_не_навык(self):
        """Навык — это название, а не предложение."""
        assert not кандидаты.похоже_на_навык("умение работать в команде и одному")

    def test_настоящий_навык_проходит(self):
        assert кандидаты.похоже_на_навык("микросервисная архитектура")
        assert кандидаты.похоже_на_навык("brokers")
        assert кандидаты.похоже_на_навык("prompt engineering")


class TestПамятьРешений:
    def test_решённое_сравнивается_по_начальным_формам(self):
        """Кандидат приходит в косвенном падеже, в словарь пишут канон:
        без приведения один навык предлагался бы бесконечно."""
        assert кандидаты.ключ("базами данных") == кандидаты.ключ("базы данных")
        assert кандидаты.ключ("системами мониторинга") == кандидаты.ключ("системы мониторинга")

    def test_разные_навыки_не_склеиваются(self):
        assert кандидаты.ключ("базы данных") != кандидаты.ключ("брокеры сообщений")


class TestРешаетЧеловек:
    def test_принятые_и_отклонённые_хранятся_раздельно(self, tmp_path, monkeypatch):
        файл = tmp_path / "решения.json"
        monkeypatch.setattr(кандидаты, "ФАЙЛ_РЕШЕНИЙ", файл)

        кандидаты.записать_решения({"принято": ["blender"], "отклонено": ["читать"]})
        решения = кандидаты.читать_решения()

        assert решения["принято"] == ["blender"]
        assert решения["отклонено"] == ["читать"]

    def test_без_файла_решений_список_пуст(self, tmp_path, monkeypatch):
        monkeypatch.setattr(кандидаты, "ФАЙЛ_РЕШЕНИЙ", tmp_path / "нет.json")

        решения = кандидаты.читать_решения()

        assert решения == {"принято": [], "отклонено": []}
