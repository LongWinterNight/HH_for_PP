class TestВалютаИПериодЧужогоИсточника:
    """
    Правила денег не привязаны к hh.ru (S8‑4a).

    Валюты не складываются и не пересчитываются между собой, а период
    выплаты — часть числа: «1 000» и «1 000 за час» разные величины.
    Оба правила должны работать для любого источника, а не только для
    того, чьи имена полей движок знал изначально.
    """

    def запись_чужого(self, **поля):
        основа = пустая_запись()
        основа.update({
            "источник": "пример.рф",
            "идентификатор": "x-1",
            "название": "Инженер",
            "работодатель": "ООО Пример",
            "регион": "Астана",
        })
        основа.update(поля)
        return основа

    def test_валюта_источника_доходит_до_базы(self, словари):
        строка = normalize_vacancy(
            self.запись_чужого(зарплата_от=500000, валюта="KZT"), словари
        )

        assert строка["salary_currency"] == "KZT"
        assert строка["salary_from"] == 500000

    def test_период_выплаты_доходит_до_базы(self, словари):
        строка = normalize_vacancy(
            self.запись_чужого(зарплата_от=1000, валюта="RUB", период="HOUR"), словари
        )

        assert строка["salary_mode"] == "HOUR"

    def test_неназванная_валюта_не_превращается_в_рубли(self, словари):
        # Подставить рубль там, где источник валюту не назвал, — значит
        # положить чужие деньги в рублёвую статистику.
        строка = normalize_vacancy(self.запись_чужого(зарплата_от=100), словари)

        assert строка["salary_currency"] is None

    def test_неназванный_период_остаётся_пустым(self, словари):
        строка = normalize_vacancy(self.запись_чужого(зарплата_от=100), словари)

        assert строка["salary_mode"] is None


class TestЗанятостьИГрафик:
    """
    Источник убрал `employment` и `schedule` и отдаёт вместо них другие
    поля. Сбор этого не заметил: оба поля были необязательными, и у
    5 312 вакансий в базе занятость и график молча опустели.
    """

    @staticmethod
    def _запись(**поля):
        from src.sources.hh import в_общую_запись

        return в_общую_запись({"id": "1", "name": "Дизайнер", **поля})

    def test_новые_поля_читаются(self):
        запись = self._запись(
            employment_form={"id": "FULL", "name": "Полная"},
            work_format=[{"id": "REMOTE", "name": "Удалённо"}, {"id": "HYBRID", "name": "Гибрид"}],
            work_schedule_by_days=[{"id": "FIVE_ON_TWO_OFF", "name": "5/2"}],
        )
        assert запись["занятость"] == "Полная занятость"
        assert запись["график"] == "Удалённо, Гибрид · 5/2"

    def test_занятость_сведена_к_прежним_названиям(self):
        """Иначе распределение раскололось бы на «Полная занятость» и «Полная»."""
        ожидается = {"FULL": "Полная занятость", "PART": "Частичная занятость", "PROJECT": "Проектная работа"}
        for код, название in ожидается.items():
            assert self._запись(employment_form={"id": код, "name": "как угодно"})["занятость"] == название

    def test_незнакомая_форма_занятости_остаётся_как_есть(self):
        assert self._запись(employment_form={"id": "FLY_IN_FLY_OUT", "name": "Вахта"})["занятость"] == "Вахта"

    def test_прежние_поля_читаются_первыми(self):
        """Сырые файлы старых сборов их ещё несут."""
        запись = self._запись(
            employment={"id": "full", "name": "Полная занятость"},
            schedule={"id": "remote", "name": "Удаленная работа"},
            employment_form={"id": "PART", "name": "Частичная"},
            work_format=[{"id": "ON_SITE", "name": "На месте работодателя"}],
        )
        assert запись["занятость"] == "Полная занятость"
        assert запись["график"] == "Удаленная работа"

    def test_ничего_нет_поля_пусты_а_не_выдуманы(self):
        запись = self._запись()
        assert запись["занятость"] == "" and запись["график"] == ""

    def test_неразрывные_пробелы_источника_заменены(self):
        """«На\xa0месте работодателя» не равно строке, набранной с клавиатуры."""
        запись = self._запись(work_format=[{"id": "ON_SITE", "name": "На\xa0месте работодателя"}])
        assert запись["график"] == "На месте работодателя"

    def test_другое_в_графике_по_дням_опускается(self):
        запись = self._запись(
            work_format=[{"id": "ON_SITE", "name": "На месте работодателя"}],
            work_schedule_by_days=[{"id": "OTHER", "name": "Другое"}],
        )
        assert запись["график"] == "На месте работодателя"

    def test_только_график_по_дням(self):
        запись = self._запись(work_schedule_by_days=[{"id": "TWO_ON_TWO_OFF", "name": "2/2"}])
        assert запись["график"] == "2/2"
