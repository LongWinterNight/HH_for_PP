"""
Проверка надзора над сервером: когда он перезапускает, а когда ждёт.

Главное правило здесь одно: сбор данных нельзя обрывать ради правки в
коде. Он идёт фоновым потоком внутри процесса сервера и живёт десятки
минут — перезапуск в этот момент стоит часа работы источника. Проверять
это настоящим сбором дорого, поэтому занятость подменяется, а проверяется
само решение: ждать или перезапускать.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]


def загрузить_надзор():
    """`scripts/` не пакет — модуль грузится по пути."""
    путь = КОРЕНЬ / "scripts" / "serve.py"
    описание = importlib.util.spec_from_file_location("serve", путь)
    модуль = importlib.util.module_from_spec(описание)
    описание.loader.exec_module(модуль)
    return модуль


@pytest.fixture
def надзор(monkeypatch):
    модуль = загрузить_надзор()
    # Ожидание в тесте не спим: проверяется решение, а не терпение.
    monkeypatch.setattr(модуль.time, "sleep", lambda _: None)
    return модуль


@pytest.fixture
def сервер(надзор):
    return надзор.Сервер("127.0.0.1", 8000)


def ответы(надзор, monkeypatch, последовательность):
    """Подменить опрос занятости заранее заданными ответами."""
    очередь = list(последовательность)
    прочитано = []

    def подмена(_порт):
        значение = очередь.pop(0) if очередь else последовательность[-1]
        прочитано.append(значение)
        return значение

    monkeypatch.setattr(надзор, "занятость", подмена)
    return прочитано


def test_ждёт_пока_идёт_сбор(надзор, сервер, monkeypatch):
    """Сбор длиной в час — нормальная работа, а не повод его оборвать."""
    прочитано = ответы(надзор, monkeypatch, [
        {"сбор_идёт": True, "секунд_тишины": 99},
        {"сбор_идёт": True, "секунд_тишины": 99},
        {"сбор_идёт": True, "секунд_тишины": 99},
        {"сбор_идёт": False, "секунд_тишины": 99},
    ])

    надзор.дождаться_покоя(сервер, тишина=5)

    # Вышли только после того, как сбор закончился: три отказа подряд.
    assert len(прочитано) == 4
    assert прочитано[-1]["сбор_идёт"] is False


def test_ждёт_пока_пользователь_работает(надзор, сервер, monkeypatch):
    """Перезапуск под руками пользователя — ошибка сети на ровном месте."""
    прочитано = ответы(надзор, monkeypatch, [
        {"сбор_идёт": False, "секунд_тишины": 0.0},
        {"сбор_идёт": False, "секунд_тишины": 2.0},
        {"сбор_идёт": False, "секунд_тишины": 6.0},
    ])

    надзор.дождаться_покоя(сервер, тишина=5)

    assert len(прочитано) == 3


def test_свободный_сервер_перезапускается_сразу(надзор, сервер, monkeypatch):
    """В простое правка должна доезжать быстро, иначе надзор бесполезен."""
    прочитано = ответы(надзор, monkeypatch, [{"сбор_идёт": False, "секунд_тишины": 30.0}])

    надзор.дождаться_покоя(сервер, тишина=5)

    assert len(прочитано) == 1


def test_молчащий_сервер_не_ждут(надзор, сервер, monkeypatch):
    """Если сервер не отвечает, беречь нечего: он либо мёртв, либо ещё встаёт."""
    прочитано = ответы(надзор, monkeypatch, [None])

    надзор.дождаться_покоя(сервер, тишина=5)

    assert прочитано == [None]


