"""
Кэш ответов источника: попадание, промах, сроки, уборка.

Проверяется главное различие, ради которого S6‑5 делалась: выдача и
карточка живут по-разному. Страница выдачи устаревает за часы —
работодатель публикует вакансию утром, и вечерний сбор по вчерашнему
кэшу её не увидит. Карточка почти не меняется, а запрашивается на
каждую новую вакансию: это тысячи обращений на сбор, и держать её
неделю выгоднее всего.

Отдельно проверяется уборка. Файл кэша рос бесконечно: срок годности у
выдачи шесть часов, а удаление было только ручное и по возрасту в семь
дней — то есть запись оставалась мусором почти неделю.
"""

from __future__ import annotations

from datetime import datetime, timedelta

import pytest

from src.api_cache import APICache

ОТВЕТ = {"items": [{"id": "1", "name": "Дизайнер"}], "found": 1, "pages": 1}
КАРТОЧКА = {"id": "1", "name": "Дизайнер", "description": "<p>Figma</p>"}


@pytest.fixture
def кэш(tmp_path):
    return APICache(cache_db=tmp_path / "api_cache.db")


class TestВыдача:

    def test_попадание(self, кэш):
        кэш.set("дизайнер", 0, ОТВЕТ)
        assert кэш.get("дизайнер", 0) == ОТВЕТ

    def test_промах_по_другому_запросу(self, кэш):
        кэш.set("дизайнер", 0, ОТВЕТ)
        assert кэш.get("аналитик", 0) is None

    def test_промах_по_другой_странице(self, кэш):
        кэш.set("дизайнер", 0, ОТВЕТ)
        assert кэш.get("дизайнер", 1) is None

    def test_срез_не_читает_чужой_ответ(self, кэш):
        """
        Регион входит в ключ.

        Раньше не входил: «Рекрутер» по Москве и по всей стране читались
        из одной ячейки, и резка на срезы молча возвращала бы одни и те
        же вакансии.
        """
        кэш.set("рекрутер", 0, ОТВЕТ)
        assert кэш.get("рекрутер", 0, area="1") is None

    def test_окно_дат_входит_в_ключ(self, кэш):
        кэш.set("рекрутер", 0, ОТВЕТ, date_from="2026-09-01")
        assert кэш.get("рекрутер", 0) is None
        assert кэш.get("рекрутер", 0, date_from="2026-09-01") == ОТВЕТ

    def test_протухшая_запись_не_отдаётся(self, кэш):
        кэш.set("дизайнер", 0, ОТВЕТ, ttl_hours=-1)
        assert кэш.get("дизайнер", 0) is None


class TestКарточка:

    def test_попадание(self, кэш):
        кэш.сохранить_карточку("137", КАРТОЧКА)
        assert кэш.получить_карточку("137") == КАРТОЧКА

    def test_промах_по_другой_вакансии(self, кэш):
        кэш.сохранить_карточку("137", КАРТОЧКА)
        assert кэш.получить_карточку("138") is None

    def test_карточка_и_выдача_не_путаются(self, кэш):
        """Разные пространства ключей: «137» как запрос и как карточка."""
        кэш.set("137", 0, ОТВЕТ)
        кэш.сохранить_карточку("137", КАРТОЧКА)

        assert кэш.get("137", 0) == ОТВЕТ
        assert кэш.получить_карточку("137") == КАРТОЧКА

    def test_карточка_живёт_дольше_выдачи(self, кэш, monkeypatch):
        """
        Срок карточки берётся из своей настройки.

        Один срок на двоих означал выбор между несвежей выдачей и
        лишними тысячами обращений за карточками.
        """
        from src import api_cache as модуль

        monkeypatch.setattr(модуль.settings, "кэш_выдачи_часов", 6)
        monkeypatch.setattr(модуль.settings, "кэш_карточек_часов", 168)

        кэш.set("дизайнер", 0, ОТВЕТ)
        кэш.сохранить_карточку("137", КАРТОЧКА)

        сроки = {}
        with кэш._get_connection() as conn:
            for ключ, годен_до in conn.execute(
                "SELECT cache_key, expires_at FROM api_cache"
            ):
                сроки[ключ] = datetime.fromisoformat(годен_до)

        самый_ранний, самый_поздний = min(сроки.values()), max(сроки.values())
        assert самый_поздний - самый_ранний > timedelta(days=6)


class TestУборка:

    def test_протухшие_удаляются(self, кэш):
        кэш.set("свежий", 0, ОТВЕТ)
        кэш.set("протухший", 0, ОТВЕТ, ttl_hours=-1)

        удалено = кэш.убрать_протухшие()

        assert удалено == 1
        assert кэш.get("свежий", 0) == ОТВЕТ
        assert кэш.get("протухший", 0) is None

    def test_уборка_без_протухших_ничего_не_трогает(self, кэш):
        кэш.set("свежий", 0, ОТВЕТ)
        assert кэш.убрать_протухшие() == 0
        assert кэш.get("свежий", 0) == ОТВЕТ

    def test_статистика_считает_записи(self, кэш):
        кэш.set("первый", 0, ОТВЕТ)
        кэш.сохранить_карточку("137", КАРТОЧКА)
        assert кэш.get_stats()["entries"] == 2
