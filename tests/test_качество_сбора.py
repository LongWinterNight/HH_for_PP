"""
Качество сбора: годятся ли собранные записи для аналитики (S6‑1).

Главное свойство: сводка обязана сходиться. Колонка, которой нет,
считается нулём с карточкой и нулём навыков — то есть худшим случаем, —
а не пропускается: молчание здесь неотличимо от «всё хорошо».
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.quality import (  # noqa: E402
    метрики,
    неполных_обходов,
    пустая_сводка,
    сводка,
    сложить,
)


def запись(has_details=True, skill_count=5):
    return {"vacancy_id": "1", "has_details": has_details, "skill_count": skill_count}


class TestМетрики:

    def test_считает_карточки_и_пустые(self):
        df = pd.DataFrame([
            запись(has_details=True, skill_count=12),
            запись(has_details=True, skill_count=0),
            запись(has_details=False, skill_count=0),
        ])

        итог = метрики(df)

        assert итог == {"всего": 3, "с_карточкой": 2, "без_навыков": 2}

    def test_пустая_выборка(self):
        assert метрики(pd.DataFrame()) == пустая_сводка()
        assert метрики(None) == пустая_сводка()

    def test_отсутствие_колонки_навыков_худший_случай(self):
        # Колонки нет — значит навыков мы не насчитали. Считать такие
        # записи полноценными значило бы отрапортовать о качестве,
        # которого не измеряли.
        df = pd.DataFrame([{"vacancy_id": "1", "has_details": True}])

        итог = метрики(df)

        assert итог["без_навыков"] == 1
        assert итог["всего"] == 1

    def test_пропуски_в_колонках(self):
        df = pd.DataFrame([
            {"vacancy_id": "1", "has_details": None, "skill_count": None},
            {"vacancy_id": "2", "has_details": 1, "skill_count": 3},
        ])

        итог = метрики(df)

        assert итог == {"всего": 2, "с_карточкой": 1, "без_навыков": 1}


class TestСложение:

    def test_порции_складываются(self):
        итог = сложить(
            {"всего": 10, "с_карточкой": 8, "без_навыков": 2},
            {"всего": 5, "с_карточкой": 5, "без_навыков": 0},
        )
        assert итог == {"всего": 15, "с_карточкой": 13, "без_навыков": 2}

    def test_складывается_с_пустой(self):
        assert сложить(пустая_сводка(), {"всего": 3, "с_карточкой": 1, "без_навыков": 2}) == {
            "всего": 3, "с_карточкой": 1, "без_навыков": 2,
        }


class TestНеполныеОбходы:

    def test_считает_неполные(self):
        by_keyword = {
            "Рекрутер": {"complete": False},
            "HR": {"complete": True},
            "Кадровик": {"complete": False},
        }
        assert неполных_обходов(by_keyword) == 2

    def test_запрос_без_отметки_считается_неполным(self):
        # Осторожная ошибка дешевле смелой: по «полному» обходу сбор
        # гасит вакансии, которых в нём не оказалось.
        assert неполных_обходов({"Рекрутер": {}}) == 1

    def test_пусто(self):
        assert неполных_обходов({}) == 0
        assert неполных_обходов(None) == 0


class TestСводка:

    def test_три_числа_для_истории(self):
        итог = сводка(
            {"всего": 100, "с_карточкой": 95, "без_навыков": 4},
            {"Рекрутер": {"complete": False}, "HR": {"complete": True}},
        )

        assert итог["с_карточкой"] == 95
        assert итог["без_навыков"] == 4
        assert итог["неполных_запросов"] == 1
