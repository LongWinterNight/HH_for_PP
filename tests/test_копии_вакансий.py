"""
Копии одной вакансии по городам.

Работодатель размещает одну вакансию в десятках городов; у каждой копии
свой идентификатор, и для базы это разные записи. На живой базе таких
15 % активных строк, рекорд — 31 копия. В медиане зарплаты одна вакансия
весила как тридцать: 81 500 ₽ по строкам против 90 000 ₽ по вакансиям.

Решение (S5‑1b): копии считаются за одну там, где число описывает рынок
труда — медиана, квартили, гистограмма. Там, где число описывает
предложения — «вакансий в базе», регионы, список на экране, — считаются
все строки: в каждом городе предложение действительно есть.

Запуск: pytest tests/test_копии_вакансий.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from src.copies import без_копий, размеры_групп, сколько_копий


def строка(название: str, компания: str, город: str, зарплата=None) -> dict:
    return {
        "vacancy_name": название,
        "employer_name": компания,
        "area": город,
        "salary_from": зарплата,
    }


@pytest.fixture
def выборка() -> pd.DataFrame:
    """Одна вакансия в трёх городах и две самостоятельные."""
    return pd.DataFrame([
        строка("Рекрутер", "Самокат", "Москва", 60000),
        строка("Рекрутер", "Самокат", "Самара", 60000),
        строка("Рекрутер", "Самокат", "Казань", 60000),
        строка("Аналитик", "СБЕР", "Москва", 200000),
        строка("Разработчик", "СБЕР", "Москва", 300000),
    ])


class TestСхлопывание:
    def test_копии_считаются_за_одну(self, выборка):
        assert len(без_копий(выборка, "salary_from")) == 3

    def test_разные_вакансии_одной_компании_не_склеиваются(self, выборка):
        """«Аналитик» и «Разработчик» в СБЕРе — две вакансии, не копии."""
        итог = без_копий(выборка, "salary_from")

        assert set(итог["vacancy_name"]) == {"Рекрутер", "Аналитик", "Разработчик"}

    def test_медиана_перестаёт_зависеть_от_числа_городов(self, выборка):
        по_строкам = выборка["salary_from"].median()
        по_вакансиям = без_копий(выборка, "salary_from")["salary_from"].median()

        assert по_строкам == 60000, "три копии перевесили две вакансии"
        assert по_вакансиям == 200000

    def test_представитель_группы_берётся_по_медиане(self):
        """У шести групп из восьмидесяти трёх ставка различается по
        регионам: брать первую строку значило бы отдать результат на
        волю порядка."""
        df = pd.DataFrame([
            строка("Курьер", "Достака", "Москва", 100000),
            строка("Курьер", "Достака", "Тверь", 50000),
            строка("Курьер", "Достака", "Клин", 70000),
        ])

        assert без_копий(df, "salary_from").iloc[0]["salary_from"] == 70000

    def test_пустые_зарплаты_не_роняют_расчёт(self):
        df = pd.DataFrame([
            строка("Курьер", "Достака", "Москва", None),
            строка("Курьер", "Достака", "Тверь", None),
        ])

        assert len(без_копий(df, "salary_from")) == 1


class TestСчёт:
    def test_размер_группы_виден(self, выборка):
        размеры = размеры_групп(выборка)

        assert размеры[("Рекрутер", "Самокат")] == 3
        assert размеры[("Аналитик", "СБЕР")] == 1

    def test_число_лишних_строк(self, выборка):
        """Для подписи «ещё в двух городах»."""
        assert сколько_копий(выборка) == 2


class TestУстойчивость:
    def test_выборка_без_нужных_полей_возвращается_как_есть(self):
        """Старые выгрузки могут не иметь работодателя — это не повод
        падать или молча терять строки."""
        df = pd.DataFrame([{"salary_from": 100000}, {"salary_from": 200000}])

        assert len(без_копий(df, "salary_from")) == 2

    def test_пустая_выборка(self):
        пусто = pd.DataFrame(columns=["vacancy_name", "employer_name", "salary_from"])

        assert без_копий(пусто, "salary_from").empty
        assert сколько_копий(пусто) == 0
