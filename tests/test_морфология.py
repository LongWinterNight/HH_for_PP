"""
Морфология русских навыков.

Словарь ищет точную форму, а работодатели пишут естественным языком: в
словаре «переговоры», в тексте «ведение переговоров». Замер по эталону
показал цену: полнота по продажам 27 % против 91 % по ИТ-разработке — в
ИТ навыки называют терминами, которые не склоняют, в продажах и HR
обычными словами, которые склоняются.

Здесь закрепляются обе стороны: что морфология находит и чего она не
должна ломать.

Запуск: pytest tests/test_морфология.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from src.morphology import начальная_форма, нужна_ли, привести
from src.normalize import PreparedSkill, SkillDictionaries, find_skills


def находит(навык: str, текст: str) -> bool:
    п = PreparedSkill(навык.lower())
    леммы = привести(текст)
    return bool(п.lemma_word and п.lemma in леммы and п.lemma_word.search(леммы))


class TestСловоформы:
    def test_склонение_не_мешает(self):
        assert находит("переговоры", "ведение технических переговоров")
        assert находит("презентации", "проведение обучений и презентаций")
        assert находит("продажи", "опыт активных продаж от двух лет")

    def test_составной_навык_тоже_склоняется(self):
        assert находит("активные продажи", "опыт активных продаж")


class TestЛатиницаНеТрогается:
    def test_английские_названия_остаются_собой(self):
        assert привести("разработка на python и node.js") .find("python") >= 0
        assert "node.js" in привести("стек: node.js, react")
        assert начальная_форма("cache") == "cache"

    def test_морфология_к_латинице_не_применяется(self):
        assert not нужна_ли("python")
        assert not нужна_ли("c#")


class TestЛожныеСрабатывания:
    """Разборщик ошибается в части речи, и это уводит навык не туда."""

    def test_прилагательное_не_становится_навыком(self):
        """«Гибка» (металла) он приводит к «гибкий» — и навык находится
        в «гибком графике». На живой базе это дало 209 ложных находок."""
        assert not находит("гибка", "гибкий график работы")

    def test_местоимение_не_становится_навыком(self):
        """«ТУ» (технические условия) он приводит к «тот»: 620 ложных."""
        assert not находит("ту", "работать в ту же смену")

    def test_существительные_морфологию_получают(self):
        assert нужна_ли("переговоры")
        assert нужна_ли("тестирование")
        assert not нужна_ли("гибка")
        assert not нужна_ли("ту")


class TestВПоиске:
    def test_навык_находится_через_леммы(self, словари):
        текст = "обязанности: ведение переговоров с поставщиками"
        все = словари.hard + словари.soft + словари.tools

        нашли = {н.lower() for н in find_skills(текст, все, привести(текст))}

        assert any("переговор" in н for н in нашли)

    def test_без_лемм_поиск_работает_как_прежде(self, словари):
        """Леммы — необязательный параметр: старые вызовы не ломаются."""
        все = словари.hard + словари.soft + словари.tools

        нашли = {н.lower() for н in find_skills("опыт с python и docker", все)}

        assert "python" in нашли and "docker" in нашли


