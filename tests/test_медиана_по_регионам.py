"""
Медиана зарплаты по регионам.

Рынок в Москве и в Ташкенте — разные рынки, и общая медиана их
смешивает. Разрез по регионам отвечает на вопрос «сколько платят здесь»,
ради которого продукт и нужен.

Проверяется то, что легко сломать незаметно: регион с тремя вакансиями
не встаёт рядом с регионом на шестьсот, длинный хвост не забивает
экран, а скрытые регионы посчитаны — иначе объём выборки под графиком
не сойдётся с тем, что человек видит в списке.

Запуск: pytest tests/test_медиана_по_регионам.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from web.app.main import MIN_SAMPLE, медиана_по_регионам


def выборка(регионы: dict, колонка: str = "salary_from") -> pd.DataFrame:
    """{'Москва': [зарплаты...]} → таблица."""
    строки = []
    for область, суммы in регионы.items():
        строки += [{"area": область, колонка: сумма} for сумма in суммы]
    return pd.DataFrame(строки)


class TestОтборРегионов:
    def test_регион_с_малой_выборкой_не_показывается(self):
        """Медиана по трём вакансиям — не зарплата региона, а случайность."""
        df = выборка({
            "Москва": [100000] * 20,
            "Урюпинск": [500000, 600000, 700000],
        })

        регионы, счёт = медиана_по_регионам(df, "salary_from")

        assert [р["area"] for р in регионы] == ["Москва"]
        assert счёт["small"] == 1, "скрытый регион посчитан, а не потерян молча"

    def test_порядок_по_объёму_а_не_по_деньгам(self):
        """Иначе первым встал бы регион с пятью вакансиями."""
        df = выборка({
            "Москва": [100000] * 20,
            "Дорогой городок": [900000] * 6,
        })

        регионы, _ = медиана_по_регионам(df, "salary_from")

        assert [р["area"] for р in регионы] == ["Москва", "Дорогой городок"]
        assert регионы[0]["sample"] > регионы[1]["sample"]

    def test_длинный_хвост_обрезан_и_посчитан(self):
        """Регионов бывает две сотни, сравнить взглядом можно десяток."""
        df = выборка({f"Город {i}": [100000 + i * 1000] * (30 - i) for i in range(15)})

        регионы, счёт = медиана_по_регионам(df, "salary_from", предел=10)

        assert len(регионы) == 10
        assert счёт["beyond"] == 5
        assert счёт["small"] == 0

    def test_объём_выборки_едет_с_каждой_медианой(self):
        """Без n число ничего не значит."""
        df = выборка({"Москва": [80000, 90000, 100000, 110000, 120000, 130000]})

        регионы, _ = медиана_по_регионам(df, "salary_from")

        assert регионы[0]["sample"] == 6
        assert регионы[0]["median"] == 105000

    def test_пустая_выборка_не_роняет_расчёт(self):
        регионы, счёт = медиана_по_регионам(pd.DataFrame(), "salary_from")

        assert регионы == []
        assert счёт == 0 or счёт == {"small": 0, "beyond": 0}


class TestВалюты:
    def test_считается_по_переданной_колонке(self):
        """Валютный вид берёт исходные суммы, рублёвый — эквивалент."""
        df = выборка({"Ташкент": [6_000_000] * 6})
        df["salary_from_rub"] = 44_000.0

        в_валюте, _ = медиана_по_регионам(df, "salary_from")
        в_рублях, _ = медиана_по_регионам(df, "salary_from_rub")

        assert в_валюте[0]["median"] == 6_000_000
        assert в_рублях[0]["median"] == 44_000

    def test_порог_совпадает_с_общим_правилом(self):
        """MIN_SAMPLE один на весь продукт: свой порог здесь означал бы,
        что одно и то же число надёжно на одном экране и нет на другом."""
        df = выборка({"Ровно порог": [100000] * MIN_SAMPLE,
                      "На одну меньше": [100000] * (MIN_SAMPLE - 1)})

        регионы, счёт = медиана_по_регионам(df, "salary_from")

        assert [р["area"] for р in регионы] == ["Ровно порог"]
        assert счёт["small"] == 1
