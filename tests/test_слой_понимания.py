class TestКэш:

    def test_второй_разбор_того_же_текста_не_зовёт_модель(self, база):
        модель = Заглушка(lambda текст: ХОРОШИЙ)
        прогон.провести(база, модель, предел=1)
        assert len(модель.вызовы) == 1

        # Отметку версии снимаем: вакансия снова в очереди, но ответ уже в кэше.
