class TestВходИВыход:

    def test_описание_без_разметки_но_с_абзацами(self):
        текст = текст_описания(ОПИСАНИЕ)
        assert "<" not in текст
        assert "Требования\nуверенное владение Zustand\nопыт с TanStack Query" in текст

    def test_вход_называет_вакансию(self):
        assert вход("Frontend", ОПИСАНИЕ).startswith("Название вакансии: Frontend\n\nОписание:\n")

    def test_короткие_ключи_модели_переводятся_в_контракт(self):
        данные = полные_ключи(ХОРОШИЙ)
        assert данные["навыки"][0] == {
            "как_в_тексте": "владение Zustand", "название": "Zustand", "вид": "технология", "уверенность": 0.9, "родитель": None,
        }
        assert данные["язык_текста"] == "ru"

    def test_хороший_ответ_разобран_с_версиями_от_нас(self):
        ответ, отброшены = из_сырого(json.dumps(ХОРОШИЙ, ensure_ascii=False), ОПИСАНИЕ, "модель:1")
        assert [н.название for н in ответ.навыки] == ["Zustand", "TanStack Query", "SQL"]
        assert ответ.версия_модели == "модель:1" and отброшены == []

    def test_цитата_сверяется_с_текстом_без_разметки(self):
        # В описании между словами стоит тег; модель видела текст без него.
        описание = "<ul><li>Jira</li><li>для задач</li></ul><p>макеты в <strong>Figma</strong></p>"
        ответ, отброшены = из_сырого(json.dumps(_ответ(("Figma", "макеты в Figma", "tool")), ensure_ascii=False), описание, "м:1")
        assert [н.название for н in ответ.навыки] == ["Figma"] and отброшены == []

    def test_выдуманный_навык_отброшен(self):
        сырой = json.dumps(_ответ(("SQL", "знание SQL", "tech"), ("Kubernetes", "опыт с Kubernetes", "tool")), ensure_ascii=False)
        ответ, отброшены = из_сырого(сырой, ОПИСАНИЕ, "м:1")
        assert [н.название for н in ответ.навыки] == ["SQL"]
        assert [н.название for н in отброшены] == ["Kubernetes"]

    def test_цитата_из_слов_одной_строки_возвращает_навык(self):
        # Модель собрала цитату из несмежных слов строки «знание основ REST, SOAP».
        описание = "<ul><li>знание основ REST, SOAP</li><li>опыт от года</li></ul>"
        сырой = "ru\nзнание основ SOAP|SOAP|tech|9\n"

        ответ, отброшены = из_сырого(сырой, описание, "м:1")

        assert [н.название for н in ответ.навыки] == ["SOAP"] and отброшены == []
        assert ответ.навыки[0].как_в_тексте == "знание основ REST, SOAP", "человеку показано то, что написано в вакансии"

    def test_слова_из_разных_строк_навык_не_возвращают(self):
        описание = "<ul><li>знание основ тестирования</li><li>наш продукт работает в Kubernetes</li></ul>"
        ответ, отброшены = из_сырого("ru\nзнание Kubernetes|Kubernetes|tool|9\n", описание, "м:1")

        assert ответ.навыки == [] and [н.название for н in отброшены] == ["Kubernetes"]

    def test_повтор_навыка_схлопнут(self):
        сырой = json.dumps(_ответ(("SQL", "знание SQL", "tech"), ("sql", "знание SQL", "tech")), ensure_ascii=False)
        ответ, _ = из_сырого(сырой, ОПИСАНИЕ, "м:1")
