def _ответ(*навыки, язык="ru"):
    """Ответ модели в её формате: короткие ключи, цитата первой."""
    return {
        "s": [{"q": цитата, "n": название, "k": вид, "c": 0.9, "p": None} for название, цитата, вид in навыки],
        "l": язык,
    }


ХОРОШИЙ = _ответ(("Zustand", "владение Zustand", "tech"), ("TanStack Query", "опыт с TanStack Query", "tech"), ("SQL", "знание SQL", "tech"))


