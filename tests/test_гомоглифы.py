"""
Латинские слова, испорченные кириллицей.

Зачем. Работодатель пишет «Exсel» с русской «с» — глазами не отличить,
поиском не найти. На живой базе так испорчены слова в 2 % описаний, и
среди них Excel, Word, Confluence, AutoCAD.

Починка опасна ровно тем, чем полезна: правило «в слове есть и латиница,
и кириллица» ломает русские слова, если применить его слишком широко.
Первая версия делила текст по пробелам — и «<p><strong>мы» превращалось
в «<p><strong>mы», потому что латинских букв из разметки было больше,
чем русских. Поэтому тесты ниже проверяют не только то, что чинится, но
и то, что остаётся нетронутым.
"""

from __future__ import annotations

import pytest

from src.normalize import без_гомоглифов


@pytest.mark.parametrize(
    "испорчено, ожидается",
    [
        ("знание exсel", "знание excel"),          # с — кириллическая
        ("wоrd и оutlook", "word и outlook"),      # о — кириллическая
        ("confluenсe", "confluence"),
        ("autoсad", "autocad"),
    ],
)
def test_вкрапление_чинится(испорчено: str, ожидается: str) -> None:
    assert без_гомоглифов(испорчено) == ожидается


@pytest.mark.parametrize(
    "текст",
    [
        "мы ищем дизайнера",                 # чистая кириллица
        "<p><strong>мы</strong> ищем",       # разметка рядом с русским словом
        "ux-метрики и smm-менеджер",         # законно смешанные термины
        "работа в 1с и битрикс24",           # цифры и кириллица
        "typography and layout",             # чистая латиница
        "опыт от 3 лет",
    ],
)
def test_остальное_не_трогается(текст: str) -> None:
    assert без_гомоглифов(текст) == текст


def test_пустой_текст() -> None:
    assert без_гомоглифов("") == ""
    assert без_гомоглифов(None) is None


def test_поиск_находит_испорченный_навык() -> None:
    """Ради чего всё: навык из испорченного слова доходит до находки."""
    from src.normalize import SkillDictionaries, find_skills

    словари = SkillDictionaries.from_config()
    все = list(словари.hard) + list(словари.soft) + list(словари.tools)

    испорченный = "требуется знание exсel на уровне сводных таблиц"
    assert not find_skills(испорченный, все)
    assert find_skills(без_гомоглифов(испорченный), все)
