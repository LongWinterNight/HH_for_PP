# Подставная модель: у текста столько «смыслов», сколько в нём слов из
# списка. «Питон» и «python» — один смысл: так проверяется, что поиск по
# смыслу находит то, чего по словам не найти.
СМЫСЛЫ = [
    ("python", "питон"), ("разработчик", "разработка", "сервис"), ("дизайнер", "дизайн"),
    ("интерьер",), ("баннер", "соцсеть", "социальный"), ("визуализатор", "визуализация", "рендер"),
]


def подставная_модель(тексты, запрос=False):
    векторы = []
    for текст in тексты:
        слова = set(привести(текст).split())
        вектор = np.array([float(any(с in слова for с in смысл)) for смысл in СМЫСЛЫ], dtype=np.float32)
        норма = np.linalg.norm(вектор)
        векторы.append(вектор / норма if норма else вектор)
    return np.vstack(векторы)


