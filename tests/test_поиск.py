class TestОпечаткиИРаскладка:

    @pytest.fixture
    def большой(self):
        """Словарю нужны частоты: слово, встреченное один раз, само может быть опечаткой."""
        соединение = sqlite3.connect(":memory:")
        документы = [собрать_документ(f"д{n}", "Дизайнер интерьеров", "Figma", "Дизайн квартир") for n in range(5)]
        документы += [собрать_документ(f"п{n}", "Архитектор-проектировщик", "Revit") for n in range(4)]
