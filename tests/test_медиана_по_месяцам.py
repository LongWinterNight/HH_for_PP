"""
Помесячная медиана зарплаты.

Недельная линия шумная — по ней не виден тренд; месяц для зарплат
естественный шаг. Считается медиана, а не средняя: сюда перенесена
проверка из E3, где недельный ряд считался средней и одна дорогая
вакансия поднимала линию, показывая рост, которого не было.

Проверяется и то, что ряд подчиняется правилам, записанным раньше:
не-месячная оплата в него не входит (правило Л), сомнительные суммы
исключены (правило E8), месяц с выборкой меньше MIN_SAMPLE отдаётся
разрывом, а не точкой.

Запуск: pytest tests/test_медиана_по_месяцам.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from web.app.main import MIN_SAMPLE, медиана_по_месяцам


def месяц_назад(n: int) -> pd.Timestamp:
    """Первое число месяца n месяцев назад — тест не зависит от календаря."""
    return pd.Timestamp.now().normalize().replace(day=1) - pd.DateOffset(months=n)


def строки(суммы, месяцев_назад: int = 1, **поля) -> list:
    дата = месяц_назад(месяцев_назад) + pd.Timedelta(days=5)
    return [
        {"published_at": дата.isoformat(), "salary_from": сумма,
         "salary_currency": "RUB", "salary_mode": None, **поля}
        for сумма in суммы
    ]


def точка(ряд, месяцев_назад: int):
    искомый = str(месяц_назад(месяцев_назад).to_period("M"))
    return next(т for т in ряд if т["month"] == искомый)


class TestРасчёт:
    def test_медиана_устойчива_к_выбросу(self):
        """Ради этого свойства средняя и заменена медианой.

        Одна вакансия на 800 000 среди шести обычных сдвинула бы среднюю
        почти вдвое, а медиану не двигает вовсе.
        """
        обычные = [80000, 85000, 90000, 95000, 100000, 105000]
        df = pd.DataFrame(строки(обычные))
        с_выбросом = pd.DataFrame(строки(обычные + [800000]))

        было = точка(медиана_по_месяцам(df, "salary_from"), 1)["median"]
        стало = точка(медиана_по_месяцам(с_выбросом, "salary_from"), 1)["median"]

        assert было == 92500
        assert стало == 95000, "медиана сдвинулась на один шаг выборки"
        # Средняя на тех же данных уехала бы со 92 500 до 193 571.
        assert pd.Series(обычные + [800000]).mean() > 190000

    def test_месяц_с_малой_выборкой_отдаётся_разрывом(self):
        """Медиана по трём вакансиям выглядит так же уверенно, как по
        восьмидесяти, — поэтому её нет вовсе, но объём назван."""
        df = pd.DataFrame(строки([80000, 90000, 100000]))

        т = точка(медиана_по_месяцам(df, "salary_from"), 1)

        assert т["median"] is None
        assert т["sample"] == 3
        assert т["sample"] < MIN_SAMPLE

    def test_ось_непрерывна_и_кончается_текущим_месяцем(self):
        df = pd.DataFrame(строки([80000] * 6, месяцев_назад=3))

        ряд = медиана_по_месяцам(df, "salary_from", месяцев=12)

        assert len(ряд) == 12
        assert ряд[-1]["month"] == str(pd.Timestamp.now().to_period("M"))
        assert точка(ряд, 3)["median"] == 80000
        # Месяцы без вакансий — пустые точки с нулевым объёмом, а не
        # пропуски: пропуск сжал бы ось.
        assert точка(ряд, 2)["median"] is None and точка(ряд, 2)["sample"] == 0

    def test_ряд_считается_по_переданной_колонке(self):
        """Рублёвый вид берёт эквивалент, валютный — исходную сумму."""
        df = pd.DataFrame(строки([80000] * 6))
        df["salary_from_rub"] = 40000.0

        в_валюте = точка(медиана_по_месяцам(df, "salary_from"), 1)["median"]
        в_рублях = точка(медиана_по_месяцам(df, "salary_from_rub"), 1)["median"]

        assert в_валюте == 80000
        assert в_рублях == 40000


class TestПравилаВыборки:
    """Ряд строится по тем же правилам, что и остальные зарплатные числа."""

    def test_часовая_ставка_в_ряд_не_входит(self):
        """Правило Л: «1 000 ₽ за час» — честная ставка, но в медиане
        месячных окладов ей делать нечего."""
        from src.salary_sanity import только_правдоподобные

        месячные = строки([80000, 85000, 90000, 95000, 100000, 105000])
        часовые = строки([1000, 1200], salary_mode="HOUR")
        df = pd.DataFrame(месячные + часовые)

        т = точка(медиана_по_месяцам(только_правдоподобные(df), "salary_from"), 1)

        assert т["sample"] == 6, "часовые ставки отсеяны"
        assert т["median"] == 92500

    def test_сомнительная_сумма_в_ряд_не_входит(self):
        """Правило E8: «50 ₽» в месяц — опечатка работодателя."""
        from src.salary_sanity import только_правдоподобные

        df = pd.DataFrame(
            строки([80000, 85000, 90000, 95000, 100000, 105000]) + строки([50])
        )

        т = точка(медиана_по_месяцам(только_правдоподобные(df), "salary_from"), 1)

        assert т["sample"] == 6
        assert т["median"] == 92500
