"""
Период выплаты: разбор, влияние на правило E8 и на агрегаты.

Случай, ради которого это писалось, стоит первым: вакансия
«Full-stack Developer — React / Golang / AI» с оплатой 1 000 ₽ за час
получала красную пометку «числу нельзя верить: слишком мало для месячной
оплаты». Число было верным — врала наша подпись.
"""

from __future__ import annotations

import pandas as pd
import pytest

from src.salary_mode import ЧАС, МЕСЯЦ, СМЕНА, период_из_ответа, подпись, это_месячная
from src.salary_sanity import МАЛО, только_правдоподобные, причина_сомнения


def test_период_из_ответа_источника():
    """Так поле приходит на самом деле — снято с вакансии 137123948."""
    вакансия = {
        "salary": {"from": 1000, "to": None, "currency": "RUR", "gross": True},
        "salary_range": {
            "from": 1000, "to": None, "currency": "RUR", "gross": True,
            "mode": {"id": "HOUR", "name": "За час"},
            "frequency": {"id": "WEEKLY", "name": "Раз в неделю"},
        },
    }
    assert период_из_ответа(вакансия) == ЧАС


def test_нет_поля_нет_периода():
    """
    Старое поле `salary` периода не содержит — и выдумывать месяц нельзя.

    Именно на этой выдумке считались бы медианы: «месяц по умолчанию»
    выглядит безобидно, пока не окажется, что треть дешёвых записей —
    часовые ставки.
    """
    assert период_из_ответа({"salary": {"from": 1000, "currency": "RUR"}}) is None
    assert период_из_ответа({"salary_range": None}) is None
    assert период_из_ответа({}) is None


def test_незнакомое_значение_отбрасывается():
    """Справочник может пополниться — чужой код мы не храним как свой."""
    вакансия = {"salary_range": {"mode": {"id": "PER_LUNAR_MONTH", "name": "За лунный месяц"}}}
    assert период_из_ответа(вакансия) is None


def test_подпись_совпадает_с_источником():
    """Расхождение с hh.ru читается как ошибка продукта, даже если число верное."""
    assert подпись(ЧАС) == "за час"
    assert подпись(СМЕНА) == "за смену"
    # Месячная не подписывается: она подразумевается, и «за месяц» в
    # каждой строке было бы шумом.
    assert подпись(МЕСЯЦ) == "за месяц"
    assert подпись(None) is None


def test_часовая_ставка_больше_не_сомнительна():
    """Тот самый случай со скриншота: 1 000 ₽ за час — честная ставка."""
    assert причина_сомнения(1000, None, "RUB", ЧАС) is None
    assert причина_сомнения(18, 18, "EUR", ЧАС) is None
    assert причина_сомнения(8, 16, "USD", ЧАС) is None


def test_месячная_опечатка_по_прежнему_помечена():
    """400 сум в месяц — настоящая опечатка, и правило обязано её ловить."""
    assert причина_сомнения(400, None, "UZS", МЕСЯЦ) == МАЛО
    # Период неизвестен — правило работает по величине, как раньше:
    # большинство вакансий месячные, и молчать здесь опаснее.
    assert причина_сомнения(400, None, "UZS", None) == МАЛО


def test_не_месячные_не_идут_в_агрегаты():
    """
    Час и месяц не складываются — по той же причине, что рубли и тенге.

    Даже правдоподобной часовой ставке нечего делать в медиане месячных
    окладов: это разные величины, а не разные значения одной.
    """
    df = pd.DataFrame([
        {"salary_from": 120_000, "salary_to": None, "salary_currency": "RUB",
         "salary_doubt": None, "salary_mode": МЕСЯЦ},
        {"salary_from": 1_000, "salary_to": None, "salary_currency": "RUB",
         "salary_doubt": None, "salary_mode": ЧАС},
        {"salary_from": 90_000, "salary_to": None, "salary_currency": "RUB",
         "salary_doubt": None, "salary_mode": None},
    ])
    в_расчёте = только_правдоподобные(df)

    assert sorted(в_расчёте["salary_from"]) == [90_000, 120_000]
    # Медиана без часовой ставки описывает месячный рынок, а не смесь.
    assert в_расчёте["salary_from"].median() == 105_000


def test_неизвестный_период_считается_месячным():
    """
    Осознанное допущение, а не недосмотр.

    Выкинуть из статистики всё, что собрано до появления колонки, значило
    бы обрушить выборку с восьми тысяч записей до сотен. Риск обратный —
    несколько часовых ставок среди месячных — гасится правилом
    правдоподобия.
    """
    assert это_месячная(None) is True
    assert это_месячная(МЕСЯЦ) is True
    assert это_месячная(ЧАС) is False


def test_период_доезжает_до_базы(tmp_path):
    """Поле должно пройти весь путь: нормализация → запись → чтение."""
    from src.storage import VacancyStorage

    хранилище = VacancyStorage(tmp_path / "проба.db")
    try:
        хранилище.save_vacancies_incremental(pd.DataFrame([
            {"vacancy_id": "1", "vacancy_name": "Часовая",
             "salary_from": 1000, "salary_to": None, "salary_currency": "RUB",
             "salary_mode": ЧАС},
            {"vacancy_id": "2", "vacancy_name": "Без периода",
             "salary_from": 90_000, "salary_to": None, "salary_currency": "RUB"},
        ]))
        по_ид = хранилище.get_all_vacancies().set_index("vacancy_id")

        assert по_ид.loc["1", "salary_mode"] == ЧАС
        assert pd.isna(по_ид.loc["1", "salary_doubt"]), "часовая ставка не сомнительна"
        assert pd.isna(по_ид.loc["2", "salary_mode"]), "выдуманный период хуже пустого"
    finally:
        хранилище.close()
