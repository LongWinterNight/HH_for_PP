"""
Тексты описаний: хранение, дедупликация, отпечаток.

Проверяется то, ради чего S13 делалась: текст можно записать и прочитать
без обращения к источнику, один текст хранится один раз, а похожие
описания узнаются по отпечатку.

Отдельно проверяется, что отпечаток различает вакансии. Первая его
версия голосовала отдельными словами и на живых описаниях почти не
работала: разные вакансии сходились до шести бит из шестидесяти
четырёх, потому что «требования», «опыт» и «оформление по ТК» есть
везде. Тест на разделение стоит здесь именно поэтому.
"""

from __future__ import annotations

import pytest

from src.texts import (
    ПОХОЖИ_ДО,
    отпечаток,
    подготовить,
    разжать,
    расстояние,
    сжать,
    хэш,
)

ОПИСАНИЕ = (
    "<p><strong>Обязанности:</strong> проектировать интерфейсы, вести дизайн-систему, "
    "готовить макеты к передаче в разработку.</p>"
    "<p><strong>Требования:</strong> уверенное владение Figma, понимание типографики "
    "и композиции, опыт продуктовой работы от трёх лет.</p>"
)

ПЕРЕПЕЧАТКА = ОПИСАНИЕ.replace("от трёх лет", "от двух лет").replace(
    "вести дизайн-систему", "поддерживать дизайн-систему"
)

ЧУЖАЯ = (
    "<p><strong>Обязанности:</strong> приём товара на склад, комплектация заказов, "
    "работа с терминалом сбора данных.</p>"
    "<p><strong>Требования:</strong> внимательность, готовность к сменному графику, "
    "опыт работы на складе приветствуется.</p>"
)


class TestХранение:

    def test_текст_возвращается_как_был(self):
        assert разжать(сжать(ОПИСАНИЕ)) == ОПИСАНИЕ

    def test_сжатие_экономит_место(self):
        """Замер на живых описаниях: вчетверо. На коротком тексте меньше."""
        assert len(сжать(ОПИСАНИЕ)) < len(ОПИСАНИЕ.encode("utf-8"))

    def test_разметка_переживает_хранение(self):
        """
        HTML хранится как есть: по тегам разбираются секции описания.

        Очищенный текст был бы на 5 % компактнее после сжатия — и
        непригоден для переразбора секций, из-за которых «Подарки» и
        ушли из топа навыков.
        """
        assert "<strong>" in разжать(сжать(ОПИСАНИЕ))

    def test_один_текст_один_хэш(self):
        assert хэш(ОПИСАНИЕ) == хэш(ОПИСАНИЕ)
        assert хэш(ОПИСАНИЕ) != хэш(ЧУЖАЯ)

    def test_пустое_описание_не_записывается(self):
        """Вакансия без описания — обычное дело, пустая запись ей не нужна."""
        assert подготовить("") is None
        assert подготовить("   ") is None
        assert подготовить(None) is None

    def test_подготовленное_несёт_всё_нужное(self):
        х, тело, отп, размер = подготовить(ОПИСАНИЕ)
        assert х == хэш(ОПИСАНИЕ)
        assert разжать(тело) == ОПИСАНИЕ
        assert отп > 0
        assert размер == len(ОПИСАНИЕ.encode("utf-8"))


class TestОтпечаток:

    def test_похожие_описания_рядом(self):
        расхождение = расстояние(отпечаток(ОПИСАНИЕ), отпечаток(ПЕРЕПЕЧАТКА))
        assert расхождение <= ПОХОЖИ_ДО, (
            f"перепечатка разошлась на {расхождение} бит — она не будет узнана"
        )

    def test_разные_вакансии_далеко(self):
        расхождение = расстояние(отпечаток(ОПИСАНИЕ), отпечаток(ЧУЖАЯ))
        assert расхождение > ПОХОЖИ_ДО, (
            f"дизайнер и кладовщик сошлись на {расхождение} бит — их сольют в одну"
        )

    def test_один_и_тот_же_текст_даёт_один_отпечаток(self):
        assert отпечаток(ОПИСАНИЕ) == отпечаток(ОПИСАНИЕ)

    def test_разметка_не_влияет(self):
        """Теги одинаковы у всех вакансий источника и только размывают отпечаток."""
        без_тегов = ОПИСАНИЕ.replace("<p>", "").replace("</p>", "")
        без_тегов = без_тегов.replace("<strong>", "").replace("</strong>", "")
        assert отпечаток(ОПИСАНИЕ) == отпечаток(без_тегов)

    def test_пустой_текст_без_отпечатка(self):
        assert отпечаток("") == 0

    def test_расстояние_симметрично(self):
        а, б = отпечаток(ОПИСАНИЕ), отпечаток(ЧУЖАЯ)
        assert расстояние(а, б) == расстояние(б, а)
        assert расстояние(а, а) == 0


class TestОтпечатокВБазе:
    """
    Отпечаток обязан пережить запись в базу.

    Сбор падал шесть раз подряд с «Python int too large to convert to
    SQLite INTEGER»: отпечаток беззнаковый, поле базы знаковое, и число
    со старшим битом в него не помещается. Таких — половина. Тесты выше
    этого не видели, потому что ни один из них не писал в базу: счёт
    отпечатка проверялся, а его хранение — нет.
    """

    @pytest.fixture
    def storage(self, tmp_path):
        from src.storage import VacancyStorage

        store = VacancyStorage(db_path=tmp_path / "test.db")
        yield store
        store.close()

    @staticmethod
    def _описание_со_старшим_битом() -> str:
        """Текст, чей отпечаток не помещается в знаковое поле."""
        for номер in range(200):
            текст = f"<p>Требования к кандидату номер {номер}: опыт работы и внимательность.</p>"
            if отпечаток(текст) >= 2 ** 63:
                return текст
        raise AssertionError("не нашлось описания со старшим битом — проверка ничего не проверяет")

    def test_знаковый_вид_обратим(self):
        from src.texts import в_поле, из_поля

        for число in (0, 1, 2 ** 63 - 1, 2 ** 63, 2 ** 64 - 1):
            assert -(2 ** 63) <= в_поле(число) < 2 ** 63
            assert из_поля(в_поле(число)) == число

    def test_расстояние_не_зависит_от_вида(self):
        from src.texts import в_поле

        а, б = отпечаток(ОПИСАНИЕ), отпечаток(self._описание_со_старшим_битом())
        assert расстояние(в_поле(а), в_поле(б)) == расстояние(а, б)
        assert расстояние(в_поле(б), б) == 0

    def test_отпечаток_со_старшим_битом_записывается(self, storage):
        import pandas as pd
        from src.texts import из_поля

        текст = self._описание_со_старшим_битом()
        итог = storage.сохранить_тексты(pd.DataFrame([{"_описание": текст}]))
        assert итог["новых"] == 1

        with storage.engine.begin() as conn:
            в_базе = conn.exec_driver_sql("SELECT simhash FROM vacancy_texts").fetchone()[0]
        assert из_поля(в_базе) == отпечаток(текст)
        assert storage.читать_текст(хэш(текст)) == текст

    def test_отказ_текстов_не_стоит_вакансий(self, storage, monkeypatch):
        """
        Шесть сборов дошли до 98 % и не сохранили ничего: отказ записи
        текстов отменял запись вакансий. Вторичное не отменяет главное.
        """
        import pandas as pd

        def упасть(df):
            raise OverflowError("Python int too large to convert to SQLite INTEGER")

        monkeypatch.setattr(storage, "сохранить_тексты", упасть)

        итог = storage.save_vacancies_incremental(pd.DataFrame([{
            "vacancy_id": "1", "vacancy_name": "Дизайнер",
            "_описание": ОПИСАНИЕ, "text_hash": хэш(ОПИСАНИЕ),
        }]))

        assert итог["inserted"] == 1
        assert "OverflowError" in storage.отказ_текстов
        with storage.engine.begin() as conn:
            ссылка = conn.exec_driver_sql("SELECT text_hash FROM vacancies").fetchone()[0]
        assert ссылка is None, "вакансия ссылается на текст, которого нет"

    def test_удачная_запись_снимает_прежний_отказ(self, storage):
        import pandas as pd

        storage.отказ_текстов = "было"
        storage.save_vacancies_incremental(pd.DataFrame([{
            "vacancy_id": "1", "vacancy_name": "Дизайнер",
            "_описание": ОПИСАНИЕ, "text_hash": хэш(ОПИСАНИЕ),
        }]))
        assert storage.отказ_текстов is None
