"""
Скорость извлечения навыков (S3).

Зачем тест на скорость. Словарь применяется к каждой вакансии, и его
рост незаметно превращается в часы: 1079 навыков × 8700 вакансий — это
десять миллионов сопоставлений на один пересчёт базы. Замер здесь
служит сторожем: он не требует рекордов, но ловит момент, когда разбор
одной вакансии становится дороже порога.

Порог намеренно щедрый — в несколько раз выше замеренного. Тест о
скорости, привязанный к точному числу, начинает падать от загрузки
машины, а не от кода, и его отключают вместе с пользой.
"""

import sys
import time
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.normalize import SkillDictionaries, find_skills  # noqa: E402

# Сколько миллисекунд на вакансию считается приемлемым.
#
# Замер на живых описаниях (1079 навыков, 2 260 символов, 09.09.2026):
# 6,8 мс до отсева по словам и 3,5 мс после. Порог втрое выше верхней
# границы — тест должен ловить порядок величины, а не шум загруженной
# машины. Он сторожит от того, чтобы разбор снова стал часами.
ПОРОГ_МС = 20

# Описание вакансии обычного размера: примерно то, что отдаёт источник.
ОПИСАНИЕ = """
Мы ищем инженера в команду разработки. Обязанности: проектирование и
развитие сервисов на Python, работа с PostgreSQL и Redis, покрытие кода
тестами, участие в код-ревью. Требования: опыт коммерческой разработки
от трёх лет, уверенное знание SQL, понимание принципов REST API, опыт
работы с Docker и CI/CD. Будет плюсом: Kubernetes, Kafka, опыт с
очередями сообщений, знание Go или TypeScript. Мы предлагаем:
оформление по ТК РФ, гибкий график, ДМС после испытательного срока,
компенсацию обучения, современное оборудование и дружную команду.
Работа с большими объёмами данных, аналитическое мышление,
коммуникативные навыки, умение работать в команде и самостоятельность.
""".lower() * 2


@pytest.fixture(scope="module")
def словари():
    return SkillDictionaries.from_config()


def замер(словари, повторов=20):
    """Среднее время разбора одной вакансии в миллисекундах."""
    все = словари.hard + словари.soft + словари.tools

    # Один прогон вхолостую: первый вызов платит за прогрев кэшей.
    find_skills(ОПИСАНИЕ, все)

    начало = time.perf_counter()
    for _ in range(повторов):
        find_skills(ОПИСАНИЕ, все)
    прошло = time.perf_counter() - начало

    return прошло / повторов * 1000


class TestСкорость:

    def test_разбор_вакансии_укладывается_в_порог(self, словари):
        мс = замер(словари)

        assert мс < ПОРОГ_МС, (
            f"Разбор одной вакансии занял {мс:.1f} мс при пороге {ПОРОГ_МС}. "
            f"Навыков в словаре: "
            f"{len(словари.hard) + len(словари.soft) + len(словари.tools)}."
        )

    def test_словарь_не_пуст(self, словари):
        # Замер скорости на пустом словаре всегда успешен и всегда бесполезен.
        assert len(словари.hard) > 100
