"""
Ограничение неудачных попыток входа.

Порт стенда открыт в интернет, и его находят за минуты: в журнале первого
же запуска — шесть чужих адресов, перебиравших пути. Пароль из двадцати
случайных знаков перебором не взять, но попытки не должны быть
бесконечными — и честный человек при этом не должен закрываться на
первой же странице.
"""

from __future__ import annotations

from web.app.main import ЗАКРЫТЬ_НА_СЕК, ОКНО_ПОПЫТОК_СЕК, ПОПЫТОК_ВХОДА, СчётчикНеудач


class TestСчётчикНеудач:

    def test_до_предела_адрес_открыт(self):
        счётчик = СчётчикНеудач()
        for n in range(ПОПЫТОК_ВХОДА - 1):
            assert счётчик.неудача("1.2.3.4", float(n)) is False
        assert счётчик.закрыт("1.2.3.4", 100.0) == 0

    def test_предел_закрывает_адрес_на_срок(self):
        счётчик = СчётчикНеудач()
        исходы = [счётчик.неудача("1.2.3.4", float(n)) for n in range(ПОПЫТОК_ВХОДА)]
        assert исходы[-1] is True and not any(исходы[:-1])

        последняя = float(ПОПЫТОК_ВХОДА - 1)
        assert счётчик.закрыт("1.2.3.4", последняя + 1) > 0
        assert счётчик.закрыт("1.2.3.4", последняя + ЗАКРЫТЬ_НА_СЕК + 1) == 0

    def test_чужие_неудачи_не_закрывают_соседа(self):
        счётчик = СчётчикНеудач()
        for n in range(ПОПЫТОК_ВХОДА):
            счётчик.неудача("1.2.3.4", float(n))
        assert счётчик.закрыт("5.6.7.8", 20.0) == 0

    def test_старые_неудачи_не_копятся(self):
        """Девять ошибок сегодня и одна завтра — не десять подряд."""
        счётчик = СчётчикНеудач()
        for n in range(ПОПЫТОК_ВХОДА - 1):
            счётчик.неудача("1.2.3.4", float(n))
        assert счётчик.неудача("1.2.3.4", ОКНО_ПОПЫТОК_СЕК + 100.0) is False

    def test_удачный_вход_обнуляет_счёт(self):
        счётчик = СчётчикНеудач()
        for n in range(ПОПЫТОК_ВХОДА - 1):
            счётчик.неудача("1.2.3.4", float(n))
        счётчик.успех("1.2.3.4")
        assert счётчик.неудача("1.2.3.4", 50.0) is False

    def test_число_адресов_ограничено(self):
        """Иначе сам счётчик стал бы способом занять память."""
        счётчик = СчётчикНеудач()
        счётчик.ПРЕДЕЛ_АДРЕСОВ = 5
        for n in range(20):
            счётчик.неудача(f"10.0.0.{n}", float(n))
        assert len(счётчик._неудачи) <= 5
