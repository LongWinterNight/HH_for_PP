"""
Разделы описания вакансии.

Навыки искались по всему тексту, и в статистику попадало содержимое
раздела «Условия»: «Подарки» у 70 вакансий дошли до топ‑10 навыков на
дашборде — корпоративные подарки, засчитанные как профессиональный
навык.

Правило отбора двухступенчатое, и тест закрепляет обе ступени: знакомый
раздел решается по заголовку, авторский — по содержимому. Плюс главное
свойство: вакансия, у которой всё отсеялось, не остаётся без навыков
вовсе.

Запуск: pytest tests/test_разделы_описания.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from src.sections import (
    похоже_на_условия,
    разделы,
    текст_для_навыков,
)


def описание(*пары: tuple) -> str:
    """Описание из пар «заголовок, текст» в разметке hh."""
    return "".join(f"<p><strong>{з}</strong></p><p>{т}</p>" for з, т in пары)


class TestРазбор:
    def test_описание_делится_по_подзаголовкам(self):
        куски = разделы(описание(
            ("Требования", "Опыт с Python"),
            ("Условия", "ДМС и печеньки"),
        ))

        # Пустой первый кусок отсутствует: между тегами нет ни одного
        # слова, и разметка за содержимое не считается.
        assert [з for з, _ in куски] == ["требования", "условия"]

    def test_вводная_часть_не_теряется(self):
        """Текст до первого заголовка — тоже текст вакансии."""
        куски = разделы("<p>Мы ищем разработчика на Go</p>" + описание(("Требования", "Опыт")))

        assert куски[0][0] == ""
        assert "Go" in куски[0][1]

    def test_выделенное_предложение_не_считается_заголовком(self):
        """Иначе разделом станет каждая фраза, выделенная полужирным."""
        текст = ("<p><strong>Мы ищем именно вас, если вы готовы работать "
                 "в команде и учиться новому</strong></p><p>Опыт с Python</p>")

        assert [з for з, _ in разделы(текст)] == [""]


class TestОтборПоЗаголовку:
    def test_условия_в_разбор_не_идут(self):
        текст = текст_для_навыков(описание(
            ("Требования", "Опыт с Python"),
            ("Условия", "Подарки на праздники, ДМС, корпоративы"),
        ))

        assert "Python" in текст
        assert "Подарки" not in текст

    def test_знакомый_раздел_берётся_даже_с_маркерами_условий(self):
        """«Опыт работы с ДМС» у кадровика — это навык, а не соцпакет."""
        текст = текст_для_навыков(описание(
            ("Обязанности", "Оформление ДМС, больничные, оклад сотрудников"),
        ))

        assert "ДМС" in текст

    def test_команда_считается_полезным_разделом(self):
        """Там часто перечисляют стек, а не рассказывают о компании."""
        текст = текст_для_навыков(описание(
            ("Команда", "Работаем со стеком: ClickHouse, RabbitMQ"),
            ("Условия", "ДМС"),
        ))

        assert "ClickHouse" in текст


class TestОтборПоСодержимому:
    def test_авторский_заголовок_с_плюшками_отсекается(self):
        """«Праздничные сюрпризы» в чёрный список не впишешь."""
        текст = текст_для_навыков(описание(
            ("Требования", "Опыт с Python"),
            ("Праздничные сюрпризы", "Подготовим приятные подарки на праздники"),
        ))

        assert "Python" in текст
        assert "подарки" not in текст.lower()

    def test_авторский_заголовок_без_плюшек_остаётся(self):
        текст = текст_для_навыков(описание(
            ("Требования", "Опыт с Python"),
            ("О проекте", "Пишем на Go, храним в PostgreSQL"),
        ))

        assert "Go" in текст and "PostgreSQL" in текст

    def test_маркеры_узкие(self):
        """«Зарплата» и «питание» — предмет работы бухгалтера и повара."""
        assert not похоже_на_условия("Расчёт зарплаты и отчётность")
        assert not похоже_на_условия("Организация питания в столовой")
        assert похоже_на_условия("ДМС после испытательного срока")


class TestНичегоНеТеряется:
    def test_описание_без_заголовков_разбирается_целиком(self):
        """У 5 % описаний структуры нет вовсе."""
        текст = "Требуется разработчик Python с опытом Django"

        assert текст_для_навыков(текст) == текст

    def test_описание_из_одних_условий_разбирается_целиком(self):
        """Пустой текст означал бы, что вакансия лишилась навыков молча."""
        исходное = описание(("Условия", "ДМС, оклад, корпоративы"))

        assert текст_для_навыков(исходное) == исходное

    def test_пустое_описание_не_роняет_разбор(self):
        assert текст_для_навыков("") == ""
        assert текст_для_навыков(None) == ""
