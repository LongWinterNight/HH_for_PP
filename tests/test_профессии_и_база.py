"""
Соответствие справочника профессий текущей базе.

Справочник перечисляет профессии рынка, база наполняется сборами по
конкретным запросам, и расходятся они молча. Число рядом с профессией
читалось из файла и описывало прошлый сбор: человек видел «3 вакансии»,
открывал профессию и попадал в пустоту.

Теперь число считается по базе. Тест закрепляет правило сопоставления —
оно единственное, что стоит между «нашли профессию» и «показали чужие
вакансии».

Запуск: pytest tests/test_профессии_и_база.py -v
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from web.app.main import _счёт_вакансий_по_профессиям


def профессия(имя: str) -> dict:
    return {"key": f"IT|Разное|{имя}", "name": имя}


def вакансии(*названия: str) -> pd.DataFrame:
    return pd.DataFrame({"vacancy_name": list(названия)})


def счёт(имя: str, *названия: str) -> int:
    п = профессия(имя)
    return _счёт_вакансий_по_профессиям(вакансии(*названия), [п])[п["key"]]


class TestСопоставление:
    def test_находит_профессию_в_названии_вакансии(self):
        assert счёт("Рекрутер", "Рекрутер в IT-компанию", "Аналитик данных") == 1

    def test_учитывает_словоформы(self):
        """«Менеджеров» и «Аналитики» — те же профессии, а не другие."""
        assert счёт("Менеджер", "Ищем менеджеров по продажам") == 1
        assert счёт("Аналитик", "Аналитики данных, двое") == 1

    def test_не_лезет_внутрь_чужих_слов(self):
        """Ровно та ошибка, ради которой правило и появилось: «Логист»
        находился внутри «Логистика», «IT» — внутри «Retail»."""
        assert счёт("Логист", "Специалист по логистике") == 0
        assert счёт("IT", "Retail-менеджер", "Digital-маркетолог") == 0

    def test_длинное_окончание_не_проходит(self):
        """Две буквы — предел: иначе «Логист» снова поймает «Логистика»."""
        assert счёт("Логист", "Логиста ищем") == 1      # +1 буква
        assert счёт("Логист", "Логистов ищем") == 1     # +2 буквы
        assert счёт("Логист", "Логистами усилим") == 0  # +3 — уже нет
        assert счёт("Логист", "Логистическая компания") == 0

    def test_регистр_не_важен(self):
        assert счёт("Рекрутер", "РЕКРУТЕР В КОМАНДУ") == 1

    def test_профессия_без_вакансий_даёт_ноль(self):
        """Ноль — то, что покажет экран пометкой «не собирали»."""
        assert счёт("Космонавт", "Рекрутер", "Аналитик") == 0

    def test_пустая_база_не_роняет_расчёт(self):
        п = профессия("Рекрутер")
        пусто = pd.DataFrame({"vacancy_name": []})

        assert _счёт_вакансий_по_профессиям(пусто, [п])[п["key"]] == 0

    def test_профессия_без_названия_не_роняет_расчёт(self):
        битая = {"key": "битая", "name": ""}

        assert _счёт_вакансий_по_профессиям(вакансии("Рекрутер"), [битая])["битая"] == 0


class TestСписокОстаётсяПолным:
    """Решение E9-2a: раздел — навигатор по направлениям, а не оглавление базы."""

    def test_пустые_профессии_считаются_но_не_исчезают(self):
        профессии = [профессия("Рекрутер"), профессия("Космонавт")]

        счёт_всех = _счёт_вакансий_по_профессиям(вакансии("Рекрутер в IT"), профессии)

        assert len(счёт_всех) == 2, "обе профессии остались в результате"
        assert счёт_всех[профессии[0]["key"]] == 1
        assert счёт_всех[профессии[1]["key"]] == 0
