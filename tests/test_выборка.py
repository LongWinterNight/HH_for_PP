"""
Отбор вакансий по фильтрам: список и отчёт считают одно и то же.

Главная проверка здесь — последняя: экран и файл отбирают одной
функцией, и число строк у них совпадает. Пока отчёт собирался по всей
базе, человек настраивал фильтры, нажимал «Собрать отчёт» и получал
файл про другое; расхождение было незаметным, потому что обе стороны
показывали правдоподобные числа.
"""

from __future__ import annotations

import pandas as pd
import pytest

from src.выборка import Фильтры, отобрать, словами

ВЫБОРКА = pd.DataFrame([
    {
        "vacancy_id": "1", "vacancy_name": "UX/UI дизайнер", "area": "Москва",
        "experience": "От 1 года до 3 лет", "hard_skills": "figma, типографика",
        "tools": "", "soft_skills": "", "salary_from": 150000,
        "salary_currency": "RUB", "source": "hh.ru",
    },
    {
        "vacancy_id": "2", "vacancy_name": "Графический дизайнер", "area": "Казань",
        "experience": "Нет опыта", "hard_skills": "photoshop",
        "tools": "figma", "soft_skills": "", "salary_from": None,
        "salary_currency": "RUB", "source": "hh.ru",
    },
    {
        "vacancy_id": "3", "vacancy_name": "Python разработчик", "area": "Москва",
        "experience": "От 3 до 6 лет", "hard_skills": "python, django",
        "tools": "", "soft_skills": "", "salary_from": 300000,
        "salary_currency": "RUB", "source": "hh.ru",
    },
])


class TestОтбор:

    def test_без_фильтров_ничего_не_теряется(self):
        assert len(отобрать(ВЫБОРКА, Фильтры())) == 3

    def test_поиск_по_названию(self):
        итог = отобрать(ВЫБОРКА, Фильтры(поиск="дизайнер"))
        assert list(итог["vacancy_id"]) == ["1", "2"]

    def test_регион(self):
        итог = отобрать(ВЫБОРКА, Фильтры(регион="Москва"))
        assert list(итог["vacancy_id"]) == ["1", "3"]

    def test_опыт_совпадает_точно(self):
        """Значения опыта приходят от источника — частичное совпадение врало бы."""
        assert len(отобрать(ВЫБОРКА, Фильтры(опыт="Нет опыта"))) == 1
        assert len(отобрать(ВЫБОРКА, Фильтры(опыт="Нет"))) == 0

    def test_навык_ищется_во_всех_трёх_колонках(self):
        """
        Человек не обязан знать, куда продукт положил «Figma».

        У первой вакансии она в жёстких навыках, у второй — в
        инструментах. Фильтр по одной колонке потерял бы половину.
        """
        итог = отобрать(ВЫБОРКА, Фильтры(навык="figma"))
        assert list(итог["vacancy_id"]) == ["1", "2"]

    def test_только_с_зарплатой(self):
        итог = отобрать(ВЫБОРКА, Фильтры(только_с_зарплатой=True))
        assert list(итог["vacancy_id"]) == ["1", "3"]

    def test_условия_складываются(self):
        итог = отобрать(ВЫБОРКА, Фильтры(регион="Москва", навык="figma"))
        assert list(итог["vacancy_id"]) == ["1"]

    def test_пустая_выборка_не_ломается(self):
        пусто = pd.DataFrame(columns=ВЫБОРКА.columns)
        assert отобрать(пусто, Фильтры(поиск="что угодно")).empty


class TestОписаниеСловами:
    """Лист «Срез» читает тот, кто экрана не видел."""

    def test_без_фильтров(self):
        assert "вся база" in словами(Фильтры())

    def test_перечисляет_применённое(self):
        текст = словами(Фильтры(поиск="дизайнер", регион="Москва", навык="figma"))
        assert "дизайнер" in текст and "Москва" in текст and "figma" in текст

    def test_состояние_названо(self):
        assert "активные вакансии" in словами(Фильтры())
        assert "включая снятые" in словами(Фильтры(включая_снятые=True))

    def test_число_вакансий_добавляется(self):
        assert "17 вакансий" in словами(Фильтры(регион="Москва"), всего=17)


def test_список_и_отчёт_считают_одинаково(tmp_path, monkeypatch):
    """
    C7‑1c: числа сходятся.

    Проверяется не сама функция отбора, а то, что её зовут обе стороны:
    экран списка и сборка отчёта. Тест берёт настоящий эндпоинт списка и
    настоящую подготовку отчёта с одинаковыми фильтрами и сравнивает
    числа. Заведи кто-нибудь вторую копию условий — расхождение всплывёт
    здесь, а не в файле у получателя.
    """
    import src.storage as storage_module
    from src.storage import VacancyStorage
    from web.app.main import get_vacancies

    # Своя база на время теста: рабочую трогать нельзя.
    monkeypatch.setattr(storage_module.settings, "db_path", tmp_path / "тест.db")
    хранилище = VacancyStorage()
    try:
        хранилище.replace_all_vacancies(ВЫБОРКА.copy())
    finally:
        хранилище.close()

    условия = dict(area="Москва", skill="figma")

    ответ_списка = get_vacancies(per_page=100, **условия)

    хранилище = VacancyStorage()
    try:
        для_отчёта = отобрать(
            хранилище.get_all_vacancies(),
            Фильтры(регион=условия["area"], навык=условия["skill"]),
        )
    finally:
        хранилище.close()

    assert ответ_списка["total"] == len(для_отчёта)
    assert ответ_списка["total"] == 1, "фильтр должен сузить выборку, иначе тест ничего не проверяет"
