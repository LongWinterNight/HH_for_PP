"""
География зарплат: страны, регионы и города.

Окно «Медиана по регионам» показывает только географию, и считает её
отдельный модуль. Проверяется привязка места к стране и региону по
справочнику источника и правила чисел на каждом уровне.

Запуск: pytest tests/test_география.py -v
"""

from __future__ import annotations

import pandas as pd
import pytest

from src import geo_slice

# Справочник в том виде, в каком его отдаёт источник: страна → регион →
# город; под «Другими регионами» вторым уровнем идут страны.
ДЕРЕВО = [
    {"id": "113", "name": "Россия", "areas": [
        {"id": "1", "name": "Москва", "areas": []},
        {"id": "1624", "name": "Республика Татарстан", "areas": [
            {"id": "88", "name": "Казань", "areas": []},
            {"id": "1679", "name": "Набережные Челны", "areas": []},
        ]},
    ]},
    {"id": "40", "name": "Казахстан", "areas": [
        {"id": "160", "name": "Алматы", "areas": []},
    ]},
    {"id": "1001", "name": "Другие регионы", "areas": [
        {"id": "85", "name": "США", "areas": [{"id": "2000", "name": "Нью-Йорк", "areas": []}]},
    ]},
]


@pytest.fixture
def где():
    return geo_slice.привязка(ДЕРЕВО)


def _вакансии(места, зарплата=100_000, валюта="RUB", название=None) -> pd.DataFrame:
    return pd.DataFrame([
        {"vacancy_id": f"{место}-{i}", "vacancy_name": название or f"Вакансия {место} {i}",
         "employer_name": "Одна компания" if название else f"Компания {место} {i}",
         "area": место, "salary_from": зарплата + i * 1000, "salary_from_rub": зарплата + i * 1000,
         "salary_currency": валюта, "salary_mode": "MONTH"}
        for место, сколько in места.items() for i in range(сколько)
    ])


def _по(строки, подпись):
    return next(с for с in строки if с["label"] == подпись)


class TestПривязка:

    def test_город_знает_страну_и_регион(self, где):
        assert где["Казань"] == ("Россия", "Республика Татарстан")

    def test_город_федерального_значения_сам_себе_регион(self, где):
        assert где["Москва"] == ("Россия", "Москва")

    def test_под_другими_регионами_второй_уровень_это_страна(self, где):
        assert где["Нью-Йорк"] == ("США", "США"), "«Другие регионы» страной не считаются"

    def test_регион_тоже_привязан(self, где):
        assert где["Республика Татарстан"] == ("Россия", "Республика Татарстан")


class TestУровни:

    def test_счёт_вакансий_складывается_снизу_вверх(self, где):
        df = _вакансии({"Москва": 8, "Казань": 6, "Набережные Челны": 5, "Алматы": 7})
        ответ = geo_slice.собрать(df, где=где)

        assert ответ["total"] == 26
        assert _по(ответ["countries"], "Россия")["total"] == 19
        assert _по(ответ["regions"], "Республика Татарстан")["total"] == 11
        assert _по(ответ["cities"], "Казань")["total"] == 6
        assert sum(с["total"] for с in ответ["countries"]) == 26

    def test_город_несёт_свои_страну_и_регион(self, где):
        город = _по(geo_slice.собрать(_вакансии({"Казань": 6}), где=где)["cities"], "Казань")
        assert город["country"] == "Россия" and город["region"] == "Республика Татарстан"

    def test_вилка_охватывает_медиану(self, где):
        ответ = geo_slice.собрать(_вакансии({"Москва": 9, "Алматы": 9}), где=где)
        for строка in ответ["countries"] + ответ["regions"] + ответ["cities"]:
            assert строка["q1"] <= строка["median"] <= строка["q3"]

    def test_малая_выборка_остаётся_но_без_чисел(self, где):
        город = _по(geo_slice.собрать(_вакансии({"Москва": 9, "Казань": 3}), где=где)["cities"], "Казань")
        assert город["total"] == 3 and город["weak"] is True and город["median"] is None

    def test_порядок_по_числу_вакансий(self, где):
        ответ = geo_slice.собрать(_вакансии({"Алматы": 9, "Москва": 5, "Казань": 7}), где=где)
        assert [с["label"] for с in ответ["cities"]] == ["Алматы", "Казань", "Москва"]

    def test_место_вне_справочника_не_выдумывается(self, где):
        ответ = geo_slice.собрать(_вакансии({"Москва": 6, "Атлантида": 4}), где=где)
        assert ответ["unknown"] == 4
        assert "Атлантида" not in [с["label"] for с in ответ["cities"]]
        assert sum(с["total"] for с in ответ["countries"]) == 6

    def test_средней_в_ответе_нет(self, где):
        текст = str(geo_slice.собрать(_вакансии({"Москва": 9}), где=где)).lower()
        assert "avg" not in текст and "mean" not in текст and "average" not in текст

    def test_пустая_база_даёт_пустые_уровни(self, где):
        ответ = geo_slice.собрать(pd.DataFrame(), где=где)
        assert ответ["countries"] == [] and ответ["total"] == 0


class TestКопииПоГородам:
    """Решение S5‑1b: одна вакансия в двадцати городах — двадцать
    предложений, но одна работа."""

    def _одна_вакансия_в_трёх_городах(self):
        одна = _вакансии({"Казань": 1, "Набережные Челны": 1, "Москва": 1}, зарплата=500_000, название="Курьер")
        одна["salary_from"] = 500_000
        одна["salary_from_rub"] = 500_000
        прочие = _вакансии({"Казань": 6, "Набережные Челны": 6, "Москва": 6})
        return pd.concat([одна, прочие], ignore_index=True)

    def test_в_городе_копия_считается(self, где):
        город = _по(geo_slice.собрать(self._одна_вакансия_в_трёх_городах(), где=где)["cities"], "Казань")
        assert город["sample"] == 7, "в городе предложение есть — и оно одно"

    def test_в_стране_копии_сводятся_к_одной(self, где):
        страна = _по(geo_slice.собрать(self._одна_вакансия_в_трёх_городах(), где=где)["countries"], "Россия")
        assert страна["total"] == 21, "предложений двадцать одно"
        assert страна["sample"] == 19, "а работ с зарплатой — восемнадцать разных и одна, размещённая трижды"

    def test_в_регионе_копии_сводятся_внутри_региона(self, где):
        регион = _по(geo_slice.собрать(self._одна_вакансия_в_трёх_городах(), где=где)["regions"], "Республика Татарстан")
        assert регион["total"] == 14 and регион["sample"] == 13


class TestВидЗарплат:

    def test_в_валютном_виде_чужая_валюта_чисел_не_даёт_но_страна_остаётся(self, где):
        df = pd.concat([_вакансии({"Москва": 8}), _вакансии({"Алматы": 8}, зарплата=400_000, валюта="KZT")], ignore_index=True)
        казахстан = _по(geo_slice.собрать(df, вид="currency", валюта="RUB", где=где)["countries"], "Казахстан")

        assert казахстан["total"] == 8 and казахстан["weak"] is True
        assert казахстан["main_currency"] == "KZT", "страна объясняет, почему чисел нет"

    def test_в_рублёвом_виде_страны_сравнимы(self, где):
        df = pd.concat([_вакансии({"Москва": 8}), _вакансии({"Алматы": 8}, зарплата=400_000, валюта="KZT")], ignore_index=True)
        df.loc[df["salary_currency"] == "KZT", "salary_from_rub"] = 70_000.0
        ответ = geo_slice.собрать(df, вид="rub", где=где)

        assert ответ["basis"] == "equivalent" and ответ["currency"] == "RUB"
        assert _по(ответ["countries"], "Казахстан")["median"] == 70_000

    def test_почасовая_ставка_и_опечатка_в_числа_не_идут(self, где):
        df = _вакансии({"Москва": 8})
        df.loc[0, "salary_mode"] = "HOUR"
        df.loc[1, ["salary_from", "salary_from_rub"]] = 50
        город = _по(geo_slice.собрать(df, где=где)["cities"], "Москва")
        assert город["total"] == 8 and город["sample"] == 6
