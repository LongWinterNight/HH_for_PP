"""
Бюджет сбора: во что он обойдётся (S6‑4a).

Экран обещал «около минуты» там, где сбор шёл восемнадцать. Проверяется
не точность до минуты — её и быть не может, — а то, что настоящее время
живых сборов попадает внутрь названной вилки, и что вилка честная: с
одной стороны повторный сбор, с другой первый.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.budget import запросов_к_источнику, минут, оценка  # noqa: E402


class TestЧислоОбращений:

    def test_страницы_и_карточки(self):
        # Один запрос, десять страниц: десять обращений за страницами и
        # тысяча за карточками, если все вакансии новые.
        assert запросов_к_источнику(1, max_pages=10, доля_новых=1.0) == 1010

    def test_известные_вакансии_дешевле(self):
        # Карточка известной вакансии не запрашивается — повторный сбор
        # по тем же запросам идёт в разы быстрее первого.
        первый = запросов_к_источнику(1, max_pages=10, доля_новых=1.0)
        повторный = запросов_к_источнику(1, max_pages=10, доля_новых=0.1)

        assert повторный < первый / 5

    def test_срезы_добавляют_страницы_но_не_карточки(self):
        """
        Резка стоит чтения выдачи, а не карточек.

        Раньше здесь стояло `со == без * 12`: цена срезов считалась
        вместе с карточками, и обход выглядел неподъёмным — 225 часов на
        конфиг из 58 запросов. Из-за этой цифры резка полгода лежала
        выключенной. С тех пор как охват отделён от глубины (S4‑5a),
        внутри среза карточки не запрашиваются: двенадцать срезов
        добавляют сто десять страниц, а не одиннадцать тысяч карточек.
        """
        без = запросов_к_источнику(1, max_pages=10, срезов=1)
        со = запросов_к_источнику(1, max_pages=10, срезов=12)

        assert со > без, "срезы всё-таки стоят запросов"
        assert со - без == 10 * 11, "лишние страницы срезов, и только они"
        assert со < без * 1.2, "рост на проценты, а не в разы"

    def test_пустой_список_ничего_не_стоит(self):
        assert запросов_к_источнику(0, max_pages=10) == 0


class TestВремя:

    def test_время_растёт_с_паузой(self):
        быстро = минут(1000, пауза=0.5)
        медленно = минут(1000, пауза=2.0)

        assert медленно > быстро * 3

    def test_нулевая_пауза(self):
        assert минут(1000, пауза=0) == 0


class TestОценка:

    def test_живой_сбор_попадает_в_вилку(self):
        # Из истории: 4 запроса, 1 411 вакансий, 18 мин 9 с при паузе
        # 0,5 с. Это и есть проверка на честность вилки.
        итог = оценка(запросов=4, max_pages=10, пауза=0.5)
        от, до = итог["минут"]

        assert от <= 18.15 <= до

    def test_второй_живой_сбор_попадает_в_вилку(self):
        # 6 запросов, 1 141 вакансия, 23 мин 35 с.
        итог = оценка(запросов=6, max_pages=10, пауза=0.5)
        от, до = итог["минут"]

        assert от <= 23.6 <= до

    def test_вилка_а_не_одно_число(self):
        # Одно число значило бы выбрать, в какую сторону соврать.
        итог = оценка(запросов=3, max_pages=10, пауза=0.5)

        assert итог["минут"][0] < итог["минут"][1]

    def test_склонение_в_фразе(self):
        assert оценка(1, 10, 0.5)["фраза"].startswith("1 запрос ·")
        assert оценка(2, 10, 0.5)["фраза"].startswith("2 запроса ·")
        assert оценка(5, 10, 0.5)["фраза"].startswith("5 запросов ·")
        assert оценка(21, 10, 0.5)["фраза"].startswith("21 запрос ·")

    def test_время_не_округляется_до_нуля(self):
        # «0 мин» читается как «мгновенно» — а это не так никогда.
        итог = оценка(1, 1, 0.05)

        assert "0 мин" not in итог["фраза"]

    def test_резка_названа_в_цене(self):
        """Резка видна в оценке, но не удорожает её в разы."""
        без = оценка(1, 10, 0.5, срезов=1)["минут"][1]
        со = оценка(1, 10, 0.5, срезов=12)["минут"][1]

        assert со > без

    def test_разведка_снижает_оценку(self):
        """
        Пока неизвестно, сколько запросов упрётся, считается по худшему.

        Разведка называет число, и оценка перестаёт обещать сотни часов
        там, где сбор идёт сорок минут: экран, врущий в двадцать раз, —
        это украшение кнопки, а не оценка.
        """
        вслепую = оценка(58, 10, 1.0, срезов=12)["минут"][1]
        по_разведке = оценка(58, 10, 1.0, срезов=12, упрутся=15)["минут"][1]
        никто_не_упрётся = оценка(58, 10, 1.0, срезов=12, упрутся=0)["минут"][1]

        assert по_разведке < вслепую
        assert никто_не_упрётся < по_разведке
