"""
Недобор выдачи: что сбор не увидел (S4‑1).

Проверяется главное свойство: молчать нельзя, но и пугать выдуманным
числом тоже. Когда данных для суждения нет — старые сборы, где «взято»
не записывалось, — недобор не выдумывается.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.coverage import недобор_запроса, склонение, сводка_недобора  # noqa: E402


def запрос(**поля):
    """Строка разбивки сбора с разумными значениями по умолчанию."""
    основа = {
        "keyword": "Рекрутер",
        "status": "partial",
        "found": 3412,
        "taken": 1000,
        "pages": 10,
    }
    основа.update(поля)
    return основа


class TestНедоборЗапроса:

    def test_разрыв_между_найдено_и_взято(self):
        assert недобор_запроса(запрос()) == 2412

    def test_полный_обход_не_даёт_недобора(self):
        # Выдача прочитана до конца: разница между found и taken здесь
        # объясняется отсевом по возрасту, а не потолком выдачи.
        assert недобор_запроса(запрос(status="complete", taken=800)) is None

    def test_старая_запись_без_взято(self):
        # Сборы до миграции 014 не писали «взято». Считать недобор
        # равным found было бы враньём в другую сторону.
        assert недобор_запроса(запрос(taken=None)) is None

    def test_без_найдено(self):
        assert недобор_запроса(запрос(found=None)) is None

    def test_взято_больше_найденного(self):
        # Источник обновляет выдачу между страницами: за время обхода
        # вакансий могло стать меньше. Отрицательного недобора нет.
        assert недобор_запроса(запрос(found=900, taken=1000)) == 0


class TestСводка:

    def test_суммирует_по_запросам(self):
        сводка = сводка_недобора([
            запрос(keyword="Рекрутер", found=3412, taken=1000),
            запрос(keyword="HR-менеджер", found=1500, taken=1000),
        ])
        assert сводка["запросов"] == 2
        assert сводка["вакансий"] == 2412 + 500

    def test_первым_идёт_самый_потерянный(self):
        сводка = сводка_недобора([
            запрос(keyword="HR-менеджер", found=1500, taken=1000),
            запрос(keyword="Рекрутер", found=3412, taken=1000),
        ])
        assert сводка["по_запросам"][0]["запрос"] == "Рекрутер"

    def test_полные_обходы_не_попадают_в_сводку(self):
        сводка = сводка_недобора([
            запрос(status="complete", taken=800),
            запрос(keyword="Другой", status="complete", taken=120, found=120),
        ])
        assert сводка["вакансий"] == 0
        assert сводка["по_запросам"] == []

    def test_нет_данных_нет_фразы(self):
        # Пустая фраза — это «сказать нечего», и экран должен молчать,
        # а не показывать «всё собрано».
        assert сводка_недобора([])["фраза"] == ""
        assert сводка_недобора([запрос(taken=None)])["фраза"] == ""

    def test_фраза_называет_число_и_причину(self):
        сводка = сводка_недобора([запрос(found=3412, taken=1000)])
        фраза = сводка["фраза"]
        # Разряды разделены неразрывным пробелом: число не должно
        # разрываться переносом строки.
        assert "2 412" in фраза
        assert "вакансий" in фраза
        assert "запросу" in фраза

    def test_ноль_недобора_не_попадает_в_список(self):
        сводка = сводка_недобора([запрос(found=1000, taken=1000)])
        assert сводка["по_запросам"] == []
        assert сводка["фраза"] == ""


class TestСклонение:

    def test_формы(self):
        assert склонение(1, "вакансия", "вакансии", "вакансий") == "вакансия"
        assert склонение(2, "вакансия", "вакансии", "вакансий") == "вакансии"
        assert склонение(5, "вакансия", "вакансии", "вакансий") == "вакансий"
        assert склонение(11, "вакансия", "вакансии", "вакансий") == "вакансий"
        assert склонение(21, "вакансия", "вакансии", "вакансий") == "вакансия"
        # 2412 оканчивается на «двенадцать»: форма та же, что у пяти.
        assert склонение(2412, "вакансия", "вакансии", "вакансий") == "вакансий"
