"""
Эталонный набор и замер по нему.

Без эталона «стало лучше» недоказуемо: «Подарки» тоже прибавляют
полноту. Набор — вакансии, прочитанные и размеченные руками; тест
следит за тем, чтобы он оставался пригодным для замера.

Сам замер тестами не покрывается — он инструмент разработчика, а не
часть продукта. Проверяется то, на чём он стоит: формат набора,
разброс по рынкам и то, что правила разметки записаны.

Запуск: pytest tests/test_эталон_навыков.py -v
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

ФАЙЛ = project_root / "tests" / "fixtures" / "эталон_навыков.json"


@pytest.fixture(scope="module")
def эталон():
    assert ФАЙЛ.exists(), "эталонный набор не найден"
    return json.loads(ФАЙЛ.read_text(encoding="utf-8"))


class TestФормат:
    def test_у_каждой_вакансии_есть_текст_и_разметка(self, эталон):
        for вакансия in эталон["вакансии"]:
            assert вакансия["описание"].strip(), вакансия["name"]
            assert isinstance(вакансия["навыки"], list)

    def test_навыки_без_повторов_и_пустых(self, эталон):
        for вакансия in эталон["вакансии"]:
            навыки = вакансия["навыки"]
            ключи = [н.strip().lower() for н in навыки]

            assert all(ключи), f"пустой навык в «{вакансия['name']}»"
            assert len(ключи) == len(set(ключи)), f"повтор в «{вакансия['name']}»"

    def test_правила_разметки_записаны(self, эталон):
        """Без них разметчик через месяц решит иначе, чем сегодня."""
        правила = эталон["правила"]

        assert "НЕ ВКЛЮЧАЕТСЯ" in правила
        assert "СПОРНЫЕ СЛУЧАИ" in правила


class TestСодержание:
    def test_набор_покрывает_разные_рынки(self, эталон):
        """Словарь писался под ИТ, и на ИТ он выглядит лучше, чем есть."""
        рынки = {в["рынок"] for в in эталон["вакансии"]}

        assert len(рынки) >= 5, f"рынков всего {len(рынки)}: {рынки}"
        assert "ИТ-разработка" in рынки
        assert рынки - {"ИТ-разработка", "ИТ-прочее"}, "не только ИТ"

    def test_есть_вакансия_почти_без_навыков(self, эталон):
        """Пустой ответ — тоже правильный: у сборщика заказов навыков нет.

        Без такой вакансии замер поощряет находить хоть что-нибудь.
        """
        минимум = min(len(в["навыки"]) for в in эталон["вакансии"])

        assert минимум <= 3

    def test_объём_набора_назван(self, эталон):
        """Пока набор меньше плана, числа замера — ориентир, и это
        должно быть видно из самого файла."""
        assert эталон["объём_план"] >= len(эталон["вакансии"])
        assert эталон["как_размечено"]
