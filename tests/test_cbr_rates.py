"""
Разбор ответа ЦБ.

Проверяется на настоящем ответе, сохранённом 08.09.2026
(`tests/fixtures/cbr_daily.xml`), а не на выдуманном XML: все три
ловушки этого источника — номинал за сотню, запятая в числе и
устаревший код валюты — видны только в живом ответе, и выдуманный
образец их бы не содержал.

В сеть тесты не ходят: работа не должна зависеть от того, доступен ли
сегодня сайт ЦБ.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pytest

from src.cbr_rates import Курсы, разобрать

ОБРАЗЕЦ = Path(__file__).parent / "fixtures" / "cbr_daily.xml"


@pytest.fixture
def курсы() -> Курсы:
    return разобрать(ОБРАЗЕЦ.read_bytes())


def test_дата_берётся_из_ответа(курсы):
    """
    В выходной ЦБ отдаёт последний рабочий день.

    Подписать пятничный курс субботним числом значит соврать в единственном
    месте, где отчёт объясняет, откуда взялось число.
    """
    assert курсы.на_дату == date(2026, 9, 9)


def test_все_наши_валюты_нашлись(курсы):
    """Девять валют выборки — все должны котироваться."""
    for код in ("USD", "EUR", "KZT", "UZS", "KGS", "BYN", "AZN", "GEL"):
        assert курсы.рублей_за(код), f"нет курса {код}"


def test_номинал_снят(курсы):
    """
    Курс приведён к одной единице валюты.

    У ЦБ он даётся за 100 тенге и за 10 000 сумов: забыть про номинал —
    ошибиться в сто и в десять тысяч раз, а такая ошибка выглядит
    правдоподобно и потому не заметна.
    """
    assert 0.005 < курсы.рублей_за("UZS") < 0.02
    assert 0.1 < курсы.рублей_за("KZT") < 0.5
    assert 0.5 < курсы.рублей_за("KGS") < 2.0


def test_запятая_разобрана(курсы):
    """Значения приходят как «86,4730» — float() без замены упал бы."""
    assert курсы.рублей_за("USD") == pytest.approx(86.473, abs=0.001)


def test_устаревший_код_валюты(курсы):
    """
    hh.ru отдаёт BYR, ЦБ котирует BYN.

    Суммы в объявлениях соответствуют новому рублю (медиана 2 000), так
    что нужна сопоставка кодов, а деления на 10 000 — нет.
    """
    assert курсы.рублей_за("BYR") == курсы.рублей_за("BYN")
    assert 20 < курсы.рублей_за("BYR") < 40


def test_рубль_сам_к_себе(курсы):
    assert курсы.рублей_за("RUB") == 1.0
    assert курсы.рублей_за("RUR") == 1.0


def test_незнакомая_валюта_даёт_пусто(курсы):
    """
    Пусто важнее нуля.

    Валюта без курса должна остаться без эквивалента и сказать об этом, а
    не превратиться в 0 ₽ — ноль выглядит как настоящее число.
    """
    assert курсы.рублей_за("XYZ") is None
    assert курсы.рублей_за(None) is None


def test_пересчёт_даёт_осмысленные_числа(курсы):
    """Проверка целиком: настоящие зарплаты из базы в рублях."""
    assert round(19_000_000 * курсы.рублей_за("UZS")) == pytest.approx(139_362, abs=100)
    assert round(350_000 * курсы.рублей_за("KZT")) == pytest.approx(66_619, abs=100)


def test_пустой_ответ_отклоняется():
    """Молча вернуть ноль валют — значит обнулить эквиваленты у всех."""
    with pytest.raises(ValueError):
        разобрать(b'<?xml version="1.0" encoding="windows-1251"?><ValCurs Date="09.09.2026"/>')


def test_непонятная_дата_отклоняется():
    with pytest.raises(ValueError):
        разобрать('<?xml version="1.0"?><ValCurs Date="завтра"><Valute><CharCode>USD</CharCode>'
                  '<Nominal>1</Nominal><Value>86,4730</Value></Valute></ValCurs>'.encode("utf-8"))


def test_битый_курс_не_роняет_остальные():
    """Одна испорченная строка не должна лишать эквивалента всю выборку."""
    xml = ('<?xml version="1.0"?><ValCurs Date="09.09.2026">'
           '<Valute><CharCode>USD</CharCode><Nominal>1</Nominal><Value>86,4730</Value></Valute>'
           '<Valute><CharCode>EUR</CharCode><Nominal>1</Nominal><Value>ерунда</Value></Valute>'
           '</ValCurs>').encode("utf-8")
    курсы = разобрать(xml)
    assert курсы.рублей_за("USD") == pytest.approx(86.473)
    assert курсы.рублей_за("EUR") is None
