"""
Границы доверия к ответу модели.

Три защиты из `src/ai_contract.py`, и каждая проверяется отдельно:
схема разбирается целиком или никак, навык без цитаты не существует,
навык с выдуманной цитатой не проходит дальше.

Тесты написаны от обратного: главное здесь не то, что верный ответ
разбирается, а то, что неверный не проходит. Выдуманный навык не падает
и не выглядит ошибкой — он выглядит результатом работы, и поймать его
можно только здесь.
"""

from __future__ import annotations

import pytest

from src.ai_contract import (
    ИзвлечённыйНавык,
    ОтветИзвлечения,
    ОтветСломан,
    без_выдуманного,
    разобрать_ответ,
)

ОПИСАНИЕ = (
    "Требования: уверенное владение Figma, знание PostgreSQL, "
    "опыт работы с React и хуками (useCallback), английский язык."
)


def верный_ответ(**замены) -> dict:
    ответ = {
        "навыки": [
            {
                "название": "Figma",
                "как_в_тексте": "владение Figma",
                "вид": "инструмент",
                "уверенность": 0.95,
            },
            {
                "название": "React",
                "как_в_тексте": "опыт работы с React",
                "вид": "технология",
                "уверенность": 0.9,
                "родитель": None,
            },
        ],
        "язык_текста": "ru",
        "версия_модели": "локальная-14b-q5",
        "версия_промпта": "v1",
    }
    ответ.update(замены)
    return ответ


class TestСхемаЦеликом:
    """Ответ разбирается весь или не разбирается вовсе."""

    def test_верный_ответ_разбирается(self):
        ответ = разобрать_ответ(верный_ответ())
        assert [н.название for н in ответ.навыки] == ["Figma", "React"]
        assert ответ.версия_модели == "локальная-14b-q5"

    def test_ответ_не_объект(self):
        with pytest.raises(ОтветСломан):
            разобрать_ответ("навыки: Figma, React")

    def test_нет_списка_навыков(self):
        with pytest.raises(ОтветСломан):
            разобрать_ответ({"язык_текста": "ru", "версия_модели": "м", "версия_промпта": "v1"})

    def test_один_сломанный_навык_рушит_весь_ответ(self):
        """Половина разобранного ответа опаснее пустого: она выглядит результатом."""
        данные = верный_ответ()
        данные["навыки"].append({"название": "Docker", "вид": "инструмент"})
        with pytest.raises(ОтветСломан):
            разобрать_ответ(данные)

    @pytest.mark.parametrize("поле", ["язык_текста", "версия_модели", "версия_промпта"])
    def test_без_версий_ответ_не_принимается(self, поле):
        """Без версий прошлые числа нечем объяснить после смены модели."""
        данные = верный_ответ()
        del данные[поле]
        with pytest.raises(ОтветСломан):
            разобрать_ответ(данные)


class TestЦитатаОбязательна:
    """Навык без основания не должен существовать как объект."""

    def test_пустая_цитата(self):
        with pytest.raises(ОтветСломан):
            ИзвлечённыйНавык("Figma", "   ", "инструмент", 0.9)

    def test_нет_поля_цитаты(self):
        данные = верный_ответ()
        del данные["навыки"][0]["как_в_тексте"]
        with pytest.raises(ОтветСломан):
            разобрать_ответ(данные)

    def test_пустое_название(self):
        with pytest.raises(ОтветСломан):
            ИзвлечённыйНавык("", "владение Figma", "инструмент", 0.9)

    def test_неизвестный_вид(self):
        with pytest.raises(ОтветСломан):
            ИзвлечённыйНавык("Figma", "владение Figma", "штуковина", 0.9)

    @pytest.mark.parametrize("уверенность", [-0.1, 1.5])
    def test_уверенность_вне_диапазона(self, уверенность):
        with pytest.raises(ОтветСломан):
            ИзвлечённыйНавык("Figma", "владение Figma", "инструмент", уверенность)


class TestВыдуманноеНеПроходит:
    """Цитата сверяется с описанием — иначе выдумку не отличить от находки."""

    def test_навык_с_настоящей_цитатой_остаётся(self):
        ответ, отброшены = без_выдуманного(разобрать_ответ(верный_ответ()), ОПИСАНИЕ)
        assert [н.название for н in ответ.навыки] == ["Figma", "React"]
        assert отброшены == []

    def test_выдуманная_цитата_отбрасывается(self):
        данные = верный_ответ()
        данные["навыки"].append({
            "название": "Kubernetes",
            "как_в_тексте": "опыт с Kubernetes и кластерами",
            "вид": "инструмент",
            "уверенность": 0.99,
        })
        ответ, отброшены = без_выдуманного(разобрать_ответ(данные), ОПИСАНИЕ)
        assert [н.название for н in ответ.навыки] == ["Figma", "React"]
        assert [н.название for н in отброшены] == ["Kubernetes"]

    def test_регистр_и_пробелы_не_считаются_расхождением(self):
        данные = верный_ответ(навыки=[{
            "название": "PostgreSQL",
            "как_в_тексте": "  Знание   PostgreSQL  ",
            "вид": "технология",
            "уверенность": 0.9,
        }])
        ответ, отброшены = без_выдуманного(разобрать_ответ(данные), ОПИСАНИЕ)
        assert len(ответ.навыки) == 1 and отброшены == []

    def test_низкая_уверенность_не_проходит(self):
        данные = верный_ответ(навыки=[{
            "название": "Figma",
            "как_в_тексте": "владение Figma",
            "вид": "инструмент",
            "уверенность": 0.1,
        }])
        ответ, отброшены = без_выдуманного(разобрать_ответ(данные), ОПИСАНИЕ)
        assert ответ.навыки == [] and len(отброшены) == 1

    def test_отброшенные_возвращаются_а_не_теряются(self):
        """Их число — мера доверия к модели, и оно должно попасть в лог."""
        данные = верный_ответ(навыки=[{
            "название": "Rust",
            "как_в_тексте": "требуется Rust",
            "вид": "язык",
            "уверенность": 0.8,
        }])
        ответ, отброшены = без_выдуманного(разобрать_ответ(данные), ОПИСАНИЕ)
        assert ответ.навыки == []
        assert отброшены[0].как_в_тексте == "требуется Rust"

    def test_цитата_с_испорченной_латиницей_находится(self):
        """«Exсel» с кириллической «с» — та же цитата, что и в тексте."""
        описание = "Требования: знание Exсel на уровне сводных таблиц"
        данные = верный_ответ(навыки=[{
            "название": "Excel",
            "как_в_тексте": "знание Excel",
            "вид": "инструмент",
            "уверенность": 0.9,
        }])
        ответ, отброшены = без_выдуманного(разобрать_ответ(данные), описание)
        assert len(ответ.навыки) == 1 and отброшены == []


def test_пустой_список_навыков_допустим():
    """Модель, ничего не нашедшая, — законный случай, а не поломка.

    В базе 974 вакансии вовсе без навыков, и по части из них честный
    ответ — пустой список. Ошибкой это считать нельзя: иначе прогон
    будет падать там, где работает правильно.
    """
    ответ = разобрать_ответ({
        "навыки": [],
        "язык_текста": "ru",
        "версия_модели": "локальная-14b-q5",
        "версия_промпта": "v1",
    })
    assert ответ.навыки == []
    очищенный, отброшены = без_выдуманного(ответ, ОПИСАНИЕ)
    assert очищенный.навыки == [] and отброшены == []


def test_родитель_сохраняется():
    """Иерархия из § 11.4: «useCallback» несёт «React» и без него бессмыслен."""
    ответ = разобрать_ответ({
        "навыки": [{
            "название": "useCallback",
            "как_в_тексте": "хуками (useCallback)",
            "вид": "технология",
            "уверенность": 0.7,
            "родитель": "React",
        }],
        "язык_текста": "ru",
        "версия_модели": "м",
        "версия_промпта": "v1",
    })
    очищенный, отброшены = без_выдуманного(ответ, ОПИСАНИЕ)
    assert отброшены == []
    assert очищенный.навыки[0].родитель == "React"
