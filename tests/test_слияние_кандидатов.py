def по_ключу(conn, статус="new", порог=3):
    return {к["ключ"]: к for к in кандидаты.список(conn, статус=статус, порог=порог)}


class TestСлияние:

    def test_слитые_считаются_вместе(self, conn):
        assert "ии" not in по_ключу(conn) and "ai" not in по_ключу(conn), "порознь порог не пройден"
        assert кандидаты.слить(conn, "ИИ", "AI")
        группа = по_ключу(conn)["ai"]
        assert группа["работодателей"] == 4
        assert группа["встреч"] == 4, "вакансия 1, где есть и «ИИ», и «AI», считается один раз"
        assert группа["написания"] == ["ИИ"]
        assert "ии" not in по_ключу(conn, порог=0), "слитый не показывается отдельной строкой"

    def test_цепочек_не_бывает(self, conn):
        кандидаты.слить(conn, "ИИ", "AI")
        кандидаты.слить(conn, "AI", "ИИ-инструменты")
        группа = по_ключу(conn)["ии-инструменты"]
        assert sorted(группа["написания"]) == ["AI", "ИИ"], "написания канона переехали вместе с ним"
        assert кандидаты.слить(conn, "Tool calling", "ИИ"), "слияние в слитого ведёт к его канону"
        assert "Tool calling" in по_ключу(conn)["ии-инструменты"]["написания"]

    def test_нельзя_слить_с_собой_и_с_несуществующим(self, conn):
        assert not кандидаты.слить(conn, "ИИ", "ии")
        assert not кандидаты.слить(conn, "ИИ", "нет такого")

    def test_подтверждённый_канон_уносит_написания_в_словарь(self, conn, словарь):
        кандидаты.слить(conn, "ИИ", "ИИ-инструменты")
        кандидаты.слить(conn, "AI", "ИИ-инструменты")
        assert кандидаты.подтвердить(conn, "ИИ-инструменты", раздел="hard", файл_словаря=словарь)
        данные = yaml.safe_load(словарь.read_text(encoding="utf-8"))
        assert {"ии-инструменты", "ии", "ai"} <= set(данные["hard"])
        assert {"ии", "ai"} <= set(данные["synonyms"]["ИИ-инструменты"])
        assert по_ключу(conn, "confirmed", 0).keys() >= {"ии-инструменты", "ии", "ai"}

    def test_отклонённый_канон_уносит_написания(self, conn):
        кандидаты.слить(conn, "ИИ", "AI")
        кандидаты.отклонить(conn, "AI")
        assert {"ai", "ии"} <= по_ключу(conn, "rejected", 0).keys()


class TestНаписаниеНавыка:

    def test_написание_ложится_под_канон_словаря(self, conn, словарь):
        кандидаты.слить(conn, "ИИ", "ИИ-инструменты")
        assert кандидаты.написание_навыка(conn, "ИИ-инструменты", "ai-инструменты", файл_словаря=словарь)
        данные = yaml.safe_load(словарь.read_text(encoding="utf-8"))
        assert {"ии-инструменты", "ии"} <= set(данные["hard"]), "в раздел — чтобы находиться в тексте"
        assert {"ии-инструменты", "ии"} <= set(данные["synonyms"]["Ai-инструменты"]), "под канон — чтобы считаться им"
        решённые = по_ключу(conn, "confirmed", 0)
        assert решённые["ии-инструменты"]["цель"] == "Ai-инструменты"

    def test_написание_находится_словарём_как_канон(self, conn, словарь):
        """S10‑12e: следующая вакансия с написанием даёт навык‑канон без модели."""
        from src.normalize import SkillDictionaries, find_skills

        кандидаты.написание_навыка(conn, "ИИ-инструменты", "ai-инструменты", файл_словаря=словарь)
        словари = SkillDictionaries.from_config()
        найдено = find_skills("используем ии-инструменты и ai-инструменты в работе", словари.hard)
        assert найдено == {"Ai-инструменты"}

    def test_неизвестный_словарю_навык_не_принимается(self, conn, словарь):
        with pytest.raises(ValueError):
            кандидаты.написание_навыка(conn, "ИИ", "нет такого навыка", файл_словаря=словарь)


class TestСписок:

    def test_сводка_и_список_сходятся(self, conn):
        """S10‑12h: требование к кандидату не считается ни там, ни там."""
        assert кандидаты.сводка(conn)["ждут_решения"] == len(кандидаты.список(conn)) == кандидаты.сколько(conn)
        assert "высшее образование" not in по_ключу(conn)

    def test_поиск_находит_по_слитому_написанию(self, conn):
        кандидаты.слить(conn, "AI", "ИИ-инструменты")
        assert [к["ключ"] for к in кандидаты.список(conn, порог=0, поиск="ai")] == ["ии-инструменты"]

    def test_короткий_запрос_ищется_по_началу_слова(self):
        assert кандидаты.совпадает("ии", "ИИ-инструменты")
        assert кандидаты.совпадает("ии", "Генеративный ИИ")
        assert not кандидаты.совпадает("ии", "Интеграции"), "буквы внутри слова — не совпадение"
        assert not кандидаты.совпадает("ai", "Tailwind")
        assert кандидаты.совпадает("grat", "Интеграции") is False and кандидаты.совпадает("тегра", "Интеграции")

    def test_порции(self, conn):
        все = [к["ключ"] for к in кандидаты.список(conn, порог=0)]
        assert [к["ключ"] for к in кандидаты.список(conn, порог=0, предел=2, смещение=1)] == все[1:3]


class TestПохожие:

    def test_одинаковый_скелет_и_транслит_идут_первыми(self):
        подсказки = кандидаты.Похожие(["ai-инструменты", "python"], [
            {"ключ": "tool calling", "название": "Tool calling", "работодателей": 3},
            {"ключ": "ии инструменты", "название": "ИИ инструменты", "работодателей": 5},
        ])
        найдено = [п["название"] for п in подсказки.для("ИИ-инструменты")]
        assert set(найдено[:2]) == {"ИИ инструменты", "ai-инструменты"}, "совпавшие по скелету — первыми"
        assert "python" not in найдено

    def test_общее_слово_даёт_подсказку(self):
        подсказки = кандидаты.Похожие(["function calling"], [{"ключ": "tool use", "название": "Tool use", "работодателей": 3}])
        assert {п["название"] for п in подсказки.для("Tool calling")} == {"function calling", "Tool use"}

    def test_себя_не_подсказывает(self):
        подсказки = кандидаты.Похожие([], [{"ключ": "ai", "название": "AI", "работодателей": 3}])
        assert подсказки.для("AI") == []
