def навык(название, вид="инструмент"):
    return ИзвлечённыйНавык(название=название, как_в_тексте=f"опыт с {название}", вид=вид, уверенность=0.9)


@pytest.fixture
def conn(словарь):
    from src.storage import VacancyStorage

    хранилище = VacancyStorage(db_path=settings.db_path)
    хранилище.save_vacancies_incremental(pd.DataFrame([{"vacancy_id": "0", "vacancy_name": "заглушка"}]))
