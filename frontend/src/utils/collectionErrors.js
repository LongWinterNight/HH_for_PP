/**
 * Объяснения отказов источника.
 *
 * Причина приходит кодом, а не текстом: «токен протух» и «сеть
 * недоступна» требуют разных действий, а в тексте исключения они
 * неразличимы. Раньше в интерфейс попадала строка вроде
 * «search_with_progress() got an unexpected keyword argument» — из неё
 * не следует ни что случилось, ни что делать.
 *
 * Каждое объяснение говорит две вещи: что произошло и какой следующий
 * шаг. Формулировки — по правилам блока «Словарь и тон» дизайн-системы.
 */

const ОБЪЯСНЕНИЯ = {
  no_token: {
    title: 'Источник не пускает без ключа доступа',
    text: 'Поиск вакансий на hh.ru требует ключ приложения. Он задаётся в настройках сервера, в файле .env.',
    action: 'Как получить ключ'
  },
  token_rejected: {
    title: 'Ключ доступа отклонён',
    text: 'Источник знает ключ, но больше его не принимает — обычно это значит, что срок действия истёк.',
    action: 'Обновить ключ'
  },
  no_email: {
    title: 'Не указана почта для запросов',
    text: 'Источник требует контакт в заголовке запроса и без него отвечает отказом.',
    action: 'Указать почту'
  },
  rate_limited: {
    title: 'Источник просит снизить частоту',
    text: 'Запросов было слишком много подряд. Собранное сохранено — сбор можно повторить через несколько минут.',
    action: 'Повторить'
  },
  network: {
    title: 'Источник недоступен',
    text: 'Не удалось связаться с hh.ru. Проверьте подключение к сети и повторите.',
    action: 'Повторить'
  },
  unknown: {
    title: 'Сбор прервался',
    text: 'Причина неизвестна. Собранные до остановки вакансии сохранены в базе.',
    action: 'Повторить'
  }
}

/**
 * Объяснение по коду причины.
 *
 * Неизвестный код не должен ломать экран: без объяснения человек
 * останется вообще без подсказки, поэтому у него есть запасное.
 */
export function объяснитьОтказ(причина, запасной = '') {
  const найдено = ОБЪЯСНЕНИЯ[причина] || ОБЪЯСНЕНИЯ.unknown
  if (!ОБЪЯСНЕНИЯ[причина] && запасной) {
    return { ...найдено, text: `${найдено.text} ${запасной}` }
  }
  return найдено
}

export const ПРИЧИНЫ = Object.keys(ОБЪЯСНЕНИЯ)
