import { onBeforeUnmount, onMounted, ref, watch } from 'vue'
import { useSteps } from '@/composables/useSteps'

/**
 * Сцена, которая проигрывается сама, когда до неё докрутили.
 *
 * Экран «Как устроено» читают прокруткой. Кнопка «показать» перед
 * каждой схемой превращала чтение в серию нажатий, и схемы, до кнопок
 * которых не дошли, оставались пустыми. Здесь сцена начинается, когда
 * её верх поднялся в окно, и один раз: ушёл и вернулся — она стоит на
 * итоге, а не дёргается заново. Повторить можно кнопкой.
 *
 * Данные сцены приходят с сервера и могут опоздать к прокрутке —
 * сцена ждёт и того, и другого.
 */
export function useScene(число, { пауза = 700, готово = () => true } = {}) {
  const корень = ref(null)
  const видна = ref(false)
  const шаги = useSteps(число, { пауза })
  let сыграна = false
  let наблюдатель = null

  function попробовать() {
    if (сыграна || !видна.value || !готово()) return
    сыграна = true
    шаги.запустить()
  }

  function повторить() {
    сыграна = true
    шаги.запустить()
  }

  onMounted(() => {
    if (typeof IntersectionObserver === 'undefined' || !корень.value) {
      // Браузер не умеет сообщать о видимости — показываем итог.
      видна.value = true
      сыграна = true
      шаги.показатьВсё()
      return
    }
    наблюдатель = new IntersectionObserver(
      ([запись]) => {
        видна.value = запись.isIntersecting
        попробовать()
      },
      // Сцена начинается, когда её верх прошёл нижнюю четверть окна:
      // раньше — её начало проиграется под краем экрана.
      { rootMargin: '0px 0px -25% 0px', threshold: 0 }
    )
    наблюдатель.observe(корень.value)
  })

  watch(готово, попробовать)

  onBeforeUnmount(() => наблюдатель?.disconnect())

  return { корень, видна, повторить, ...шаги }
}
