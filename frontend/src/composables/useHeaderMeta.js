import { onBeforeUnmount, readonly, ref, watch } from 'vue'
import { overview } from '@/api/endpoints'

/**
 * Правая часть шапки: состояние базы и подпись текущего экрана.
 *
 * Состояние живёт вне компонентов намеренно. Шапка стоит над
 * RouterView, а экраны подставляются в слот по умолчанию — передать
 * что-либо в именованный слот шапки они не могут. Второй вариант,
 * событие через шину, теряется при быстром переходе между экранами:
 * подпись приходит раньше, чем шапка успевает на неё подписаться.
 *
 * Счётчик базы обновляется при смене экрана, а не по таймеру. Давность
 * измеряется часами — секундная точность здесь никому не нужна, а
 * постоянный опрос на шести экранах это тысячи запросов за день.
 */

const состояние = ref(null)
const подпись = ref('')

let идётЗапрос = false

async function обновитьСостояниеБазы() {
  if (идётЗапрос) return
  идётЗапрос = true
  try {
    состояние.value = await overview.get()
  } catch {
    // Шапка без счётчика остаётся рабочей: разделы на месте. Ошибку
    // показывает экран, который за данные отвечает.
    состояние.value = null
  } finally {
    идётЗапрос = false
  }
}

export function useHeaderMeta() {
  return {
    состояниеБазы: readonly(состояние),
    подписьЭкрана: readonly(подпись),
    обновить: обновитьСостояниеБазы,
  }
}

/**
 * Экран объявляет, что показывать в шапке вместо счётчика базы.
 *
 * Подпись снимается при уходе с экрана: «17 из 909 по фильтру» на
 * чужом разделе — прямая ложь о том, что человек видит.
 */
export function useScreenMeta(источник) {
  watch(источник, (значение) => { подпись.value = значение || '' }, { immediate: true })
  onBeforeUnmount(() => { подпись.value = '' })
}
