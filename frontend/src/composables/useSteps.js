import { onBeforeUnmount, ref } from 'vue'

/**
 * Проигрывание по шагам: объясняющая анимация, которая идёт один раз.
 *
 * В системе нет бесконечных анимаций, и здесь их тоже нет: движение
 * запускается действием человека, доходит до конца и останавливается
 * на итоге. Повторить можно — тем же действием.
 *
 * Тем, кто просил убрать движение (prefers-reduced-motion), итог
 * показывается сразу: шаги нужны, чтобы объяснить порядок, а не чтобы
 * заставить ждать.
 */
export function useSteps(число, { пауза = 700 } = {}) {
  // Сколько шагов уже показано. Ноль — ничего не проиграно.
  const шаг = ref(0)
  const идёт = ref(false)
  let таймер = null

  const безДвижения = () =>
    typeof window !== 'undefined' && window.matchMedia?.('(prefers-reduced-motion: reduce)').matches

  function остановить() {
    if (таймер) clearTimeout(таймер)
    таймер = null
    идёт.value = false
  }

  function запустить(всего = число) {
    остановить()
    const предел = typeof всего === 'function' ? всего() : всего
    if (безДвижения()) {
      шаг.value = предел
      return
    }
    шаг.value = 0
    идёт.value = true
    const дальше = () => {
      if (шаг.value >= предел) {
        остановить()
        return
      }
      шаг.value += 1
      // После последнего шага — та же пауза, что после остальных: без
      // неё он сменялся итогом, не успев показаться.
      таймер = setTimeout(дальше, пауза)
    }
    // Первый шаг — сразу: пауза перед началом читается как «не нажалось».
    таймер = setTimeout(дальше, 60)
  }

  function показатьВсё(всего = число) {
    остановить()
    шаг.value = typeof всего === 'function' ? всего() : всего
  }

  onBeforeUnmount(остановить)

  return { шаг, идёт, запустить, показатьВсё, остановить }
}
