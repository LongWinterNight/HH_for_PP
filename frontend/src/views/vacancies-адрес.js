import { изСписка, поле, флажок, число } from '@/app/адрес'

/**
 * Что живёт в адресе экрана «Вакансии».
 *
 * Читается как предложение:
 * /vacancies?q=python&area=Москва&exp=3-6&skill=fastapi&paid=1&sort=salary-desc&page=2&id=4471120
 * — вакансии по «python» в Москве, опыт 3–6 лет, навык FastAPI, только с
 * зарплатой, по убыванию зарплаты, вторая страница, открыта вакансия
 * 4471120.
 *
 * Имена параметров короткие и не совпадают с именами полей API: адрес
 * читают глазами и пересылают в переписке, а `include_inactive=true`
 * в ссылке выглядит как отладочный вывод.
 */

export const ПОРЯДОК_СОРТИРОВКИ = ['date_desc', 'salary_desc', 'salary_asc', 'none']

// Сортировка в адресе пишется через дефис: «salary-desc» вместо
// «salary_desc». Подчёркивание в ссылке часто съедается подчёркиванием
// самой ссылки в почте и мессенджерах.
const вДефис = (v) => v.replace(/_/g, '-')
const изДефиса = (v) => v.replace(/-/g, '_')

export const СХЕМА = {
  search: поле('q', ''),
  area: поле('area', ''),
  experience: поле('exp', ''),
  skill: поле('skill', ''),
  currency: поле('cur', ''),
  // Источник пока один, но параметр в схеме есть: со вторым источником
  // ссылка «только hh.ru» должна работать сразу, а не после правки.
  source: поле('src', ''),
  salary_only: флажок('paid'),
  // Архив расширяет выборку, а не сужает: в ссылке это видно словом.
  include_inactive: флажок('archive'),
  sort: {
    ...изСписка('sort', 'date_desc', ПОРЯДОК_СОРТИРОВКИ),
    читать: (v) => {
      const значение = изДефиса(v)
      return ПОРЯДОК_СОРТИРОВКИ.includes(значение) ? значение : 'date_desc'
    },
    писать: вДефис,
  },
  page: число('page', 1),
  // Открытая панель вакансии — состояние экрана, а не отдельная
  // страница: список под ней остаётся тем же.
  id: поле('id', ''),
}

/**
 * Поля, которые уходят на сервер как фильтры списка.
 *
 * Сортировка, страница и открытая панель сюда не входят: первые две
 * идут отдельными параметрами запроса, третья не влияет на выборку.
 */
export const ПОЛЯ_ФИЛЬТРОВ = [
  'search', 'area', 'experience', 'skill',
  'currency', 'source', 'salary_only', 'include_inactive',
]

/**
 * Срез для отчёта: те же фильтры, без сортировки, страницы и панели.
 *
 * Порядок строк и открытая карточка к содержимому файла отношения не
 * имеют, а в ссылке на «Отчёты» выглядели бы как часть среза.
 */
export const СХЕМА_СРЕЗА = Object.fromEntries(
  ПОЛЯ_ФИЛЬТРОВ.map((ключ) => [ключ, СХЕМА[ключ]]),
)
