/**
 * Состояние экрана в адресе: перевод туда и обратно.
 *
 * Правило разделения одно: в адрес идёт то, что человек захочет
 * переслать или открыть заново. Черновик в поле, позиция прокрутки и
 * ход сбора в адрес не идут — ссылка на «43 %» бессмысленна через
 * минуту, а запись в историю на каждую букву делает кнопку «назад»
 * бесполезной.
 *
 * Схема описывает параметры явно, а не выводится из объекта состояния.
 * Так видно весь состав ссылки в одном месте, и случайное поле
 * компонента не утекает в адрес, который люди пересылают друг другу.
 */

/**
 * Одно поле схемы.
 *
 * @param {string} параметр имя в адресе — короткое, его читают глазами
 * @param {*} поумолчанию значение, которое в адрес не пишется
 * @param {Function} [читать] строка из адреса → значение состояния
 * @param {Function} [писать] значение состояния → строка (пусто = не писать)
 */
export function поле(параметр, поумолчанию, читать = (v) => v, писать = (v) => String(v)) {
  return { параметр, поумолчанию, читать, писать }
}

/** Флажок: в адресе «1», отсутствие означает «выключен». */
export function флажок(параметр) {
  return поле(параметр, false, (v) => v === '1' || v === 'true', (v) => (v ? '1' : ''))
}

/** Целое: страница списка. Мусор в адресе не роняет экран, а игнорируется. */
export function число(параметр, поумолчанию = 1) {
  return поле(
    параметр,
    поумолчанию,
    (v) => {
      const n = Number.parseInt(v, 10)
      return Number.isFinite(n) && n > 0 ? n : поумолчанию
    },
    (v) => String(v),
  )
}

/**
 * Значение из закрытого списка: сортировка.
 *
 * Чужая ссылка может содержать что угодно, в том числе параметр от
 * прошлой версии продукта. Неизвестное значение — это значение по
 * умолчанию, а не пустой экран.
 */
export function изСписка(параметр, поумолчанию, допустимые) {
  return поле(
    параметр,
    поумолчанию,
    (v) => (допустимые.includes(v) ? v : поумолчанию),
    (v) => String(v),
  )
}

/**
 * Состояние → объект параметров адреса.
 *
 * Значения по умолчанию не пишутся: чистый экран должен давать чистый
 * адрес, иначе ссылка на список без фильтров тащит за собой десяток
 * пустых параметров и выглядит как настроенная выборка.
 */
export function вАдрес(состояние, схема) {
  const query = {}
  for (const [ключ, описание] of Object.entries(схема)) {
    const значение = состояние[ключ]
    if (значение === undefined || значение === null) continue
    if (значение === описание.поумолчанию) continue

    const строка = описание.писать(значение)
    if (строка === '' || строка === undefined) continue
    query[описание.параметр] = строка
  }
  return query
}

/**
 * Параметры адреса → состояние.
 *
 * Неизвестные параметры молча отбрасываются: адрес мог прийти из чужой
 * переписки, от прошлой версии продукта или из чужого продукта вовсе.
 * Экран от этого не падает и не сбрасывает остальное.
 */
export function изАдреса(query, схема) {
  const состояние = {}
  for (const [ключ, описание] of Object.entries(схема)) {
    const сырое = query[описание.параметр]
    состояние[ключ] = сырое === undefined || сырое === '' ? описание.поумолчанию : описание.читать(сырое)
  }
  return состояние
}

/**
 * Совпадают ли адреса по существу.
 *
 * Нужно, чтобы не писать в историю переход, который ничего не меняет:
 * иначе восстановление состояния из адреса само порождает новую запись,
 * и «назад» перестаёт работать.
 */
export function одинаковые(а, б) {
  const ключи = new Set([...Object.keys(а), ...Object.keys(б)])
  for (const ключ of ключи) {
    if (String(а[ключ] ?? '') !== String(б[ключ] ?? '')) return false
  }
  return true
}
